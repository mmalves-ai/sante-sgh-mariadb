const chave = (tabela: string, coluna: string) => `${tabela}.${coluna}`;
const COBERTAS = new Map(REFERENCIAS_PACIENTE.map((r) => [chave(r.tabela, r.coluna), r]));

export interface PlanoUnificacao {
  /** As referências a transferir, na ordem da lista (a reversão segue a ordem inversa dos itens). */
  readonly transferir: readonly ReferenciaPaciente[];
  /** Referências que o banco tem e a lista não cobre: a unificação é recusada. */
  readonly naoCobertas: readonly string[];
}

/** O plano da unificação pelas referências que o banco do cliente declara para paciente(id). */
export function planoDeUnificacao(
  doBanco: readonly { readonly tabela: string; readonly coluna: string }[],
): PlanoUnificacao {
  const naoCobertas = doBanco
    .map((r) => chave(r.tabela, r.coluna))
    .filter((k) => !COBERTAS.has(k))
    .sort();
  return { transferir: REFERENCIAS_PACIENTE.filter((r) => r.destino === 'transferir'), naoCobertas };
}

/** As tabelas que a operação de unificação grava (a transação do núcleo recusa as não declaradas). */
export function tabelasDaUnificacao(): string[] {
  return [...new Set(REFERENCIAS_PACIENTE.filter((r) => r.destino === 'transferir').map((r) => r.tabela))];
}
