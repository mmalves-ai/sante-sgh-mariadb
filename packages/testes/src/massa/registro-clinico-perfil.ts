// Consultas do perfil do registro clínico (corretor do M22): só CONTAGENS agregadas sobre as tabelas do legado (o
// rascunho encadeado, a correção, o preceptor e as preferências do PEP), usadas pela integração na cópia
// (registro-clinico-perfil.int.spec.ts). Nenhum conteúdo, nome ou ID sai daqui.
export const PERFIL_REGISTRO = {
  anterior: `SELECT IIF(p.DATA_HORA_ARQUIVADO IS NULL, 0, 1) A, IIF(p.DATA_HORA_EXCLUSAO IS NULL, 0, 1) E, COUNT(*) N
         FROM PRCABEVOLTMP c JOIN PRCABEVOLTMP p ON p.ID_CABEVOL = c.ID_PRCABEVOLTMP GROUP BY 1, 2`,
  encadeado: `SELECT IIF(c.DATA_HORA_ARQUIVADO IS NULL, 0, 1) A, IIF(c.DATA_HORA_EXCLUSAO IS NULL, 0, 1) E, COUNT(*) N
         FROM PRCABEVOLTMP c WHERE c.ID_PRCABEVOLTMP IS NOT NULL GROUP BY 1, 2`,
  herda: `SELECT IIF(c.DATA_HORA_LANCAMENTO = p.DATA_HORA_LANCAMENTO, 1, 0) L, IIF(c.ID_CABEVOL > p.ID_CABEVOL, 1, 0) M,
              IIF(c.ID_EVOLUCAO = p.ID_EVOLUCAO, 1, 0) MO, IIF(c.ID_TBCBOPRO_EVOLUCAO = p.ID_TBCBOPRO_EVOLUCAO, 1, 0) C,
              IIF(c.ID_HTATENDIMENTO = p.ID_HTATENDIMENTO, 1, 0) HA, IIF(c.ID_HTPACIENTE = p.ID_HTPACIENTE, 1, 0) HP,
              IIF(ac.ID_ATCABECATEND = ap.ID_ATCABECATEND, 1, 0) ATD,
              IIF(c.DATA_HORA_EVOLUCAO = p.DATA_HORA_EVOLUCAO, 1, 0) EV, COUNT(*) N
         FROM PRCABEVOLTMP c JOIN PRCABEVOLTMP p ON p.ID_CABEVOL = c.ID_PRCABEVOLTMP
         LEFT JOIN HTATENDIMENTO ac ON ac.ID = c.ID_HTATENDIMENTO LEFT JOIN HTATENDIMENTO ap ON ap.ID = p.ID_HTATENDIMENTO
        GROUP BY 1, 2, 3, 4, 5, 6, 7, 8`,
  folhas: `SELECT A, E, R, COUNT(*) N FROM (
         SELECT IIF(t.DATA_HORA_ARQUIVADO IS NULL, 0, 1) A, IIF(t.DATA_HORA_EXCLUSAO IS NULL, 0, 1) E,
                IIF(EXISTS (SELECT 1 FROM PRCABEVOL r WHERE r.ID_HTATENDIMENTO = t.ID_HTATENDIMENTO
                              AND r.ID_EVOLUCAO = t.ID_EVOLUCAO AND r.ID_TBCBOPRO_EVOLUCAO = t.ID_TBCBOPRO_EVOLUCAO
                              AND r.DATA_HORA_EVOLUCAO = t.DATA_HORA_EVOLUCAO), 1, 0) R
           FROM PRCABEVOLTMP t
          WHERE t.DATA_HORA_LANCAMENTO >= DATEADD(-180 DAY TO CURRENT_DATE)
            AND NOT EXISTS (SELECT 1 FROM PRCABEVOLTMP c WHERE c.ID_PRCABEVOLTMP = t.ID_CABEVOL))
        GROUP BY A, E, R`,
  irmaos: `SELECT COUNT(*) N FROM (SELECT c.ID_PRCABEVOLTMP X FROM PRCABEVOLTMP c WHERE c.ID_PRCABEVOLTMP IS NOT NULL
         GROUP BY c.ID_PRCABEVOLTMP HAVING COUNT(*) > 1)`,
  quando: `SELECT IIF(p.DATA_HORA_EXCLUSAO IS NULL, 0, IIF(p.DATA_HORA_EXCLUSAO >= c.DATA_HORA_LANCAMENTO, 1, 2)) Q, COUNT(*) N
         FROM PRCABEVOLTMP c JOIN PRCABEVOLTMP p ON p.ID_CABEVOL = c.ID_PRCABEVOLTMP GROUP BY 1`,
  todos: `SELECT IIF(DATA_HORA_ARQUIVADO IS NULL, 0, 1) A, IIF(DATA_HORA_EXCLUSAO IS NULL, 0, 1) E,
              IIF(ID_PRCABEVOLTMP IS NULL, 0, 1) F, COUNT(*) N FROM PRCABEVOLTMP GROUP BY 1, 2, 3`,
  correcaoOriginal: `SELECT IIF(o.DATA_HORA_SUSPENSAO IS NULL, 0, 1) S, IIF(hc.ID_RICADPAC = ho.ID_RICADPAC, 1, 0) P,
              IIF(c.ID_EVOLUCAO = o.ID_EVOLUCAO, 1, 0) M, IIF(c.ID_TBCBOPRO_EVOLUCAO = o.ID_TBCBOPRO_EVOLUCAO, 1, 0) C,
              IIF(c.ID_HTATENDIMENTO = o.ID_HTATENDIMENTO, 1, 0) HA, COUNT(*) N
         FROM PRCABEVOL c JOIN PRCABEVOL o ON o.ID_CABEVOL = c.ID_PRCABEVOL_ORIG_CORREC
         JOIN HTPACIENTE hc ON hc.ID = c.ID_HTPACIENTE JOIN HTPACIENTE ho ON ho.ID = o.ID_HTPACIENTE
        GROUP BY 1, 2, 3, 4, 5`,
  correcaoOrdem: `SELECT IIF(o.DATA_HORA_SUSPENSAO IS NULL, 0, IIF(c.DATA_HORA_LANCAMENTO >= o.DATA_HORA_SUSPENSAO, 1, 2)) Q,
              IIF(o.ID_TBCBOPRO_SUSPENSAO = c.ID_TBCBOPRO_EVOLUCAO, 1, 0) QS, IIF(c.DATA_HORA_SUSPENSAO IS NULL, 0, 1) CS, COUNT(*) N
         FROM PRCABEVOL c JOIN PRCABEVOL o ON o.ID_CABEVOL = c.ID_PRCABEVOL_ORIG_CORREC GROUP BY 1, 2, 3`,
  correcaoVarias: `SELECT COUNT(*) N FROM (SELECT ID_PRCABEVOL_ORIG_CORREC X FROM PRCABEVOL WHERE ID_PRCABEVOL_ORIG_CORREC IS NOT NULL
         GROUP BY 1 HAVING COUNT(*) > 1)`,
  correcaoSemOriginal: `SELECT COUNT(*) N FROM PRCABEVOL c WHERE c.ID_PRCABEVOL_ORIG_CORREC IS NOT NULL
          AND NOT EXISTS (SELECT 1 FROM PRCABEVOL o WHERE o.ID_CABEVOL = c.ID_PRCABEVOL_ORIG_CORREC)`,
  correcaoAno: `SELECT EXTRACT(YEAR FROM DATA_HORA_LANCAMENTO) ANO, COUNT(*) N FROM PRCABEVOL
        WHERE ID_PRCABEVOL_ORIG_CORREC IS NOT NULL GROUP BY 1`,
  correcaoRascunho: `SELECT COUNT(*) N FROM PRCABEVOLTMP WHERE ID_PRCABEVOL_ORIG_CORREC IS NOT NULL`,
  preceptor: `SELECT EXTRACT(YEAR FROM DATA_HORA_LANCAMENTO) ANO, COUNT(*) N FROM PRCABEVOL
        WHERE ID_TBPROFIS_ACOMP_RESP IS NOT NULL GROUP BY 1`,
  preferencias: `SELECT IIF(USUARIO IS NULL, 0, 1) U, COUNT(*) N FROM PRLOCPACDEFAULT GROUP BY 1`,
} as const;
