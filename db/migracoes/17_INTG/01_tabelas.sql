  origem                          VARCHAR(20) NOT NULL DEFAULT 'sistema',
  criado_em                       DATETIME(3) NOT NULL,
  criado_por                      BIGINT UNSIGNED NULL,
  alterado_em                     DATETIME(3) NULL,
  alterado_por                    BIGINT UNSIGNED NULL,
  versao                          INT UNSIGNED NOT NULL DEFAULT 1,
  excluido_em                     DATETIME(3) NULL,
  excluido_por                    BIGINT UNSIGNED NULL,
  CONSTRAINT ck_chave_api_situacao CHECK (situacao IN ('ativa','expirada','revogada')),
  CONSTRAINT ck_chave_api_validade CHECK (valida_ate IS NULL OR valida_ate > valida_desde),
  CONSTRAINT ck_chave_api_revogacao CHECK (situacao <> 'revogada' OR revogada_em IS NOT NULL),
  CONSTRAINT ck_chave_api_origem CHECK (origem IN ('sistema','migracao','integracao')),
  UNIQUE KEY uq_chave_api_cliente_sequencia (cliente_api_id, sequencia),
  UNIQUE KEY uq_chave_api_prefixo (prefixo),
  UNIQUE KEY uq_chave_api_hash_chave (hash_chave),
  KEY ix_chave_api_revogada_por (revogada_por_usuario_id)
) COMMENT='Chaves do cliente guardadas por resumo criptográfico, com validade e revogação';

