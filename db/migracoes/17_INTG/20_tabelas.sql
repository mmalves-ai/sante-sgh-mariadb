CREATE TABLE vinculo_responsavel_portal (
  id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
  estabelecimento_id BIGINT UNSIGNED NOT NULL,
  conta_portal_paciente_id BIGINT UNSIGNED NOT NULL COMMENT 'Conta do responsável',
  paciente_id BIGINT UNSIGNED NOT NULL COMMENT 'Paciente representado',
  situacao VARCHAR(20) NOT NULL DEFAULT 'pendente',
  tipo_vinculo VARCHAR(30) NOT NULL,
  prova VARCHAR(40) NOT NULL COMMENT 'Documento que prova o vínculo',
  prova_arquivo_id BIGINT UNSIGNED NULL,
  prova_resumo CHAR(64) NULL COMMENT 'SHA-256 do arquivo da prova',
  escopos LONGTEXT NOT NULL COMMENT 'O que o responsável pode ver e fazer (JSON)',
  canal VARCHAR(10) NOT NULL,
  pedido_em DATETIME(3) NOT NULL,
  pedido_por VARCHAR(60) NOT NULL,
  decidido_por_usuario_id BIGINT UNSIGNED NULL,
  decidido_em DATETIME(3) NULL,
  motivo_recusa VARCHAR(200) NULL,
  motivo_fim VARCHAR(40) NULL,
  encerrado_em DATETIME(3) NULL,
  origem VARCHAR(20) NOT NULL DEFAULT 'sistema',
  criado_em DATETIME(3) NOT NULL,
  criado_por BIGINT UNSIGNED NULL,
  alterado_em DATETIME(3) NULL,
  alterado_por BIGINT UNSIGNED NULL,
  versao INT UNSIGNED NOT NULL DEFAULT 1,
  excluido_em DATETIME(3) NULL,
  excluido_por BIGINT UNSIGNED NULL,
  CONSTRAINT ck_vinculo_responsavel_portal_situacao CHECK (situacao IN ('pendente','ativo','recusado','encerrado')),
  CONSTRAINT ck_vinculo_responsavel_portal_tipo CHECK (tipo_vinculo IN ('pai_mae','tutor','curador','procurador','outro')),
  CONSTRAINT ck_vinculo_responsavel_portal_canal CHECK (canal IN ('portal','balcao')),
  CONSTRAINT ck_vinculo_responsavel_portal_decisao CHECK (situacao = 'pendente' OR (decidido_em IS NOT NULL AND decidido_por_usuario_id IS NOT NULL)),
  CONSTRAINT ck_vinculo_responsavel_portal_recusa CHECK (situacao <> 'recusado' OR motivo_recusa IS NOT NULL),
  CONSTRAINT ck_vinculo_responsavel_portal_encerramento CHECK (situacao <> 'encerrado' OR (encerrado_em IS NOT NULL AND motivo_fim IS NOT NULL)),
  CONSTRAINT ck_vinculo_responsavel_portal_escopos CHECK (JSON_VALID(escopos)),
  KEY ix_vinculo_responsavel_portal_fila (estabelecimento_id, situacao, id),
  KEY ix_vinculo_responsavel_portal_conta (conta_portal_paciente_id),
  KEY ix_vinculo_responsavel_portal_paciente (paciente_id),
  KEY ix_vinculo_responsavel_portal_prova_arquivo (prova_arquivo_id),
  KEY ix_vinculo_responsavel_portal_decidido_por (decidido_por_usuario_id),
  CONSTRAINT ck_vinculo_responsavel_portal_origem CHECK (origem IN ('sistema','migracao','integracao'))
) COMMENT='Pedido e decisão do vínculo de um responsável (pais, tutor, curador, procurador) a um paciente no portal, com prova e escopos';

CREATE TABLE intencao_pagamento_portal (
  id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
  estabelecimento_id BIGINT UNSIGNED NOT NULL,
  conta_portal_paciente_id BIGINT UNSIGNED NOT NULL,
  paciente_id BIGINT UNSIGNED NOT NULL,
  marcacao_horario_id BIGINT UNSIGNED NULL,
  valor DECIMAL(12,2) NOT NULL,
  forma VARCHAR(20) NOT NULL,
  conector VARCHAR(20) NOT NULL COMMENT 'simulado fora de produção',
  transacao VARCHAR(80) NOT NULL,
  situacao VARCHAR(20) NOT NULL DEFAULT 'pendente',
  expira_em DATETIME(3) NOT NULL,
  confirmado_em DATETIME(3) NULL,
  confirmado_por_usuario_id BIGINT UNSIGNED NULL,
  pix_copia_e_cola TEXT NULL,
  endereco_cartao VARCHAR(500) NULL COMMENT 'Endereço da página de pagamento com cartão',
  recebimento_particular_id BIGINT UNSIGNED NULL COMMENT 'Baixa no financeiro',
  origem VARCHAR(20) NOT NULL DEFAULT 'sistema',
  criado_em DATETIME(3) NOT NULL,
  criado_por BIGINT UNSIGNED NULL,
  alterado_em DATETIME(3) NULL,
  alterado_por BIGINT UNSIGNED NULL,
  versao INT UNSIGNED NOT NULL DEFAULT 1,
  excluido_em DATETIME(3) NULL,
  excluido_por BIGINT UNSIGNED NULL,
  CONSTRAINT ck_intencao_pagamento_portal_valor CHECK (valor > 0),
  CONSTRAINT ck_intencao_pagamento_portal_forma CHECK (forma IN ('pix','cartao_credito')),
  CONSTRAINT ck_intencao_pagamento_portal_conector CHECK (conector IN ('simulado','gateway')),
  CONSTRAINT ck_intencao_pagamento_portal_situacao CHECK (situacao IN ('pendente','confirmado','recusado','expirado','duplicado')),
  CONSTRAINT ck_intencao_pagamento_portal_confirmacao CHECK (situacao <> 'confirmado' OR confirmado_em IS NOT NULL),
  UNIQUE KEY uq_intencao_pagamento_portal_transacao (transacao),
  KEY ix_intencao_pagamento_portal_estabelecimento (estabelecimento_id, situacao),
  KEY ix_intencao_pagamento_portal_conta (conta_portal_paciente_id),
  KEY ix_intencao_pagamento_portal_paciente (paciente_id),
  KEY ix_intencao_pagamento_portal_marcacao (marcacao_horario_id),
  KEY ix_intencao_pagamento_portal_confirmado_por (confirmado_por_usuario_id),
  KEY ix_intencao_pagamento_portal_recebimento (recebimento_particular_id),
  CONSTRAINT ck_intencao_pagamento_portal_origem CHECK (origem IN ('sistema','migracao','integracao'))
) COMMENT='Pagamento iniciado pelo paciente no portal (pix ou cartão), com transação, situação e baixa no recebimento particular';

CREATE TABLE conciliacao_pagamento_portal (
  id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
  intencao_pagamento_portal_id BIGINT UNSIGNED NOT NULL,
  acao VARCHAR(20) NOT NULL,
  acao_unica VARCHAR(20) AS (IF(acao IN ('conciliado','estorno'), acao, NULL)) PERSISTENT COMMENT 'Só para a unicidade: uma baixa e um estorno por pagamento',
  valor DECIMAL(12,2) NOT NULL,
  referencia VARCHAR(80) NULL,
  motivo VARCHAR(500) NULL,
  usuario_id BIGINT UNSIGNED NOT NULL,
  criado_em DATETIME(3) NOT NULL,
  criado_por BIGINT UNSIGNED NULL,
  alterado_em DATETIME(3) NULL,
  alterado_por BIGINT UNSIGNED NULL,
  versao INT UNSIGNED NOT NULL DEFAULT 1,
  CONSTRAINT ck_conciliacao_pagamento_portal_acao CHECK (acao IN ('conciliado','divergente','estorno')),
  CONSTRAINT ck_conciliacao_pagamento_portal_motivo CHECK (acao = 'conciliado' OR motivo IS NOT NULL),
  CONSTRAINT ck_conciliacao_pagamento_portal_valor CHECK (valor >= 0),
  UNIQUE KEY uq_conciliacao_pagamento_portal_acao (intencao_pagamento_portal_id, acao_unica),
  KEY ix_conciliacao_pagamento_portal_usuario (usuario_id)
) COMMENT='Conciliação do pagamento do portal pela tesouraria: conciliado, divergente ou estorno';

