CREATE TABLE documento_origem_titulo (
  id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
  natureza_titulo VARCHAR(30) NOT NULL COMMENT 'pagar ou receber',
  titulo_pagar_id BIGINT UNSIGNED NULL,
  titulo_receber_id BIGINT UNSIGNED NULL,
  tipo_documento VARCHAR(30) NOT NULL,
  nota_entrada_id BIGINT UNSIGNED NULL,
  entrada_servico_id BIGINT UNSIGNED NULL,
  contrato_fornecedor_id BIGINT UNSIGNED NULL,
  recibo_id BIGINT UNSIGNED NULL,
  recibo_autonomo_id BIGINT UNSIGNED NULL,
  guia_recolhimento_id BIGINT UNSIGNED NULL,
  nota_servico_id BIGINT UNSIGNED NULL,
  entidade VARCHAR(64) NULL COMMENT 'Tabela de origem para tipos sem coluna própria (folha, comissão, outro)',
  entidade_id BIGINT UNSIGNED NULL,
  numero_documento VARCHAR(60) NULL,
  descricao VARCHAR(200) NULL,
  arquivo_id BIGINT UNSIGNED NULL COMMENT 'Cópia digital do documento',
  titulo_referencia_id BIGINT UNSIGNED AS (COALESCE(titulo_pagar_id, titulo_receber_id)) STORED COMMENT 'Calculado: id do título, para a unicidade',
  documento_referencia_id BIGINT UNSIGNED AS (COALESCE(nota_entrada_id, entrada_servico_id, contrato_fornecedor_id, recibo_id, recibo_autonomo_id, guia_recolhimento_id, nota_servico_id, entidade_id)) STORED COMMENT 'Calculado: id do documento, para a unicidade',
  criado_em DATETIME(3) NOT NULL,
  criado_por BIGINT UNSIGNED NULL,
  alterado_em DATETIME(3) NULL,
  alterado_por BIGINT UNSIGNED NULL,
  versao INT UNSIGNED NOT NULL DEFAULT 1,
  excluido_em DATETIME(3) NULL,
  excluido_por BIGINT UNSIGNED NULL,
  CONSTRAINT ck_documento_origem_titulo_natureza CHECK ((natureza_titulo = 'pagar' AND titulo_pagar_id IS NOT NULL AND titulo_receber_id IS NULL) OR (natureza_titulo = 'receber' AND titulo_receber_id IS NOT NULL AND titulo_pagar_id IS NULL)),
  CONSTRAINT ck_documento_origem_titulo_tipo CHECK (tipo_documento IN ('nota_entrada','entrada_servico','contrato','recibo','recibo_autonomo','guia_recolhimento','nota_servico','folha','comissao','outro')),
  CONSTRAINT ck_documento_origem_titulo_referencia CHECK (
    (tipo_documento = 'nota_entrada' AND nota_entrada_id IS NOT NULL) OR
    (tipo_documento = 'entrada_servico' AND entrada_servico_id IS NOT NULL) OR
    (tipo_documento = 'contrato' AND contrato_fornecedor_id IS NOT NULL) OR
    (tipo_documento = 'recibo' AND recibo_id IS NOT NULL) OR
    (tipo_documento = 'recibo_autonomo' AND recibo_autonomo_id IS NOT NULL) OR
    (tipo_documento = 'guia_recolhimento' AND guia_recolhimento_id IS NOT NULL) OR
    (tipo_documento = 'nota_servico' AND nota_servico_id IS NOT NULL) OR
    (tipo_documento IN ('folha','comissao','outro') AND (entidade_id IS NOT NULL OR arquivo_id IS NOT NULL OR numero_documento IS NOT NULL))),
  UNIQUE KEY uq_documento_origem_titulo_par (natureza_titulo, titulo_referencia_id, tipo_documento, documento_referencia_id),
  KEY ix_documento_origem_titulo_titulo_pagar (titulo_pagar_id),
  KEY ix_documento_origem_titulo_titulo_receber (titulo_receber_id),
  KEY ix_documento_origem_titulo_nota_entrada (nota_entrada_id),
  KEY ix_documento_origem_titulo_entrada_servico (entrada_servico_id),
  KEY ix_documento_origem_titulo_contrato_fornecedor (contrato_fornecedor_id),
  KEY ix_documento_origem_titulo_recibo (recibo_id),
  KEY ix_documento_origem_titulo_recibo_autonomo (recibo_autonomo_id),
  KEY ix_documento_origem_titulo_guia_recolhimento (guia_recolhimento_id),
  KEY ix_documento_origem_titulo_nota_servico (nota_servico_id),
  KEY ix_documento_origem_titulo_arquivo (arquivo_id)
) COMMENT='Documento que originou o título (nota de entrada, contrato, recibo, folha, guia), com tipo e chave';

