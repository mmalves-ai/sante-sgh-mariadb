CREATE TABLE modelo_recibo (
  id                BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
  estabelecimento_id BIGINT UNSIGNED NOT NULL,
  nome              VARCHAR(150) NOT NULL,
  tipo_recebimento  VARCHAR(30) NOT NULL COMMENT 'particular, adiantamento, fonte_pagadora, avulso, autonomo',
  serie             VARCHAR(10) NULL COMMENT 'Série impressa no número do recibo',
  sequencia_negocio_id BIGINT UNSIGNED NULL COMMENT 'Sequência que numera os recibos deste modelo',
  texto_cabecalho   TEXT NULL,
  texto_corpo       TEXT NOT NULL COMMENT 'Texto com campos de mesclagem do recebimento',
  texto_rodape      TEXT NULL,
  logotipo_arquivo_id BIGINT UNSIGNED NULL,
  exibe_valor_extenso BOOLEAN NOT NULL DEFAULT TRUE,
  quantidade_vias   TINYINT UNSIGNED NOT NULL DEFAULT 1,
  padrao            BOOLEAN NOT NULL DEFAULT FALSE COMMENT 'Modelo usado quando o tipo de recebimento não indica outro',
  ativo             BOOLEAN NOT NULL DEFAULT TRUE,
  criado_em         DATETIME(3) NOT NULL,
  criado_por        BIGINT UNSIGNED NULL,
  alterado_em       DATETIME(3) NULL,
  alterado_por      BIGINT UNSIGNED NULL,
  versao            INT UNSIGNED NOT NULL DEFAULT 1,
  CONSTRAINT ck_modelo_recibo_tipo_recebimento CHECK (tipo_recebimento IN ('particular','adiantamento','fonte_pagadora','avulso','autonomo')),
  CONSTRAINT ck_modelo_recibo_quantidade_vias CHECK (quantidade_vias BETWEEN 1 AND 5),
  UNIQUE KEY uq_modelo_recibo_estabelecimento_tipo_nome (estabelecimento_id, tipo_recebimento, nome),
  KEY ix_modelo_recibo_sequencia_negocio_id (sequencia_negocio_id),
  KEY ix_modelo_recibo_logotipo_arquivo_id (logotipo_arquivo_id)
) COMMENT='Modelo e numeração do recibo por estabelecimento e tipo de recebimento';

