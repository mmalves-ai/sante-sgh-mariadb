  CONSTRAINT ck_conferencia_sessao_caixa_especie CHECK (especie IS NULL OR especie IN ('cedula','moeda')),
  CONSTRAINT ck_conferencia_sessao_caixa_valores CHECK (valor_esperado >= 0 AND valor_contado >= 0 AND (valor_face IS NULL OR valor_face > 0)),
