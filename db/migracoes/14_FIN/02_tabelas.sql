CREATE TABLE boleto (
  id                BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
  estabelecimento_id BIGINT UNSIGNED NOT NULL,
  carteira_cobranca_id BIGINT UNSIGNED NOT NULL,
  nosso_numero      VARCHAR(30) NOT NULL,
  numero_documento  VARCHAR(30) NULL COMMENT 'Número do documento informado ao banco (seu número)',
  linha_digitavel   VARCHAR(60) NULL,
  codigo_barras     VARCHAR(50) NULL,
  pix_copia_cola    VARCHAR(500) NULL COMMENT 'Código Pix do boleto híbrido',
  pessoa_fisica_id  BIGINT UNSIGNED NULL COMMENT 'Pagador pessoa física',
  pessoa_juridica_id BIGINT UNSIGNED NULL COMMENT 'Pagador pessoa jurídica',
  cliente_financeiro_id BIGINT UNSIGNED NULL COMMENT 'Pagador cadastrado como cliente do financeiro',
  pagador_nome      VARCHAR(150) NOT NULL COMMENT 'Nome do pagador como enviado ao banco',
  pagador_documento VARCHAR(14) NOT NULL COMMENT 'CPF ou CNPJ do pagador, só dígitos',
  data_emissao      DATE NOT NULL,
  data_vencimento   DATE NOT NULL,
  data_vencimento_original DATE NULL COMMENT 'Vencimento antes de prorrogação',
  valor             DECIMAL(15,2) NOT NULL,
  valor_desconto    DECIMAL(15,2) NOT NULL DEFAULT 0,
  valor_acrescimo   DECIMAL(15,2) NOT NULL DEFAULT 0,
  valor_pago        DECIMAL(15,2) NULL,
  data_pagamento    DATE NULL,
  situacao          VARCHAR(30) NOT NULL DEFAULT 'emitido',
  impresso          BOOLEAN NOT NULL DEFAULT FALSE,
  entregue          BOOLEAN NOT NULL DEFAULT FALSE,
  remessa_cobranca_id BIGINT UNSIGNED NULL,
  data_cancelamento DATE NULL,
  cancelado_por_usuario_id BIGINT UNSIGNED NULL,
  motivo_cancelamento VARCHAR(500) NULL,
  origem            VARCHAR(20) NOT NULL DEFAULT 'sistema' COMMENT 'sistema, migracao ou integracao',
  criado_em         DATETIME(3) NOT NULL,
  criado_por        BIGINT UNSIGNED NULL,
  alterado_em       DATETIME(3) NULL,
  alterado_por      BIGINT UNSIGNED NULL,
  versao            INT UNSIGNED NOT NULL DEFAULT 1,
  excluido_em       DATETIME(3) NULL,
  excluido_por      BIGINT UNSIGNED NULL,
  CONSTRAINT ck_boleto_origem CHECK (origem IN ('sistema','migracao','integracao')),
  CONSTRAINT ck_boleto_situacao CHECK (situacao IN ('emitido','registrado','rejeitado','pago','baixado','cancelado','protestado')),
  CONSTRAINT ck_boleto_valores CHECK (valor > 0 AND valor_desconto >= 0 AND valor_acrescimo >= 0 AND (valor_pago IS NULL OR valor_pago >= 0)),
  CONSTRAINT ck_boleto_vencimento CHECK (data_vencimento >= data_emissao),
  CONSTRAINT ck_boleto_cancelamento CHECK (situacao <> 'cancelado' OR data_cancelamento IS NOT NULL),
  CONSTRAINT ck_boleto_documento CHECK (pagador_documento REGEXP '^([0-9]{11}|[0-9]{14})$'),
  UNIQUE KEY uq_boleto_carteira_nosso_numero (carteira_cobranca_id, nosso_numero),
  KEY ix_boleto_estabelecimento_vencimento (estabelecimento_id, data_vencimento, situacao),
  KEY ix_boleto_pessoa_fisica (pessoa_fisica_id),
  KEY ix_boleto_pessoa_juridica (pessoa_juridica_id),
  KEY ix_boleto_cliente_financeiro (cliente_financeiro_id),
  KEY ix_boleto_remessa_cobranca (remessa_cobranca_id),
  KEY ix_boleto_cancelado_por_usuario (cancelado_por_usuario_id)
) COMMENT='Boleto emitido para uma ou mais parcelas a receber, com nosso número, linha digitável, código Pix, vencimento e situação';

