CREATE TABLE gestor_contrato (
  id                      BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
  contrato_fornecedor_id  BIGINT UNSIGNED NOT NULL,
  usuario_id              BIGINT UNSIGNED NOT NULL COMMENT 'Usuário que exerce o papel no contrato',
  papel                   VARCHAR(30) NOT NULL COMMENT 'gestor, fiscal, fiscal_substituto, aprovador ou acompanhante',
  setor_funcional_id      BIGINT UNSIGNED NULL COMMENT 'Setor que o gestor representa no contrato',
  descricao_vinculo       VARCHAR(100) NULL,
  vigencia_inicio         DATE NOT NULL,
  vigencia_fim            DATE NULL,
  aprovador               BOOLEAN NOT NULL DEFAULT FALSE COMMENT 'Aprova medições, aditivos e pagamentos do contrato',
  prazo_resposta_dias     SMALLINT UNSIGNED NULL COMMENT 'Prazo para responder às pendências do contrato',
  email_notificacao       VARCHAR(254) NULL COMMENT 'Endereço alternativo ao do cadastro do usuário',
  permite_incluir         BOOLEAN NOT NULL DEFAULT FALSE,
  permite_suspender       BOOLEAN NOT NULL DEFAULT FALSE,
  permite_cancelar        BOOLEAN NOT NULL DEFAULT FALSE,
  permite_apontar         BOOLEAN NOT NULL DEFAULT FALSE COMMENT 'Registra apontamento de produção',
  permite_aprovar         BOOLEAN NOT NULL DEFAULT FALSE,
  permite_aditar          BOOLEAN NOT NULL DEFAULT FALSE,
  permite_renovar         BOOLEAN NOT NULL DEFAULT FALSE,
  permite_ativar          BOOLEAN NOT NULL DEFAULT FALSE,
  finaliza_discussao      BOOLEAN NOT NULL DEFAULT FALSE COMMENT 'Pode encerrar a discussão de uma ocorrência',
  criado_em               DATETIME(3) NOT NULL,
  criado_por              BIGINT UNSIGNED NULL,
  alterado_em             DATETIME(3) NULL,
  alterado_por            BIGINT UNSIGNED NULL,
  versao                  INT UNSIGNED NOT NULL DEFAULT 1,
  excluido_em             DATETIME(3) NULL,
  excluido_por            BIGINT UNSIGNED NULL,
  CONSTRAINT ck_gestor_contrato_papel CHECK (papel IN ('gestor','fiscal','fiscal_substituto','aprovador','acompanhante')),
  CONSTRAINT ck_gestor_contrato_vigencia CHECK (vigencia_fim IS NULL OR vigencia_fim >= vigencia_inicio),
  UNIQUE KEY uq_gestor_contrato_contrato_usuario_papel_inicio (contrato_fornecedor_id, usuario_id, papel, vigencia_inicio),
  KEY ix_gestor_contrato_usuario (usuario_id),
  KEY ix_gestor_contrato_setor (setor_funcional_id)
) COMMENT='Gestor e fiscal do contrato, com período';

