CREATE TABLE titulo_pagar (
  id                BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
  estabelecimento_id BIGINT UNSIGNED NOT NULL,
  numero            VARCHAR(30) NOT NULL COMMENT 'Número de negócio do título, gerado por sequencia_negocio',
  tipo_credor_id    BIGINT UNSIGNED NOT NULL COMMENT 'Fornecedor, médico, empresa médica, folha, colaborador ou tributos',
  empresa_fornecedora_id BIGINT UNSIGNED NULL COMMENT 'Credor pessoa jurídica ou órgão arrecadador',
  profissional_id   BIGINT UNSIGNED NULL COMMENT 'Credor profissional de saúde (honorário, repasse)',
  colaborador_id    BIGINT UNSIGNED NULL COMMENT 'Credor colaborador (reembolso, adiantamento, folha)',
  tipo_titulo       VARCHAR(30) NOT NULL DEFAULT 'normal',
  modulo_origem     VARCHAR(30) NOT NULL DEFAULT 'financeiro' COMMENT 'Módulo que gerou o título',
  tipo_documento_financeiro_id BIGINT UNSIGNED NOT NULL,
  numero_documento  VARCHAR(30) NOT NULL COMMENT 'Número do documento do credor (nota, fatura, recibo, guia)',
  serie_documento   VARCHAR(10) NULL,
  chave_acesso_documento CHAR(44) NULL COMMENT 'Chave de acesso do documento fiscal eletrônico, quando houver',
  nota_entrada_id   BIGINT UNSIGNED NULL COMMENT 'Nota de entrada de estoque que originou o título',
  contrato_fornecedor_id BIGINT UNSIGNED NULL COMMENT 'Contrato com o fornecedor que o título consome',
  lancamento_repasse_id BIGINT UNSIGNED NULL COMMENT 'Repasse médico que originou o título',
  nota_empenho_id   BIGINT UNSIGNED NULL,
  atendimento_id    BIGINT UNSIGNED NULL COMMENT 'Atendimento relacionado (devolução ou reembolso a paciente)',
  referencia_titulo_pagar_id BIGINT UNSIGNED NULL COMMENT 'Título de referência: previsão substituída, adiantamento prestado ou título devolvido',
  data_emissao      DATE NOT NULL,
  data_entrada      DATE NULL COMMENT 'Entrada do documento no hospital',
  data_lancamento   DATE NOT NULL,
  data_prevista_pagamento DATE NULL,
  valor_bruto       DECIMAL(15,2) NOT NULL,
  valor_desconto    DECIMAL(15,2) NOT NULL DEFAULT 0,
  valor_acrescimo   DECIMAL(15,2) NOT NULL DEFAULT 0,
  valor_retencoes   DECIMAL(15,2) NOT NULL DEFAULT 0 COMMENT 'Soma das retenções (detalhadas em retencao_titulo)',
  valor_liquido     DECIMAL(15,2) NOT NULL COMMENT 'Bruto - desconto + acréscimo - retenções',
  valor_base_irrf   DECIMAL(15,2) NULL,
  valor_base_inss   DECIMAL(15,2) NULL,
  valor_base_iss    DECIMAL(15,2) NULL,
  quantidade_parcelas SMALLINT UNSIGNED NOT NULL DEFAULT 1,
  moeda_id          BIGINT UNSIGNED NULL COMMENT 'Nulo para real',
  taxa_cambio       DECIMAL(15,6) NULL COMMENT 'Taxa de câmbio usada na conversão, quando em moeda estrangeira',
  valor_moeda_estrangeira DECIMAL(15,2) NULL,
  natureza_financeira_id BIGINT UNSIGNED NOT NULL COMMENT 'Classificação gerencial (grupo, subgrupo e item)',
  centro_custo_id   BIGINT UNSIGNED NULL COMMENT 'Centro de custo do documento; o rateio fica em tabela própria',
  historico_padrao_id BIGINT UNSIGNED NULL,
  condicao_pagamento_id BIGINT UNSIGNED NULL,
  conta_bancaria_id BIGINT UNSIGNED NULL COMMENT 'Conta prevista para o pagamento (portador)',
  referente         VARCHAR(150) NULL COMMENT 'Do que se trata o título, como aparece em relatórios',
  observacao        VARCHAR(2000) NULL,
  numero_processo   VARCHAR(30) NULL COMMENT 'Processo administrativo de compra ou pagamento',
  contabiliza       BOOLEAN NOT NULL DEFAULT TRUE,
  lancamento_contabil_id BIGINT UNSIGNED NULL,
  autorizado        BOOLEAN NOT NULL DEFAULT FALSE,
  autorizado_em     DATETIME(3) NULL,
  autorizador_usuario_id BIGINT UNSIGNED NULL,
  pedido_aprovacao_id BIGINT UNSIGNED NULL COMMENT 'Pedido de alçada da aprovação',
  situacao          VARCHAR(30) NOT NULL DEFAULT 'aberto',
  cancelado_em      DATETIME(3) NULL,
  motivo_cancelamento VARCHAR(300) NULL,
  origem            VARCHAR(20) NOT NULL DEFAULT 'sistema',
  criado_em         DATETIME(3) NOT NULL,
  criado_por        BIGINT UNSIGNED NULL,
  alterado_em       DATETIME(3) NULL,
  alterado_por      BIGINT UNSIGNED NULL,
  versao            INT UNSIGNED NOT NULL DEFAULT 1,
  excluido_em       DATETIME(3) NULL,
  excluido_por      BIGINT UNSIGNED NULL,
  CONSTRAINT ck_titulo_pagar_origem CHECK (origem IN ('sistema','migracao','integracao')),
  CONSTRAINT ck_titulo_pagar_credor CHECK ((empresa_fornecedora_id IS NOT NULL) + (profissional_id IS NOT NULL) + (colaborador_id IS NOT NULL) = 1),
  CONSTRAINT ck_titulo_pagar_tipo_titulo CHECK (tipo_titulo IN ('normal','adiantamento','prestacao_contas','devolucao','previsao','reembolso')),
  CONSTRAINT ck_titulo_pagar_modulo_origem CHECK (modulo_origem IN ('financeiro','estoque','compras','repasse','folha','faturamento','contrato','patrimonio','integracao')),
  CONSTRAINT ck_titulo_pagar_situacao CHECK (situacao IN ('aberto','em_bordero','pago_parcial','pago','renegociado','cancelado')),
  CONSTRAINT ck_titulo_pagar_valores CHECK (valor_bruto > 0 AND valor_desconto >= 0 AND valor_acrescimo >= 0 AND valor_retencoes >= 0 AND valor_liquido >= 0),
  CONSTRAINT ck_titulo_pagar_liquido CHECK (valor_liquido = valor_bruto - valor_desconto + valor_acrescimo - valor_retencoes),
  CONSTRAINT ck_titulo_pagar_parcelas CHECK (quantidade_parcelas BETWEEN 1 AND 360),
  CONSTRAINT ck_titulo_pagar_cambio CHECK (moeda_id IS NULL OR (taxa_cambio IS NOT NULL AND taxa_cambio > 0)),
  CONSTRAINT ck_titulo_pagar_datas CHECK (data_lancamento >= data_emissao),
  CONSTRAINT ck_titulo_pagar_autorizacao CHECK (autorizado = FALSE OR autorizado_em IS NOT NULL),
  CONSTRAINT ck_titulo_pagar_cancelamento CHECK (situacao <> 'cancelado' OR (cancelado_em IS NOT NULL AND motivo_cancelamento IS NOT NULL)),
  UNIQUE KEY uq_titulo_pagar_estabelecimento_numero (estabelecimento_id, numero),
  KEY ix_titulo_pagar_tipo_credor (tipo_credor_id),
  KEY ix_titulo_pagar_fornecedor_documento (empresa_fornecedora_id, numero_documento),
  KEY ix_titulo_pagar_profissional (profissional_id),
  KEY ix_titulo_pagar_colaborador (colaborador_id),
  KEY ix_titulo_pagar_tipo_documento_financeiro (tipo_documento_financeiro_id),
  KEY ix_titulo_pagar_nota_entrada (nota_entrada_id),
  KEY ix_titulo_pagar_contrato_fornecedor (contrato_fornecedor_id),
  KEY ix_titulo_pagar_lancamento_repasse (lancamento_repasse_id),
  KEY ix_titulo_pagar_nota_empenho (nota_empenho_id),
  KEY ix_titulo_pagar_atendimento (atendimento_id),
  KEY ix_titulo_pagar_referencia (referencia_titulo_pagar_id),
  KEY ix_titulo_pagar_moeda (moeda_id),
  KEY ix_titulo_pagar_natureza_financeira (natureza_financeira_id),
  KEY ix_titulo_pagar_centro_custo (centro_custo_id),
  KEY ix_titulo_pagar_historico_padrao (historico_padrao_id),
  KEY ix_titulo_pagar_condicao_pagamento (condicao_pagamento_id),
  KEY ix_titulo_pagar_conta_bancaria (conta_bancaria_id),
  KEY ix_titulo_pagar_lancamento_contabil (lancamento_contabil_id),
  KEY ix_titulo_pagar_autorizador (autorizador_usuario_id),
  KEY ix_titulo_pagar_pedido_aprovacao (pedido_aprovacao_id),
  KEY ix_titulo_pagar_situacao (estabelecimento_id, situacao, data_prevista_pagamento),
  KEY ix_titulo_pagar_emissao (estabelecimento_id, data_emissao)
) COMMENT='Título a pagar ao credor, com documento, emissão, valor bruto e líquido, natureza gerencial e situação';

CREATE TABLE titulo_receber (
  id                BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
  estabelecimento_id BIGINT UNSIGNED NOT NULL,
  numero            VARCHAR(30) NOT NULL COMMENT 'Número de negócio do título, gerado por sequencia_negocio',
  tipo_devedor      VARCHAR(30) NOT NULL,
  fonte_pagadora_id BIGINT UNSIGNED NULL COMMENT 'Devedor convênio, operadora ou gestor público',
  paciente_id       BIGINT UNSIGNED NULL COMMENT 'Devedor particular',
  cliente_financeiro_id BIGINT UNSIGNED NULL COMMENT 'Devedor empresa ou pessoa sem vínculo assistencial',
  tipo_origem       VARCHAR(30) NOT NULL COMMENT 'O que originou o título',
  fatura_fonte_pagadora_id BIGINT UNSIGNED NULL,
  conta_hospitalar_id BIGINT UNSIGNED NULL,
  renegociacao_id   BIGINT UNSIGNED NULL COMMENT 'Acordo de renegociação que gerou o título',
  nota_servico_id   BIGINT UNSIGNED NULL,
  atendimento_id    BIGINT UNSIGNED NULL,
  tipo_documento_financeiro_id BIGINT UNSIGNED NOT NULL,
  numero_documento  VARCHAR(30) NOT NULL,
  serie_documento   VARCHAR(10) NULL,
  data_emissao      DATE NOT NULL,
  data_lancamento   DATE NOT NULL,
  data_prevista_recebimento DATE NULL,
  competencia       DATE NULL COMMENT 'Primeiro dia do mês de referência do faturamento',
  valor_bruto       DECIMAL(15,2) NOT NULL,
  valor_desconto    DECIMAL(15,2) NOT NULL DEFAULT 0,
  valor_acrescimo   DECIMAL(15,2) NOT NULL DEFAULT 0,
  valor_impostos    DECIMAL(15,2) NOT NULL DEFAULT 0 COMMENT 'Tributos retidos pelo devedor',
  valor_liquido     DECIMAL(15,2) NOT NULL COMMENT 'Bruto - desconto + acréscimo - impostos',
  valor_glosa       DECIMAL(15,2) NOT NULL DEFAULT 0,
  valor_glosa_aceita DECIMAL(15,2) NOT NULL DEFAULT 0,
  valor_recebido    DECIMAL(15,2) NOT NULL DEFAULT 0 COMMENT 'Acumulado das baixas, mantido pelo domínio',
  quantidade_parcelas SMALLINT UNSIGNED NOT NULL DEFAULT 1,
  moeda_id          BIGINT UNSIGNED NULL COMMENT 'Nulo para real',
  taxa_cambio       DECIMAL(15,6) NULL,
  natureza_financeira_id BIGINT UNSIGNED NOT NULL,
  centro_custo_id   BIGINT UNSIGNED NULL,
  historico_padrao_id BIGINT UNSIGNED NULL,
  forma_recebimento_id BIGINT UNSIGNED NULL,
  conta_bancaria_id BIGINT UNSIGNED NULL COMMENT 'Conta prevista para o recebimento',
  contrato_cobranca_bancaria_id BIGINT UNSIGNED NULL COMMENT 'Carteira de cobrança, quando cobrado por boleto',
  referente         VARCHAR(150) NULL,
  observacao        VARCHAR(2000) NULL,
  contabiliza       BOOLEAN NOT NULL DEFAULT TRUE,
  lancamento_contabil_id BIGINT UNSIGNED NULL,
  situacao          VARCHAR(30) NOT NULL DEFAULT 'aberto',
  cancelado_em      DATETIME(3) NULL,
  motivo_cancelamento VARCHAR(300) NULL,
  origem            VARCHAR(20) NOT NULL DEFAULT 'sistema',
  criado_em         DATETIME(3) NOT NULL,
  criado_por        BIGINT UNSIGNED NULL,
  alterado_em       DATETIME(3) NULL,
  alterado_por      BIGINT UNSIGNED NULL,
  versao            INT UNSIGNED NOT NULL DEFAULT 1,
  excluido_em       DATETIME(3) NULL,
  excluido_por      BIGINT UNSIGNED NULL,
  CONSTRAINT ck_titulo_receber_origem CHECK (origem IN ('sistema','migracao','integracao')),
  CONSTRAINT ck_titulo_receber_tipo_devedor CHECK (tipo_devedor IN ('fonte_pagadora','paciente','cliente')),
  CONSTRAINT ck_titulo_receber_devedor CHECK (
    (tipo_devedor = 'fonte_pagadora' AND fonte_pagadora_id IS NOT NULL AND paciente_id IS NULL AND cliente_financeiro_id IS NULL)
    OR (tipo_devedor = 'paciente' AND paciente_id IS NOT NULL AND fonte_pagadora_id IS NULL AND cliente_financeiro_id IS NULL)
    OR (tipo_devedor = 'cliente' AND cliente_financeiro_id IS NOT NULL AND fonte_pagadora_id IS NULL AND paciente_id IS NULL)),
  CONSTRAINT ck_titulo_receber_tipo_origem CHECK (tipo_origem IN ('fatura','conta','acordo','nota_servico','mensalidade','adiantamento','avulso')),
  CONSTRAINT ck_titulo_receber_origem_fatura CHECK (tipo_origem <> 'fatura' OR fatura_fonte_pagadora_id IS NOT NULL),
  CONSTRAINT ck_titulo_receber_origem_conta CHECK (tipo_origem <> 'conta' OR conta_hospitalar_id IS NOT NULL),
  CONSTRAINT ck_titulo_receber_origem_acordo CHECK (tipo_origem <> 'acordo' OR renegociacao_id IS NOT NULL),
  CONSTRAINT ck_titulo_receber_situacao CHECK (situacao IN ('aberto','recebido_parcial','recebido','renegociado','cancelado')),
  CONSTRAINT ck_titulo_receber_valores CHECK (valor_bruto > 0 AND valor_desconto >= 0 AND valor_acrescimo >= 0 AND valor_impostos >= 0 AND valor_liquido >= 0 AND valor_glosa >= 0 AND valor_glosa_aceita BETWEEN 0 AND valor_glosa AND valor_recebido >= 0),
  CONSTRAINT ck_titulo_receber_liquido CHECK (valor_liquido = valor_bruto - valor_desconto + valor_acrescimo - valor_impostos),
  CONSTRAINT ck_titulo_receber_parcelas CHECK (quantidade_parcelas BETWEEN 1 AND 360),
  CONSTRAINT ck_titulo_receber_competencia CHECK (competencia IS NULL OR DAYOFMONTH(competencia) = 1),
  CONSTRAINT ck_titulo_receber_cambio CHECK (moeda_id IS NULL OR (taxa_cambio IS NOT NULL AND taxa_cambio > 0)),
  CONSTRAINT ck_titulo_receber_cancelamento CHECK (situacao <> 'cancelado' OR (cancelado_em IS NOT NULL AND motivo_cancelamento IS NOT NULL)),
  UNIQUE KEY uq_titulo_receber_estabelecimento_numero (estabelecimento_id, numero),
  KEY ix_titulo_receber_fonte_pagadora (fonte_pagadora_id, situacao),
  KEY ix_titulo_receber_paciente (paciente_id),
  KEY ix_titulo_receber_cliente_financeiro (cliente_financeiro_id),
  KEY ix_titulo_receber_fatura_fonte_pagadora (fatura_fonte_pagadora_id),
  KEY ix_titulo_receber_conta_hospitalar (conta_hospitalar_id),
  KEY ix_titulo_receber_renegociacao (renegociacao_id),
  KEY ix_titulo_receber_nota_servico (nota_servico_id),
  KEY ix_titulo_receber_atendimento (atendimento_id),
  KEY ix_titulo_receber_tipo_documento_financeiro (tipo_documento_financeiro_id),
  KEY ix_titulo_receber_moeda (moeda_id),
  KEY ix_titulo_receber_natureza_financeira (natureza_financeira_id),
  KEY ix_titulo_receber_centro_custo (centro_custo_id),
  KEY ix_titulo_receber_historico_padrao (historico_padrao_id),
  KEY ix_titulo_receber_forma_recebimento (forma_recebimento_id),
  KEY ix_titulo_receber_conta_bancaria (conta_bancaria_id),
  KEY ix_titulo_receber_contrato_cobranca_bancaria (contrato_cobranca_bancaria_id),
  KEY ix_titulo_receber_lancamento_contabil (lancamento_contabil_id),
  KEY ix_titulo_receber_documento (estabelecimento_id, numero_documento),
  KEY ix_titulo_receber_situacao (estabelecimento_id, situacao, data_prevista_recebimento)
) COMMENT='Título a receber de fonte pagadora, empresa ou particular, com origem (fatura, conta, acordo) e situação';

CREATE TABLE titulo_renegociado (
  id                BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
  renegociacao_id   BIGINT UNSIGNED NOT NULL,
  parcela_receber_id BIGINT UNSIGNED NOT NULL COMMENT 'Parcela original incluída no acordo',
  valor_original    DECIMAL(15,2) NOT NULL COMMENT 'Valor da parcela na emissão',
  valor_saldo       DECIMAL(15,2) NOT NULL COMMENT 'Saldo em aberto levado ao acordo',
  valor_juros       DECIMAL(15,2) NOT NULL DEFAULT 0,
  valor_multa       DECIMAL(15,2) NOT NULL DEFAULT 0,
  valor_desconto    DECIMAL(15,2) NOT NULL DEFAULT 0,
  criado_em         DATETIME(3) NOT NULL,
  criado_por        BIGINT UNSIGNED NULL,
  alterado_em       DATETIME(3) NULL,
  alterado_por      BIGINT UNSIGNED NULL,
  versao            INT UNSIGNED NOT NULL DEFAULT 1,
  excluido_em       DATETIME(3) NULL,
  excluido_por      BIGINT UNSIGNED NULL,
  CONSTRAINT ck_titulo_renegociado_valores CHECK (valor_original > 0 AND valor_saldo > 0 AND valor_saldo <= valor_original AND valor_juros >= 0 AND valor_multa >= 0 AND valor_desconto >= 0),
  UNIQUE KEY uq_titulo_renegociado_par (renegociacao_id, parcela_receber_id),
  KEY ix_titulo_renegociado_parcela_receber (parcela_receber_id)
) COMMENT='Parcela original incluída numa renegociação, com saldo levado ao acordo';

CREATE TABLE transacao_cartao (
  id                BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
  estabelecimento_id BIGINT UNSIGNED NOT NULL,
  administradora_cartao_id BIGINT UNSIGNED NOT NULL COMMENT 'Credenciadora (adquirente) da transação',
  bandeira_cartao_id BIGINT UNSIGNED NOT NULL,
  terminal_cartao_id BIGINT UNSIGNED NULL,
  caixa_id          BIGINT UNSIGNED NULL,
  sessao_caixa_id   BIGINT UNSIGNED NULL,
  operador_usuario_id BIGINT UNSIGNED NULL COMMENT 'Usuário que operou o terminal',
  tipo_operacao     VARCHAR(30) NOT NULL DEFAULT 'venda',
  estornada_transacao_cartao_id BIGINT UNSIGNED NULL COMMENT 'Transação original, quando esta é um estorno',
  tipo_cartao       VARCHAR(30) NOT NULL,
  modalidade        VARCHAR(30) NOT NULL DEFAULT 'a_vista',
  quantidade_parcelas SMALLINT UNSIGNED NOT NULL DEFAULT 1,
  nsu               VARCHAR(30) NOT NULL COMMENT 'Número sequencial único da credenciadora',
  codigo_autorizacao VARCHAR(20) NOT NULL,
  final_cartao      CHAR(4) NULL COMMENT 'Quatro últimos dígitos; o número completo nunca é guardado',
  data_hora_transacao DATETIME(3) NOT NULL,
  valor_bruto       DECIMAL(15,2) NOT NULL,
  percentual_taxa   DECIMAL(7,4) NULL COMMENT 'Taxa de administração contratada',
  valor_taxa        DECIMAL(15,2) NOT NULL DEFAULT 0,
  valor_liquido     DECIMAL(15,2) NOT NULL,
  modulo_origem     VARCHAR(30) NOT NULL DEFAULT 'caixa',
  titulo_receber_id BIGINT UNSIGNED NULL,
  atendimento_id    BIGINT UNSIGNED NULL,
  comprovante       TEXT NULL COMMENT 'Texto do comprovante impresso',
  retorno_autorizador JSON NULL COMMENT 'Resposta técnica do autorizador, sem dados do portador do cartão',
  situacao          VARCHAR(30) NOT NULL DEFAULT 'pendente',
  origem            VARCHAR(20) NOT NULL DEFAULT 'sistema',
  criado_em         DATETIME(3) NOT NULL,
  criado_por        BIGINT UNSIGNED NULL,
  alterado_em       DATETIME(3) NULL,
  alterado_por      BIGINT UNSIGNED NULL,
  versao            INT UNSIGNED NOT NULL DEFAULT 1,
  excluido_em       DATETIME(3) NULL,
  excluido_por      BIGINT UNSIGNED NULL,
  CONSTRAINT ck_transacao_cartao_origem CHECK (origem IN ('sistema','migracao','integracao')),
  CONSTRAINT ck_transacao_cartao_tipo_operacao CHECK (tipo_operacao IN ('venda','estorno')),
  CONSTRAINT ck_transacao_cartao_estorno CHECK (tipo_operacao <> 'estorno' OR estornada_transacao_cartao_id IS NOT NULL),
  CONSTRAINT ck_transacao_cartao_tipo_cartao CHECK (tipo_cartao IN ('credito','debito','pre_pago','voucher')),
  CONSTRAINT ck_transacao_cartao_modalidade CHECK (modalidade IN ('a_vista','parcelado_estabelecimento','parcelado_emissor')),
  CONSTRAINT ck_transacao_cartao_parcelas CHECK (quantidade_parcelas BETWEEN 1 AND 99 AND (modalidade <> 'a_vista' OR quantidade_parcelas = 1)),
  CONSTRAINT ck_transacao_cartao_final CHECK (final_cartao IS NULL OR final_cartao REGEXP '^[0-9]{4}$'),
  CONSTRAINT ck_transacao_cartao_valores CHECK (valor_bruto > 0 AND valor_taxa >= 0 AND valor_liquido = valor_bruto - valor_taxa),
  CONSTRAINT ck_transacao_cartao_modulo_origem CHECK (modulo_origem IN ('caixa','recepcao','financeiro','portal','integracao')),
  CONSTRAINT ck_transacao_cartao_situacao CHECK (situacao IN ('pendente','autorizada','negada','cancelada','estornada','conciliada')),
  UNIQUE KEY uq_transacao_cartao_autorizacao (administradora_cartao_id, nsu, codigo_autorizacao, tipo_operacao),
  KEY ix_transacao_cartao_estabelecimento_data (estabelecimento_id, data_hora_transacao),
  KEY ix_transacao_cartao_bandeira_cartao (bandeira_cartao_id),
  KEY ix_transacao_cartao_terminal_cartao (terminal_cartao_id),
  KEY ix_transacao_cartao_caixa (caixa_id),
  KEY ix_transacao_cartao_sessao_caixa (sessao_caixa_id),
  KEY ix_transacao_cartao_operador (operador_usuario_id),
  KEY ix_transacao_cartao_estornada (estornada_transacao_cartao_id),
  KEY ix_transacao_cartao_titulo_receber (titulo_receber_id),
  KEY ix_transacao_cartao_atendimento (atendimento_id)
) COMMENT='Transação de cartão autorizada, com NSU, bandeira, parcelas, valor bruto e taxa';

