CREATE TABLE reavaliacao_bem (
  id                BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
  bem_patrimonial_id BIGINT UNSIGNED NOT NULL,
  sequencia         SMALLINT UNSIGNED NOT NULL,
  tipo              VARCHAR(30) NOT NULL COMMENT 'reavaliacao (novo valor justo) ou teste_recuperabilidade (impairment)',
  data_reavaliacao  DATE NOT NULL,
  valor_contabil_anterior DECIMAL(15,2) NOT NULL COMMENT 'Valor líquido contábil antes da reavaliação',
  valor_reavaliado  DECIMAL(15,2) NOT NULL COMMENT 'Novo valor do bem (justo ou recuperável)',
  valor_recuperavel DECIMAL(15,2) NULL COMMENT 'Valor recuperável apurado no teste de recuperabilidade',
  valor_residual    DECIMAL(15,2) NULL,
  valor_depreciavel DECIMAL(15,2) NULL,
  valor_mais_menos_valia DECIMAL(15,2) NOT NULL COMMENT 'Diferença positiva (mais-valia) ou negativa (perda) reconhecida',
  anterior_taxa_depreciacao DECIMAL(7,4) NULL COMMENT 'Taxa anual de depreciação antes, em percentual',
  nova_taxa_depreciacao DECIMAL(7,4) NULL COMMENT 'Taxa anual de depreciação aplicada daqui em diante, em percentual',
  anterior_vida_util_meses SMALLINT UNSIGNED NULL,
  nova_vida_util_meses SMALLINT UNSIGNED NULL,
  numero_laudo      VARCHAR(60) NULL,
  laudo_arquivo_id  BIGINT UNSIGNED NULL COMMENT 'Laudo de avaliação digitalizado',
  avaliador_nome    VARCHAR(150) NULL COMMENT 'Perito ou empresa avaliadora',
  lancamento_contabil_id BIGINT UNSIGNED NULL COMMENT 'Lançamento que reconheceu a diferença',
  situacao          VARCHAR(30) NOT NULL DEFAULT 'registrada',
  observacao        TEXT NULL,
  origem            VARCHAR(20) NOT NULL DEFAULT 'sistema' COMMENT 'sistema, migracao ou integracao',
  criado_em         DATETIME(3) NOT NULL,
  criado_por        BIGINT UNSIGNED NULL,
  alterado_em       DATETIME(3) NULL,
  alterado_por      BIGINT UNSIGNED NULL,
  versao            INT UNSIGNED NOT NULL DEFAULT 1,
  excluido_em       DATETIME(3) NULL,
  excluido_por      BIGINT UNSIGNED NULL,
  CONSTRAINT ck_reavaliacao_bem_origem CHECK (origem IN ('sistema','migracao','integracao')),
  CONSTRAINT ck_reavaliacao_bem_tipo CHECK (tipo IN ('reavaliacao','teste_recuperabilidade')),
  CONSTRAINT ck_reavaliacao_bem_situacao CHECK (situacao IN ('registrada','aprovada','contabilizada','cancelada')),
  CONSTRAINT ck_reavaliacao_bem_valores CHECK (valor_contabil_anterior >= 0 AND valor_reavaliado >= 0 AND (valor_recuperavel IS NULL OR valor_recuperavel >= 0) AND (valor_residual IS NULL OR valor_residual >= 0)),
  CONSTRAINT ck_reavaliacao_bem_taxas CHECK ((anterior_taxa_depreciacao IS NULL OR anterior_taxa_depreciacao BETWEEN 0 AND 100) AND (nova_taxa_depreciacao IS NULL OR nova_taxa_depreciacao BETWEEN 0 AND 100)),
  UNIQUE KEY uq_reavaliacao_bem_bem_sequencia (bem_patrimonial_id, sequencia),
  KEY ix_reavaliacao_bem_data (data_reavaliacao),
  KEY ix_reavaliacao_bem_laudo_arquivo (laudo_arquivo_id),
  KEY ix_reavaliacao_bem_lancamento (lancamento_contabil_id)
) COMMENT='Reavaliação ou teste de recuperabilidade do bem, com laudo e novo valor';

