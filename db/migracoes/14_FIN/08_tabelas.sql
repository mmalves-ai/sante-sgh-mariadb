  CONSTRAINT ck_recebimento_situacao CHECK (situacao IN ('efetivado','estornado')),
  CONSTRAINT ck_recebimento_valores CHECK (valor_recebido >= 0 AND valor_glosa >= 0 AND valor_desconto >= 0 AND valor_juros >= 0 AND valor_multa >= 0 AND valor_retencao >= 0 AND valor_troco >= 0),
  CONSTRAINT ck_recebimento_destino CHECK (conta_bancaria_id IS NOT NULL OR caixa_id IS NOT NULL),
  CONSTRAINT ck_recebimento_credito CHECK (data_credito IS NULL OR data_credito >= data_recebimento),
  CONSTRAINT ck_recebimento_estorno CHECK ((situacao = 'estornado') = (estornado_em IS NOT NULL)),
  UNIQUE KEY uq_recebimento_estabelecimento_numero (estabelecimento_id, numero),
  KEY ix_recebimento_parcela (parcela_receber_id),
  KEY ix_recebimento_data (estabelecimento_id, data_recebimento),
  KEY ix_recebimento_forma (forma_recebimento_id),
  KEY ix_recebimento_conta_bancaria (conta_bancaria_id),
  KEY ix_recebimento_caixa (caixa_id),
  KEY ix_recebimento_movimento_bancario (movimento_bancario_id),
  KEY ix_recebimento_movimento_caixa (movimento_caixa_id),
  KEY ix_recebimento_lancamento (lancamento_contabil_id),
  KEY ix_recebimento_estorno_usuario (estorno_usuario_id)
) COMMENT='Recebimento de parcela, total ou parcial, com data, conta de entrada, forma, glosa e retenções';

