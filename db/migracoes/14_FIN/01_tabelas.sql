  CONSTRAINT ck_adiantamento_paciente_valores CHECK (valor > 0 AND saldo >= 0 AND saldo <= valor),
  CONSTRAINT ck_adiantamento_paciente_parcelas CHECK (quantidade_parcelas BETWEEN 1 AND 99),
  CONSTRAINT ck_adiantamento_paciente_urgencia CHECK (tipo <> 'caucao' OR atendimento_urgencia = FALSE OR declaracao_voluntaria = TRUE),
  UNIQUE KEY uq_adiantamento_paciente_estabelecimento_numero (estabelecimento_id, numero),
  KEY ix_adiantamento_paciente_paciente (paciente_id, situacao),
  KEY ix_adiantamento_paciente_atendimento (atendimento_id),
  KEY ix_adiantamento_paciente_responsavel_paciente (responsavel_paciente_id),
  KEY ix_adiantamento_paciente_motivo (motivo_adiantamento_paciente_id),
  KEY ix_adiantamento_paciente_contrato (contrato_adiantamento_paciente_id),
  KEY ix_adiantamento_paciente_forma_recebimento (forma_recebimento_id),
  KEY ix_adiantamento_paciente_sessao_caixa (sessao_caixa_id),
  KEY ix_adiantamento_paciente_conta_bancaria (conta_bancaria_id),
  KEY ix_adiantamento_paciente_administradora_cartao (administradora_cartao_id),
  KEY ix_adiantamento_paciente_bandeira_cartao (bandeira_cartao_id),
  KEY ix_adiantamento_paciente_transacao_cartao (transacao_cartao_id),
  KEY ix_adiantamento_paciente_cheque_banco (cheque_banco_id),
  KEY ix_adiantamento_paciente_moeda (moeda_id)
) COMMENT='Adiantamento ou caução do paciente particular, com saldo, tipo e vedação na urgência (Lei 12.653)';

CREATE TABLE aditivo_contrato (
  id                BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
  contrato_fornecedor_id BIGINT UNSIGNED NOT NULL,
  numero            VARCHAR(30) NOT NULL COMMENT 'Número do aditivo dentro do contrato',
  tipo              VARCHAR(30) NOT NULL COMMENT 'prazo, valor, objeto, prazo_valor, supressao, outro',
  data_assinatura   DATE NULL,
  vigencia_inicio   DATE NOT NULL,
  vigencia_fim      DATE NULL COMMENT 'Nova data final do contrato, quando o aditivo é de prazo',
  valor_anterior    DECIMAL(15,2) NULL,
  valor_aditivo     DECIMAL(15,2) NULL COMMENT 'Acréscimo (positivo) ou supressão (negativo)',
  valor_novo        DECIMAL(15,2) NULL,
  percentual        DECIMAL(7,4) NULL,
  objeto            TEXT NULL COMMENT 'Alteração de objeto ou cláusula',
  justificativa     VARCHAR(2000) NOT NULL,
  contrato_vinculado_id BIGINT UNSIGNED NULL COMMENT 'Outro contrato relacionado pelo aditivo (substituição, desmembramento)',
  arquivo_id        BIGINT UNSIGNED NULL COMMENT 'Documento assinado',
  assinado          BOOLEAN NOT NULL DEFAULT FALSE,
  situacao          VARCHAR(30) NOT NULL DEFAULT 'rascunho',
  origem            VARCHAR(20) NOT NULL DEFAULT 'sistema',
  criado_em         DATETIME(3) NOT NULL,
  criado_por        BIGINT UNSIGNED NULL,
  alterado_em       DATETIME(3) NULL,
  alterado_por      BIGINT UNSIGNED NULL,
  versao            INT UNSIGNED NOT NULL DEFAULT 1,
  excluido_em       DATETIME(3) NULL,
  excluido_por      BIGINT UNSIGNED NULL,
  CONSTRAINT ck_aditivo_contrato_origem CHECK (origem IN ('sistema','migracao','integracao')),
  CONSTRAINT ck_aditivo_contrato_tipo CHECK (tipo IN ('prazo','valor','objeto','prazo_valor','supressao','outro')),
  CONSTRAINT ck_aditivo_contrato_situacao CHECK (situacao IN ('rascunho','em_aprovacao','assinado','vigente','cancelado')),
  CONSTRAINT ck_aditivo_contrato_vigencia CHECK (vigencia_fim IS NULL OR vigencia_fim >= vigencia_inicio),
  UNIQUE KEY uq_aditivo_contrato_contrato_numero (contrato_fornecedor_id, numero),
  KEY ix_aditivo_contrato_contrato_vinculado (contrato_vinculado_id),
  KEY ix_aditivo_contrato_arquivo (arquivo_id)
) COMMENT='Aditivo de prazo, valor ou objeto, com justificativa e assinatura';

