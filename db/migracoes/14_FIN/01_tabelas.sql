CREATE TABLE adiantamento (
  id                BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
  estabelecimento_id BIGINT UNSIGNED NOT NULL,
  numero            VARCHAR(30) NOT NULL COMMENT 'Número de negócio, gerado por sequencia_negocio',
  tipo_credor       VARCHAR(30) NOT NULL COMMENT 'fornecedor ou profissional (médico)',
  empresa_fornecedora_id BIGINT UNSIGNED NULL COMMENT 'Credor quando tipo_credor = fornecedor',
  profissional_id   BIGINT UNSIGNED NULL COMMENT 'Credor quando tipo_credor = profissional',
  data_emissao      DATE NOT NULL,
  data_vencimento   DATE NULL COMMENT 'Prazo para compensar ou prestar contas',
  data_prevista_pagamento DATE NULL,
  pagamento_autorizado_para DATE NULL COMMENT 'Data a partir da qual o pagamento está liberado',
  data_pagamento    DATE NULL,
  valor             DECIMAL(15,2) NOT NULL,
  valor_pago        DECIMAL(15,2) NOT NULL DEFAULT 0,
  saldo_compensar   DECIMAL(15,2) NOT NULL DEFAULT 0 COMMENT 'Valor ainda não compensado com títulos ou prestação de contas',
  referente         VARCHAR(250) NULL COMMENT 'Finalidade do adiantamento',
  conta_bancaria_id BIGINT UNSIGNED NULL COMMENT 'Conta de saída do dinheiro',
  forma_pagamento   VARCHAR(30) NULL,
  cheque_emitido_id BIGINT UNSIGNED NULL,
  natureza_financeira_id BIGINT UNSIGNED NULL,
  historico_padrao_id BIGINT UNSIGNED NULL,
  centro_custo_id   BIGINT UNSIGNED NULL,
  titulo_pagar_id   BIGINT UNSIGNED NULL COMMENT 'Título gerado para pagar o adiantamento',
  moeda_id          BIGINT UNSIGNED NULL,
  situacao          VARCHAR(30) NOT NULL DEFAULT 'aberto',
  aprovado_em       DATETIME(3) NULL,
  aprovador_usuario_id BIGINT UNSIGNED NULL,
  encerrado_em      DATETIME(3) NULL,
  observacao        VARCHAR(1000) NULL,
  origem            VARCHAR(20) NOT NULL DEFAULT 'sistema',
  criado_em         DATETIME(3) NOT NULL,
  criado_por        BIGINT UNSIGNED NULL,
  alterado_em       DATETIME(3) NULL,
  alterado_por      BIGINT UNSIGNED NULL,
  versao            INT UNSIGNED NOT NULL DEFAULT 1,
  excluido_em       DATETIME(3) NULL,
  excluido_por      BIGINT UNSIGNED NULL,
  CONSTRAINT ck_adiantamento_origem CHECK (origem IN ('sistema','migracao','integracao')),
  CONSTRAINT ck_adiantamento_tipo_credor CHECK (tipo_credor IN ('fornecedor','profissional')),
  CONSTRAINT ck_adiantamento_credor CHECK ((tipo_credor = 'fornecedor' AND empresa_fornecedora_id IS NOT NULL AND profissional_id IS NULL) OR (tipo_credor = 'profissional' AND profissional_id IS NOT NULL AND empresa_fornecedora_id IS NULL)),
  CONSTRAINT ck_adiantamento_forma_pagamento CHECK (forma_pagamento IS NULL OR forma_pagamento IN ('dinheiro','cheque','transferencia','pix','boleto','cartao','debito_em_conta')),
  CONSTRAINT ck_adiantamento_situacao CHECK (situacao IN ('aberto','aprovado','pago','compensado_parcial','compensado','cancelado')),
  CONSTRAINT ck_adiantamento_valores CHECK (valor > 0 AND valor_pago >= 0 AND saldo_compensar >= 0 AND saldo_compensar <= valor),
  CONSTRAINT ck_adiantamento_vencimento CHECK (data_vencimento IS NULL OR data_vencimento >= data_emissao),
  UNIQUE KEY uq_adiantamento_estabelecimento_numero (estabelecimento_id, numero),
  KEY ix_adiantamento_empresa_fornecedora (empresa_fornecedora_id),
  KEY ix_adiantamento_profissional (profissional_id),
  KEY ix_adiantamento_conta_bancaria (conta_bancaria_id),
  KEY ix_adiantamento_cheque_emitido (cheque_emitido_id),
  KEY ix_adiantamento_natureza_financeira (natureza_financeira_id),
  KEY ix_adiantamento_historico_padrao (historico_padrao_id),
  KEY ix_adiantamento_centro_custo (centro_custo_id),
  KEY ix_adiantamento_titulo_pagar (titulo_pagar_id),
  KEY ix_adiantamento_moeda (moeda_id),
  KEY ix_adiantamento_aprovador_usuario (aprovador_usuario_id),
  KEY ix_adiantamento_situacao (estabelecimento_id, situacao, data_vencimento)
) COMMENT='Adiantamento concedido a fornecedor ou médico, com valor, conta de saída, saldo a compensar e prazo';

