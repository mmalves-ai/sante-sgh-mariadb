CREATE TABLE nova_coleta (
  id                         BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
  estabelecimento_id         BIGINT UNSIGNED NOT NULL,
  numero                     VARCHAR(20) NOT NULL COMMENT 'Número de negócio, gerado por sequencia_negocio',
  paciente_id                BIGINT UNSIGNED NOT NULL,
  requisicao_exame_id        BIGINT UNSIGNED NOT NULL,
  amostra_biologica_id       BIGINT UNSIGNED NOT NULL COMMENT 'Amostra original que precisa ser coletada de novo',
  nova_amostra_biologica_id  BIGINT UNSIGNED NULL COMMENT 'Amostra gerada pela recoleta',
  motivo_nova_coleta_id      BIGINT UNSIGNED NOT NULL,
  solicitante_usuario_id     BIGINT UNSIGNED NOT NULL,
  solicitado_em              DATETIME(3) NOT NULL,
  situacao                   VARCHAR(30) NOT NULL DEFAULT 'pendente',
  coleta_prevista_em         DATETIME(3) NULL COMMENT 'Data marcada para o paciente comparecer',
  contato_realizado_em       DATETIME(3) NULL,
  contato_usuario_id         BIGINT UNSIGNED NULL,
  contato_observacao         TEXT NULL,
  coletada_em                DATETIME(3) NULL,
  cancelada_em               DATETIME(3) NULL,
  motivo_cancelamento        VARCHAR(500) NULL,
  observacao                 TEXT NULL,
  origem                     VARCHAR(20) NOT NULL DEFAULT 'sistema',
  criado_em                  DATETIME(3) NOT NULL,
  criado_por                 BIGINT UNSIGNED NULL,
  alterado_em                DATETIME(3) NULL,
  alterado_por               BIGINT UNSIGNED NULL,
  versao                     INT UNSIGNED NOT NULL DEFAULT 1,
  excluido_em                DATETIME(3) NULL,
  excluido_por               BIGINT UNSIGNED NULL,
  UNIQUE KEY uq_nova_coleta_estabelecimento_numero (estabelecimento_id, numero),
  CONSTRAINT ck_nova_coleta_situacao CHECK (situacao IN ('pendente','contato_realizado','agendada','coletada','cancelada')),
  CONSTRAINT ck_nova_coleta_amostras CHECK (nova_amostra_biologica_id IS NULL OR nova_amostra_biologica_id <> amostra_biologica_id),
  CONSTRAINT ck_nova_coleta_coletada CHECK (situacao <> 'coletada' OR (nova_amostra_biologica_id IS NOT NULL AND coletada_em IS NOT NULL)),
  CONSTRAINT ck_nova_coleta_cancelada CHECK (situacao <> 'cancelada' OR (cancelada_em IS NOT NULL AND motivo_cancelamento IS NOT NULL)),
  KEY ix_nova_coleta_situacao (estabelecimento_id, situacao, solicitado_em),
  CONSTRAINT ck_nova_coleta_origem CHECK (origem IN ('sistema','migracao','integracao')),
  KEY ix_nova_coleta_paciente (paciente_id),
  KEY ix_nova_coleta_requisicao_exame (requisicao_exame_id),
  KEY ix_nova_coleta_amostra_biologica (amostra_biologica_id),
  KEY ix_nova_coleta_nova_amostra_biologica (nova_amostra_biologica_id),
  KEY ix_nova_coleta_motivo_nova_coleta (motivo_nova_coleta_id),
  KEY ix_nova_coleta_solicitante_usuario (solicitante_usuario_id),
  KEY ix_nova_coleta_contato_usuario (contato_usuario_id)
) COMMENT='Pedido de recoleta de amostra, com motivo, exames afetados, quem pediu e a amostra nova gerada';

