CREATE TABLE motivo_retificacao_laudo (
  id                         BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
  codigo                     VARCHAR(30) NOT NULL,
  descricao                  VARCHAR(150) NOT NULL,
  exige_justificativa        BOOLEAN NOT NULL DEFAULT TRUE COMMENT 'Obriga texto livre explicando a retificação',
  comunica_solicitante       BOOLEAN NOT NULL DEFAULT TRUE COMMENT 'A retificação gera aviso ao médico solicitante',
  ativo                      BOOLEAN NOT NULL DEFAULT TRUE,
  criado_em                  DATETIME(3) NOT NULL,
  criado_por                 BIGINT UNSIGNED NULL,
  alterado_em                DATETIME(3) NULL,
  alterado_por               BIGINT UNSIGNED NULL,
  versao                     INT UNSIGNED NOT NULL DEFAULT 1,
  UNIQUE KEY uq_motivo_retificacao_laudo_codigo (codigo)
) COMMENT='Motivo para retificar resultado ou laudo já liberado';

CREATE TABLE motivo_retirada_amostra (
