CREATE TABLE intervalo_repeticao_exame (
  id                     BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
  estabelecimento_id     BIGINT UNSIGNED NOT NULL,
  exame_id               BIGINT UNSIGNED NOT NULL COMMENT 'Exame que está sendo pedido',
  exame_conflitante_id   BIGINT UNSIGNED NOT NULL COMMENT 'Exame já pedido que restringe o novo (pode ser o mesmo exame)',
  fonte_pagadora_id      BIGINT UNSIGNED NULL COMMENT 'Nulo vale para todas as fontes pagadoras',
  intervalo_minimo_horas INT UNSIGNED NOT NULL DEFAULT 0 COMMENT 'Zero com mesmo_dia = proibido no mesmo dia civil',
  mesmo_dia              BOOLEAN NOT NULL DEFAULT FALSE COMMENT 'Proíbe os dois exames no mesmo dia civil, independentemente das horas',
  acao                   VARCHAR(30) NOT NULL DEFAULT 'bloquear',
  mensagem               VARCHAR(500) NULL COMMENT 'Orientação mostrada ao solicitante',
  vigencia_inicio        DATE NOT NULL,
  vigencia_fim           DATE NULL,
  ativo                  BOOLEAN NOT NULL DEFAULT TRUE,
  criado_em              DATETIME(3) NOT NULL,
  criado_por             BIGINT UNSIGNED NULL,
  alterado_em            DATETIME(3) NULL,
  alterado_por           BIGINT UNSIGNED NULL,
  versao                 INT UNSIGNED NOT NULL DEFAULT 1,
  UNIQUE KEY uq_intervalo_repeticao_exame_par (estabelecimento_id, exame_id, exame_conflitante_id, fonte_pagadora_id, vigencia_inicio),
  CONSTRAINT ck_intervalo_repeticao_exame_acao CHECK (acao IN ('bloquear','alertar','exigir_justificativa')),
  CONSTRAINT ck_intervalo_repeticao_exame_regra CHECK (mesmo_dia OR intervalo_minimo_horas > 0),
  CONSTRAINT ck_intervalo_repeticao_exame_vigencia CHECK (vigencia_fim IS NULL OR vigencia_fim >= vigencia_inicio),
  KEY ix_intervalo_repeticao_exame_exame (exame_id),
  KEY ix_intervalo_repeticao_exame_exame_conflitante (exame_conflitante_id),
  KEY ix_intervalo_repeticao_exame_fonte_pagadora (fonte_pagadora_id)
) COMMENT='Intervalo mínimo entre dois pedidos do mesmo exame ou de exames incompatíveis no mesmo dia';

