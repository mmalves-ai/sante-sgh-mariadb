CREATE TABLE restricao_exame (
  id                          BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
  estabelecimento_id          BIGINT UNSIGNED NOT NULL,
  exame_id                    BIGINT UNSIGNED NOT NULL,
  setor_diagnostico_id        BIGINT UNSIGNED NULL COMMENT 'Setor executante a que a regra se limita',
  unidade_assistencial_id     BIGINT UNSIGNED NULL COMMENT 'Unidade solicitante a que a regra se limita',
  material_biologico_id       BIGINT UNSIGNED NULL,
  motivo_restricao_exame_id   BIGINT UNSIGNED NULL,
  tipo_restricao              VARCHAR(20) NOT NULL DEFAULT 'bloqueio',
  sexo                        VARCHAR(20) NULL COMMENT 'Sexo a que o exame se restringe',
  idade_minima_dias           INT UNSIGNED NULL,
  idade_maxima_dias           INT UNSIGNED NULL,
  tipo_atendimento            VARCHAR(30) NULL,
  dia_semana                  TINYINT UNSIGNED NULL COMMENT '1 = domingo a 7 = sábado',
  hora_inicio                 TIME NULL,
  hora_fim                    TIME NULL,
  intervalo_minimo_dias       SMALLINT UNSIGNED NULL COMMENT 'Dias mínimos entre duas solicitações do mesmo exame',
  apenas_resultado_liberado   BOOLEAN NOT NULL DEFAULT FALSE COMMENT 'Conta só exames anteriores com resultado liberado',
  permite_excecao             BOOLEAN NOT NULL DEFAULT FALSE,
  mensagem                    VARCHAR(200) NOT NULL COMMENT 'Texto mostrado ao solicitante',
  motivo                      VARCHAR(2000) NULL,
  vigencia_inicio             DATE NOT NULL,
  vigencia_fim                DATE NULL,
  ativo                       BOOLEAN NOT NULL DEFAULT TRUE,
  criado_em                   DATETIME(3) NOT NULL,
  criado_por                  BIGINT UNSIGNED NULL,
  alterado_em                 DATETIME(3) NULL,
  alterado_por                BIGINT UNSIGNED NULL,
  versao                      INT UNSIGNED NOT NULL DEFAULT 1,
  CONSTRAINT ck_restricao_exame_tipo CHECK (tipo_restricao IN ('bloqueio','alerta')),
  CONSTRAINT ck_restricao_exame_sexo CHECK (sexo IS NULL OR sexo IN ('feminino','masculino')),
  CONSTRAINT ck_restricao_exame_idade CHECK (idade_minima_dias IS NULL OR idade_maxima_dias IS NULL OR idade_maxima_dias >= idade_minima_dias),
  CONSTRAINT ck_restricao_exame_tipo_atendimento CHECK (tipo_atendimento IS NULL OR tipo_atendimento IN ('ambulatorial','internacao','urgencia','externo','domiciliar')),
  CONSTRAINT ck_restricao_exame_dia_semana CHECK (dia_semana IS NULL OR dia_semana BETWEEN 1 AND 7),
  CONSTRAINT ck_restricao_exame_horario CHECK ((hora_inicio IS NULL) = (hora_fim IS NULL)),
  CONSTRAINT ck_restricao_exame_vigencia CHECK (vigencia_fim IS NULL OR vigencia_fim >= vigencia_inicio),
  KEY ix_restricao_exame_estabelecimento_exame (estabelecimento_id, exame_id),
  KEY ix_restricao_exame_exame (exame_id),
  KEY ix_restricao_exame_setor (setor_diagnostico_id),
  KEY ix_restricao_exame_unidade (unidade_assistencial_id),
  KEY ix_restricao_exame_material (material_biologico_id),
  KEY ix_restricao_exame_motivo (motivo_restricao_exame_id)
) COMMENT='Regra clínica que bloqueia ou alerta a solicitação do exame por sexo, idade, material, horário ou setor';

CREATE TABLE resultado_analito (
  id                          BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
  resultado_exame_id          BIGINT UNSIGNED NOT NULL,
  sequencia                   SMALLINT UNSIGNED NOT NULL COMMENT 'Ordem do analito no laudo',
  analito_id                  BIGINT UNSIGNED NOT NULL,
  valor_numerico              DECIMAL(18,6) NULL,
