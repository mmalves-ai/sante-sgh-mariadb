CREATE TABLE requisicao_exame (
  id                          BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
  estabelecimento_id          BIGINT UNSIGNED NOT NULL,
  numero                      VARCHAR(30) NOT NULL COMMENT 'Número de negócio da requisição, gerado por sequencia_negocio',
  paciente_id                 BIGINT UNSIGNED NOT NULL,
  atendimento_id              BIGINT UNSIGNED NOT NULL,
  setor_diagnostico_id        BIGINT UNSIGNED NOT NULL COMMENT 'Setor executante',
  solicitante_profissional_id BIGINT UNSIGNED NOT NULL COMMENT 'Profissional solicitante (interno ou externo cadastrado); nunca por nome',
  unidade_assistencial_id     BIGINT UNSIGNED NULL COMMENT 'Unidade de onde partiu o pedido',
  prescricao_id               BIGINT UNSIGNED NULL COMMENT 'Prescrição que originou o pedido, quando veio do prontuário',
  fonte_pagadora_id           BIGINT UNSIGNED NOT NULL,
  plano_fonte_pagadora_id     BIGINT UNSIGNED NULL,
  guia_tiss_id                BIGINT UNSIGNED NULL,
  conta_hospitalar_id         BIGINT UNSIGNED NULL,
  orcamento_particular_id     BIGINT UNSIGNED NULL,
  ponto_coleta_id             BIGINT UNSIGNED NULL,
  marcacao_horario_id         BIGINT UNSIGNED NULL COMMENT 'Marcação na agenda, quando o exame foi agendado',
  tipo_solicitacao            VARCHAR(30) NOT NULL DEFAULT 'pedido_prontuario',
  prioridade                  VARCHAR(20) NOT NULL DEFAULT 'rotina',
  situacao                    VARCHAR(30) NOT NULL DEFAULT 'solicitada',
  solicitado_em               DATETIME(3) NOT NULL,
  coleta_prevista_em          DATETIME(3) NULL,
  entrega_prevista_em         DATETIME(3) NULL,
  senha_autorizacao           VARCHAR(50) NULL COMMENT 'Senha de autorização da operadora',
  autorizado_em               DATETIME(3) NULL,
  autorizacao_valida_ate      DATE NULL,
  peso_kg                     DECIMAL(6,2) NULL COMMENT 'Peso informado no pedido (cálculos e contraste)',
  altura_cm                   DECIMAL(5,1) NULL,
  indicacao_clinica           VARCHAR(2000) NULL,
  observacao                  TEXT NULL,
  identificador_integracao    VARCHAR(50) NULL COMMENT 'Código do pedido no sistema externo que o enviou',
  cancelado_em                DATETIME(3) NULL,
  cancelado_por_usuario_id    BIGINT UNSIGNED NULL,
  motivo_cancelamento         VARCHAR(500) NULL,
  origem                      VARCHAR(20) NOT NULL DEFAULT 'sistema' COMMENT 'sistema, migracao ou integracao',
  criado_em                   DATETIME(3) NOT NULL,
  criado_por                  BIGINT UNSIGNED NULL,
  alterado_em                 DATETIME(3) NULL,
  alterado_por                BIGINT UNSIGNED NULL,
  versao                      INT UNSIGNED NOT NULL DEFAULT 1,
  excluido_em                 DATETIME(3) NULL,
  excluido_por                BIGINT UNSIGNED NULL,
  CONSTRAINT ck_requisicao_exame_tipo_solicitacao CHECK (tipo_solicitacao IN ('pedido_prontuario','lancado_no_setor','externo','integracao')),
  CONSTRAINT ck_requisicao_exame_prioridade CHECK (prioridade IN ('rotina','urgente','emergencia')),
  CONSTRAINT ck_requisicao_exame_situacao CHECK (situacao IN ('solicitada','em_andamento','concluida','cancelada')),
  CONSTRAINT ck_requisicao_exame_cancelamento CHECK (situacao <> 'cancelada' OR cancelado_em IS NOT NULL),
  CONSTRAINT ck_requisicao_exame_peso CHECK (peso_kg IS NULL OR peso_kg > 0),
  CONSTRAINT ck_requisicao_exame_altura CHECK (altura_cm IS NULL OR altura_cm > 0),
  CONSTRAINT ck_requisicao_exame_origem CHECK (origem IN ('sistema','migracao','integracao')),
  UNIQUE KEY uq_requisicao_exame_estabelecimento_numero (estabelecimento_id, numero),
  KEY ix_requisicao_exame_estabelecimento_solicitado (estabelecimento_id, solicitado_em),
  KEY ix_requisicao_exame_paciente (paciente_id, solicitado_em),
  KEY ix_requisicao_exame_atendimento (atendimento_id),
  KEY ix_requisicao_exame_setor_situacao (setor_diagnostico_id, situacao),
  KEY ix_requisicao_exame_solicitante (solicitante_profissional_id),
  KEY ix_requisicao_exame_unidade_assistencial (unidade_assistencial_id),
  KEY ix_requisicao_exame_prescricao (prescricao_id),
  KEY ix_requisicao_exame_fonte_pagadora (fonte_pagadora_id),
  KEY ix_requisicao_exame_plano (plano_fonte_pagadora_id),
  KEY ix_requisicao_exame_guia_tiss (guia_tiss_id),
  KEY ix_requisicao_exame_conta (conta_hospitalar_id),
  KEY ix_requisicao_exame_orcamento (orcamento_particular_id),
  KEY ix_requisicao_exame_ponto_coleta (ponto_coleta_id),
  KEY ix_requisicao_exame_marcacao (marcacao_horario_id),
  KEY ix_requisicao_exame_cancelado_por (cancelado_por_usuario_id),
  KEY ix_requisicao_exame_integracao (identificador_integracao)
) COMMENT='Atendimento de diagnóstico que agrupa os exames pedidos para o paciente, com solicitante, origem, fonte pagadora e prioridade';

CREATE TABLE requisicao_transfusao (
  id                          BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
  estabelecimento_id          BIGINT UNSIGNED NOT NULL,
  numero                      VARCHAR(30) NOT NULL COMMENT 'Número de negócio da requisição transfusional',
  paciente_id                 BIGINT UNSIGNED NOT NULL,
  atendimento_id              BIGINT UNSIGNED NOT NULL,
  prescricao_item_hemocomponente_id BIGINT UNSIGNED NULL COMMENT 'Item de hemoterapia da prescrição que gerou a requisição',
  solicitante_profissional_id BIGINT UNSIGNED NOT NULL,
  unidade_assistencial_id     BIGINT UNSIGNED NULL,
  agendamento_cirurgico_id    BIGINT UNSIGNED NULL COMMENT 'Reserva para cirurgia, quando houver',
  servico_hemoterapia_fornecedor_id BIGINT UNSIGNED NULL COMMENT 'Serviço que atenderá a requisição',
  tipo_transfusao_id          BIGINT UNSIGNED NOT NULL COMMENT 'Caráter: programada, rotina, urgente, extrema urgência',
  programada_para             DATETIME(3) NULL COMMENT 'Dia e hora da transfusão programada',
  indicacao                   VARCHAR(2000) NOT NULL COMMENT 'Indicação clínica escrita pelo médico',
  exames_apoio                VARCHAR(500) NULL COMMENT 'Exames que embasam a indicação (hemoglobina, plaquetas, coagulograma)',
  termo_consentimento_paciente_id BIGINT UNSIGNED NULL,
  justificativa_urgencia      VARCHAR(500) NULL COMMENT 'Justificativa da extrema urgência sem termo nem provas pré-transfusionais',
  transfusao_anterior         VARCHAR(20) NOT NULL DEFAULT 'nao_sabe',
  reacao_anterior             VARCHAR(20) NOT NULL DEFAULT 'nao_sabe',
  gestacao_anterior           VARCHAR(20) NOT NULL DEFAULT 'nao_se_aplica',
  situacao                    VARCHAR(30) NOT NULL DEFAULT 'requisitada',
  solicitado_em               DATETIME(3) NOT NULL,
  cancelado_em                DATETIME(3) NULL,
  cancelado_por_usuario_id    BIGINT UNSIGNED NULL,
  motivo_cancelamento_requisicao_transfusao_id BIGINT UNSIGNED NULL,
  observacao_cancelamento     VARCHAR(500) NULL,
  observacao                  VARCHAR(1000) NULL,
  origem                      VARCHAR(20) NOT NULL DEFAULT 'sistema' COMMENT 'sistema, migracao ou integracao',
  criado_em                   DATETIME(3) NOT NULL,
  criado_por                  BIGINT UNSIGNED NULL,
  alterado_em                 DATETIME(3) NULL,
  alterado_por                BIGINT UNSIGNED NULL,
  versao                      INT UNSIGNED NOT NULL DEFAULT 1,
  excluido_em                 DATETIME(3) NULL,
  excluido_por                BIGINT UNSIGNED NULL,
  CONSTRAINT ck_requisicao_transfusao_indicacao CHECK (CHAR_LENGTH(indicacao) >= 10),
  CONSTRAINT ck_requisicao_transfusao_transfusao_anterior CHECK (transfusao_anterior IN ('sim','nao','nao_sabe')),
  CONSTRAINT ck_requisicao_transfusao_reacao_anterior CHECK (reacao_anterior IN ('sim','nao','nao_sabe')),
  CONSTRAINT ck_requisicao_transfusao_gestacao_anterior CHECK (gestacao_anterior IN ('sim','nao','nao_se_aplica')),
  CONSTRAINT ck_requisicao_transfusao_situacao CHECK (situacao IN ('requisitada','amostra_coletada','em_atendimento','atendida','cancelada')),
  CONSTRAINT ck_requisicao_transfusao_cancelamento CHECK (situacao <> 'cancelada' OR (cancelado_em IS NOT NULL AND motivo_cancelamento_requisicao_transfusao_id IS NOT NULL)),
  CONSTRAINT ck_requisicao_transfusao_consentimento CHECK (termo_consentimento_paciente_id IS NOT NULL OR CHAR_LENGTH(justificativa_urgencia) >= 10),
  CONSTRAINT ck_requisicao_transfusao_origem CHECK (origem IN ('sistema','migracao','integracao')),
  UNIQUE KEY uq_requisicao_transfusao_estabelecimento_numero (estabelecimento_id, numero),
  KEY ix_requisicao_transfusao_estabelecimento_situacao (estabelecimento_id, situacao, solicitado_em),
  KEY ix_requisicao_transfusao_paciente (paciente_id, solicitado_em),
  KEY ix_requisicao_transfusao_atendimento (atendimento_id),
  KEY ix_requisicao_transfusao_prescricao_item (prescricao_item_hemocomponente_id),
  KEY ix_requisicao_transfusao_solicitante (solicitante_profissional_id),
  KEY ix_requisicao_transfusao_unidade (unidade_assistencial_id),
  KEY ix_requisicao_transfusao_agendamento (agendamento_cirurgico_id),
  KEY ix_requisicao_transfusao_fornecedor (servico_hemoterapia_fornecedor_id),
  KEY ix_requisicao_transfusao_tipo (tipo_transfusao_id),
  KEY ix_requisicao_transfusao_termo (termo_consentimento_paciente_id),
  KEY ix_requisicao_transfusao_cancelado_por (cancelado_por_usuario_id),
  KEY ix_requisicao_transfusao_motivo_cancelamento (motivo_cancelamento_requisicao_transfusao_id)
) COMMENT='Requisição de transfusão com indicação, urgência, dados clínicos e médico solicitante';

CREATE TABLE requisicao_transfusao_item (
  id                          BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
  requisicao_transfusao_id    BIGINT UNSIGNED NOT NULL,
  sequencia                   SMALLINT UNSIGNED NOT NULL,
  hemocomponente_id           BIGINT UNSIGNED NOT NULL,
  prescricao_item_hemocomponente_id BIGINT UNSIGNED NULL,
  quantidade_bolsas           SMALLINT UNSIGNED NOT NULL DEFAULT 1,
  volume_ml                   INT UNSIGNED NULL,
  quantidade_atendida         SMALLINT UNSIGNED NOT NULL DEFAULT 0 COMMENT 'Bolsas já liberadas para o item',
  irradiado                   BOOLEAN NOT NULL DEFAULT FALSE,
  filtrado                    BOOLEAN NOT NULL DEFAULT FALSE COMMENT 'Desleucocitado',
  lavado                      BOOLEAN NOT NULL DEFAULT FALSE,
  aliquotado                  BOOLEAN NOT NULL DEFAULT FALSE,
  fenotipado                  BOOLEAN NOT NULL DEFAULT FALSE,
  situacao                    VARCHAR(30) NOT NULL DEFAULT 'pendente',
  cancelado_em                DATETIME(3) NULL,
  cancelado_por_usuario_id    BIGINT UNSIGNED NULL,
  motivo_cancelamento_requisicao_transfusao_id BIGINT UNSIGNED NULL,
  origem                      VARCHAR(20) NOT NULL DEFAULT 'sistema' COMMENT 'sistema, migracao ou integracao',
  criado_em                   DATETIME(3) NOT NULL,
  criado_por                  BIGINT UNSIGNED NULL,
  alterado_em                 DATETIME(3) NULL,
  alterado_por                BIGINT UNSIGNED NULL,
  versao                      INT UNSIGNED NOT NULL DEFAULT 1,
  excluido_em                 DATETIME(3) NULL,
  excluido_por                BIGINT UNSIGNED NULL,
  CONSTRAINT ck_requisicao_transfusao_item_quantidade CHECK (quantidade_bolsas BETWEEN 1 AND 50),
  CONSTRAINT ck_requisicao_transfusao_item_volume CHECK (volume_ml IS NULL OR volume_ml BETWEEN 1 AND 5000),
  CONSTRAINT ck_requisicao_transfusao_item_atendida CHECK (quantidade_atendida <= quantidade_bolsas),
  CONSTRAINT ck_requisicao_transfusao_item_situacao CHECK (situacao IN ('pendente','parcial','atendido','cancelado')),
  CONSTRAINT ck_requisicao_transfusao_item_cancelamento CHECK (situacao <> 'cancelado' OR cancelado_em IS NOT NULL),
  CONSTRAINT ck_requisicao_transfusao_item_origem CHECK (origem IN ('sistema','migracao','integracao')),
  UNIQUE KEY uq_requisicao_transfusao_item_sequencia (requisicao_transfusao_id, sequencia),
  KEY ix_requisicao_transfusao_item_hemocomponente (hemocomponente_id),
  KEY ix_requisicao_transfusao_item_prescricao_item (prescricao_item_hemocomponente_id),
  KEY ix_requisicao_transfusao_item_cancelado_por (cancelado_por_usuario_id),
  KEY ix_requisicao_transfusao_item_motivo (motivo_cancelamento_requisicao_transfusao_id)
) COMMENT='Hemocomponente e quantidade pedidos na requisição, com procedimento especial (irradiado, filtrado)';

