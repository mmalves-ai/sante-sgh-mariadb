CREATE TABLE ensaio_analise (
  id                BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
  estabelecimento_id BIGINT UNSIGNED NOT NULL,
  codigo            VARCHAR(30) NOT NULL,
  descricao         VARCHAR(150) NOT NULL,
  numero_versao     SMALLINT UNSIGNED NOT NULL DEFAULT 1 COMMENT 'Versão técnica do ensaio (método revisado)',
  metodo_analitico_id BIGINT UNSIGNED NULL,
  referencia_bibliografica_analise_id BIGINT UNSIGNED NULL,
  unidade_resultado_id BIGINT UNSIGNED NULL,
  situacao          VARCHAR(30) NOT NULL DEFAULT 'em_elaboracao',
  origem            VARCHAR(20) NOT NULL DEFAULT 'sistema',
  criado_em         DATETIME(3) NOT NULL,
  criado_por        BIGINT UNSIGNED NULL,
  alterado_em       DATETIME(3) NULL,
  alterado_por      BIGINT UNSIGNED NULL,
  versao            INT UNSIGNED NOT NULL DEFAULT 1,
  excluido_em       DATETIME(3) NULL,
  excluido_por      BIGINT UNSIGNED NULL,
  CONSTRAINT ck_ensaio_analise_origem CHECK (origem IN ('sistema','migracao','integracao')),
  CONSTRAINT ck_ensaio_analise_situacao CHECK (situacao IN ('em_elaboracao','vigente','suspenso','obsoleto')),
  UNIQUE KEY uq_ensaio_analise_estabelecimento_codigo_versao (estabelecimento_id, codigo, numero_versao),
  KEY ix_ensaio_analise_metodo (metodo_analitico_id),
  KEY ix_ensaio_analise_bibliografia (referencia_bibliografica_analise_id),
  KEY ix_ensaio_analise_unidade (unidade_resultado_id)
) COMMENT='Ensaio do laboratório de análises de produtos e ambiente, com versão e situação';

