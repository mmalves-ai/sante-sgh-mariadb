CREATE TABLE achado_mama (
  id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
  laudo_mama_id BIGINT UNSIGNED NOT NULL,
  sequencia SMALLINT UNSIGNED NOT NULL,
  lateralidade VARCHAR(30) NOT NULL COMMENT 'Mama do achado',
  quadrante VARCHAR(30) NULL,
  tipo_achado VARCHAR(30) NOT NULL,
  categoria_achado_mama_id BIGINT UNSIGNED NULL,
  tamanho_mm DECIMAL(7,2) NULL COMMENT 'Maior eixo do achado, em milímetros',
  posicao_horaria TINYINT UNSIGNED NULL COMMENT 'Posição em horas de relógio (1 a 12)',
  distancia_mamilo_mm DECIMAL(7,2) NULL,
  forma VARCHAR(30) NULL,
  contorno VARCHAR(30) NULL,
  densidade VARCHAR(30) NULL,
  morfologia_calcificacao VARCHAR(60) NULL,
  distribuicao_calcificacao VARCHAR(30) NULL,
  correlacao_ultrassom BOOLEAN NOT NULL DEFAULT FALSE COMMENT 'Achado com correspondente na ultrassonografia',
  descricao TEXT NULL,
  origem VARCHAR(20) NOT NULL DEFAULT 'sistema',
  criado_em DATETIME(3) NOT NULL,
  criado_por BIGINT UNSIGNED NULL,
  alterado_em DATETIME(3) NULL,
  alterado_por BIGINT UNSIGNED NULL,
  versao INT UNSIGNED NOT NULL DEFAULT 1,
  excluido_em DATETIME(3) NULL,
  excluido_por BIGINT UNSIGNED NULL,
  CONSTRAINT ck_achado_mama_origem CHECK (origem IN ('sistema','migracao','integracao')),
  CONSTRAINT ck_achado_mama_lateralidade CHECK (lateralidade IN ('direita','esquerda')),
  CONSTRAINT ck_achado_mama_quadrante CHECK (quadrante IS NULL OR quadrante IN ('superior_lateral','superior_medial','inferior_lateral','inferior_medial','central','retroareolar','prolongamento_axilar','axila')),
  CONSTRAINT ck_achado_mama_tipo_achado CHECK (tipo_achado IN ('nodulo','calcificacao','assimetria','assimetria_focal','assimetria_global','distorcao_arquitetural','linfonodo','implante','dilatacao_ductal','achado_benigno','outro')),
  CONSTRAINT ck_achado_mama_forma CHECK (forma IS NULL OR forma IN ('oval','redonda','irregular')),
  CONSTRAINT ck_achado_mama_contorno CHECK (contorno IS NULL OR contorno IN ('circunscrito','microlobulado','obscurecido','indistinto','espiculado')),
  CONSTRAINT ck_achado_mama_densidade CHECK (densidade IS NULL OR densidade IN ('alta','igual','baixa','contendo_gordura')),
  CONSTRAINT ck_achado_mama_distribuicao_calcificacao CHECK (distribuicao_calcificacao IS NULL OR distribuicao_calcificacao IN ('difusa','regional','agrupada','linear','segmentar')),
  CONSTRAINT ck_achado_mama_posicao_horaria CHECK (posicao_horaria IS NULL OR posicao_horaria BETWEEN 1 AND 12),
  CONSTRAINT ck_achado_mama_tamanho_mm CHECK (tamanho_mm IS NULL OR tamanho_mm > 0),
  UNIQUE KEY uq_achado_mama_laudo_sequencia (laudo_mama_id, sequencia),
  KEY ix_achado_mama_categoria_achado_mama_id (categoria_achado_mama_id)
) COMMENT='Achado radiológico da mamografia por mama e quadrante, com tipo e categoria';

