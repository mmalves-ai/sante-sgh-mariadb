CREATE TABLE agendamento_relatorio (
  id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
  estabelecimento_id BIGINT UNSIGNED NOT NULL,
  relatorio_id BIGINT UNSIGNED NOT NULL,
  nome VARCHAR(150) NOT NULL,
  periodicidade VARCHAR(30) NOT NULL,
  hora_envio TIME NOT NULL COMMENT 'Hora local do estabelecimento',
  dia_semana TINYINT UNSIGNED NULL COMMENT '1 = domingo a 7 = sábado; obrigatório na periodicidade semanal',
  dia_mes TINYINT UNSIGNED NULL COMMENT 'Obrigatório na periodicidade mensal; 31 vale como último dia',
  condicao_envio VARCHAR(500) NULL COMMENT 'Condição para enviar (ex.: só se houver linhas)',
  enviar_sem_linhas BOOLEAN NOT NULL DEFAULT FALSE,
  parametros JSON NULL COMMENT 'Valores dos parâmetros do relatório, com datas relativas',
  formato VARCHAR(30) NOT NULL DEFAULT 'pdf',
  entrega VARCHAR(30) NOT NULL DEFAULT 'link' COMMENT 'anexo ou link com validade',
  validade_link_horas SMALLINT UNSIGNED NULL,
  dono_usuario_id BIGINT UNSIGNED NOT NULL COMMENT 'Responsável que recebe o alerta de falha',
  avisar_falha BOOLEAN NOT NULL DEFAULT TRUE,
  proximo_envio_em DATETIME(3) NULL,
  ultimo_envio_em DATETIME(3) NULL,
  ativo BOOLEAN NOT NULL DEFAULT TRUE,
  criado_em DATETIME(3) NOT NULL,
  criado_por BIGINT UNSIGNED NULL,
  alterado_em DATETIME(3) NULL,
  alterado_por BIGINT UNSIGNED NULL,
  versao INT UNSIGNED NOT NULL DEFAULT 1,
  CONSTRAINT ck_agendamento_relatorio_periodicidade CHECK (periodicidade IN ('diaria','semanal','mensal')),
  CONSTRAINT ck_agendamento_relatorio_formato CHECK (formato IN ('pdf','xlsx','csv','html')),
  CONSTRAINT ck_agendamento_relatorio_entrega CHECK (entrega IN ('anexo','link')),
  CONSTRAINT ck_agendamento_relatorio_dia_semana CHECK (dia_semana IS NULL OR dia_semana BETWEEN 1 AND 7),
  CONSTRAINT ck_agendamento_relatorio_dia_mes CHECK (dia_mes IS NULL OR dia_mes BETWEEN 1 AND 31),
  CONSTRAINT ck_agendamento_relatorio_semanal CHECK (periodicidade <> 'semanal' OR dia_semana IS NOT NULL),
  CONSTRAINT ck_agendamento_relatorio_mensal CHECK (periodicidade <> 'mensal' OR dia_mes IS NOT NULL),
  CONSTRAINT ck_agendamento_relatorio_link CHECK (entrega <> 'link' OR validade_link_horas IS NOT NULL),
  CONSTRAINT ck_agendamento_relatorio_parametros CHECK (parametros IS NULL OR JSON_VALID(parametros)),
  UNIQUE KEY uq_agendamento_relatorio_estabelecimento_id_nome (estabelecimento_id, nome),
  KEY ix_agendamento_relatorio_ativo_proximo_envio_em (ativo, proximo_envio_em),
  KEY ix_agendamento_relatorio_relatorio_id (relatorio_id),
  KEY ix_agendamento_relatorio_dono_usuario_id (dono_usuario_id)
) COMMENT='Envio agendado de relatório: periodicidade, parâmetros, formato e alerta de falha ao dono';

