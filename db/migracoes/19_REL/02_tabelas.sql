  UNIQUE KEY uq_painel_gerencial_permissao_usuario (painel_gerencial_id, usuario_id),
  KEY ix_painel_gerencial_permissao_perfil_acesso (perfil_acesso_id),
  KEY ix_painel_gerencial_permissao_usuario (usuario_id)
) COMMENT='Perfis ou usuários que podem abrir cada painel gerencial';

CREATE TABLE tipo_painel_tv (
  id                BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
  codigo            VARCHAR(30) NOT NULL,
  descricao         VARCHAR(150) NOT NULL,
  categoria         VARCHAR(30) NOT NULL,
  componente        VARCHAR(100) NOT NULL COMMENT 'Identificador do componente de tela que desenha o painel',
  atualizacao_padrao_segundos SMALLINT UNSIGNED NOT NULL DEFAULT 60 COMMENT 'Intervalo padrão de atualização dos dados',
  ativo             BOOLEAN NOT NULL DEFAULT TRUE,
  criado_em         DATETIME(3) NOT NULL,
  criado_por        BIGINT UNSIGNED NULL,
  alterado_em       DATETIME(3) NULL,
  alterado_por      BIGINT UNSIGNED NULL,
  versao            INT UNSIGNED NOT NULL DEFAULT 1,
  UNIQUE KEY uq_tipo_painel_tv_codigo (codigo),
  CONSTRAINT ck_tipo_painel_tv_categoria CHECK (categoria IN ('ocupacao_leitos','farmacia','mapa_cirurgico','laboratorio','chamada','fluxo_atendimento','indicadores','outro')),
