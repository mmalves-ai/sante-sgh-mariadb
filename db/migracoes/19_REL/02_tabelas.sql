CREATE TABLE ponderacao_procedimento (
  id                BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
  estabelecimento_id BIGINT UNSIGNED NOT NULL,
  tipo_item         VARCHAR(30) NOT NULL,
  item_faturavel_id BIGINT UNSIGNED NULL COMMENT 'Procedimento ponderado, quando tipo_item = procedimento',
  exame_id          BIGINT UNSIGNED NULL COMMENT 'Exame ponderado, quando tipo_item = exame',
  item_prescritivel_id BIGINT UNSIGNED NULL COMMENT 'Item de prescrição ponderado, quando tipo_item = item_prescrito',
  procedimento_sigtap_id BIGINT UNSIGNED NULL COMMENT 'Procedimento SUS ponderado, quando tipo_item = procedimento_sus',
  item_referencia_chave BIGINT UNSIGNED AS (COALESCE(item_faturavel_id, exame_id, item_prescritivel_id, procedimento_sigtap_id)) STORED COMMENT 'Chave do item ponderado, qualquer que seja o tipo (coluna gerada, só para a unicidade; sem FK por ser polimórfica)',
  tempo_padrao_minutos DECIMAL(9,2) NULL COMMENT 'Tempo padrão de execução',
  fator_peso        DECIMAL(9,4) NOT NULL DEFAULT 1 COMMENT 'Peso relativo na produção ponderada',
  fator_minuto      DECIMAL(12,4) NULL COMMENT 'Peso por minuto de execução',
  vigencia_inicio   DATE NOT NULL,
  vigencia_fim      DATE NULL,
  ativo             BOOLEAN NOT NULL DEFAULT TRUE,
  criado_em         DATETIME(3) NOT NULL,
  criado_por        BIGINT UNSIGNED NULL,
  alterado_em       DATETIME(3) NULL,
  alterado_por      BIGINT UNSIGNED NULL,
  versao            INT UNSIGNED NOT NULL DEFAULT 1,
  CONSTRAINT ck_ponderacao_procedimento_tipo CHECK (tipo_item IN ('procedimento','exame','item_prescrito','procedimento_sus')),
  CONSTRAINT ck_ponderacao_procedimento_alvo CHECK (
    (tipo_item = 'procedimento'     AND item_faturavel_id IS NOT NULL AND exame_id IS NULL AND item_prescritivel_id IS NULL AND procedimento_sigtap_id IS NULL) OR
    (tipo_item = 'exame'            AND exame_id IS NOT NULL AND item_faturavel_id IS NULL AND item_prescritivel_id IS NULL AND procedimento_sigtap_id IS NULL) OR
    (tipo_item = 'item_prescrito'   AND item_prescritivel_id IS NOT NULL AND item_faturavel_id IS NULL AND exame_id IS NULL AND procedimento_sigtap_id IS NULL) OR
    (tipo_item = 'procedimento_sus' AND procedimento_sigtap_id IS NOT NULL AND item_faturavel_id IS NULL AND exame_id IS NULL AND item_prescritivel_id IS NULL)),
  CONSTRAINT ck_ponderacao_procedimento_valores CHECK (fator_peso > 0 AND (tempo_padrao_minutos IS NULL OR tempo_padrao_minutos > 0) AND (fator_minuto IS NULL OR fator_minuto >= 0)),
  CONSTRAINT ck_ponderacao_procedimento_vigencia CHECK (vigencia_fim IS NULL OR vigencia_fim >= vigencia_inicio),
  UNIQUE KEY uq_ponderacao_procedimento_item_vigencia (estabelecimento_id, tipo_item, item_referencia_chave, vigencia_inicio),
  KEY ix_ponderacao_procedimento_item_faturavel (item_faturavel_id),
  KEY ix_ponderacao_procedimento_exame (exame_id),
  KEY ix_ponderacao_procedimento_item_prescritivel (item_prescritivel_id),
  KEY ix_ponderacao_procedimento_procedimento_sigtap (procedimento_sigtap_id)
) COMMENT='Peso e tempo padrão por procedimento, exame ou item prescrito, para medir produção ponderada e carga de trabalho';

CREATE TABLE proposta_iniciativa (
  id                BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
  estabelecimento_id BIGINT UNSIGNED NOT NULL,
  numero            VARCHAR(30) NOT NULL COMMENT 'Número de negócio da proposta (sequencia_negocio)',
  titulo            VARCHAR(150) NOT NULL,
  mapa_estrategico_id BIGINT UNSIGNED NULL COMMENT 'Mapa estratégico a que a proposta se liga',
  centro_custo_id   BIGINT UNSIGNED NULL COMMENT 'Centro de custo solicitante',
  solicitante_usuario_id BIGINT UNSIGNED NOT NULL,
  responsavel_usuario_id BIGINT UNSIGNED NULL,
  aprovador_usuario_id BIGINT UNSIGNED NULL,
  prioridade        VARCHAR(30) NOT NULL DEFAULT 'media',
  importancia       VARCHAR(30) NOT NULL DEFAULT 'media',
  objetivo          TEXT NOT NULL,
  produto           TEXT NULL COMMENT 'Produto ou entrega esperada',
  marcos            TEXT NULL,
  justificativa     TEXT NULL,
  requisitos        TEXT NULL,
  exclusoes         TEXT NULL COMMENT 'O que fica fora do escopo',
  riscos            TEXT NULL,
  horas_estimadas   DECIMAL(9,2) NULL,
  custo_estimado    DECIMAL(15,2) NULL,
  cobranca_interna  BOOLEAN NOT NULL DEFAULT FALSE COMMENT 'Custo cobrado da área solicitante',
  data_inicio_prevista DATE NULL,
  data_fim_prevista DATE NULL,
  situacao          VARCHAR(30) NOT NULL DEFAULT 'rascunho',
  parecer           TEXT NULL COMMENT 'Parecer da aprovação ou da reprovação',
  decidido_em       DATETIME(3) NULL,
  iniciativa_estrategica_id BIGINT UNSIGNED NULL COMMENT 'Iniciativa criada a partir da proposta aprovada',
  origem            VARCHAR(20) NOT NULL DEFAULT 'sistema',
  criado_em         DATETIME(3) NOT NULL,
  criado_por        BIGINT UNSIGNED NULL,
  alterado_em       DATETIME(3) NULL,
  alterado_por      BIGINT UNSIGNED NULL,
  versao            INT UNSIGNED NOT NULL DEFAULT 1,
  excluido_em       DATETIME(3) NULL,
  excluido_por      BIGINT UNSIGNED NULL,
  CONSTRAINT ck_proposta_iniciativa_prioridade CHECK (prioridade IN ('baixa','media','alta','critica')),
  CONSTRAINT ck_proposta_iniciativa_importancia CHECK (importancia IN ('baixa','media','alta','critica')),
  CONSTRAINT ck_proposta_iniciativa_situacao CHECK (situacao IN ('rascunho','em_analise','aprovada','reprovada','cancelada','convertida')),
  CONSTRAINT ck_proposta_iniciativa_origem CHECK (origem IN ('sistema','migracao','integracao')),
  CONSTRAINT ck_proposta_iniciativa_datas CHECK (data_fim_prevista IS NULL OR data_inicio_prevista IS NULL OR data_fim_prevista >= data_inicio_prevista),
  CONSTRAINT ck_proposta_iniciativa_valores CHECK ((horas_estimadas IS NULL OR horas_estimadas >= 0) AND (custo_estimado IS NULL OR custo_estimado >= 0)),
  CONSTRAINT ck_proposta_iniciativa_decisao CHECK (situacao NOT IN ('aprovada','reprovada','convertida') OR (decidido_em IS NOT NULL AND aprovador_usuario_id IS NOT NULL)),
  CONSTRAINT ck_proposta_iniciativa_conversao CHECK (situacao <> 'convertida' OR iniciativa_estrategica_id IS NOT NULL),
  UNIQUE KEY uq_proposta_iniciativa_estabelecimento_numero (estabelecimento_id, numero),
  KEY ix_proposta_iniciativa_mapa_estrategico (mapa_estrategico_id),
  KEY ix_proposta_iniciativa_centro_custo (centro_custo_id),
  KEY ix_proposta_iniciativa_solicitante (solicitante_usuario_id),
  KEY ix_proposta_iniciativa_responsavel (responsavel_usuario_id),
  KEY ix_proposta_iniciativa_aprovador (aprovador_usuario_id),
  KEY ix_proposta_iniciativa_iniciativa_estrategica (iniciativa_estrategica_id),
  KEY ix_proposta_iniciativa_situacao (estabelecimento_id, situacao)
) COMMENT='Proposta de projeto antes da aprovação: objetivo, produto, marcos, prioridade, custo estimado e parecer';

CREATE TABLE proposta_iniciativa_recurso (
  id                BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
  proposta_iniciativa_id BIGINT UNSIGNED NOT NULL,
  sequencia         SMALLINT UNSIGNED NOT NULL,
  tipo_recurso      VARCHAR(30) NOT NULL,
  descricao         VARCHAR(200) NOT NULL,
  cargo_id          BIGINT UNSIGNED NULL COMMENT 'Cargo do pessoal estimado, quando tipo_recurso = pessoal',
  senioridade       VARCHAR(30) NULL,
  aquisicao         BOOLEAN NOT NULL DEFAULT FALSE COMMENT 'Material a adquirir (falso: já existente)',
  quantidade        DECIMAL(15,4) NOT NULL DEFAULT 1,
  horas_estimadas   DECIMAL(9,2) NULL COMMENT 'Horas por pessoa, quando tipo_recurso = pessoal',
  custo_unitario    DECIMAL(15,2) NULL COMMENT 'Custo por unidade de material ou por hora de pessoal',
  custo_total       DECIMAL(15,2) NULL,
  origem            VARCHAR(20) NOT NULL DEFAULT 'sistema',
  criado_em         DATETIME(3) NOT NULL,
  criado_por        BIGINT UNSIGNED NULL,
  alterado_em       DATETIME(3) NULL,
  alterado_por      BIGINT UNSIGNED NULL,
  versao            INT UNSIGNED NOT NULL DEFAULT 1,
  excluido_em       DATETIME(3) NULL,
  excluido_por      BIGINT UNSIGNED NULL,
  CONSTRAINT ck_proposta_iniciativa_recurso_tipo CHECK (tipo_recurso IN ('material','pessoal','servico')),
  CONSTRAINT ck_proposta_iniciativa_recurso_senioridade CHECK (senioridade IS NULL OR senioridade IN ('junior','pleno','senior','especialista')),
  CONSTRAINT ck_proposta_iniciativa_recurso_pessoal CHECK (tipo_recurso <> 'pessoal' OR horas_estimadas IS NOT NULL),
  CONSTRAINT ck_proposta_iniciativa_recurso_valores CHECK (quantidade > 0 AND (horas_estimadas IS NULL OR horas_estimadas > 0) AND (custo_unitario IS NULL OR custo_unitario >= 0) AND (custo_total IS NULL OR custo_total >= 0)),
  CONSTRAINT ck_proposta_iniciativa_recurso_origem CHECK (origem IN ('sistema','migracao','integracao')),
  UNIQUE KEY uq_proposta_iniciativa_recurso_sequencia (proposta_iniciativa_id, sequencia),
  KEY ix_proposta_iniciativa_recurso_cargo (cargo_id)
) COMMENT='Recurso estimado da proposta: material a adquirir ou horas de pessoal por senioridade, com quantidade e custo';

