) COMMENT='Tipos de painel de TV (ocupação de UTI, farmácia, mapa cirúrgico, laboratório, chamada)';

CREATE TABLE painel_tv (
  id                BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
  estabelecimento_id BIGINT UNSIGNED NOT NULL,
  tipo_painel_tv_id BIGINT UNSIGNED NOT NULL,
  codigo            VARCHAR(30) NOT NULL,
  nome              VARCHAR(150) NOT NULL,
  unidade_assistencial_id BIGINT UNSIGNED NULL COMMENT 'Unidade cujos dados o painel mostra (nulo para o estabelecimento inteiro)',
  setor_funcional_id BIGINT UNSIGNED NULL COMMENT 'Setor cujos dados o painel mostra',
  ordem             SMALLINT UNSIGNED NOT NULL DEFAULT 0,
  tema_cor          VARCHAR(30) NULL COMMENT 'Tema ou cor de fundo do painel',
  tempo_rotacao_segundos SMALLINT UNSIGNED NOT NULL DEFAULT 30 COMMENT 'Tempo de cada bloco em tela quando o painel alterna blocos',
  atualizacao_segundos SMALLINT UNSIGNED NOT NULL DEFAULT 60 COMMENT 'Intervalo de atualização dos dados',
  periodo_listagem_horas SMALLINT UNSIGNED NULL COMMENT 'Janela de tempo dos registros listados',
  alterna_blocos    BOOLEAN NOT NULL DEFAULT TRUE,
  configuracao      JSON NULL COMMENT 'Opções de exibição específicas do tipo (colunas visíveis, ordenação, limites de permanência)',
  situacao          VARCHAR(30) NOT NULL DEFAULT 'ativo',
  origem            VARCHAR(20) NOT NULL DEFAULT 'sistema',
  criado_em         DATETIME(3) NOT NULL,
  criado_por        BIGINT UNSIGNED NULL,
  alterado_em       DATETIME(3) NULL,
  alterado_por      BIGINT UNSIGNED NULL,
  versao            INT UNSIGNED NOT NULL DEFAULT 1,
  excluido_em       DATETIME(3) NULL,
  excluido_por      BIGINT UNSIGNED NULL,
  CONSTRAINT ck_painel_tv_situacao CHECK (situacao IN ('rascunho','ativo','suspenso','inativo')),
  CONSTRAINT ck_painel_tv_origem CHECK (origem IN ('sistema','migracao','integracao')),
  CONSTRAINT ck_painel_tv_tempos CHECK (tempo_rotacao_segundos >= 5 AND atualizacao_segundos >= 5),
  CONSTRAINT ck_painel_tv_configuracao CHECK (configuracao IS NULL OR JSON_VALID(configuracao)),
  UNIQUE KEY uq_painel_tv_estabelecimento_codigo (estabelecimento_id, codigo),
  KEY ix_painel_tv_tipo_painel_tv (tipo_painel_tv_id),
  KEY ix_painel_tv_unidade_assistencial (unidade_assistencial_id),
  KEY ix_painel_tv_setor_funcional (setor_funcional_id)
) COMMENT='Painel de TV operacional: tipo, estabelecimento, unidade, tempo de rotação e situação';

