CREATE TABLE painel_gerencial_permissao (
  id                BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
  painel_gerencial_id BIGINT UNSIGNED NOT NULL,
  perfil_acesso_id  BIGINT UNSIGNED NULL COMMENT 'Perfil autorizado (exclusivo com usuario_id)',
  usuario_id        BIGINT UNSIGNED NULL COMMENT 'Usuário autorizado (exclusivo com perfil_acesso_id)',
  pode_editar       BOOLEAN NOT NULL DEFAULT FALSE,
  pode_exportar     BOOLEAN NOT NULL DEFAULT FALSE,
  vigencia_inicio   DATE NULL,
  vigencia_fim      DATE NULL,
  criado_em         DATETIME(3) NOT NULL,
  criado_por        BIGINT UNSIGNED NULL,
  alterado_em       DATETIME(3) NULL,
  alterado_por      BIGINT UNSIGNED NULL,
  versao            INT UNSIGNED NOT NULL DEFAULT 1,
  excluido_em       DATETIME(3) NULL,
  excluido_por      BIGINT UNSIGNED NULL,
  CONSTRAINT ck_painel_gerencial_permissao_alvo CHECK ((perfil_acesso_id IS NULL) <> (usuario_id IS NULL)),
