CREATE TABLE acesso_paciente_portaria (
  id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
  estabelecimento_id BIGINT UNSIGNED NOT NULL,
  paciente_id BIGINT UNSIGNED NOT NULL,
  atendimento_id BIGINT UNSIGNED NULL COMMENT 'Atendimento que motivou a entrada, quando houver',
  marcacao_horario_id BIGINT UNSIGNED NULL COMMENT 'Marcação agendada ligada à entrada',
  pessoa_portaria_id BIGINT UNSIGNED NULL COMMENT 'Cadastro de portaria do próprio paciente, quando existir',
  cracha_visitante_id BIGINT UNSIGNED NULL,
  forma_identificacao_visitante_id BIGINT UNSIGNED NULL,
  destino_setor_funcional_id BIGINT UNSIGNED NULL COMMENT 'Setor para onde o paciente foi encaminhado',
  entrada_ponto_acesso_id BIGINT UNSIGNED NULL COMMENT 'Portaria ou catraca da entrada',
  saida_ponto_acesso_id BIGINT UNSIGNED NULL COMMENT 'Portaria ou catraca da saída',
  entrada_em DATETIME(3) NOT NULL,
  entrada_usuario_id BIGINT UNSIGNED NULL COMMENT 'Porteiro que registrou a entrada',
  saida_em DATETIME(3) NULL,
  saida_usuario_id BIGINT UNSIGNED NULL COMMENT 'Porteiro que registrou a saída',
  agendado BOOLEAN NOT NULL DEFAULT FALSE,
  custodia_policial BOOLEAN NOT NULL DEFAULT FALSE COMMENT 'Paciente sob custódia policial',
  situacao VARCHAR(30) NOT NULL DEFAULT 'presente',
  observacao VARCHAR(2000) NULL,
  origem VARCHAR(20) NOT NULL DEFAULT 'sistema',
  criado_em DATETIME(3) NOT NULL,
  criado_por BIGINT UNSIGNED NULL,
  alterado_em DATETIME(3) NULL,
  alterado_por BIGINT UNSIGNED NULL,
  versao INT UNSIGNED NOT NULL DEFAULT 1,
  excluido_em DATETIME(3) NULL,
  excluido_por BIGINT UNSIGNED NULL,
  CONSTRAINT ck_acesso_paciente_portaria_origem CHECK (origem IN ('sistema','migracao','integracao')),
  CONSTRAINT ck_acesso_paciente_portaria_situacao CHECK (situacao IN ('presente','saiu','cancelado')),
  CONSTRAINT ck_acesso_paciente_portaria_saida CHECK (saida_em IS NULL OR saida_em >= entrada_em),
  CONSTRAINT ck_acesso_paciente_portaria_saida_situacao CHECK (situacao <> 'saiu' OR saida_em IS NOT NULL),
  KEY ix_acesso_paciente_portaria_estabelecimento_entrada (estabelecimento_id, entrada_em),
  KEY ix_acesso_paciente_portaria_paciente (paciente_id, entrada_em),
  KEY ix_acesso_paciente_portaria_atendimento (atendimento_id),
  KEY ix_acesso_paciente_portaria_marcacao_horario (marcacao_horario_id),
  KEY ix_acesso_paciente_portaria_pessoa_portaria (pessoa_portaria_id),
  KEY ix_acesso_paciente_portaria_cracha_visitante (cracha_visitante_id),
  KEY ix_acesso_paciente_portaria_forma_identificacao_visitante (forma_identificacao_visitante_id),
  KEY ix_acesso_paciente_portaria_destino_setor_funcional (destino_setor_funcional_id),
  KEY ix_acesso_paciente_portaria_entrada_ponto_acesso (entrada_ponto_acesso_id),
  KEY ix_acesso_paciente_portaria_saida_ponto_acesso (saida_ponto_acesso_id),
  KEY ix_acesso_paciente_portaria_entrada_usuario (entrada_usuario_id),
  KEY ix_acesso_paciente_portaria_saida_usuario (saida_usuario_id)
) COMMENT='Entrada e saída de paciente pela portaria, com crachá, setor, marcação ligada, custódia e permanência';


