  CONSTRAINT ck_plano_preventivo_atividade CHECK (atividade IN ('preventiva','calibracao','seguranca_eletrica','inspecao','climatizacao')),
  CONSTRAINT ck_plano_preventivo_unidade CHECK (periodicidade_unidade IN ('dias','semanas','meses','anos')),
  CONSTRAINT ck_plano_preventivo_quantidade CHECK (periodicidade_quantidade BETWEEN 1 AND 730),
  CONSTRAINT ck_plano_preventivo_antecedencia CHECK (antecedencia_dias IS NULL OR antecedencia_dias <= 180),
  CONSTRAINT ck_plano_preventivo_executor CHECK (executor IN ('interno','contrato')),
  CONSTRAINT ck_plano_preventivo_contrato CHECK (executor = 'interno' OR contrato_servico_terceirizado_id IS NOT NULL),
  CONSTRAINT ck_plano_preventivo_interferencia CHECK (percentual_interferencia IS NULL OR percentual_interferencia BETWEEN 0 AND 100),
  KEY ix_plano_preventivo_oficina_manutencao (oficina_manutencao_id),
  KEY ix_plano_preventivo_tipo_ordem_servico_manutencao (tipo_ordem_servico_manutencao_id),
  KEY ix_plano_preventivo_motivo_ordem_servico_manutencao (motivo_ordem_servico_manutencao_id),
  KEY ix_plano_preventivo_contrato_servico_terceirizado (contrato_servico_terceirizado_id),
  KEY ix_plano_preventivo_responsavel_colaborador (responsavel_colaborador_id)
