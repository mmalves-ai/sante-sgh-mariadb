  horas_execucao    DECIMAL(7,2) NULL COMMENT 'Horas previstas de execução',
  horas_parada      DECIMAL(7,2) NULL COMMENT 'Horas previstas de equipamento parado',
  percentual_interferencia DECIMAL(7,4) NULL COMMENT 'Interferência prevista na operação do setor',
  horario_preferencial TIME NULL,
  procedimento      TEXT NULL COMMENT 'Procedimento operacional da execução',
  observacao        VARCHAR(1000) NULL,
