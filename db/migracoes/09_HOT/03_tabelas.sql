  proxima_execucao  DATE NULL,
  ultima_geracao_em DATETIME(3) NULL COMMENT 'Última geração automática de ordens',
  antecedencia_dias SMALLINT UNSIGNED NULL COMMENT 'Antecedência do aviso "a vencer"; nulo usa o parâmetro do estabelecimento',
  manter_ciclo      BOOLEAN NOT NULL DEFAULT TRUE COMMENT 'A próxima data conta da data programada, não da data executada',
