CREATE TABLE suspeita_duplicidade (
  id                BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
  primeiro_paciente_id BIGINT UNSIGNED NOT NULL COMMENT 'Lado A do par (sempre o menor id)',
  segundo_paciente_id BIGINT UNSIGNED NOT NULL COMMENT 'Lado B do par (sempre o maior id)',
  escore            TINYINT UNSIGNED NOT NULL COMMENT 'Pontuação de semelhança, de 0 a 100',
  criterio_cpf      BOOLEAN NOT NULL DEFAULT FALSE,
  criterio_fonetica BOOLEAN NOT NULL DEFAULT FALSE COMMENT 'Nome com a mesma chave fonética',
  criterio_nascimento BOOLEAN NOT NULL DEFAULT FALSE,
  criterio_mae      BOOLEAN NOT NULL DEFAULT FALSE COMMENT 'Mesmo nome da mãe',
  criterio_telefone BOOLEAN NOT NULL DEFAULT FALSE,
  detectado_em      DATETIME(3) NOT NULL,
  situacao          VARCHAR(30) NOT NULL DEFAULT 'aberto',
  decidido_por_usuario_id BIGINT UNSIGNED NULL,
  decidido_em       DATETIME(3) NULL,
  justificativa     VARCHAR(200) NULL,
  unificacao_cadastro_id BIGINT UNSIGNED NULL COMMENT 'Fusão que resolveu o par, quando unificado',
  origem            VARCHAR(20) NOT NULL DEFAULT 'sistema',
  criado_em         DATETIME(3) NOT NULL,
  criado_por        BIGINT UNSIGNED NULL,
  alterado_em       DATETIME(3) NULL,
  alterado_por      BIGINT UNSIGNED NULL,
  versao            INT UNSIGNED NOT NULL DEFAULT 1,
  excluido_em       DATETIME(3) NULL,
  excluido_por      BIGINT UNSIGNED NULL,
  CONSTRAINT ck_suspeita_duplicidade_origem CHECK (origem IN ('sistema','migracao','integracao')),
  CONSTRAINT ck_suspeita_duplicidade_situacao CHECK (situacao IN ('aberto','outra_pessoa','unificado')),
  CONSTRAINT ck_suspeita_duplicidade_par CHECK (primeiro_paciente_id < segundo_paciente_id),
  CONSTRAINT ck_suspeita_duplicidade_escore CHECK (escore <= 100),
  CONSTRAINT ck_suspeita_duplicidade_decisao CHECK (situacao = 'aberto' OR (decidido_em IS NOT NULL AND decidido_por_usuario_id IS NOT NULL)),
  CONSTRAINT ck_suspeita_duplicidade_outra_pessoa CHECK (situacao <> 'outra_pessoa' OR (justificativa IS NOT NULL AND CHAR_LENGTH(TRIM(justificativa)) >= 5)),
  CONSTRAINT ck_suspeita_duplicidade_unificado CHECK (situacao <> 'unificado' OR unificacao_cadastro_id IS NOT NULL),
  UNIQUE KEY uq_suspeita_duplicidade_par (primeiro_paciente_id, segundo_paciente_id),
  KEY ix_suspeita_duplicidade_segundo (segundo_paciente_id),
  KEY ix_suspeita_duplicidade_situacao (situacao, escore),
  KEY ix_suspeita_duplicidade_decidido_por (decidido_por_usuario_id),
  KEY ix_suspeita_duplicidade_unificacao (unificacao_cadastro_id)
) COMMENT='Pares de cadastros com indício de duplicidade, com pontuação, critério e decisão do analista';

