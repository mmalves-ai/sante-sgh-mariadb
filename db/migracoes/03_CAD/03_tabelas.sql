CREATE TABLE paciente_vulnerabilidade (
  id                BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
  paciente_id       BIGINT UNSIGNED NOT NULL,
  condicao_vulnerabilidade_id BIGINT UNSIGNED NOT NULL,
  declarada_em      DATE NOT NULL COMMENT 'Data em que a vulnerabilidade foi declarada',
  informante_tipo   VARCHAR(30) NOT NULL DEFAULT 'paciente' COMMENT 'Quem informou a vulnerabilidade',
  informante_nome   VARCHAR(150) NULL COMMENT 'Nome de quem informou, quando não é o próprio paciente',
  registrado_por_profissional_id BIGINT UNSIGNED NULL,
  vigencia_fim      DATE NULL COMMENT 'Data em que a condição deixou de existir',
  observacao        VARCHAR(500) NULL,
  criado_em         DATETIME(3) NOT NULL,
  criado_por        BIGINT UNSIGNED NULL,
  alterado_em       DATETIME(3) NULL,
  alterado_por      BIGINT UNSIGNED NULL,
  versao            INT UNSIGNED NOT NULL DEFAULT 1,
  excluido_em       DATETIME(3) NULL,
  excluido_por      BIGINT UNSIGNED NULL,
  CONSTRAINT ck_paciente_vulnerabilidade_informante_tipo CHECK (informante_tipo IN ('paciente','responsavel','familiar','profissional','servico_social','outro')),
  CONSTRAINT ck_paciente_vulnerabilidade_vigencia CHECK (vigencia_fim IS NULL OR vigencia_fim >= declarada_em),
  UNIQUE KEY uq_paciente_vulnerabilidade_paciente_condicao_data (paciente_id, condicao_vulnerabilidade_id, declarada_em),
  KEY ix_paciente_vulnerabilidade_condicao (condicao_vulnerabilidade_id),
  KEY ix_paciente_vulnerabilidade_profissional (registrado_por_profissional_id)
) COMMENT='Vulnerabilidades declaradas do paciente, com data e informante';

