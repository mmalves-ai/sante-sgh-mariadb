  excluido_por      BIGINT UNSIGNED NULL,
  CONSTRAINT ck_pendencia_profissional_situacao CHECK (situacao IN ('aberta','baixada','cancelada')),
  CONSTRAINT ck_pendencia_profissional_baixa CHECK ((situacao = 'aberta' AND baixada_em IS NULL) OR (situacao <> 'aberta' AND baixada_em IS NOT NULL AND baixada_em >= aberta_em)),
