CREATE TABLE pendencia_plano (
  id                BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
  plano_fonte_pagadora_id BIGINT UNSIGNED NOT NULL,
  estabelecimento_id BIGINT UNSIGNED NULL COMMENT 'Nulo: vale para todos os estabelecimentos',
  tipo              VARCHAR(30) NOT NULL COMMENT 'Natureza da pendência imposta pelo plano',
  tipo_atendimento  VARCHAR(30) NOT NULL DEFAULT 'todos' COMMENT 'Tipo de atendimento em que a pendência se aplica',
  modo_checagem     VARCHAR(30) NOT NULL DEFAULT 'alerta' COMMENT 'bloqueia: impede o atendimento; alerta: exige ciência; informa: só exibe',
  mensagem          TEXT NULL COMMENT 'Texto exibido à recepção',
  ativo             BOOLEAN NOT NULL DEFAULT TRUE,
  criado_em         DATETIME(3) NOT NULL,
  criado_por        BIGINT UNSIGNED NULL,
  alterado_em       DATETIME(3) NULL,
  alterado_por      BIGINT UNSIGNED NULL,
  versao            INT UNSIGNED NOT NULL DEFAULT 1,
  CONSTRAINT ck_pendencia_plano_tipo CHECK (tipo IN ('carencia','coparticipacao','aviso','documento','autorizacao','senha','guia','outro')),
  CONSTRAINT ck_pendencia_plano_tipo_atendimento CHECK (tipo_atendimento IN ('todos','ambulatorial','urgencia','internacao','externo','domiciliar')),
  CONSTRAINT ck_pendencia_plano_modo_checagem CHECK (modo_checagem IN ('bloqueia','alerta','informa')),
  UNIQUE KEY uq_pendencia_plano_plano_estab_tipo_atend (plano_fonte_pagadora_id, estabelecimento_id, tipo, tipo_atendimento),
  KEY ix_pendencia_plano_estabelecimento (estabelecimento_id)
) COMMENT='Pendências que o plano impõe antes do atendimento (carência, coparticipação, aviso)';

CREATE TABLE pendencia_profissional (
  id                BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
  estabelecimento_id BIGINT UNSIGNED NOT NULL,
  profissional_id   BIGINT UNSIGNED NOT NULL,
  tipo_pendencia_profissional_id BIGINT UNSIGNED NOT NULL,
  aberta_em         DATETIME(3) NOT NULL,
  prazo             DATE NULL COMMENT 'Data limite para a regularização',
  situacao          VARCHAR(30) NOT NULL DEFAULT 'aberta',
  baixada_em        DATETIME(3) NULL,
  baixada_por_usuario_id BIGINT UNSIGNED NULL,
  ocorrencia        TEXT NULL COMMENT 'Descrição da ocorrência e da baixa',
  origem            VARCHAR(20) NOT NULL DEFAULT 'sistema',
  criado_em         DATETIME(3) NOT NULL,
  criado_por        BIGINT UNSIGNED NULL,
  alterado_em       DATETIME(3) NULL,
  alterado_por      BIGINT UNSIGNED NULL,
  versao            INT UNSIGNED NOT NULL DEFAULT 1,
