  KEY ix_pendencia_profissional_estabelecimento (estabelecimento_id, situacao),
  KEY ix_pendencia_profissional_tipo (tipo_pendencia_profissional_id),
  KEY ix_pendencia_profissional_baixada_por (baixada_por_usuario_id)
