CREATE TABLE estado_civil (
  id              BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
  codigo          VARCHAR(30) NOT NULL,
  descricao       VARCHAR(150) NOT NULL,
  ativo           BOOLEAN NOT NULL DEFAULT TRUE,
  codigo_esocial  SMALLINT UNSIGNED NULL COMMENT 'Código do estado civil no eSocial',
  codigo_cadsus   VARCHAR(5) NULL COMMENT 'Código no cadastro nacional de usuários de saúde',
  exige_conjuge   BOOLEAN NOT NULL DEFAULT FALSE COMMENT 'Pede nome do cônjuge no cadastro',
  criado_em       DATETIME(3) NOT NULL,
  criado_por      BIGINT UNSIGNED NULL,
  alterado_em     DATETIME(3) NULL,
  alterado_por    BIGINT UNSIGNED NULL,
  versao          INT UNSIGNED NOT NULL DEFAULT 1,
  UNIQUE KEY uq_estado_civil_codigo (codigo)
) COMMENT='Estados civis aceitos no cadastro, com código para trocas oficiais';

