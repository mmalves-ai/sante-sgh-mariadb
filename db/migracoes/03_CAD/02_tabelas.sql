CREATE TABLE paciente_versao (
  id                       BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
  paciente_id              BIGINT UNSIGNED NOT NULL,
  operacao                 VARCHAR(20) NOT NULL,
  dados                    JSON NOT NULL COMMENT 'Retrato completo do registro no momento da operação',
  ocorrido_em              DATETIME(3) NOT NULL,
  usuario_id               BIGINT UNSIGNED NULL COMMENT 'Usuário que fez a operação (nulo para processo automático)',
  motivo                   VARCHAR(30) NOT NULL DEFAULT 'alteracao_cadastro' COMMENT 'O que provocou o retrato',
  atendimento_id           BIGINT UNSIGNED NULL COMMENT 'Atendimento a que o retrato se refere',
  documento_prontuario_id  BIGINT UNSIGNED NULL COMMENT 'Registro clínico que pediu o retrato',
  estabelecimento_id       BIGINT UNSIGNED NULL,
  nome                     VARCHAR(150) NOT NULL COMMENT 'Nome exibido no momento do retrato',
  data_nascimento          DATE NULL,
  hash_dados               CHAR(64) NOT NULL COMMENT 'SHA-256 dos dados, para evitar retrato repetido e provar integridade',
  criado_em                DATETIME(3) NOT NULL,
  criado_por               BIGINT UNSIGNED NULL,
  alterado_em              DATETIME(3) NULL,
  alterado_por             BIGINT UNSIGNED NULL,
  versao                   INT UNSIGNED NOT NULL DEFAULT 1,
  CONSTRAINT ck_paciente_versao_operacao CHECK (operacao IN ('inclusao','alteracao','exclusao')),
  CONSTRAINT ck_paciente_versao_motivo CHECK (motivo IN ('alteracao_cadastro','registro_clinico','atendimento','unificacao','migracao')),
  KEY ix_paciente_versao_paciente (paciente_id, ocorrido_em),
  KEY ix_paciente_versao_hash (paciente_id, hash_dados),
  KEY ix_paciente_versao_usuario_id (usuario_id),
  KEY ix_paciente_versao_atendimento_id (atendimento_id),
  KEY ix_paciente_versao_documento_prontuario_id (documento_prontuario_id),
  KEY ix_paciente_versao_estabelecimento_id (estabelecimento_id)
) COMMENT='Retrato imutável do cadastro do paciente, com contatos, gravado a cada registro clínico ou mudança relevante';
