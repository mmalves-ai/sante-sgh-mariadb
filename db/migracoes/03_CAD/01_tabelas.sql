  CONSTRAINT ck_calendario_trabalho_excecao_dia_semana CHECK (dia_semana IS NULL OR dia_semana BETWEEN 1 AND 7),
  CONSTRAINT ck_calendario_trabalho_excecao_horas CHECK ((sem_expediente AND horas_produtivas IS NULL) OR (NOT sem_expediente AND horas_produtivas BETWEEN 0 AND 24)),
  CONSTRAINT ck_calendario_trabalho_excecao_origem CHECK (origem IN ('sistema','migracao','integracao')),
  UNIQUE KEY uq_calendario_trabalho_excecao_sequencia (calendario_trabalho_id, sequencia),
