  CONSTRAINT ck_bloqueio_carteira_liberacao CHECK (situacao <> 'liberado' OR (liberado_usuario_id IS NOT NULL AND liberado_em IS NOT NULL AND motivo_liberacao IS NOT NULL)),
  CONSTRAINT ck_bloqueio_carteira_origem CHECK (origem IN ('sistema','migracao','integracao')),
