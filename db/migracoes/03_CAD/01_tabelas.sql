CREATE TABLE bloqueio_carteira (
  id                BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
  estabelecimento_id BIGINT UNSIGNED NULL COMMENT 'Estabelecimento onde vale o bloqueio (nulo: todos)',
  fonte_pagadora_id BIGINT UNSIGNED NOT NULL,
  cobertura_paciente_id BIGINT UNSIGNED NULL COMMENT 'Cobertura bloqueada, quando a carteira já está cadastrada',
  numero_carteira   VARCHAR(30) NOT NULL,
  motivo            VARCHAR(500) NOT NULL,
  inicio_em         DATE NOT NULL,
  fim_em            DATE NULL,
  situacao          VARCHAR(30) NOT NULL DEFAULT 'ativo',
  bloqueado_usuario_id BIGINT UNSIGNED NOT NULL,
  bloqueado_em      DATETIME(3) NOT NULL,
  liberado_usuario_id BIGINT UNSIGNED NULL,
  liberado_em       DATETIME(3) NULL,
  motivo_liberacao  VARCHAR(500) NULL,
  origem            VARCHAR(20) NOT NULL DEFAULT 'sistema',
  criado_em         DATETIME(3) NOT NULL,
  criado_por        BIGINT UNSIGNED NULL,
  alterado_em       DATETIME(3) NULL,
  alterado_por      BIGINT UNSIGNED NULL,
  versao            INT UNSIGNED NOT NULL DEFAULT 1,
  excluido_em       DATETIME(3) NULL,
  excluido_por      BIGINT UNSIGNED NULL,
