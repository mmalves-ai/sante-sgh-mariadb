  id                BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
  estabelecimento_id BIGINT UNSIGNED NOT NULL,
  sequencia         SMALLINT UNSIGNED NOT NULL,
  papel             VARCHAR(30) NOT NULL,
  profissional_id   BIGINT UNSIGNED NULL COMMENT 'Responsável, quando é profissional cadastrado',
  pessoa_fisica_id  BIGINT UNSIGNED NULL COMMENT 'Responsável sem cadastro de profissional (ex.: diretor administrativo)',
  inscricao_conselho_id BIGINT UNSIGNED NULL COMMENT 'Registro no conselho usado na responsabilidade técnica',
  regime_atendimento_id BIGINT UNSIGNED NULL COMMENT 'Restringe a responsabilidade a um tipo de atendimento (ex.: alta complexidade ambulatorial)',
  vigencia_inicio   DATE NOT NULL,
  vigencia_fim      DATE NULL,
  origem            VARCHAR(20) NOT NULL DEFAULT 'sistema',
  criado_em         DATETIME(3) NOT NULL,
  criado_por        BIGINT UNSIGNED NULL,
  alterado_em       DATETIME(3) NULL,
  alterado_por      BIGINT UNSIGNED NULL,
  versao            INT UNSIGNED NOT NULL DEFAULT 1,
  excluido_em       DATETIME(3) NULL,
  excluido_por      BIGINT UNSIGNED NULL,
  CONSTRAINT ck_estabelecimento_responsavel_papel CHECK (papel IN ('tecnico','clinico','administrativo','diretor_geral','enfermagem','farmaceutico','nutricionista','controle_infeccao','protecao_dados','outro')),
  CONSTRAINT ck_estabelecimento_responsavel_pessoa CHECK (profissional_id IS NOT NULL OR pessoa_fisica_id IS NOT NULL),
  CONSTRAINT ck_estabelecimento_responsavel_vigencia CHECK (vigencia_fim IS NULL OR vigencia_fim >= vigencia_inicio),
  CONSTRAINT ck_estabelecimento_responsavel_origem CHECK (origem IN ('sistema','migracao','integracao')),
  UNIQUE KEY uq_estabelecimento_responsavel_sequencia (estabelecimento_id, sequencia),
  KEY ix_estabelecimento_responsavel_papel (estabelecimento_id, papel, vigencia_inicio),
  KEY ix_estabelecimento_responsavel_profissional (profissional_id),
  KEY ix_estabelecimento_responsavel_pessoa (pessoa_fisica_id),
  KEY ix_estabelecimento_responsavel_inscricao (inscricao_conselho_id),
  KEY ix_estabelecimento_responsavel_regime (regime_atendimento_id)
) COMMENT='Responsáveis técnico, clínico e administrativo do estabelecimento, com registro e vigência';
