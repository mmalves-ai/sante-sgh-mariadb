  KEY ix_bloqueio_carteira_cobertura (cobertura_paciente_id),
  KEY ix_bloqueio_carteira_estabelecimento (estabelecimento_id),
  KEY ix_bloqueio_carteira_bloqueado_usuario (bloqueado_usuario_id),
  KEY ix_bloqueio_carteira_liberado_usuario (liberado_usuario_id)
) COMMENT='Bloqueio de uma carteira ou cobertura para atendimento, com motivo, período e quem bloqueou';

