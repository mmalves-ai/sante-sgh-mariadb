CREATE TABLE justificativa_mutirao_cirurgico (
  id                 BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
  codigo             VARCHAR(30) NOT NULL,
  descricao          VARCHAR(150) NOT NULL,
  ativo              BOOLEAN NOT NULL DEFAULT TRUE,
  texto_detalhado    VARCHAR(250) NULL COMMENT 'Texto completo da justificativa, quando a descrição não basta',
  aplica_inclusao    BOOLEAN NOT NULL DEFAULT TRUE COMMENT 'Pode ser usada ao incluir paciente no mutirão',
  aplica_alteracao   BOOLEAN NOT NULL DEFAULT TRUE COMMENT 'Pode ser usada ao alterar ou retirar paciente do mutirão',
  exige_complemento  BOOLEAN NOT NULL DEFAULT FALSE COMMENT 'Obriga texto livre complementar ao usar a justificativa',
  criado_em          DATETIME(3) NOT NULL,
  criado_por         BIGINT UNSIGNED NULL,
  alterado_em        DATETIME(3) NULL,
  alterado_por       BIGINT UNSIGNED NULL,
  versao             INT UNSIGNED NOT NULL DEFAULT 1,
  UNIQUE KEY uq_justificativa_mutirao_cirurgico_codigo (codigo)
