CREATE TABLE lancamento_ficha_anestesica (
  id                          BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
  ficha_anestesica_id         BIGINT UNSIGNED NOT NULL,
  sequencia                   SMALLINT UNSIGNED NOT NULL COMMENT 'Ordem do item dentro do pai',
  parte                       VARCHAR(30) NOT NULL COMMENT 'Parte da ficha a que o lançamento pertence',
  momento_inicio              DATETIME(3) NOT NULL COMMENT 'Momento do lançamento ou início da infusão',
  momento_fim                 DATETIME(3) NULL COMMENT 'Fim da infusão, do gás, do evento ou do procedimento',
  tipo_sinal_monitorado_id    BIGINT UNSIGNED NULL COMMENT 'Sinal vital medido (parte sinal)',
  valor_numerico              DECIMAL(15,4) NULL COMMENT 'Valor medido do sinal ou concentração do gás',
  insumo_id                   BIGINT UNSIGNED NULL COMMENT 'Medicamento, soro ou material do estoque',
  dose                        DECIMAL(15,4) NULL,
  unidade_medida_id           BIGINT UNSIGNED NULL,
  via_de_uso_id               BIGINT UNSIGNED NULL,
  infusao_continua            BOOLEAN NOT NULL DEFAULT FALSE COMMENT 'Fica aberta até ganhar o fim; impede a assinatura enquanto aberta',
  vazao                       DECIMAL(15,4) NULL COMMENT 'Vazão da bomba de infusão, na unidade informada',
  gas                         VARCHAR(30) NULL COMMENT 'Gás ou agente inalatório',
  fluido                      VARCHAR(30) NULL COMMENT 'Tipo de fluido administrado',
  hemocomponente_id           BIGINT UNSIGNED NULL COMMENT 'Hemocomponente transfundido, vindo da agência transfusional',
  volume_ml                   DECIMAL(15,4) NULL COMMENT 'Volume em mililitros de fluido administrado ou de perda',
  perda                       VARCHAR(30) NULL COMMENT 'Tipo de perda (sangramento, diurese, aspiração)',
  evento                      VARCHAR(40) NULL COMMENT 'Evento ou intercorrência anestésica',
  intercorrencia              BOOLEAN NOT NULL DEFAULT FALSE COMMENT 'O evento é intercorrência e entra nos indicadores',
  modo_ventilatorio_id        BIGINT UNSIGNED NULL,
  posicao_cirurgica_id        BIGINT UNSIGNED NULL,
  profissional_id             BIGINT UNSIGNED NULL COMMENT 'Profissional que entrou na equipe (parte equipe)',
  funcao_equipe_cirurgica_id  BIGINT UNSIGNED NULL,
  exame_id                    BIGINT UNSIGNED NULL COMMENT 'Exame feito na sala, quando do cadastro',
  descricao                   VARCHAR(255) NULL COMMENT 'Descrição do procedimento, exame, evento ou item avulso',
  resultado                   VARCHAR(255) NULL COMMENT 'Resultado do exame feito na sala',
  quantidade                  DECIMAL(15,4) NULL,
  observacao                  VARCHAR(255) NULL,
  origem                      VARCHAR(20) NOT NULL DEFAULT 'sistema',
  criado_em                   DATETIME(3) NOT NULL,
  criado_por                  BIGINT UNSIGNED NULL,
  alterado_em                 DATETIME(3) NULL,
  alterado_por                BIGINT UNSIGNED NULL,
  versao                      INT UNSIGNED NOT NULL DEFAULT 1,
  excluido_em                 DATETIME(3) NULL,
  excluido_por                BIGINT UNSIGNED NULL,
  UNIQUE KEY uq_lancamento_ficha_anestesica_ficha_anestesica_sequencia (ficha_anestesica_id, sequencia),
  CONSTRAINT ck_lancamento_ficha_anestesica_parte CHECK (parte IN ('sinal','medicamento','gas','fluido','perda','evento','modo_ventilatorio','posicao','equipe','procedimento','exame','avulso','bomba_infusao')),
  CONSTRAINT ck_lancamento_ficha_anestesica_periodo CHECK (momento_fim IS NULL OR momento_fim >= momento_inicio),
  CONSTRAINT ck_lancamento_ficha_anestesica_gas CHECK (gas IS NULL OR gas IN ('oxigenio','ar_comprimido','oxido_nitroso','sevoflurano','isoflurano','desflurano','outro')),
  CONSTRAINT ck_lancamento_ficha_anestesica_fluido CHECK (fluido IS NULL OR fluido IN ('cristaloide','coloide','concentrado_hemacias','plasma','plaquetas','crioprecipitado','outro')),
  CONSTRAINT ck_lancamento_ficha_anestesica_perda CHECK (perda IS NULL OR perda IN ('sangramento','diurese','aspiracao','outra')),
  CONSTRAINT ck_lancamento_ficha_anestesica_sinal CHECK (parte <> 'sinal' OR (tipo_sinal_monitorado_id IS NOT NULL AND valor_numerico IS NOT NULL)),
  CONSTRAINT ck_lancamento_ficha_anestesica_medicamento CHECK (parte <> 'medicamento' OR (insumo_id IS NOT NULL AND dose IS NOT NULL AND dose > 0)),
  CONSTRAINT ck_lancamento_ficha_anestesica_parte_gas CHECK (parte <> 'gas' OR (gas IS NOT NULL AND valor_numerico BETWEEN 0 AND 100)),
  CONSTRAINT ck_lancamento_ficha_anestesica_parte_fluido CHECK (parte <> 'fluido' OR (fluido IS NOT NULL AND volume_ml > 0)),
  CONSTRAINT ck_lancamento_ficha_anestesica_parte_perda CHECK (parte <> 'perda' OR (perda IS NOT NULL AND volume_ml >= 0)),
  CONSTRAINT ck_lancamento_ficha_anestesica_parte_evento CHECK (parte <> 'evento' OR evento IS NOT NULL),
  CONSTRAINT ck_lancamento_ficha_anestesica_parte_equipe CHECK (parte <> 'equipe' OR (profissional_id IS NOT NULL AND funcao_equipe_cirurgica_id IS NOT NULL)),
  CONSTRAINT ck_lancamento_ficha_anestesica_parte_modo CHECK (parte <> 'modo_ventilatorio' OR modo_ventilatorio_id IS NOT NULL),
  CONSTRAINT ck_lancamento_ficha_anestesica_parte_posicao CHECK (parte <> 'posicao' OR posicao_cirurgica_id IS NOT NULL),
  KEY ix_lancamento_ficha_anestesica_ficha_parte_momento (ficha_anestesica_id, parte, momento_inicio),
  CONSTRAINT ck_lancamento_ficha_anestesica_origem CHECK (origem IN ('sistema','migracao','integracao')),
  KEY ix_lancamento_ficha_anestesica_tipo_sinal_monitorado (tipo_sinal_monitorado_id),
  KEY ix_lancamento_ficha_anestesica_insumo (insumo_id),
  KEY ix_lancamento_ficha_anestesica_unidade_medida (unidade_medida_id),
  KEY ix_lancamento_ficha_anestesica_via_de_uso (via_de_uso_id),
  KEY ix_lancamento_ficha_anestesica_hemocomponente (hemocomponente_id),
  KEY ix_lancamento_ficha_anestesica_modo_ventilatorio (modo_ventilatorio_id),
  KEY ix_lancamento_ficha_anestesica_posicao_cirurgica (posicao_cirurgica_id),
  KEY ix_lancamento_ficha_anestesica_profissional (profissional_id),
  KEY ix_lancamento_ficha_anestesica_funcao_equipe_cirurgica (funcao_equipe_cirurgica_id),
  KEY ix_lancamento_ficha_anestesica_exame (exame_id)
) COMMENT='Lançamento por horário na ficha: droga, dose, fluido, gás, hemocomponente ou sinal vital medido';

