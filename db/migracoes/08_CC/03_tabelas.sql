CREATE TABLE taxa_sala_cirurgica (
  id                       BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
  estabelecimento_id       BIGINT UNSIGNED NOT NULL,
  descricao                VARCHAR(150) NOT NULL,
  tipo_cobranca            VARCHAR(30) NOT NULL COMMENT 'taxa_sala ou uso_equipamento',
  criterio                 VARCHAR(30) NOT NULL COMMENT 'porte: pelo porte cirúrgico; tempo: por faixa de duração; fixo: valor único por uso',
  sala_cirurgica_id        BIGINT UNSIGNED NULL COMMENT 'Nulo: vale para todas as salas',
  equipamento_saude_id     BIGINT UNSIGNED NULL COMMENT 'Equipamento cobrado, quando tipo_cobranca = uso_equipamento',
  porte_cirurgico_id       BIGINT UNSIGNED NULL,
  fonte_pagadora_id        BIGINT UNSIGNED NULL COMMENT 'Nulo: vale para todas as fontes pagadoras',
  plano_fonte_pagadora_id  BIGINT UNSIGNED NULL,
  tempo_minimo_minutos     SMALLINT UNSIGNED NULL,
  tempo_maximo_minutos     SMALLINT UNSIGNED NULL,
  fracao_adicional_minutos SMALLINT UNSIGNED NULL COMMENT 'Tempo de cada fração cobrada além da faixa',
  item_faturavel_id        BIGINT UNSIGNED NOT NULL COMMENT 'Item lançado na conta; o preço vem da tabela de preço do faturamento',
  quantidade               DECIMAL(15,4) NOT NULL DEFAULT 1,
  prioridade               SMALLINT UNSIGNED NOT NULL DEFAULT 0 COMMENT 'Desempate quando mais de uma regra se aplica (maior vence)',
  vigencia_inicio          DATE NOT NULL,
  vigencia_fim             DATE NULL,
  ativo                    BOOLEAN NOT NULL DEFAULT TRUE,
  criado_em                DATETIME(3) NOT NULL,
  criado_por               BIGINT UNSIGNED NULL,
  alterado_em              DATETIME(3) NULL,
  alterado_por             BIGINT UNSIGNED NULL,
  versao                   INT UNSIGNED NOT NULL DEFAULT 1,
  CONSTRAINT ck_taxa_sala_cirurgica_tipo_cobranca CHECK (tipo_cobranca IN ('taxa_sala','uso_equipamento')),
  CONSTRAINT ck_taxa_sala_cirurgica_criterio CHECK (criterio IN ('porte','tempo','fixo')),
  CONSTRAINT ck_taxa_sala_cirurgica_equipamento CHECK (tipo_cobranca <> 'uso_equipamento' OR equipamento_saude_id IS NOT NULL),
  CONSTRAINT ck_taxa_sala_cirurgica_porte CHECK (criterio <> 'porte' OR porte_cirurgico_id IS NOT NULL),
  CONSTRAINT ck_taxa_sala_cirurgica_tempo CHECK (criterio <> 'tempo' OR tempo_minimo_minutos IS NOT NULL),
  CONSTRAINT ck_taxa_sala_cirurgica_faixa CHECK (tempo_maximo_minutos IS NULL OR tempo_minimo_minutos IS NULL OR tempo_maximo_minutos >= tempo_minimo_minutos),
  CONSTRAINT ck_taxa_sala_cirurgica_quantidade CHECK (quantidade > 0),
  CONSTRAINT ck_taxa_sala_cirurgica_vigencia CHECK (vigencia_fim IS NULL OR vigencia_fim >= vigencia_inicio),
  KEY ix_taxa_sala_cirurgica_busca (estabelecimento_id, tipo_cobranca, ativo, vigencia_inicio),
  KEY ix_taxa_sala_cirurgica_sala (sala_cirurgica_id),
  KEY ix_taxa_sala_cirurgica_equipamento (equipamento_saude_id),
  KEY ix_taxa_sala_cirurgica_porte (porte_cirurgico_id),
  KEY ix_taxa_sala_cirurgica_fonte_pagadora (fonte_pagadora_id),
  KEY ix_taxa_sala_cirurgica_plano (plano_fonte_pagadora_id),
  KEY ix_taxa_sala_cirurgica_item_faturavel (item_faturavel_id)
) COMMENT='Regra de taxa de sala e de uso de equipamento por porte, tempo e convênio';

