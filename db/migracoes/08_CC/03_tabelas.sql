CREATE TABLE sala_cirurgica_procedimento (
  id                        BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
  sala_cirurgica_id         BIGINT UNSIGNED NOT NULL,
  procedimento_cirurgico_id BIGINT UNSIGNED NOT NULL,
  regra                     VARCHAR(30) NOT NULL DEFAULT 'permitido' COMMENT 'permitido: a sala aceita; vedado: a agenda recusa o procedimento nesta sala',
  observacao                VARCHAR(500) NULL,
  criado_em                 DATETIME(3) NOT NULL,
  criado_por                BIGINT UNSIGNED NULL,
  alterado_em               DATETIME(3) NULL,
  alterado_por              BIGINT UNSIGNED NULL,
  versao                    INT UNSIGNED NOT NULL DEFAULT 1,
  excluido_em               DATETIME(3) NULL,
  excluido_por              BIGINT UNSIGNED NULL,
  CONSTRAINT ck_sala_cirurgica_procedimento_regra CHECK (regra IN ('permitido','vedado')),
  UNIQUE KEY uq_sala_cirurgica_procedimento_par (sala_cirurgica_id, procedimento_cirurgico_id),
  KEY ix_sala_cirurgica_procedimento_procedimento (procedimento_cirurgico_id)
) COMMENT='Procedimentos cirúrgicos permitidos ou vedados em cada sala cirúrgica';

CREATE TABLE situacao_bloco (
  id                BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
  codigo            VARCHAR(30) NOT NULL,
  descricao         VARCHAR(150) NOT NULL,
  ativo             BOOLEAN NOT NULL DEFAULT TRUE,
  aplica_a          VARCHAR(30) NOT NULL DEFAULT 'paciente' COMMENT 'paciente: andamento do paciente no bloco; sala: estado da sala',
  sigla             VARCHAR(5) NULL,
  cor               CHAR(7) NULL COMMENT 'Cor no painel, em hexadecimal (#RRGGBB)',
  ordem_exibicao    SMALLINT UNSIGNED NOT NULL DEFAULT 0,
  exibe_painel_familia BOOLEAN NOT NULL DEFAULT FALSE,
  texto_painel_familia VARCHAR(150) NULL COMMENT 'Texto mostrado à família, sem dado clínico',
  situacao_final    BOOLEAN NOT NULL DEFAULT FALSE COMMENT 'Encerra o percurso (ex.: liberado)',
  chave_traducao    VARCHAR(60) NULL,
  criado_em         DATETIME(3) NOT NULL,
  criado_por        BIGINT UNSIGNED NULL,
  alterado_em       DATETIME(3) NULL,
  alterado_por      BIGINT UNSIGNED NULL,
  versao            INT UNSIGNED NOT NULL DEFAULT 1,
  CONSTRAINT ck_situacao_bloco_aplica_a CHECK (aplica_a IN ('paciente','sala')),
  CONSTRAINT ck_situacao_bloco_cor CHECK (cor IS NULL OR cor REGEXP '^#[0-9A-Fa-f]{6}$'),
  UNIQUE KEY uq_situacao_bloco_codigo (codigo)
) COMMENT='Situação exibida no painel do bloco e da família (aguardando, em preparo, em cirurgia, em recuperação, liberado)';

