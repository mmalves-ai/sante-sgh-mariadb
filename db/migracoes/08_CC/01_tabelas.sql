CREATE TABLE ato_cirurgico (
  id                               BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
  estabelecimento_id               BIGINT UNSIGNED NOT NULL,
  numero                           VARCHAR(20) NOT NULL COMMENT 'Número do registro da cirurgia, gerado por sequencia_negocio',
  agendamento_cirurgico_id         BIGINT UNSIGNED NULL COMMENT 'Agendamento de origem; vazio em urgência sem agenda',
  atendimento_id                   BIGINT UNSIGNED NOT NULL,
  paciente_id                      BIGINT UNSIGNED NOT NULL,
  sala_cirurgica_id                BIGINT UNSIGNED NOT NULL,
  carater_cirurgia_id              BIGINT UNSIGNED NOT NULL,
  tipo_anestesia_id                BIGINT UNSIGNED NULL COMMENT 'Técnica principal; as demais em ficha_anestesica_tecnica',
  classe_contaminacao_cirurgica_id BIGINT UNSIGNED NULL,
  porte_cirurgico_id               BIGINT UNSIGNED NULL,
  fonte_pagadora_id                BIGINT UNSIGNED NULL,
  plano_fonte_pagadora_id          BIGINT UNSIGNED NULL,
  codigo_cid10_pre_operatorio      VARCHAR(6) NULL COMMENT 'Código CID-10 sem ponto (o catálogo CID-10 ainda não tem tabela no modelo)',
  codigo_cid10_pos_operatorio      VARCHAR(6) NULL COMMENT 'Código CID-10 sem ponto (o catálogo CID-10 ainda não tem tabela no modelo)',
  diagnostico_pre_operatorio       VARCHAR(400) NULL,
  entrada_sala_em                  DATETIME(3) NULL,
  inicio_anestesia_em              DATETIME(3) NULL,
  inicio_cirurgia_em               DATETIME(3) NULL COMMENT 'Incisão',
  fim_cirurgia_em                  DATETIME(3) NULL,
  fim_anestesia_em                 DATETIME(3) NULL,
  saida_sala_em                    DATETIME(3) NULL,
  peso_kg                          DECIMAL(6,3) NULL,
  supuracao                        BOOLEAN NOT NULL DEFAULT FALSE COMMENT 'Supuração presente no sítio no início do ato (CCIH)',
  reabordagem                      BOOLEAN NOT NULL DEFAULT FALSE COMMENT 'Reoperação não planejada',
  destino_pos_operatorio           VARCHAR(30) NULL,
  situacao                         VARCHAR(30) NOT NULL DEFAULT 'em_andamento',
  observacao                       VARCHAR(500) NULL,
  origem                           VARCHAR(20) NOT NULL DEFAULT 'sistema',
  criado_em                        DATETIME(3) NOT NULL,
  criado_por                       BIGINT UNSIGNED NULL,
  alterado_em                      DATETIME(3) NULL,
  alterado_por                     BIGINT UNSIGNED NULL,
  versao                           INT UNSIGNED NOT NULL DEFAULT 1,
  excluido_em                      DATETIME(3) NULL,
  excluido_por                     BIGINT UNSIGNED NULL,
  CONSTRAINT ck_ato_cirurgico_origem CHECK (origem IN ('sistema','migracao','integracao')),
  CONSTRAINT ck_ato_cirurgico_situacao CHECK (situacao IN ('em_andamento','realizado','cancelado')),
  CONSTRAINT ck_ato_cirurgico_destino CHECK (destino_pos_operatorio IS NULL OR destino_pos_operatorio IN ('recuperacao','uti','unidade','domicilio','obito')),
  CONSTRAINT ck_ato_cirurgico_sala CHECK (saida_sala_em IS NULL OR entrada_sala_em IS NULL OR saida_sala_em >= entrada_sala_em),
  CONSTRAINT ck_ato_cirurgico_cirurgia CHECK (fim_cirurgia_em IS NULL OR inicio_cirurgia_em IS NULL OR fim_cirurgia_em >= inicio_cirurgia_em),
  CONSTRAINT ck_ato_cirurgico_anestesia CHECK (fim_anestesia_em IS NULL OR inicio_anestesia_em IS NULL OR fim_anestesia_em >= inicio_anestesia_em),
  CONSTRAINT ck_ato_cirurgico_incisao CHECK (inicio_cirurgia_em IS NULL OR entrada_sala_em IS NULL OR inicio_cirurgia_em >= entrada_sala_em),
  CONSTRAINT ck_ato_cirurgico_realizado CHECK (situacao <> 'realizado' OR (entrada_sala_em IS NOT NULL AND inicio_cirurgia_em IS NOT NULL AND fim_cirurgia_em IS NOT NULL AND saida_sala_em IS NOT NULL)),
  CONSTRAINT ck_ato_cirurgico_peso CHECK (peso_kg IS NULL OR peso_kg > 0),
  UNIQUE KEY uq_ato_cirurgico_numero (estabelecimento_id, numero),
  KEY ix_ato_cirurgico_sala_entrada (sala_cirurgica_id, entrada_sala_em),
  KEY ix_ato_cirurgico_agendamento_cirurgico_id (agendamento_cirurgico_id),
  KEY ix_ato_cirurgico_atendimento_id (atendimento_id),
  KEY ix_ato_cirurgico_paciente_id (paciente_id),
  KEY ix_ato_cirurgico_carater_cirurgia_id (carater_cirurgia_id),
  KEY ix_ato_cirurgico_tipo_anestesia_id (tipo_anestesia_id),
  KEY ix_ato_cirurgico_classe_contaminacao_cirurgica_id (classe_contaminacao_cirurgica_id),
  KEY ix_ato_cirurgico_porte_cirurgico_id (porte_cirurgico_id),
  KEY ix_ato_cirurgico_fonte_pagadora_id (fonte_pagadora_id),
  KEY ix_ato_cirurgico_plano_fonte_pagadora_id (plano_fonte_pagadora_id)
) COMMENT='Cirurgia realizada: sala, horários de entrada, incisão, fim e saída, caráter, anestesia e ligação ao agendamento';

