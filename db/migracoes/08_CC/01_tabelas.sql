CREATE TABLE achado_cirurgico_padrao (
  id             BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
  codigo         VARCHAR(30) NOT NULL,
  descricao      VARCHAR(150) NOT NULL,
  texto_sugerido TEXT NULL COMMENT 'Texto proposto ao selecionar o achado, editável pelo cirurgião',
  ativo          BOOLEAN NOT NULL DEFAULT TRUE,
  criado_em      DATETIME(3) NOT NULL,
  criado_por     BIGINT UNSIGNED NULL,
  alterado_em    DATETIME(3) NULL,
  alterado_por   BIGINT UNSIGNED NULL,
  versao         INT UNSIGNED NOT NULL DEFAULT 1,
  UNIQUE KEY uq_achado_cirurgico_padrao_codigo (codigo)
) COMMENT='Achados intraoperatórios padronizados para seleção na descrição da cirurgia';

CREATE TABLE agendamento_cirurgico (
  id                                         BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
  estabelecimento_id                         BIGINT UNSIGNED NOT NULL,
  numero                                     VARCHAR(20) NOT NULL COMMENT 'Número do agendamento, gerado por sequencia_negocio',
  paciente_id                                BIGINT UNSIGNED NOT NULL,
  atendimento_id                             BIGINT UNSIGNED NULL COMMENT 'Atendimento ou internação ao qual a cirurgia pertence',
  sala_cirurgica_id                          BIGINT UNSIGNED NULL COMMENT 'Sala reservada; obrigatória a partir do agendamento',
  cirurgiao_profissional_id                  BIGINT UNSIGNED NOT NULL,
  solicitante_profissional_id                BIGINT UNSIGNED NULL,
  especialidade_medica_id                    BIGINT UNSIGNED NULL,
  carater_cirurgia_id                        BIGINT UNSIGNED NOT NULL,
  tipo_anestesia_id                          BIGINT UNSIGNED NULL COMMENT 'Técnica anestésica prevista',
  classe_contaminacao_cirurgica_id           BIGINT UNSIGNED NULL,
  regime_paciente                            VARCHAR(30) NOT NULL DEFAULT 'internado' COMMENT 'Paciente internado ou externo (ambulatorial/dia)',
  tipo_cobertura                             VARCHAR(30) NOT NULL DEFAULT 'convenio',
  fonte_pagadora_id                          BIGINT UNSIGNED NULL,
  plano_fonte_pagadora_id                    BIGINT UNSIGNED NULL,
  senha_autorizacao                          VARCHAR(30) NULL COMMENT 'Senha de autorização da fonte pagadora',
  codigo_cid10                               VARCHAR(6) NULL COMMENT 'Código CID-10 sem ponto (o catálogo CID-10 ainda não tem tabela no modelo)',
  solicitado_em                              DATETIME(3) NOT NULL,
  inicio_previsto_em                         DATETIME(3) NULL,
  duracao_prevista_minutos                   SMALLINT UNSIGNED NULL,
  tempo_limpeza_minutos                      SMALLINT UNSIGNED NOT NULL DEFAULT 0 COMMENT 'Intervalo de limpeza e preparo da sala após a cirurgia',
  reserva_uti                                BOOLEAN NOT NULL DEFAULT FALSE COMMENT 'Exige vaga de UTI no pós-operatório',
  reserva_hemocomponente                     BOOLEAN NOT NULL DEFAULT FALSE COMMENT 'Exige reserva de sangue (itens em reserva_hemocomponente_cirurgia)',
  canal_solicitacao                          VARCHAR(30) NOT NULL DEFAULT 'interno' COMMENT 'Pedido feito no sistema interno ou pelo portal do médico',
  situacao                                   VARCHAR(30) NOT NULL DEFAULT 'solicitado',
  motivo_reprovacao_agendamento_cirurgico_id BIGINT UNSIGNED NULL,
  cancelado_em                               DATETIME(3) NULL,
  motivo_suspensao_cirurgia_id               BIGINT UNSIGNED NULL COMMENT 'Motivo do cancelamento ou da suspensão',
  observacao                                 VARCHAR(500) NULL,
  origem                                     VARCHAR(20) NOT NULL DEFAULT 'sistema',
  criado_em                                  DATETIME(3) NOT NULL,
  criado_por                                 BIGINT UNSIGNED NULL,
  alterado_em                                DATETIME(3) NULL,
  alterado_por                               BIGINT UNSIGNED NULL,
  versao                                     INT UNSIGNED NOT NULL DEFAULT 1,
  excluido_em                                DATETIME(3) NULL,
  excluido_por                               BIGINT UNSIGNED NULL,
  CONSTRAINT ck_agendamento_cirurgico_origem CHECK (origem IN ('sistema','migracao','integracao')),
  CONSTRAINT ck_agendamento_cirurgico_regime CHECK (regime_paciente IN ('internado','externo')),
  CONSTRAINT ck_agendamento_cirurgico_cobertura CHECK (tipo_cobertura IN ('convenio','particular','sus')),
  CONSTRAINT ck_agendamento_cirurgico_fonte CHECK (tipo_cobertura <> 'convenio' OR fonte_pagadora_id IS NOT NULL),
  CONSTRAINT ck_agendamento_cirurgico_situacao CHECK (situacao IN ('solicitado','em_analise','reprovado','agendado','confirmado','em_andamento','realizado','suspenso','cancelado')),
  CONSTRAINT ck_agendamento_cirurgico_sala CHECK (situacao IN ('solicitado','em_analise','reprovado','cancelado') OR (sala_cirurgica_id IS NOT NULL AND inicio_previsto_em IS NOT NULL AND duracao_prevista_minutos IS NOT NULL)),
  CONSTRAINT ck_agendamento_cirurgico_duracao CHECK (duracao_prevista_minutos IS NULL OR duracao_prevista_minutos BETWEEN 5 AND 1440),
  CONSTRAINT ck_agendamento_cirurgico_cancelamento CHECK (situacao NOT IN ('cancelado','suspenso') OR cancelado_em IS NOT NULL),
  CONSTRAINT ck_agendamento_cirurgico_reprovacao CHECK (situacao <> 'reprovado' OR motivo_reprovacao_agendamento_cirurgico_id IS NOT NULL),
  UNIQUE KEY uq_agendamento_cirurgico_numero (estabelecimento_id, numero),
  KEY ix_agendamento_cirurgico_sala_inicio (sala_cirurgica_id, inicio_previsto_em),
  KEY ix_agendamento_cirurgico_situacao (estabelecimento_id, situacao, inicio_previsto_em),
  KEY ix_agendamento_cirurgico_paciente_id (paciente_id),
  KEY ix_agendamento_cirurgico_atendimento_id (atendimento_id),
  KEY ix_agendamento_cirurgico_cirurgiao_profissional_id (cirurgiao_profissional_id),
  KEY ix_agendamento_cirurgico_solicitante_profissional_id (solicitante_profissional_id),
  KEY ix_agendamento_cirurgico_especialidade_medica_id (especialidade_medica_id),
  KEY ix_agendamento_cirurgico_carater_cirurgia_id (carater_cirurgia_id),
  KEY ix_agendamento_cirurgico_tipo_anestesia_id (tipo_anestesia_id),
  KEY ix_agendamento_cirurgico_classe_contaminacao_cirurgica_id (classe_contaminacao_cirurgica_id),
  KEY ix_agendamento_cirurgico_fonte_pagadora_id (fonte_pagadora_id),
  KEY ix_agendamento_cirurgico_plano_fonte_pagadora_id (plano_fonte_pagadora_id),
  KEY ix_agendamento_cirurgico_motivo_reprovacao_agendamento_cirurgico (motivo_reprovacao_agendamento_cirurgico_id),
  KEY ix_agendamento_cirurgico_motivo_suspensao_cirurgia_id (motivo_suspensao_cirurgia_id)
) COMMENT='Pedido e agenda da cirurgia: paciente, sala, data, duração, cirurgião, convênio, caráter, origem e situação';

