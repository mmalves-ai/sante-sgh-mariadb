CREATE TABLE credito_fatura_plano (
  id                             BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
  estabelecimento_id             BIGINT UNSIGNED NOT NULL,
  numero                         VARCHAR(30) NOT NULL COMMENT 'Número de negócio do crédito (sequencia_negocio)',
  contrato_plano_id              BIGINT UNSIGNED NOT NULL,
  fatura_origem_fatura_plano_id  BIGINT UNSIGNED NULL COMMENT 'Fatura que originou o crédito (pagamento a maior, cancelamento)',
  tipo_credito                   VARCHAR(30) NOT NULL,
  data_credito                   DATE NOT NULL,
  valor                          DECIMAL(15,2) NOT NULL,
  saldo                          DECIMAL(15,2) NOT NULL COMMENT 'Valor ainda não abatido; atualizado pelas baixas',
  lancamento_manual              BOOLEAN NOT NULL DEFAULT FALSE COMMENT 'Crédito lançado à mão (e não gerado por rotina)',
  motivo                         VARCHAR(500) NULL,
  situacao                       VARCHAR(30) NOT NULL DEFAULT 'aberto',
  arquivo_id                     BIGINT UNSIGNED NULL COMMENT 'Comprovante anexado',
  origem                         VARCHAR(20) NOT NULL DEFAULT 'sistema',
  criado_em                      DATETIME(3) NOT NULL,
  criado_por                     BIGINT UNSIGNED NULL,
  alterado_em                    DATETIME(3) NULL,
  alterado_por                   BIGINT UNSIGNED NULL,
  versao                         INT UNSIGNED NOT NULL DEFAULT 1,
  excluido_em                    DATETIME(3) NULL,
  excluido_por                   BIGINT UNSIGNED NULL,
  CONSTRAINT ck_credito_fatura_plano_tipo_credito CHECK (tipo_credito IN ('pagamento_a_maior','devolucao','ajuste','cancelamento_fatura','bonificacao','outro')),
  CONSTRAINT ck_credito_fatura_plano_valor CHECK (valor > 0),
  CONSTRAINT ck_credito_fatura_plano_saldo CHECK (saldo >= 0 AND saldo <= valor),
  CONSTRAINT ck_credito_fatura_plano_situacao CHECK (situacao IN ('aberto','parcialmente_utilizado','utilizado','estornado','cancelado')),
  UNIQUE KEY uq_credito_fatura_plano_estabelecimento_id_numero (estabelecimento_id, numero),
  CONSTRAINT ck_credito_fatura_plano_origem CHECK (origem IN ('sistema','migracao','integracao')),
  KEY ix_credito_fatura_plano_contrato_plano_id (contrato_plano_id),
  KEY ix_credito_fatura_plano_fatura_origem_fatura_plano_id (fatura_origem_fatura_plano_id),
  KEY ix_credito_fatura_plano_arquivo_id (arquivo_id)
) COMMENT='Crédito do contratante na operadora (pagamento a maior, devolução, ajuste) com saldo a abater em faturas futuras';

