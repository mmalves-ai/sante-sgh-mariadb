CREATE TABLE tipo_lancamento_fatura (
  id                BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
  codigo            VARCHAR(30) NOT NULL,
  descricao         VARCHAR(150) NOT NULL,
  natureza          VARCHAR(30) NOT NULL COMMENT 'Efeito no valor da fatura: debito soma, credito abate',
  categoria         VARCHAR(30) NOT NULL DEFAULT 'outro',
  informa_quantidade BOOLEAN NOT NULL DEFAULT FALSE COMMENT 'O lançamento pede quantidade além do valor',
  lancamento_automatico_individual BOOLEAN NOT NULL DEFAULT FALSE COMMENT 'Lançado automaticamente no faturamento de contrato individual/familiar',
  lancamento_automatico_empresarial BOOLEAN NOT NULL DEFAULT FALSE COMMENT 'Lançado automaticamente no faturamento de contrato empresarial',
  lancamento_automatico_adesao BOOLEAN NOT NULL DEFAULT FALSE COMMENT 'Lançado automaticamente no faturamento de contrato coletivo por adesão',
  calcula_por_segmentacao BOOLEAN NOT NULL DEFAULT FALSE COMMENT 'Valor varia pela segmentação assistencial do plano',
  aplica_pro_rata   BOOLEAN NOT NULL DEFAULT FALSE COMMENT 'Valor proporcional aos dias de vigência no mês',
  pro_rata_tipo_lancamento_fatura_id BIGINT UNSIGNED NULL COMMENT 'Tipo usado para lançar a parcela proporcional',
  desconto_tipo_lancamento_fatura_id BIGINT UNSIGNED NULL COMMENT 'Tipo usado para lançar o desconto vinculado',
  retroativo_tipo_lancamento_fatura_id BIGINT UNSIGNED NULL COMMENT 'Tipo usado para lançar diferença retroativa',
  permite_lancamento_manual BOOLEAN NOT NULL DEFAULT TRUE,
  gera_titulo_receber BOOLEAN NOT NULL DEFAULT TRUE COMMENT 'Evento gerador de título no contas a receber',
  contabiliza       BOOLEAN NOT NULL DEFAULT TRUE,
  ignora_validacao_contabil BOOLEAN NOT NULL DEFAULT FALSE,
  conta_contabil_id BIGINT UNSIGNED NULL,
  grupo_faturamento_id BIGINT UNSIGNED NULL COMMENT 'Grupo para a nota fiscal de serviço',
  segrega_ato_cooperativo BOOLEAN NOT NULL DEFAULT FALSE COMMENT 'Separa ato cooperativo e não cooperativo na receita',
  incide_pis        BOOLEAN NOT NULL DEFAULT FALSE,
  incide_cofins     BOOLEAN NOT NULL DEFAULT FALSE,
  situacao_tributaria_pis VARCHAR(5) NULL COMMENT 'Código de situação tributária do PIS',
  situacao_tributaria_cofins VARCHAR(5) NULL COMMENT 'Código de situação tributária do COFINS',
  codigo_intercambio VARCHAR(10) NULL COMMENT 'Código do lançamento na tabela do intercâmbio nacional',
  tipo_receita      VARCHAR(10) NULL COMMENT 'Classificação da receita no envio regulatório',
  visivel_portal    BOOLEAN NOT NULL DEFAULT TRUE COMMENT 'Aparece no demonstrativo do portal do beneficiário',
  ativo             BOOLEAN NOT NULL DEFAULT TRUE,
  inativado_em      DATETIME(3) NULL,
  criado_em         DATETIME(3) NOT NULL,
  criado_por        BIGINT UNSIGNED NULL,
  alterado_em       DATETIME(3) NULL,
  alterado_por      BIGINT UNSIGNED NULL,
  versao            INT UNSIGNED NOT NULL DEFAULT 1,
  UNIQUE KEY uq_tipo_lancamento_fatura_codigo (codigo),
  CONSTRAINT ck_tipo_lancamento_fatura_natureza CHECK (natureza IN ('debito','credito')),
  CONSTRAINT ck_tipo_lancamento_fatura_categoria CHECK (categoria IN ('mensalidade','coparticipacao','taxa_adesao','taxa_administrativa','adicional','franquia','desconto','acrescimo','juros','multa','reembolso','outro')),
  KEY ix_tipo_lancamento_fatura_pro_rata (pro_rata_tipo_lancamento_fatura_id),
  KEY ix_tipo_lancamento_fatura_desconto (desconto_tipo_lancamento_fatura_id),
  KEY ix_tipo_lancamento_fatura_retroativo (retroativo_tipo_lancamento_fatura_id),
  KEY ix_tipo_lancamento_fatura_conta_contabil (conta_contabil_id),
  KEY ix_tipo_lancamento_fatura_grupo_faturamento (grupo_faturamento_id)
) COMMENT='Tipos de lançamento e de evento gerador de valor a receber na fatura';

CREATE TABLE tipo_lancamento_fatura_vigencia (
  id                BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
  tipo_lancamento_fatura_id BIGINT UNSIGNED NOT NULL,
  vigencia_inicio   DATE NOT NULL,
  vigencia_fim      DATE NULL,
  valor             DECIMAL(15,2) NULL COMMENT 'Valor padrão na vigência',
  percentual        DECIMAL(7,4) NULL COMMENT 'Percentual padrão na vigência',
  aplica_pro_rata   BOOLEAN NOT NULL DEFAULT FALSE,
  operacao          VARCHAR(30) NOT NULL DEFAULT 'inclusao',
  dados             JSON NULL COMMENT 'Fotografia do registro na operação',
  ocorrido_em       DATETIME(3) NOT NULL,
  usuario_id        BIGINT UNSIGNED NULL,
  criado_em         DATETIME(3) NOT NULL,
  criado_por        BIGINT UNSIGNED NULL,
  alterado_em       DATETIME(3) NULL,
  alterado_por      BIGINT UNSIGNED NULL,
  versao            INT UNSIGNED NOT NULL DEFAULT 1,
  CONSTRAINT ck_tipo_lancamento_fatura_vigencia_operacao CHECK (operacao IN ('inclusao','alteracao','exclusao')),
  CONSTRAINT ck_tipo_lancamento_fatura_vigencia_periodo CHECK (vigencia_fim IS NULL OR vigencia_fim >= vigencia_inicio),
  CONSTRAINT ck_tipo_lancamento_fatura_vigencia_valor CHECK ((valor IS NULL OR valor >= 0) AND (percentual IS NULL OR percentual BETWEEN 0 AND 100)),
  KEY ix_tipo_lancamento_fatura_vigencia_tipo (tipo_lancamento_fatura_id, vigencia_inicio),
  KEY ix_tipo_lancamento_fatura_vigencia_usuario (usuario_id)
