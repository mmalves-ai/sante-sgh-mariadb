  KEY ix_token_atendimento_beneficiario_estabelecimento (estabelecimento_id, gerado_em),
  KEY ix_token_atendimento_beneficiario_prestador (prestador_rede_id),
  KEY ix_token_atendimento_beneficiario_guia (guia_tiss_id)
) COMMENT='Código de uso único gerado pelo beneficiário para confirmar presença no prestador, com validade e uso';

