CREATE TABLE fatura_plano (
  id                                 BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
  estabelecimento_id                 BIGINT UNSIGNED NOT NULL,
  numero                             VARCHAR(30) NOT NULL COMMENT 'Número de negócio da fatura (sequencia_negocio)',
  contrato_plano_id                  BIGINT UNSIGNED NOT NULL,
  responsavel_beneficiario_plano_id  BIGINT UNSIGNED NULL COMMENT 'Beneficiário pagador quando a cobrança é individual; nulo quando o pagador é o contratante',
  lote_faturamento_plano_id          BIGINT UNSIGNED NULL COMMENT 'Lote de geração que criou a fatura; nulo para fatura avulsa',
  fatura_origem_id                   BIGINT UNSIGNED NULL COMMENT 'Fatura original, quando esta é complementar, repactuação ou substituta',
  tipo_fatura                        VARCHAR(30) NOT NULL DEFAULT 'mensalidade',
  competencia                        DATE NOT NULL COMMENT 'Primeiro dia do mês de competência',
  competencia_fim                    DATE NULL COMMENT 'Último mês coberto, quando a fatura cobre mais de uma competência',
  parcela                            SMALLINT UNSIGNED NULL COMMENT 'Número da parcela, quando a fatura é parcelada ou de carnê',
  data_emissao                       DATE NOT NULL,
  data_vencimento                    DATE NOT NULL,
  data_vencimento_original           DATE NULL COMMENT 'Vencimento antes de prorrogação',
  cobertura_inicio                   DATE NULL COMMENT 'Início do período de cobertura cobrado',
  cobertura_fim                      DATE NULL,
  data_base_comissao                 DATE NULL COMMENT 'Data que serve de base para o cálculo da comissão de venda',
  forma_cobranca_plano_id            BIGINT UNSIGNED NOT NULL,
  forma_emissao_documento_id         BIGINT UNSIGNED NULL,
  conta_bancaria_id                  BIGINT UNSIGNED NULL COMMENT 'Conta de cobrança (cedente) do boleto ou débito',
  nosso_numero                       VARCHAR(30) NULL COMMENT 'Identificador do título no banco cobrador',
  valor_bruto                        DECIMAL(15,2) NOT NULL DEFAULT 0 COMMENT 'Soma dos itens a débito',
  valor_desconto                     DECIMAL(15,2) NOT NULL DEFAULT 0,
  valor_acrescimo                    DECIMAL(15,2) NOT NULL DEFAULT 0,
  valor_abatimento                   DECIMAL(15,2) NOT NULL DEFAULT 0,
  valor_tributo                      DECIMAL(15,2) NOT NULL DEFAULT 0 COMMENT 'Tributos destacados ou retidos na fatura',
  valor_tarifa                       DECIMAL(15,2) NOT NULL DEFAULT 0 COMMENT 'Tarifas e custas bancárias repassadas',
  valor_total                        DECIMAL(15,2) NOT NULL DEFAULT 0 COMMENT 'Valor a pagar',
  percentual_multa                   DECIMAL(7,4) NULL,
  percentual_juros_mes               DECIMAL(7,4) NULL,
  valor_pago                         DECIMAL(15,2) NULL,
  data_pagamento                     DATE NULL,
  data_credito                       DATE NULL,
  situacao                           VARCHAR(30) NOT NULL DEFAULT 'aberta',
  titulo_receber_id                  BIGINT UNSIGNED NULL COMMENT 'Título gerado no financeiro',
  cancelada_em                       DATETIME(3) NULL,
  cancelada_por_usuario_id           BIGINT UNSIGNED NULL,
  motivo_ajuste_fatura_id            BIGINT UNSIGNED NULL COMMENT 'Motivo do cancelamento ou ajuste',
  contabilizada_em                   DATETIME(3) NULL,
  observacao                         VARCHAR(2000) NULL,
  origem                             VARCHAR(20) NOT NULL DEFAULT 'sistema',
  criado_em                          DATETIME(3) NOT NULL,
  criado_por                         BIGINT UNSIGNED NULL,
  alterado_em                        DATETIME(3) NULL,
  alterado_por                       BIGINT UNSIGNED NULL,
  versao                             INT UNSIGNED NOT NULL DEFAULT 1,
  excluido_em                        DATETIME(3) NULL,
  excluido_por                       BIGINT UNSIGNED NULL,
  CONSTRAINT ck_fatura_plano_origem CHECK (origem IN ('sistema','migracao','integracao')),
  UNIQUE KEY uq_fatura_plano_estabelecimento_id_numero (estabelecimento_id, numero),
  KEY ix_fatura_plano_contrato_plano_id_competencia (contrato_plano_id, competencia),
  KEY ix_fatura_plano_situacao_data_vencimento (situacao, data_vencimento),
  CONSTRAINT ck_fatura_plano_tipo_fatura CHECK (tipo_fatura IN ('mensalidade','coparticipacao','avulsa','adesao','pro_rata','complementar','repactuacao')),
  CONSTRAINT ck_fatura_plano_situacao CHECK (situacao IN ('aberta','emitida','paga','paga_parcial','cancelada','renegociada')),
  CONSTRAINT ck_fatura_plano_vencimento CHECK (data_vencimento >= data_emissao),
  CONSTRAINT ck_fatura_plano_cobertura CHECK (cobertura_fim IS NULL OR cobertura_fim >= cobertura_inicio),
  CONSTRAINT ck_fatura_plano_competencia_fim CHECK (competencia_fim IS NULL OR competencia_fim >= competencia),
  CONSTRAINT ck_fatura_plano_valores CHECK (valor_bruto >= 0 AND valor_desconto >= 0 AND valor_acrescimo >= 0 AND valor_abatimento >= 0 AND valor_tributo >= 0 AND valor_tarifa >= 0 AND valor_total >= 0 AND (valor_pago IS NULL OR valor_pago >= 0)),
  CONSTRAINT ck_fatura_plano_cancelamento CHECK ((situacao = 'cancelada') = (cancelada_em IS NOT NULL)),
  CONSTRAINT ck_fatura_plano_pagamento CHECK (valor_pago IS NULL OR data_pagamento IS NOT NULL),
  KEY ix_fatura_plano_responsavel_beneficiario_plano_id (responsavel_beneficiario_plano_id),
  KEY ix_fatura_plano_lote_faturamento_plano_id (lote_faturamento_plano_id),
  KEY ix_fatura_plano_fatura_origem_id (fatura_origem_id),
  KEY ix_fatura_plano_forma_cobranca_plano_id (forma_cobranca_plano_id),
  KEY ix_fatura_plano_forma_emissao_documento_id (forma_emissao_documento_id),
  KEY ix_fatura_plano_conta_bancaria_id (conta_bancaria_id),
  KEY ix_fatura_plano_titulo_receber_id (titulo_receber_id),
  KEY ix_fatura_plano_cancelada_por_usuario_id (cancelada_por_usuario_id),
  KEY ix_fatura_plano_motivo_ajuste_fatura_id (motivo_ajuste_fatura_id)
) COMMENT='Fatura da competência por contrato ou responsável financeiro; gera o título a receber do financeiro';

