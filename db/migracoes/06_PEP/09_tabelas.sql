  arredondar                    BOOLEAN NOT NULL DEFAULT FALSE COMMENT 'Arredondar a velocidade para a bomba de infusão',
  inicio_em                     DATETIME(3) NOT NULL COMMENT 'Início da vigência da nova velocidade',
  fim_em                        DATETIME(3) NULL,
  tipo_registro                 VARCHAR(20) NOT NULL DEFAULT 'prescricao',
  profissional_id               BIGINT UNSIGNED NOT NULL COMMENT 'Quem alterou a velocidade',
  justificativa                 VARCHAR(1000) NULL,
  criado_em                     DATETIME(3) NOT NULL,
  criado_por                    BIGINT UNSIGNED NULL,
  alterado_em                   DATETIME(3) NULL,
  alterado_por                  BIGINT UNSIGNED NULL,
  versao                        INT UNSIGNED NOT NULL DEFAULT 1,
  CONSTRAINT ck_prescricao_item_velocidade_operacao CHECK (operacao IN ('inclusao','alteracao','exclusao')),
  CONSTRAINT ck_prescricao_item_velocidade_tipo_registro CHECK (tipo_registro IN ('prescricao','titulacao','enfermagem')),
  CONSTRAINT ck_prescricao_item_velocidade_valor CHECK (velocidade >= 0 AND (volume_ml IS NULL OR volume_ml > 0)),
  CONSTRAINT ck_prescricao_item_velocidade_periodo CHECK (fim_em IS NULL OR fim_em >= inicio_em),
  KEY ix_prescricao_item_velocidade_solucao (prescricao_item_solucao_id, inicio_em),
  KEY ix_prescricao_item_velocidade_usuario (usuario_id),
  KEY ix_prescricao_item_velocidade_unidade_infusao (unidade_infusao_id),
  KEY ix_prescricao_item_velocidade_profissional (profissional_id)
) COMMENT='Mudanças de velocidade de infusão de uma solução durante a vigência';

CREATE TABLE prescricao_item_ventilacao (
