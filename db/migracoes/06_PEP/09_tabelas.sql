  CONSTRAINT ck_problema_paciente_periodo CHECK (resolvido_em IS NULL OR inicio_em IS NULL OR resolvido_em >= inicio_em),
  CONSTRAINT ck_problema_paciente_resolvido CHECK (situacao <> 'resolvido' OR resolvido_em IS NOT NULL),
  CONSTRAINT ck_problema_paciente_inativacao CHECK (situacao NOT IN ('inativo','refutado') OR (inativado_em IS NOT NULL AND justificativa_inativacao IS NOT NULL)),
