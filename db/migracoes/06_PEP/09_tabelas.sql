CREATE TABLE problema_paciente (
  id                            BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
  estabelecimento_id            BIGINT UNSIGNED NOT NULL COMMENT 'Onde o problema foi registrado; a lista vale para o paciente no cliente inteiro',
  paciente_id                   BIGINT UNSIGNED NOT NULL,
  atendimento_id                BIGINT UNSIGNED NULL,
  tipo                          VARCHAR(30) NOT NULL DEFAULT 'problema',
  descricao                     VARCHAR(500) NOT NULL,
  cid_termo_terminologia_id     BIGINT UNSIGNED NULL COMMENT 'CID-10',
  ciap_termo_terminologia_id    BIGINT UNSIGNED NULL COMMENT 'CIAP-2',
