  volume_corrente_ml            DECIMAL(7,1) NULL,
  pressao_controlada_cmh2o      DECIMAL(5,1) NULL,
  pressao_suporte_cmh2o         DECIMAL(5,1) NULL,
  pressao_inspiratoria_cmh2o    DECIMAL(5,1) NULL COMMENT 'IPAP na ventilação não invasiva',
