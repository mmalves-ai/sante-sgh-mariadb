  CONSTRAINT ck_prescricao_item_ventilacao_modalidade CHECK (modalidade IN ('invasiva','nao_invasiva','oxigenoterapia','alto_fluxo')),
  CONSTRAINT ck_prescricao_item_ventilacao_modo CHECK (modalidade IN ('oxigenoterapia','alto_fluxo') OR modo_ventilatorio_id IS NOT NULL),
  CONSTRAINT ck_prescricao_item_ventilacao_fio2 CHECK (fracao_inspirada_oxigenio IS NULL OR fracao_inspirada_oxigenio BETWEEN 21 AND 100),
  CONSTRAINT ck_prescricao_item_ventilacao_faixas CHECK ((frequencia_respiratoria IS NULL OR frequencia_respiratoria <= 150) AND (peep_cmh2o IS NULL OR peep_cmh2o BETWEEN 0 AND 50)),
  UNIQUE KEY uq_prescricao_item_ventilacao_item_sequencia (prescricao_item_id, sequencia),
  KEY ix_prescricao_item_ventilacao_via_aerea (via_aerea_id),
  KEY ix_prescricao_item_ventilacao_modo (modo_ventilatorio_id)
) COMMENT='Suporte ventilatório prescrito (invasivo, não invasivo, oxigênio), com modo e parâmetros';

