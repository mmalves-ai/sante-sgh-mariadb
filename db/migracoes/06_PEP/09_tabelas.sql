CREATE TABLE prescricao_item_solucao_etapa (
  id                            BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
  prescricao_item_solucao_id    BIGINT UNSIGNED NOT NULL COMMENT 'Solução prescrita a que o componente pertence',
  sequencia                     SMALLINT UNSIGNED NOT NULL,
  etapa                         SMALLINT UNSIGNED NOT NULL COMMENT 'Número da etapa ou fase do esquema (esquema alternado)',
  item_prescritivel_id          BIGINT UNSIGNED NULL COMMENT 'Componente padronizado',
  item_nao_padronizado_id       BIGINT UNSIGNED NULL COMMENT 'Componente fora da padronização',
  justificativa_nao_padronizado VARCHAR(200) NULL,
  indicacao_termo_terminologia_id BIGINT UNSIGNED NULL COMMENT 'CID que justifica o item não padronizado',
  componente_principal          BOOLEAN NOT NULL DEFAULT FALSE COMMENT 'Verdadeiro para o componente base da solução (ex.: soro)',
  quantidade                    DECIMAL(15,4) NULL COMMENT 'Quantidade a dispensar do componente na etapa',
  dose                          DECIMAL(15,4) NOT NULL COMMENT 'Dose do componente na etapa',
  unidade_prescricao_id         BIGINT UNSIGNED NOT NULL,
  formula_calculo_dose_id       BIGINT UNSIGNED NULL COMMENT 'Fórmula usada para chegar à dose',
  kit_prescricao_id             BIGINT UNSIGNED NULL COMMENT 'Kit de solução de onde o componente veio',
  volume_ml                     DECIMAL(15,4) NULL COMMENT 'Volume da etapa em mililitros',
  inicio_previsto_em            DATETIME(3) NULL,
  dose_extra_antimicrobiano     BOOLEAN NOT NULL DEFAULT FALSE,
  justificativa_item_alergico   VARCHAR(255) NULL COMMENT 'Justificativa do prescritor ao manter item com alerta de alergia',
  observacao_enfermagem         VARCHAR(1000) NULL,
  origem                        VARCHAR(20) NOT NULL DEFAULT 'sistema',
  criado_em                     DATETIME(3) NOT NULL,
  criado_por                    BIGINT UNSIGNED NULL,
  alterado_em                   DATETIME(3) NULL,
  alterado_por                  BIGINT UNSIGNED NULL,
  versao                        INT UNSIGNED NOT NULL DEFAULT 1,
  excluido_em                   DATETIME(3) NULL,
  excluido_por                  BIGINT UNSIGNED NULL,
  CONSTRAINT ck_prescricao_item_solucao_etapa_origem CHECK (origem IN ('sistema','migracao','integracao')),
  CONSTRAINT ck_prescricao_item_solucao_etapa_item CHECK ((item_prescritivel_id IS NOT NULL) + (item_nao_padronizado_id IS NOT NULL) = 1),
  CONSTRAINT ck_prescricao_item_solucao_etapa_nao_padronizado CHECK (item_nao_padronizado_id IS NULL OR justificativa_nao_padronizado IS NOT NULL),
  CONSTRAINT ck_prescricao_item_solucao_etapa_etapa CHECK (etapa >= 1),
  CONSTRAINT ck_prescricao_item_solucao_etapa_dose CHECK (dose > 0 AND (quantidade IS NULL OR quantidade > 0) AND (volume_ml IS NULL OR volume_ml > 0)),
  UNIQUE KEY uq_prescricao_item_solucao_etapa_solucao_sequencia (prescricao_item_solucao_id, sequencia),
  KEY ix_prescricao_item_solucao_etapa_solucao_etapa (prescricao_item_solucao_id, etapa),
  KEY ix_prescricao_item_solucao_etapa_item_prescritivel (item_prescritivel_id),
  KEY ix_prescricao_item_solucao_etapa_item_nao_padronizado (item_nao_padronizado_id),
  KEY ix_prescricao_item_solucao_etapa_indicacao (indicacao_termo_terminologia_id),
  KEY ix_prescricao_item_solucao_etapa_unidade_prescricao (unidade_prescricao_id),
  KEY ix_prescricao_item_solucao_etapa_formula (formula_calculo_dose_id),
  KEY ix_prescricao_item_solucao_etapa_kit (kit_prescricao_id)
) COMMENT='Etapa ou fase do esquema de uma solução, com volume, horário e velocidade';

