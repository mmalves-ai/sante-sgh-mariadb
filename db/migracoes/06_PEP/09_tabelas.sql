  KEY ix_problema_paciente_estabelecimento (estabelecimento_id),
  KEY ix_problema_paciente_atendimento (atendimento_id),
  KEY ix_problema_paciente_cid (cid_termo_terminologia_id),
  KEY ix_problema_paciente_ciap (ciap_termo_terminologia_id),
  KEY ix_problema_paciente_snomed (snomed_termo_terminologia_id),
  KEY ix_problema_paciente_certeza (certeza_diagnostico_id),
  KEY ix_problema_paciente_presenca_admissao (presenca_admissao_id),
  KEY ix_problema_paciente_registrado_por (registrado_por_profissional_id),
