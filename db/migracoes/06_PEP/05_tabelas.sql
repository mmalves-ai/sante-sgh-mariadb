CREATE TABLE frequencia_horario_relativo (
  id                           BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
  frequencia_administracao_id  BIGINT UNSIGNED NOT NULL,
  sequencia                    SMALLINT UNSIGNED NOT NULL,
  descricao                    VARCHAR(60) NOT NULL COMMENT 'Ex.: em jejum, antes do almoço, ao deitar',
  horario_referencia           TIME NOT NULL COMMENT 'Hora usada no aprazamento quando o horário é relativo',
  ativo                        BOOLEAN NOT NULL DEFAULT TRUE,
  origem                       VARCHAR(20) NOT NULL DEFAULT 'sistema',
  criado_em                    DATETIME(3) NOT NULL,
  criado_por                   BIGINT UNSIGNED NULL,
  alterado_em                  DATETIME(3) NULL,
  alterado_por                 BIGINT UNSIGNED NULL,
  versao                       INT UNSIGNED NOT NULL DEFAULT 1,
  excluido_em                  DATETIME(3) NULL,
  excluido_por                 BIGINT UNSIGNED NULL,
  CONSTRAINT ck_frequencia_horario_relativo_origem CHECK (origem IN ('sistema','migracao','integracao')),
  CONSTRAINT ck_frequencia_horario_relativo_descricao CHECK (CHAR_LENGTH(TRIM(descricao)) > 0),
  UNIQUE KEY uq_frequencia_horario_relativo_frequencia_sequencia (frequencia_administracao_id, sequencia),
  UNIQUE KEY uq_frequencia_horario_relativo_frequencia_descricao (frequencia_administracao_id, descricao)
) COMMENT='Horários relativos de uma frequência (em jejum, antes do almoço, ao deitar)';

