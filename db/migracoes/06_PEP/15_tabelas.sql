-- PEP, lote 15 (F2.2 onda 3; pedidos do lote 03-04: terapia nutricional e serviço social). Convenções do ADR 0002 (parte 2). Só para frente.
-- Sem FOREIGN KEY aqui (15_chaves.sql).

CREATE TABLE acompanhamento_terapia_nutricional (
  id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
  terapia_nutricional_id BIGINT UNSIGNED NOT NULL,
  data_referencia DATE NOT NULL,
  volume_prescrito_ml DECIMAL(15,4) NULL,
  volume_infundido_ml DECIMAL(15,4) NOT NULL,
  origem_volume VARCHAR(20) NOT NULL COMMENT 'checagem, balanco ou informado',
  calorias_atingidas_kcal DECIMAL(15,4) NOT NULL,
  proteina_atingida_g DECIMAL(15,4) NOT NULL,
  percentual_calorico DECIMAL(7,4) NOT NULL COMMENT 'Percentual da meta calórica atingido',
  percentual_proteico DECIMAL(7,4) NOT NULL COMMENT 'Percentual da meta proteica atingido',
  motivo_meta_nao_atingida VARCHAR(40) NULL,
  observacao VARCHAR(2000) NULL,
  profissional_id BIGINT UNSIGNED NOT NULL,
  situacao VARCHAR(20) NOT NULL DEFAULT 'ativo',
  substitui_id BIGINT UNSIGNED NULL COMMENT 'Acompanhamento que este retifica',
  motivo_correcao VARCHAR(500) NULL,
  dia_vigente DATE AS (IF(situacao = 'ativo' AND excluido_em IS NULL, data_referencia, NULL)) PERSISTENT COMMENT 'Um acompanhamento vigente por terapia e dia',
  origem VARCHAR(20) NOT NULL DEFAULT 'sistema',
  excluido_em DATETIME(3) NULL,
  excluido_por BIGINT UNSIGNED NULL,
  criado_em DATETIME(3) NOT NULL,
  criado_por BIGINT UNSIGNED NULL,
  alterado_em DATETIME(3) NULL,
  alterado_por BIGINT UNSIGNED NULL,
  versao INT UNSIGNED NOT NULL DEFAULT 1,
  CONSTRAINT ck_acompanhamento_terapia_nutricional_origem CHECK (origem IN ('sistema','migracao','integracao')),
  CONSTRAINT ck_acompanhamento_terapia_nutricional_origem_volume CHECK (origem_volume IN ('checagem','balanco','informado')),
  CONSTRAINT ck_acompanhamento_terapia_nutricional_situacao CHECK (situacao IN ('ativo','retificado','estornado')),
  CONSTRAINT ck_acompanhamento_terapia_nutricional_valores CHECK (volume_infundido_ml >= 0 AND calorias_atingidas_kcal >= 0 AND proteina_atingida_g >= 0 AND percentual_calorico >= 0 AND percentual_proteico >= 0),
  CONSTRAINT ck_acompanhamento_terapia_nutricional_correcao CHECK (substitui_id IS NULL OR motivo_correcao IS NOT NULL),
  UNIQUE KEY uq_acompanhamento_terapia_nutricional_dia (terapia_nutricional_id, dia_vigente),
  KEY ix_acompanhamento_terapia_nutricional_profissional_id (profissional_id),
  KEY ix_acompanhamento_terapia_nutricional_substitui_id (substitui_id)
) COMMENT='Acompanhamento diário da meta da terapia nutricional: volume infundido e percentual calórico e proteico atingido';

CREATE TABLE registro_social (
  id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
  estabelecimento_id BIGINT UNSIGNED NOT NULL,
  internacao_id BIGINT UNSIGNED NOT NULL,
  paciente_id BIGINT UNSIGNED NOT NULL,
  tipo VARCHAR(20) NOT NULL COMMENT 'avaliacao, evolucao ou adendo',
  rede_apoio VARCHAR(30) NOT NULL COMMENT 'Situação da rede de apoio do paciente',
  vulnerabilidades JSON NOT NULL COMMENT 'Lista de códigos de vulnerabilidade social',
  risco VARCHAR(20) NOT NULL COMMENT 'Risco social avaliado',
  encaminhamentos JSON NOT NULL COMMENT 'Lista de códigos de encaminhamento',
  parecer TEXT NOT NULL,
  orientacoes VARCHAR(2000) NULL,
  barreira_alta_id BIGINT UNSIGNED NULL COMMENT 'Barreira de alta social aberta pelo registro',
  adendo_registro_social_id BIGINT UNSIGNED NULL COMMENT 'Registro a que este adendo se refere',
  motivo_adendo VARCHAR(500) NULL,
  profissional_id BIGINT UNSIGNED NOT NULL,
  situacao VARCHAR(20) NOT NULL DEFAULT 'ativo',
  origem VARCHAR(20) NOT NULL DEFAULT 'sistema',
  excluido_em DATETIME(3) NULL,
  excluido_por BIGINT UNSIGNED NULL,
  criado_em DATETIME(3) NOT NULL,
  criado_por BIGINT UNSIGNED NULL,
  alterado_em DATETIME(3) NULL,
  alterado_por BIGINT UNSIGNED NULL,
  versao INT UNSIGNED NOT NULL DEFAULT 1,
  CONSTRAINT ck_registro_social_origem CHECK (origem IN ('sistema','migracao','integracao')),
  CONSTRAINT ck_registro_social_tipo CHECK (tipo IN ('avaliacao','evolucao','adendo')),
  CONSTRAINT ck_registro_social_situacao CHECK (situacao IN ('ativo','retificado','estornado','encerrado')),
  CONSTRAINT ck_registro_social_adendo CHECK (tipo <> 'adendo' OR (adendo_registro_social_id IS NOT NULL AND motivo_adendo IS NOT NULL)),
  KEY ix_registro_social_internacao_id (internacao_id),
  KEY ix_registro_social_paciente_id (paciente_id),
  KEY ix_registro_social_estabelecimento_id (estabelecimento_id),
  KEY ix_registro_social_barreira_alta_id (barreira_alta_id),
  KEY ix_registro_social_adendo_registro_social_id (adendo_registro_social_id),
  KEY ix_registro_social_profissional_id (profissional_id)
) COMMENT='Avaliação, evolução e adendo do serviço social na internação: rede de apoio, vulnerabilidades, risco, encaminhamentos e parecer';

CREATE TABLE correcao_registro_nutricao (
  id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
  estabelecimento_id BIGINT UNSIGNED NOT NULL,
  internacao_id BIGINT UNSIGNED NOT NULL,
  tipo_registro VARCHAR(20) NOT NULL COMMENT 'triagem, meta, acompanhamento ou social',
  registro_id BIGINT UNSIGNED NOT NULL COMMENT 'Registro corrigido, na tabela do tipo_registro',
  acao VARCHAR(20) NOT NULL COMMENT 'retificacao, estorno, nova_versao ou encerramento',
  novo_registro_id BIGINT UNSIGNED NULL COMMENT 'Registro que substitui o corrigido, na tabela do tipo_registro',
  motivo VARCHAR(500) NOT NULL,
  profissional_id BIGINT UNSIGNED NOT NULL,
  criado_em DATETIME(3) NOT NULL,
  criado_por BIGINT UNSIGNED NULL,
  alterado_em DATETIME(3) NULL,
  alterado_por BIGINT UNSIGNED NULL,
  versao INT UNSIGNED NOT NULL DEFAULT 1,
  CONSTRAINT ck_correcao_registro_nutricao_tipo CHECK (tipo_registro IN ('triagem','meta','acompanhamento','social')),
  CONSTRAINT ck_correcao_registro_nutricao_acao CHECK (acao IN ('retificacao','estorno','nova_versao','encerramento')),
  CONSTRAINT ck_correcao_registro_nutricao_novo CHECK (acao NOT IN ('retificacao','nova_versao') OR novo_registro_id IS NOT NULL),
  KEY ix_correcao_registro_nutricao_registro (tipo_registro, registro_id),
  KEY ix_correcao_registro_nutricao_internacao_id (internacao_id),
  KEY ix_correcao_registro_nutricao_estabelecimento_id (estabelecimento_id),
  KEY ix_correcao_registro_nutricao_profissional_id (profissional_id)
) COMMENT='Histórico de retificação, estorno, nova versão e encerramento dos registros da nutrição e do serviço social';

CREATE TABLE avaliacao_nutricao_parenteral (
  id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
  terapia_nutricional_id BIGINT UNSIGNED NOT NULL,
  parecer VARCHAR(20) NOT NULL COMMENT 'Parecer farmacêutico da formulação',
  acesso VARCHAR(20) NOT NULL COMMENT 'Via de acesso avaliada (central ou periférica)',
  osmolaridade_mosm_l DECIMAL(15,4) NOT NULL,
  estavel BOOLEAN NOT NULL DEFAULT FALSE,
  compativel BOOLEAN NOT NULL DEFAULT FALSE,
  observacao VARCHAR(2000) NULL,
  profissional_id BIGINT UNSIGNED NOT NULL,
  origem VARCHAR(20) NOT NULL DEFAULT 'sistema',
  excluido_em DATETIME(3) NULL,
  excluido_por BIGINT UNSIGNED NULL,
  criado_em DATETIME(3) NOT NULL,
  criado_por BIGINT UNSIGNED NULL,
  alterado_em DATETIME(3) NULL,
  alterado_por BIGINT UNSIGNED NULL,
  versao INT UNSIGNED NOT NULL DEFAULT 1,
  CONSTRAINT ck_avaliacao_nutricao_parenteral_origem CHECK (origem IN ('sistema','migracao','integracao')),
  CONSTRAINT ck_avaliacao_nutricao_parenteral_osmolaridade CHECK (osmolaridade_mosm_l > 0),
  UNIQUE KEY uq_avaliacao_nutricao_parenteral_terapia (terapia_nutricional_id),
  KEY ix_avaliacao_nutricao_parenteral_profissional_id (profissional_id)
) COMMENT='Avaliação farmacêutica da nutrição parenteral: parecer, acesso, osmolaridade, estabilidade e compatibilidade';
