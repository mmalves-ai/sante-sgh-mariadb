CREATE TABLE recurso_previsto_urgencia (
  id                    BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
  codigo                VARCHAR(30) NOT NULL,
  descricao             VARCHAR(150) NOT NULL,
  ativo                 BOOLEAN NOT NULL DEFAULT TRUE,
  categoria             VARCHAR(30) NOT NULL COMMENT 'Natureza do recurso no protocolo por recursos',
  conta_como_recurso    BOOLEAN NOT NULL DEFAULT TRUE COMMENT 'Falso para itens que o protocolo não conta (ex.: medicação oral, exame simples à beira do leito)',
  ordem                 SMALLINT UNSIGNED NULL COMMENT 'Ordem de exibição',
  criado_em             DATETIME(3) NOT NULL,
  criado_por            BIGINT UNSIGNED NULL,
  alterado_em           DATETIME(3) NULL,
  alterado_por          BIGINT UNSIGNED NULL,
  versao                INT UNSIGNED NOT NULL DEFAULT 1,
  CONSTRAINT ck_recurso_previsto_urgencia_categoria CHECK (categoria IN ('exame_laboratorial','exame_imagem','medicacao_venosa','medicacao_intramuscular','medicacao_nebulizacao','procedimento_simples','procedimento_complexo','consulta_especializada','outro')),
  UNIQUE KEY uq_recurso_previsto_urgencia_codigo (codigo)
) COMMENT='Recurso previsto para o paciente no protocolo por recursos (exame laboratorial, imagem, medicação venosa, procedimento, consulta especializada)';

CREATE TABLE referencia_dose (
  id                    BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
  codigo                VARCHAR(30) NOT NULL,
  descricao             VARCHAR(150) NOT NULL,
  ativo                 BOOLEAN NOT NULL DEFAULT TRUE,
  base_calculo          VARCHAR(30) NOT NULL COMMENT 'Grandeza que multiplica a dose de referência',
  unidade_base          VARCHAR(20) NULL COMMENT 'Unidade da base (kg, m2); nulo para dose fixa',
  criado_em             DATETIME(3) NOT NULL,
  criado_por            BIGINT UNSIGNED NULL,
  alterado_em           DATETIME(3) NULL,
  alterado_por          BIGINT UNSIGNED NULL,
  versao                INT UNSIGNED NOT NULL DEFAULT 1,
  CONSTRAINT ck_referencia_dose_base_calculo CHECK (base_calculo IN ('peso','superficie_corporal','dose_fixa','idade','area_sob_curva')),
  CONSTRAINT ck_referencia_dose_unidade_base CHECK (base_calculo = 'dose_fixa' OR unidade_base IS NOT NULL),
  UNIQUE KEY uq_referencia_dose_codigo (codigo)
) COMMENT='Referência da dose prescrita (por quilo, por metro quadrado, dose fixa)';

