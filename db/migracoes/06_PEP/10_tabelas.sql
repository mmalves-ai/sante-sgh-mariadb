  id                          BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
  registro_assistencial_id    BIGINT UNSIGNED NOT NULL,
  sequencia                   SMALLINT UNSIGNED NOT NULL COMMENT 'Ordem da resposta no registro',
  modelo_campo_id             BIGINT UNSIGNED NOT NULL COMMENT 'Campo do modelo respondido',
  tipo_valor                  VARCHAR(30) NOT NULL COMMENT 'Qual coluna de valor está preenchida',
  valor_texto                 TEXT NULL,
  valor_numero                DECIMAL(15,4) NULL,
  valor_data                  DATE NULL,
  valor_data_hora             DATETIME(3) NULL,
  valor_hora                  TIME NULL,
  valor_booleano              BOOLEAN NULL,
  modelo_campo_opcao_id       BIGINT UNSIGNED NULL COMMENT 'Opção escolhida, em campo de escolha única',
  valor_estruturado           JSON NULL COMMENT 'Grade, escolha múltipla ou texto formatado, no formato do contrato',
  codigo_cid10                VARCHAR(6) NULL COMMENT 'Código CID-10 sem ponto, em campo de diagnóstico (o catálogo CID-10 ainda não tem tabela no modelo)',
  justificativa_diagnostico   VARCHAR(255) NULL,
  unidade                     VARCHAR(20) NULL COMMENT 'Unidade do valor numérico, quando o campo admite mais de uma',
  arquivo_id                  BIGINT UNSIGNED NULL COMMENT 'Imagem ou anexo do campo',
  observacao                  VARCHAR(255) NULL,
  autopreenchido              BOOLEAN NOT NULL DEFAULT FALSE COMMENT 'Valor trazido do histórico do paciente',
  confirmado                  BOOLEAN NOT NULL DEFAULT FALSE COMMENT 'O autor confirmou o valor autopreenchido',
  origem                      VARCHAR(20) NOT NULL DEFAULT 'sistema',
  criado_em                   DATETIME(3) NOT NULL,
  criado_por                  BIGINT UNSIGNED NULL,
  alterado_em                 DATETIME(3) NULL,
  alterado_por                BIGINT UNSIGNED NULL,
  versao                      INT UNSIGNED NOT NULL DEFAULT 1,
  excluido_em                 DATETIME(3) NULL,
  excluido_por                BIGINT UNSIGNED NULL,
  CONSTRAINT ck_registro_assistencial_resposta_tipo_valor CHECK (tipo_valor IN ('texto','numero','data','data_hora','hora','booleano','opcao','cid','grade','multipla','formatado','imagem')),
  CONSTRAINT ck_registro_assistencial_resposta_opcao CHECK (tipo_valor <> 'opcao' OR modelo_campo_opcao_id IS NOT NULL),
  CONSTRAINT ck_registro_assistencial_resposta_cid CHECK (tipo_valor <> 'cid' OR codigo_cid10 IS NOT NULL),
  CONSTRAINT ck_registro_assistencial_resposta_autopreenchido CHECK (autopreenchido OR NOT confirmado),
  CONSTRAINT ck_registro_assistencial_resposta_origem CHECK (origem IN ('sistema','migracao','integracao')),
  UNIQUE KEY uq_registro_assistencial_resposta_sequencia (registro_assistencial_id, sequencia),
  KEY ix_registro_assistencial_resposta_campo (modelo_campo_id, valor_numero),
  KEY ix_registro_assistencial_resposta_opcao (modelo_campo_opcao_id),
  KEY ix_registro_assistencial_resposta_cid (codigo_cid10),
  KEY ix_registro_assistencial_resposta_arquivo (arquivo_id)
) COMMENT='Resposta de cada campo do registro clínico, com valor tipado e opção escolhida';

