CREATE TABLE situacao_procedimento_prescrito (
  id                   BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
  codigo               VARCHAR(30) NOT NULL,
  descricao            VARCHAR(150) NOT NULL,
  ativo                BOOLEAN NOT NULL DEFAULT TRUE,
  etapa                VARCHAR(30) NOT NULL COMMENT 'Etapa do ciclo do procedimento ou exame prescrito',
  final                BOOLEAN NOT NULL DEFAULT FALSE COMMENT 'Verdadeiro quando a situação encerra o ciclo (não admite nova transição)',
  codigo_rnds          VARCHAR(30) NULL COMMENT 'Código equivalente na terminologia da RNDS, para o sumário de alta',
  ordem                SMALLINT UNSIGNED NULL COMMENT 'Ordem de exibição',
  criado_em            DATETIME(3) NOT NULL,
  criado_por           BIGINT UNSIGNED NULL,
  alterado_em          DATETIME(3) NULL,
  alterado_por         BIGINT UNSIGNED NULL,
  versao               INT UNSIGNED NOT NULL DEFAULT 1,
  CONSTRAINT ck_situacao_procedimento_prescrito_etapa CHECK (etapa IN ('pedido','agendado','coletado','em_execucao','realizado','laudado','cancelado','suspenso')),
  UNIQUE KEY uq_situacao_procedimento_prescrito_codigo (codigo)
) COMMENT='Situações do procedimento ou exame prescrito (pedido, coletado, realizado, cancelado)';

