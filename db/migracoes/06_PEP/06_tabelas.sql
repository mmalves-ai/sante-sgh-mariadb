  insumo_id         BIGINT UNSIGNED NULL COMMENT 'Produto de estoque ligado (medicamento, material, dieta industrializada)',
  principio_ativo_id BIGINT UNSIGNED NULL,
  exame_id          BIGINT UNSIGNED NULL COMMENT 'Exame laboratorial ou de imagem pedido por este item',
  cuidado_enfermagem_id BIGINT UNSIGNED NULL,
  hemocomponente_id BIGINT UNSIGNED NULL,
  modalidade_dieta_id BIGINT UNSIGNED NULL,
  item_faturavel_id BIGINT UNSIGNED NULL COMMENT 'Item cobrado na conta quando a cobrança não vem do insumo',
  procedimento_sigtap_id BIGINT UNSIGNED NULL COMMENT 'Procedimento SUS correspondente',
  via_de_uso_id     BIGINT UNSIGNED NULL COMMENT 'Via padrão',
  frequencia_administracao_id BIGINT UNSIGNED NULL COMMENT 'Frequência padrão',
  unidade_prescricao_id BIGINT UNSIGNED NULL COMMENT 'Unidade em que o item é prescrito',
  maxima_unidade_prescricao_id BIGINT UNSIGNED NULL COMMENT 'Unidade da quantidade máxima por aplicação',
  dispensacao_unidade_medida_id BIGINT UNSIGNED NULL COMMENT 'Unidade em que a farmácia dispensa',
  quantidade_padrao DECIMAL(15,4) NULL,
  dose_padrao       DECIMAL(15,4) NULL,
  quantidade_maxima_aplicacao DECIMAL(15,4) NULL,
  dias_padrao       SMALLINT UNSIGNED NULL COMMENT 'Duração padrão do tratamento, em dias',
  validade_horas    SMALLINT UNSIGNED NULL COMMENT 'Por quanto tempo o item fica aberto na prescrição',
  duracao_minutos   SMALLINT UNSIGNED NULL COMMENT 'Duração da execução (procedimento, exame, infusão)',
  tempo_assistencia_horas DECIMAL(10,2) NULL COMMENT 'Horas de assistência de enfermagem consumidas, para dimensionamento',
  sexo_permitido    VARCHAR(30) NOT NULL DEFAULT 'ambos',
  tipo_balanco_hidrico VARCHAR(30) NULL COMMENT 'Se entra no balanço hídrico como ganho ou perda',
  padronizado       BOOLEAN NOT NULL DEFAULT TRUE,
  exige_justificativa BOOLEAN NOT NULL DEFAULT FALSE,
