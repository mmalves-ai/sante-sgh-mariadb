CREATE TABLE item_prescritivel_conflito (
  id                BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
  item_prescritivel_id BIGINT UNSIGNED NOT NULL,
  conflitante_item_prescritivel_id BIGINT UNSIGNED NOT NULL COMMENT 'Item que não pode ser prescrito junto',
  gravidade         VARCHAR(30) NOT NULL DEFAULT 'impeditivo',
  motivo            VARCHAR(300) NULL,
  excluido_em       DATETIME(3) NULL,
  excluido_por      BIGINT UNSIGNED NULL,
  criado_em         DATETIME(3) NOT NULL,
  criado_por        BIGINT UNSIGNED NULL,
  alterado_em       DATETIME(3) NULL,
  alterado_por      BIGINT UNSIGNED NULL,
  versao            INT UNSIGNED NOT NULL DEFAULT 1,
  UNIQUE KEY uq_item_prescritivel_conflito_par (item_prescritivel_id, conflitante_item_prescritivel_id),
  CONSTRAINT ck_item_prescritivel_conflito_gravidade CHECK (gravidade IN ('alerta','impeditivo')),
  CONSTRAINT ck_item_prescritivel_conflito_distinto CHECK (item_prescritivel_id <> conflitante_item_prescritivel_id),
  KEY ix_item_prescritivel_conflito_conflitante (conflitante_item_prescritivel_id)
