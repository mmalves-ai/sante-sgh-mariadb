  descricao         VARCHAR(200) NOT NULL,
  descricao_impressao VARCHAR(200) NULL COMMENT 'Texto impresso na prescrição, quando diferente da descrição',
  tipo_item_prescricao_id BIGINT UNSIGNED NOT NULL COMMENT 'Medicamento, solução, dieta, cuidado, exame, procedimento, hemocomponente, material',
