  copia_justificativa BOOLEAN NOT NULL DEFAULT FALSE COMMENT 'Copia a justificativa ao repetir a prescrição',
  uso_continuo      BOOLEAN NOT NULL DEFAULT FALSE,
  permite_uso_simultaneo BOOLEAN NOT NULL DEFAULT TRUE,
  alerta_duplicidade BOOLEAN NOT NULL DEFAULT TRUE,
  fracionavel       BOOLEAN NOT NULL DEFAULT FALSE,
  imprime_horario   BOOLEAN NOT NULL DEFAULT TRUE,
  dupla_checagem    BOOLEAN NOT NULL DEFAULT FALSE COMMENT 'Exige segunda conferência na administração',
  alta_vigilancia   BOOLEAN NOT NULL DEFAULT FALSE COMMENT 'Medicamento potencialmente perigoso',
  controlado        BOOLEAN NOT NULL DEFAULT FALSE COMMENT 'Sujeito a controle especial',
  antimicrobiano    BOOLEAN NOT NULL DEFAULT FALSE COMMENT 'Exige ficha de antimicrobiano',
  medicamento_gatilho BOOLEAN NOT NULL DEFAULT FALSE COMMENT 'Indica possível evento adverso quando prescrito',
  prescrito_por_enfermagem BOOLEAN NOT NULL DEFAULT FALSE COMMENT 'Pode ser prescrito pelo enfermeiro',
  exige_paciente_intubado BOOLEAN NOT NULL DEFAULT FALSE,
  controle_liga_desliga BOOLEAN NOT NULL DEFAULT FALSE COMMENT 'Item contínuo com registro de início e fim (oxigênio, ventilação)',
  exige_material    BOOLEAN NOT NULL DEFAULT FALSE,
  lanca_conta_na_checagem BOOLEAN NOT NULL DEFAULT FALSE,
  faturavel         BOOLEAN NOT NULL DEFAULT TRUE,
  gera_solicitacao  BOOLEAN NOT NULL DEFAULT FALSE COMMENT 'Gera pedido ao setor executante (exame, dieta, hemocomponente)',
  bloqueado         BOOLEAN NOT NULL DEFAULT FALSE,
  motivo_bloqueio   VARCHAR(200) NULL,
  ordem_impressao   SMALLINT UNSIGNED NULL,
  observacao        TEXT NULL,
  observacao_adicional VARCHAR(500) NULL,
  ativo             BOOLEAN NOT NULL DEFAULT TRUE,
  origem            VARCHAR(20) NOT NULL DEFAULT 'sistema',
  excluido_em       DATETIME(3) NULL,
  excluido_por      BIGINT UNSIGNED NULL,
