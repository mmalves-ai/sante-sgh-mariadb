  CONSTRAINT ck_item_prescritivel_sexo CHECK (sexo_permitido IN ('ambos','feminino','masculino')),
  CONSTRAINT ck_item_prescritivel_balanco CHECK (tipo_balanco_hidrico IS NULL OR tipo_balanco_hidrico IN ('ganho','perda')),
  CONSTRAINT ck_item_prescritivel_quantidades CHECK ((quantidade_padrao IS NULL OR quantidade_padrao > 0) AND (dose_padrao IS NULL OR dose_padrao > 0) AND (quantidade_maxima_aplicacao IS NULL OR quantidade_maxima_aplicacao > 0)),
  CONSTRAINT ck_item_prescritivel_bloqueio CHECK (bloqueado = FALSE OR motivo_bloqueio IS NOT NULL),
  KEY ix_item_prescritivel_descricao (descricao),
  KEY ix_item_prescritivel_tipo (tipo_item_prescricao_id),
  KEY ix_item_prescritivel_grupo (grupo_exibicao_prescricao_id),
  KEY ix_item_prescritivel_insumo (insumo_id),
  KEY ix_item_prescritivel_principio (principio_ativo_id),
  KEY ix_item_prescritivel_exame (exame_id),
  KEY ix_item_prescritivel_cuidado (cuidado_enfermagem_id),
  KEY ix_item_prescritivel_hemocomponente (hemocomponente_id),
  KEY ix_item_prescritivel_dieta (modalidade_dieta_id),
  KEY ix_item_prescritivel_faturavel (item_faturavel_id),
  KEY ix_item_prescritivel_sigtap (procedimento_sigtap_id),
  KEY ix_item_prescritivel_via (via_de_uso_id),
  KEY ix_item_prescritivel_frequencia (frequencia_administracao_id),
  KEY ix_item_prescritivel_unidade (unidade_prescricao_id),
  KEY ix_item_prescritivel_unidade_maxima (maxima_unidade_prescricao_id),
  KEY ix_item_prescritivel_unidade_dispensacao (dispensacao_unidade_medida_id),
  KEY ix_item_prescritivel_justificativa (justificativa_padrao_medicacao_id)
