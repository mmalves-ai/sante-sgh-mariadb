-- configuracao
CREATE TABLE equipe_assistencial_padrao (
  id                BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
  estabelecimento_id BIGINT UNSIGNED NOT NULL,
  nome              VARCHAR(100) NOT NULL,
  setor_funcional_id BIGINT UNSIGNED NULL COMMENT 'Setor onde a equipe é sugerida; nulo quando vale pela especialidade',
  especialidade_medica_id BIGINT UNSIGNED NULL COMMENT 'Especialidade ou serviço da equipe',
  sugerir_automaticamente BOOLEAN NOT NULL DEFAULT TRUE COMMENT 'Sugere a equipe ao paciente que entra no setor',
  observacao        VARCHAR(500) NULL,
  ativo             BOOLEAN NOT NULL DEFAULT TRUE,
  criado_em         DATETIME(3) NOT NULL,
  criado_por        BIGINT UNSIGNED NULL,
  alterado_em       DATETIME(3) NULL,
  alterado_por      BIGINT UNSIGNED NULL,
  versao            INT UNSIGNED NOT NULL DEFAULT 1,
  CONSTRAINT ck_equipe_assistencial_padrao_alvo CHECK (setor_funcional_id IS NOT NULL OR especialidade_medica_id IS NOT NULL),
  UNIQUE KEY uq_equipe_assistencial_padrao_nome (estabelecimento_id, nome),
  KEY ix_equipe_assistencial_padrao_setor (setor_funcional_id),
  KEY ix_equipe_assistencial_padrao_especialidade (especialidade_medica_id)
) COMMENT='Equipe fixa por setor ou serviço, sugerida automaticamente ao paciente que entra no setor';

