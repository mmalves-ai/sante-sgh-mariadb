-- dominio
CREATE TABLE escala_clinica (
  id                BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
  codigo            VARCHAR(30) NOT NULL,
  descricao         VARCHAR(150) NOT NULL,
  ativo             BOOLEAN NOT NULL DEFAULT TRUE,
  sigla             VARCHAR(20) NULL,
  tipo              VARCHAR(30) NOT NULL DEFAULT 'escala',
  finalidade        VARCHAR(500) NULL,
  tipo_documento_clinico_id BIGINT UNSIGNED NULL COMMENT 'Tipo de documento em que a escala é registrada',
  calculo_resultado VARCHAR(20) NOT NULL DEFAULT 'soma' COMMENT 'Como as pontuações das variáveis viram o resultado',
  expressao_resultado VARCHAR(4000) NULL COMMENT 'Fórmula do resultado quando o cálculo é por expressão',
  pontuacao_minima  DECIMAL(16,4) NULL,
  pontuacao_maxima  DECIMAL(16,4) NULL,
  unidade_resultado VARCHAR(30) NULL COMMENT 'Ex.: pontos, %, risco de óbito',
  periodicidade_horas SMALLINT UNSIGNED NULL COMMENT 'Reavaliação sugerida, em horas',
  inicio_avaliacao_horas SMALLINT UNSIGNED NULL COMMENT 'Prazo para a primeira aplicação após a admissão, em horas',
  avaliar_na_alta   BOOLEAN NOT NULL DEFAULT FALSE,
  usar_regras_exibicao BOOLEAN NOT NULL DEFAULT FALSE,
  permite_observacao BOOLEAN NOT NULL DEFAULT TRUE,
  numero_versao_atual SMALLINT UNSIGNED NOT NULL DEFAULT 1,
  referencia_bibliografica VARCHAR(500) NULL,
  ordem             SMALLINT UNSIGNED NULL,
  criado_em         DATETIME(3) NOT NULL,
  criado_por        BIGINT UNSIGNED NULL,
  alterado_em       DATETIME(3) NULL,
  alterado_por      BIGINT UNSIGNED NULL,
  versao            INT UNSIGNED NOT NULL DEFAULT 1,
  CONSTRAINT ck_escala_clinica_tipo CHECK (tipo IN ('escala','indice_prognostico','questionario','formula')),
  CONSTRAINT ck_escala_clinica_calculo CHECK (calculo_resultado IN ('soma','media','maximo','expressao','sem_pontuacao')),
  CONSTRAINT ck_escala_clinica_expressao CHECK (calculo_resultado <> 'expressao' OR expressao_resultado IS NOT NULL),
  CONSTRAINT ck_escala_clinica_faixa CHECK (pontuacao_minima IS NULL OR pontuacao_maxima IS NULL OR pontuacao_maxima >= pontuacao_minima),
  UNIQUE KEY uq_escala_clinica_codigo (codigo),
  KEY ix_escala_clinica_tipo_documento (tipo_documento_clinico_id)
) COMMENT='Escala, índice prognóstico ou questionário pontuado (Glasgow, NEWS, Braden, Morse, APACHE)';

-- item
CREATE TABLE escala_clinica_faixa (
  id                BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
  escala_clinica_id BIGINT UNSIGNED NOT NULL,
  sequencia         SMALLINT UNSIGNED NOT NULL,
  escala_clinica_variavel_id BIGINT UNSIGNED NULL COMMENT 'Preenchido quando a faixa converte o valor medido de uma variável em pontos; nulo quando interpreta o resultado total',
  valor_inicial     DECIMAL(16,4) NOT NULL,
  valor_final       DECIMAL(16,4) NOT NULL,
  pontos            DECIMAL(16,4) NULL COMMENT 'Pontos atribuídos quando a faixa é de variável',
  interpretacao     VARCHAR(200) NULL,
  sigla_interpretacao VARCHAR(10) NULL,
  conduta_sugerida  VARCHAR(500) NULL,
  sigla_conduta     VARCHAR(10) NULL,
  nivel_risco       VARCHAR(20) NULL,
  cor_hex           CHAR(7) NULL COMMENT 'Cor de exibição, #RRGGBB',
  gera_alerta       BOOLEAN NOT NULL DEFAULT FALSE,
  origem            VARCHAR(20) NOT NULL DEFAULT 'sistema',
  criado_em         DATETIME(3) NOT NULL,
  criado_por        BIGINT UNSIGNED NULL,
  alterado_em       DATETIME(3) NULL,
  alterado_por      BIGINT UNSIGNED NULL,
  versao            INT UNSIGNED NOT NULL DEFAULT 1,
  excluido_em       DATETIME(3) NULL,
  excluido_por      BIGINT UNSIGNED NULL,
  CONSTRAINT ck_escala_clinica_faixa_origem CHECK (origem IN ('sistema','migracao','integracao')),
  CONSTRAINT ck_escala_clinica_faixa_intervalo CHECK (valor_final >= valor_inicial),
  CONSTRAINT ck_escala_clinica_faixa_conteudo CHECK ((escala_clinica_variavel_id IS NULL AND interpretacao IS NOT NULL) OR (escala_clinica_variavel_id IS NOT NULL AND pontos IS NOT NULL)),
  CONSTRAINT ck_escala_clinica_faixa_nivel_risco CHECK (nivel_risco IS NULL OR nivel_risco IN ('sem_risco','baixo','moderado','alto','muito_alto')),
  CONSTRAINT ck_escala_clinica_faixa_cor CHECK (cor_hex IS NULL OR cor_hex REGEXP '^#[0-9A-Fa-f]{6}$'),
  UNIQUE KEY uq_escala_clinica_faixa_sequencia (escala_clinica_id, sequencia),
  KEY ix_escala_clinica_faixa_variavel (escala_clinica_variavel_id)
) COMMENT='Faixa de pontuação da escala, com interpretação, cor e conduta sugerida';

