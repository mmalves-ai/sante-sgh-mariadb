-- dominio
CREATE TABLE frequencia_administracao (
  id                BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
  codigo            VARCHAR(30) NOT NULL,
  descricao         VARCHAR(150) NOT NULL,
  ativo             BOOLEAN NOT NULL DEFAULT TRUE,
  descricao_resumida VARCHAR(15) NULL COMMENT 'Ex.: 6/6h, 1x/dia',
  tipo              VARCHAR(20) NOT NULL,
  intervalo_minutos INT UNSIGNED NULL,
  doses_por_dia     SMALLINT UNSIGNED NULL,
  limite_horas      SMALLINT UNSIGNED NULL COMMENT 'Validade da frequência, em horas, para dose única ou agora',
  horario_fixo      BOOLEAN NOT NULL DEFAULT FALSE COMMENT 'Usa os horários padrão do setor em vez de contar do início',
  arredondar_horario BOOLEAN NOT NULL DEFAULT FALSE,
  uso_prescricao    VARCHAR(20) NOT NULL DEFAULT 'todos' COMMENT 'Tipos de item em que a frequência pode ser usada',
  movimenta_estoque BOOLEAN NOT NULL DEFAULT TRUE,
  receita_estruturada BOOLEAN NOT NULL DEFAULT TRUE COMMENT 'Disponível na receita de alta',
  copiar_na_renovacao BOOLEAN NOT NULL DEFAULT TRUE,
  domingo           BOOLEAN NOT NULL DEFAULT TRUE,
  segunda           BOOLEAN NOT NULL DEFAULT TRUE,
  terca             BOOLEAN NOT NULL DEFAULT TRUE,
  quarta            BOOLEAN NOT NULL DEFAULT TRUE,
  quinta            BOOLEAN NOT NULL DEFAULT TRUE,
  sexta             BOOLEAN NOT NULL DEFAULT TRUE,
  sabado            BOOLEAN NOT NULL DEFAULT TRUE,
  frequencia_agrupadora_id BIGINT UNSIGNED NULL COMMENT 'Frequência que agrupa esta nas listas',
  escopo_setor      VARCHAR(20) NOT NULL DEFAULT 'todos' COMMENT 'Como a lista de setores da frequência é lida',
  ordem             SMALLINT UNSIGNED NULL,
  criado_em         DATETIME(3) NOT NULL,
  criado_por        BIGINT UNSIGNED NULL,
  alterado_em       DATETIME(3) NULL,
  alterado_por      BIGINT UNSIGNED NULL,
  versao            INT UNSIGNED NOT NULL DEFAULT 1,
  CONSTRAINT ck_frequencia_administracao_tipo CHECK (tipo IN ('intervalo','vezes_ao_dia','continuo','agora','se_necessario','dias_semana','dose_unica','a_criterio_medico')),
  CONSTRAINT ck_frequencia_administracao_intervalo CHECK (tipo <> 'intervalo' OR (intervalo_minutos IS NOT NULL AND intervalo_minutos > 0)),
  CONSTRAINT ck_frequencia_administracao_doses CHECK (tipo <> 'vezes_ao_dia' OR (doses_por_dia IS NOT NULL AND doses_por_dia BETWEEN 1 AND 48)),
  CONSTRAINT ck_frequencia_administracao_uso CHECK (uso_prescricao IN ('todos','medicamento','cuidado','dieta','procedimento')),
  CONSTRAINT ck_frequencia_administracao_escopo CHECK (escopo_setor IN ('todos','somente_listados','exceto_listados')),
  UNIQUE KEY uq_frequencia_administracao_codigo (codigo)
) COMMENT='Frequências de administração (de 6 em 6 horas, 1 vez ao dia, contínuo, agora), com intervalo e número de doses';

