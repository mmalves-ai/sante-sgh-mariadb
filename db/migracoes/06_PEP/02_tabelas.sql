CREATE TABLE balanco_hidrico_paciente (
  id                       BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
  estabelecimento_id       BIGINT UNSIGNED NOT NULL,
  atendimento_id           BIGINT UNSIGNED NOT NULL,
  paciente_id              BIGINT UNSIGNED NOT NULL,
  setor_funcional_id       BIGINT UNSIGNED NOT NULL COMMENT 'Setor onde o balanço foi aberto',
  configuracao_balanco_setor_id BIGINT UNSIGNED NULL COMMENT 'Regra do setor vigente na abertura',
