  CONSTRAINT ck_balanco_hidrico_paciente_situacao CHECK (situacao IN ('aberto','fechado_parcial','fechado','cancelado')),
  CONSTRAINT ck_balanco_hidrico_paciente_janela CHECK (fim_janela_em > inicio_janela_em),
  CONSTRAINT ck_balanco_hidrico_paciente_turnos CHECK (quantidade_turnos BETWEEN 1 AND 24),
