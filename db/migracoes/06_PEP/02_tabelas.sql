  UNIQUE KEY uq_balanco_hidrico_paciente_atendimento_data (atendimento_id, data_referencia),
  KEY ix_balanco_hidrico_paciente_estabelecimento (estabelecimento_id, data_referencia),
  KEY ix_balanco_hidrico_paciente_paciente (paciente_id),
  KEY ix_balanco_hidrico_paciente_setor_funcional (setor_funcional_id),
  KEY ix_balanco_hidrico_paciente_configuracao_balanco_setor (configuracao_balanco_setor_id)
) COMMENT='Balanço hídrico do paciente por dia de referência e setor, com turnos, horário de fechamento e situação';

CREATE TABLE balanco_lancamento (
  id                       BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
  balanco_hidrico_paciente_id BIGINT UNSIGNED NOT NULL,
  sentido                  VARCHAR(10) NOT NULL COMMENT 'ganho ou perda',
  grupo_balanco_hidrico_id BIGINT UNSIGNED NULL COMMENT 'Grupo do ganho (via oral, enteral, parenteral, venosa) ou tipo de perda (diurese, dreno, vômito)',
  via_de_uso_id            BIGINT UNSIGNED NULL COMMENT 'Via do ganho, quando informada',
  item_prescritivel_id     BIGINT UNSIGNED NULL COMMENT 'Item administrado que gerou o ganho',
  prescricao_item_id       BIGINT UNSIGNED NULL COMMENT 'Item da prescrição checado que gerou o ganho',
  afericao_id              BIGINT UNSIGNED NULL COMMENT 'Aferição de sinais que gerou a perda (ex.: diurese)',
  intensidade              TINYINT UNSIGNED NULL COMMENT 'Intensidade da perda, de 1+ a 4+',
  aspecto                  VARCHAR(40) NULL,
  estimado                 BOOLEAN NOT NULL DEFAULT FALSE COMMENT 'Volume estimado, sem medição',
  volume_ml                DECIMAL(15,4) NOT NULL,
  unidade_medida_id        BIGINT UNSIGNED NULL COMMENT 'Unidade em que o volume foi digitado, quando não é mililitro',
  quantidade_digitada      DECIMAL(15,4) NULL COMMENT 'Quantidade na unidade digitada, antes da conversão',
  fator_conversao          DECIMAL(15,4) NULL COMMENT 'Fator usado para converter a quantidade digitada em mililitros',
  soma_total               BOOLEAN NOT NULL DEFAULT TRUE COMMENT 'Entra no total do balanço',
  descricao                VARCHAR(120) NULL,
  ocorrido_em              DATETIME(3) NOT NULL COMMENT 'Hora real do ganho ou da perda',
  registrado_em            DATETIME(3) NOT NULL,
  fonte_lancamento         VARCHAR(20) NOT NULL DEFAULT 'manual' COMMENT 'manual, checagem, sinal ou estorno',
  registrado_sem_conexao   BOOLEAN NOT NULL DEFAULT FALSE COMMENT 'Lançado no modo sem conexão e sincronizado depois',
  profissional_id          BIGINT UNSIGNED NOT NULL,
  estornado_balanco_lancamento_id BIGINT UNSIGNED NULL COMMENT 'Lançamento anulado por este estorno',
  motivo_estorno           VARCHAR(200) NULL,
  origem              VARCHAR(20) NOT NULL DEFAULT 'sistema',
  criado_em           DATETIME(3) NOT NULL,
  criado_por          BIGINT UNSIGNED NULL,
  alterado_em         DATETIME(3) NULL,
  alterado_por        BIGINT UNSIGNED NULL,
  versao              INT UNSIGNED NOT NULL DEFAULT 1,
  excluido_em         DATETIME(3) NULL,
  excluido_por        BIGINT UNSIGNED NULL,
  CONSTRAINT ck_balanco_lancamento_origem CHECK (origem IN ('sistema','migracao','integracao')),
  CONSTRAINT ck_balanco_lancamento_sentido CHECK (sentido IN ('ganho','perda')),
  CONSTRAINT ck_balanco_lancamento_fonte CHECK (fonte_lancamento IN ('manual','checagem','sinal','estorno')),
  CONSTRAINT ck_balanco_lancamento_volume CHECK (volume_ml >= 0 AND volume_ml <= 20000),
  CONSTRAINT ck_balanco_lancamento_intensidade CHECK (intensidade IS NULL OR intensidade BETWEEN 1 AND 4),
  CONSTRAINT ck_balanco_lancamento_estorno CHECK (fonte_lancamento <> 'estorno' OR (estornado_balanco_lancamento_id IS NOT NULL AND motivo_estorno IS NOT NULL)),
  KEY ix_balanco_lancamento_balanco (balanco_hidrico_paciente_id, ocorrido_em),
  KEY ix_balanco_lancamento_grupo_balanco_hidrico (grupo_balanco_hidrico_id),
  KEY ix_balanco_lancamento_via_de_uso (via_de_uso_id),
  KEY ix_balanco_lancamento_item_prescritivel (item_prescritivel_id),
  KEY ix_balanco_lancamento_prescricao_item (prescricao_item_id),
  KEY ix_balanco_lancamento_afericao (afericao_id),
  KEY ix_balanco_lancamento_unidade_medida (unidade_medida_id),
  KEY ix_balanco_lancamento_profissional (profissional_id),
  KEY ix_balanco_lancamento_estornado_balanco_lancamento (estornado_balanco_lancamento_id)
) COMMENT='Lançamento de ganho ou perda no balanço hídrico, com tipo, volume, intensidade e horário';

CREATE TABLE balanco_fechamento (
  id                       BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
  balanco_hidrico_paciente_id BIGINT UNSIGNED NOT NULL,
  tipo                     VARCHAR(10) NOT NULL COMMENT 'parcial ou total (24 horas)',
  inicio_em                DATETIME(3) NOT NULL,
  fim_em                   DATETIME(3) NOT NULL,
  fechado_em               DATETIME(3) NOT NULL,
  total_ganhos_ml          DECIMAL(15,4) NOT NULL,
  total_perdas_ml          DECIMAL(15,4) NOT NULL,
  perda_insensivel_ml      DECIMAL(15,4) NOT NULL DEFAULT 0,
  saldo_ml                 DECIMAL(15,4) NOT NULL COMMENT 'Ganhos menos perdas menos perda insensível',
  formula_perda_insensivel VARCHAR(30) NOT NULL DEFAULT 'nenhuma' COMMENT 'Versão da fórmula usada na perda insensível',
  peso_kg                  DECIMAL(7,3) NULL,
  impressao_conferida_hash CHAR(64) NULL COMMENT 'Resumo criptográfico do balanço que o profissional viu ao fechar',
  profissional_id          BIGINT UNSIGNED NOT NULL,
  documento_prontuario_id  BIGINT UNSIGNED NULL,
  situacao                 VARCHAR(30) NOT NULL DEFAULT 'valido',
  origem              VARCHAR(20) NOT NULL DEFAULT 'sistema',
  criado_em           DATETIME(3) NOT NULL,
  criado_por          BIGINT UNSIGNED NULL,
  alterado_em         DATETIME(3) NULL,
  alterado_por        BIGINT UNSIGNED NULL,
  versao              INT UNSIGNED NOT NULL DEFAULT 1,
  excluido_em         DATETIME(3) NULL,
  excluido_por        BIGINT UNSIGNED NULL,
  CONSTRAINT ck_balanco_fechamento_origem CHECK (origem IN ('sistema','migracao','integracao')),
  CONSTRAINT ck_balanco_fechamento_tipo CHECK (tipo IN ('parcial','total')),
  CONSTRAINT ck_balanco_fechamento_situacao CHECK (situacao IN ('valido','cancelado')),
  CONSTRAINT ck_balanco_fechamento_periodo CHECK (fim_em > inicio_em),
  CONSTRAINT ck_balanco_fechamento_totais CHECK (total_ganhos_ml >= 0 AND total_perdas_ml >= 0 AND perda_insensivel_ml >= 0),
  CONSTRAINT ck_balanco_fechamento_saldo CHECK (saldo_ml = total_ganhos_ml - total_perdas_ml - perda_insensivel_ml),
  CONSTRAINT ck_balanco_fechamento_peso CHECK (peso_kg IS NULL OR peso_kg BETWEEN 0.3 AND 400),
  KEY ix_balanco_fechamento_balanco (balanco_hidrico_paciente_id, fim_em),
  KEY ix_balanco_fechamento_profissional (profissional_id),
  KEY ix_balanco_fechamento_documento_prontuario (documento_prontuario_id)
) COMMENT='Fechamento parcial ou de 24 horas do balanço, com totais de ganhos, perdas e saldo';

