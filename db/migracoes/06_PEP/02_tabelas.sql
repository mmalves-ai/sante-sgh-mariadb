CREATE TABLE avaliacao_farmaceutica_item (
  id                       BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
  avaliacao_farmaceutica_id BIGINT UNSIGNED NOT NULL,
  sequencia                SMALLINT UNSIGNED NOT NULL,
  prescricao_item_id       BIGINT UNSIGNED NOT NULL COMMENT 'Item prescrito avaliado',
  parecer                  VARCHAR(30) NOT NULL COMMENT 'aprovado, aprovado_com_ressalva, recusado ou substituido',
  substituto_prescricao_item_id BIGINT UNSIGNED NULL COMMENT 'Item que substitui o avaliado, quando o parecer é de troca',
  justificativa_prescricao_item_id BIGINT UNSIGNED NULL COMMENT 'Item que justifica a avaliação (ex.: o item que motivou a ressalva)',
  justificativa            TEXT NULL COMMENT 'Texto do parecer farmacêutico sobre o item',
  liberador_profissional_id BIGINT UNSIGNED NULL COMMENT 'Farmacêutico que liberou o item',
  avaliado_em              DATETIME(3) NOT NULL,
  substituido              BOOLEAN NOT NULL DEFAULT FALSE COMMENT 'O item avaliado foi trocado na prescrição',
  origem              VARCHAR(20) NOT NULL DEFAULT 'sistema',
  criado_em           DATETIME(3) NOT NULL,
  criado_por          BIGINT UNSIGNED NULL,
  alterado_em         DATETIME(3) NULL,
  alterado_por        BIGINT UNSIGNED NULL,
  versao              INT UNSIGNED NOT NULL DEFAULT 1,
  excluido_em         DATETIME(3) NULL,
  excluido_por        BIGINT UNSIGNED NULL,
  CONSTRAINT ck_avaliacao_farmaceutica_item_origem CHECK (origem IN ('sistema','migracao','integracao')),
  CONSTRAINT ck_avaliacao_farmaceutica_item_parecer CHECK (parecer IN ('aprovado','aprovado_com_ressalva','recusado','substituido')),
  CONSTRAINT ck_avaliacao_farmaceutica_item_substituto CHECK (parecer <> 'substituido' OR substituto_prescricao_item_id IS NOT NULL),
  CONSTRAINT ck_avaliacao_farmaceutica_item_justificativa CHECK (parecer NOT IN ('aprovado_com_ressalva','recusado') OR justificativa IS NOT NULL),
  UNIQUE KEY uq_avaliacao_farmaceutica_item_sequencia (avaliacao_farmaceutica_id, sequencia),
  UNIQUE KEY uq_avaliacao_farmaceutica_item_prescricao_item (avaliacao_farmaceutica_id, prescricao_item_id),
  KEY ix_avaliacao_farmaceutica_item_prescricao_item (prescricao_item_id),
  KEY ix_avaliacao_farmaceutica_item_substituto_prescricao_item (substituto_prescricao_item_id),
  KEY ix_avaliacao_farmaceutica_item_justificativa_prescricao_item (justificativa_prescricao_item_id),
  KEY ix_avaliacao_farmaceutica_item_liberador_profissional (liberador_profissional_id)
) COMMENT='Parecer do farmacêutico sobre cada item prescrito (aprovado, com ressalva, recusado, trocado)';

