CREATE TABLE modelo_receita_item (
  id                             BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
  modelo_receita_id              BIGINT UNSIGNED NOT NULL,
  sequencia                      SMALLINT UNSIGNED NOT NULL,
  item_prescritivel_id           BIGINT UNSIGNED NULL COMMENT 'Item padronizado receitado; nulo quando o item é texto livre',
  tipo_item_prescricao_id        BIGINT UNSIGNED NULL,
  descricao_livre                VARCHAR(500) NULL COMMENT 'Item escrito livremente quando não há item padronizado',
  dose                           DECIMAL(15,4) NULL,
  unidade_prescricao_id          BIGINT UNSIGNED NULL,
  quantidade                     DECIMAL(15,4) NULL COMMENT 'Quantidade total a dispensar',
  frequencia_administracao_id    BIGINT UNSIGNED NULL,
  via_de_uso_id                  BIGINT UNSIGNED NULL,
  duracao                        SMALLINT UNSIGNED NULL COMMENT 'Duração do tratamento, na unidade indicada',
  unidade_duracao_tratamento_id  BIGINT UNSIGNED NULL,
  uso_continuo                   BOOLEAN NOT NULL DEFAULT FALSE,
  posologia                      VARCHAR(2000) NULL COMMENT 'Modo de usar impresso na receita',
  observacao                     VARCHAR(2000) NULL,
  ativo                          BOOLEAN NOT NULL DEFAULT TRUE,
  origem                         VARCHAR(20) NOT NULL DEFAULT 'sistema',
  criado_em                      DATETIME(3) NOT NULL,
  criado_por                     BIGINT UNSIGNED NULL,
  alterado_em                    DATETIME(3) NULL,
  alterado_por                   BIGINT UNSIGNED NULL,
  versao                         INT UNSIGNED NOT NULL DEFAULT 1,
  excluido_em                    DATETIME(3) NULL,
  excluido_por                   BIGINT UNSIGNED NULL,
  CONSTRAINT ck_modelo_receita_item_origem CHECK (origem IN ('sistema','migracao','integracao')),
  CONSTRAINT ck_modelo_receita_item_item CHECK (item_prescritivel_id IS NOT NULL OR descricao_livre IS NOT NULL),
  CONSTRAINT ck_modelo_receita_item_dose CHECK (dose IS NULL OR dose > 0),
  CONSTRAINT ck_modelo_receita_item_quantidade CHECK (quantidade IS NULL OR quantidade > 0),
  CONSTRAINT ck_modelo_receita_item_duracao CHECK (duracao IS NULL OR unidade_duracao_tratamento_id IS NOT NULL),
  UNIQUE KEY uq_modelo_receita_item_receita_sequencia (modelo_receita_id, sequencia),
  KEY ix_modelo_receita_item_item_prescritivel_id (item_prescritivel_id),
  KEY ix_modelo_receita_item_tipo_item_prescricao_id (tipo_item_prescricao_id),
  KEY ix_modelo_receita_item_unidade_prescricao_id (unidade_prescricao_id),
  KEY ix_modelo_receita_item_frequencia_administracao_id (frequencia_administracao_id),
  KEY ix_modelo_receita_item_via_de_uso_id (via_de_uso_id),
  KEY ix_modelo_receita_item_unidade_duracao_tratamento_id (unidade_duracao_tratamento_id)
) COMMENT='Item da receita padrão';

CREATE TABLE modelo_regra (
  id                           BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
  modelo_documento_clinico_id  BIGINT UNSIGNED NOT NULL,
  descricao                    VARCHAR(300) NOT NULL,
  tipo_regra                   VARCHAR(30) NOT NULL,
  momento                      VARCHAR(30) NOT NULL DEFAULT 'ao_alterar' COMMENT 'Quando a regra é avaliada',
  alvo_modelo_campo_id         BIGINT UNSIGNED NULL COMMENT 'Campo afetado pela regra',
  alvo_modelo_secao_id         BIGINT UNSIGNED NULL COMMENT 'Seção afetada pela regra',
  condicao                     JSON NULL COMMENT 'Condições: campo, operador, valor inicial e final, conector e/ou; nulo = sempre',
  expressao                    JSON NULL COMMENT 'Cálculo ou valor a preencher, por referência aos campos do modelo',
  mensagem                     VARCHAR(300) NULL COMMENT 'Mensagem mostrada ao usuário quando a regra dispara',
  ordem                        SMALLINT UNSIGNED NOT NULL DEFAULT 0,
  ativo                        BOOLEAN NOT NULL DEFAULT TRUE,
  criado_em                    DATETIME(3) NOT NULL,
  criado_por                   BIGINT UNSIGNED NULL,
  alterado_em                  DATETIME(3) NULL,
  alterado_por                 BIGINT UNSIGNED NULL,
  versao                       INT UNSIGNED NOT NULL DEFAULT 1,
  CONSTRAINT ck_modelo_regra_tipo_regra CHECK (tipo_regra IN ('habilitar','desabilitar','exibir','ocultar','exigir','calcular','preencher','validar','filtrar_opcoes')),
  CONSTRAINT ck_modelo_regra_momento CHECK (momento IN ('ao_abrir','ao_alterar','ao_salvar','ao_assinar')),
  CONSTRAINT ck_modelo_regra_alvo CHECK (alvo_modelo_campo_id IS NOT NULL OR alvo_modelo_secao_id IS NOT NULL),
  CONSTRAINT ck_modelo_regra_expressao CHECK (tipo_regra NOT IN ('calcular','preencher') OR expressao IS NOT NULL),
  KEY ix_modelo_regra_modelo_ordem (modelo_documento_clinico_id, ordem),
  KEY ix_modelo_regra_alvo_modelo_campo_id (alvo_modelo_campo_id),
  KEY ix_modelo_regra_alvo_modelo_secao_id (alvo_modelo_secao_id)
