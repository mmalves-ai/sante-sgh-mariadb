CREATE TABLE contencao_paciente_avaliacao (
  id                       BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
  contencao_paciente_id    BIGINT UNSIGNED NOT NULL,
  sequencia                SMALLINT UNSIGNED NOT NULL,
  previsto_em              DATETIME(3) NOT NULL COMMENT 'Horário previsto da reavaliação pelo intervalo da contenção',
  avaliado_em              DATETIME(3) NULL,
  profissional_id          BIGINT UNSIGNED NULL COMMENT 'Profissional que fez a reavaliação',
  achado_perfusao          VARCHAR(10) NULL COMMENT 'Perfusão, cor e temperatura dos membros contidos',
  achado_pele              VARCHAR(10) NULL COMMENT 'Integridade da pele sob a contenção',
  achado_posicao           VARCHAR(10) NULL COMMENT 'Posição e alinhamento do corpo',
  achado_necessidades      VARCHAR(10) NULL COMMENT 'Hidratação, alimentação e eliminações atendidas',
  mantem_contencao         BOOLEAN NOT NULL DEFAULT TRUE COMMENT 'A necessidade da contenção persiste',
  situacao                 VARCHAR(30) NOT NULL DEFAULT 'pendente',
  observacao               VARCHAR(2000) NULL,
  origem                   VARCHAR(20) NOT NULL DEFAULT 'sistema',
  criado_em                DATETIME(3) NOT NULL,
  criado_por               BIGINT UNSIGNED NULL,
  alterado_em              DATETIME(3) NULL,
  alterado_por             BIGINT UNSIGNED NULL,
  versao                   INT UNSIGNED NOT NULL DEFAULT 1,
  excluido_em              DATETIME(3) NULL,
  excluido_por             BIGINT UNSIGNED NULL,
  CONSTRAINT ck_contencao_paciente_avaliacao_achado_perfusao CHECK (achado_perfusao IS NULL OR achado_perfusao IN ('normal','alterado')),
  CONSTRAINT ck_contencao_paciente_avaliacao_achado_pele CHECK (achado_pele IS NULL OR achado_pele IN ('normal','alterado')),
  CONSTRAINT ck_contencao_paciente_avaliacao_achado_posicao CHECK (achado_posicao IS NULL OR achado_posicao IN ('normal','alterado')),
  CONSTRAINT ck_contencao_paciente_avaliacao_achado_necessidades CHECK (achado_necessidades IS NULL OR achado_necessidades IN ('normal','alterado')),
  CONSTRAINT ck_contencao_paciente_avaliacao_situacao CHECK (situacao IN ('pendente','realizada','atrasada','nao_realizada','inativada')),
  CONSTRAINT ck_contencao_paciente_avaliacao_realizada CHECK (situacao <> 'realizada' OR (avaliado_em IS NOT NULL AND profissional_id IS NOT NULL)),
  CONSTRAINT ck_contencao_paciente_avaliacao_origem CHECK (origem IN ('sistema','migracao','integracao')),
  UNIQUE KEY uq_contencao_paciente_avaliacao_contencao_sequencia (contencao_paciente_id, sequencia),
  KEY ix_contencao_paciente_avaliacao_profissional (profissional_id),
  KEY ix_contencao_paciente_avaliacao_previsto (previsto_em, situacao)
) COMMENT='Reavaliação periódica da contenção (pele, circulação, necessidade)';

