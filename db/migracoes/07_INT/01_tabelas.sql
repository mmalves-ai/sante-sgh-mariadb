  municipio_ibge_id           BIGINT UNSIGNED NULL,
  empregador_cnpj             CHAR(14) NULL,
  empregador_nome             VARCHAR(150) NULL,
  atividade_economica_cnae    VARCHAR(7) NULL COMMENT 'CNAE da atividade do empregador',
  vinculo_previdenciario      VARCHAR(30) NULL,
  ocupacao_cbo_id             BIGINT UNSIGNED NULL COMMENT 'Ocupação do acidentado',
  numero_comunicacao_acidente VARCHAR(30) NULL COMMENT 'Número da comunicação de acidente de trabalho (CAT)',
  comunicacao_emitida_em      DATE NULL,
  origem_atendimento_id       BIGINT UNSIGNED NULL COMMENT 'Atendimento em que o acidente foi registrado primeiro',
  protocolo_origem            VARCHAR(100) NULL,
  sequela_atendimento_id      BIGINT UNSIGNED NULL COMMENT 'Atendimento anterior do mesmo acidente, quando esta internação trata sequela',
  protocolo_sequela           VARCHAR(100) NULL,
  boletim_ocorrencia          VARCHAR(50) NULL,
  descricao                   TEXT NULL,
  origem                      VARCHAR(20) NOT NULL DEFAULT 'sistema' COMMENT 'sistema, migracao ou integracao',
  criado_em                   DATETIME(3) NOT NULL,
  criado_por                  BIGINT UNSIGNED NULL,
  alterado_em                 DATETIME(3) NULL,
  alterado_por                BIGINT UNSIGNED NULL,
  versao                      INT UNSIGNED NOT NULL DEFAULT 1,
  excluido_em                 DATETIME(3) NULL,
  excluido_por                BIGINT UNSIGNED NULL,
  CONSTRAINT ck_acidente_internacao_tipo_acidente CHECK (tipo_acidente IN ('trabalho','trabalho_trajeto','transito','violencia','queda','outro')),
  CONSTRAINT ck_acidente_internacao_vinculo_previdenciario CHECK (vinculo_previdenciario IS NULL OR vinculo_previdenciario IN ('empregado','empregado_domestico','avulso','segurado_especial','contribuinte_individual','servidor_publico','desempregado','nao_segurado','outro')),
  CONSTRAINT ck_acidente_internacao_origem CHECK (origem IN ('sistema','migracao','integracao')),
  UNIQUE KEY uq_acidente_internacao_internacao_sequencia (internacao_id, sequencia),
  KEY ix_acidente_internacao_municipio_ibge (municipio_ibge_id),
  KEY ix_acidente_internacao_ocupacao_cbo (ocupacao_cbo_id),
  KEY ix_acidente_internacao_origem_atendimento (origem_atendimento_id),
  KEY ix_acidente_internacao_sequela_atendimento (sequela_atendimento_id)
) COMMENT='Dados do acidente que motivou a internação (trabalho, trânsito, outro) com local, data e comunicação de acidente de trabalho';

