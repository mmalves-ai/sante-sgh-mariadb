CREATE TABLE acidente_internacao (
  id                          BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
  internacao_id               BIGINT UNSIGNED NOT NULL,
  sequencia                   SMALLINT UNSIGNED NOT NULL DEFAULT 1,
  tipo_acidente               VARCHAR(30) NOT NULL,
  ocorrido_em                 DATETIME(3) NULL,
