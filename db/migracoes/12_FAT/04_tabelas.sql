CREATE TABLE item_faturavel_relacionado (
  id                             BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
  item_faturavel_id              BIGINT UNSIGNED NOT NULL COMMENT 'Item de partida',
  relacionado_item_faturavel_id  BIGINT UNSIGNED NOT NULL COMMENT 'Item ligado ao de partida',
  tipo_relacao                   VARCHAR(30) NOT NULL COMMENT 'hierarquia (item pai e filho), acessorio (lançado junto), equivalente, incompativel',
  lancamento_automatico          BOOLEAN NOT NULL DEFAULT FALSE COMMENT 'Acessório lançado automaticamente junto com o item de partida',
  quantidade                     DECIMAL(15,4) NULL COMMENT 'Quantidade do acessório por unidade do item de partida',
  percentual_valor               DECIMAL(7,4) NULL COMMENT 'Percentual do valor do item de partida cobrado no relacionado',
  faixa_valor_inicial            DECIMAL(15,2) NULL COMMENT 'Faixa de valor do item de partida em que o percentual vale',
  faixa_valor_final              DECIMAL(15,2) NULL,
  valor_teto                     DECIMAL(15,2) NULL COMMENT 'Teto do valor calculado por percentual',
  vigencia_inicio                DATE NOT NULL,
  vigencia_fim                   DATE NULL COMMENT 'Nulo enquanto vigente',
  criado_em                      DATETIME(3) NOT NULL,
  criado_por                     BIGINT UNSIGNED NULL,
  alterado_em                    DATETIME(3) NULL,
  alterado_por                   BIGINT UNSIGNED NULL,
  versao                         INT UNSIGNED NOT NULL DEFAULT 1,
  excluido_em                    DATETIME(3) NULL,
  excluido_por                   BIGINT UNSIGNED NULL,
  CONSTRAINT ck_item_faturavel_relacionado_tipo_relacao CHECK (tipo_relacao IN ('hierarquia','acessorio','equivalente','incompativel')),
  CONSTRAINT ck_item_faturavel_relacionado_itens_distintos CHECK (relacionado_item_faturavel_id <> item_faturavel_id),
  CONSTRAINT ck_item_faturavel_relacionado_percentual CHECK (percentual_valor IS NULL OR percentual_valor BETWEEN 0 AND 1000),
  CONSTRAINT ck_item_faturavel_relacionado_faixa CHECK (faixa_valor_final IS NULL OR faixa_valor_inicial IS NULL OR faixa_valor_final >= faixa_valor_inicial),
  CONSTRAINT ck_item_faturavel_relacionado_quantidade CHECK (quantidade IS NULL OR quantidade > 0),
  CONSTRAINT ck_item_faturavel_relacionado_vigencia CHECK (vigencia_fim IS NULL OR vigencia_fim >= vigencia_inicio),
  UNIQUE KEY uq_item_faturavel_relacionado_par (item_faturavel_id, relacionado_item_faturavel_id, tipo_relacao, vigencia_inicio),
  KEY ix_item_faturavel_relacionado_relacionado_item_faturavel (relacionado_item_faturavel_id)
) COMMENT='Itens ligados a outro item faturável (hierarquia, item acessório lançado junto, equivalente)';

