CREATE TABLE transferencia_conta (
  id                   BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
  estabelecimento_id   BIGINT UNSIGNED NOT NULL,
  numero               BIGINT UNSIGNED NOT NULL COMMENT 'Número de negócio da transferência (sequencia_negocio)',
  tipo                 VARCHAR(30) NOT NULL COMMENT 'fonte_pagadora, conta, estabelecimento, lote',
  conta_origem_id      BIGINT UNSIGNED NOT NULL COMMENT 'Conta hospitalar de onde os itens saem',
  conta_destino_id     BIGINT UNSIGNED NOT NULL COMMENT 'Conta hospitalar que recebe os itens',
  fonte_pagadora_origem_id BIGINT UNSIGNED NULL,
  fonte_pagadora_destino_id BIGINT UNSIGNED NULL,
  estabelecimento_destino_id BIGINT UNSIGNED NULL COMMENT 'Preenchido quando a transferência é entre estabelecimentos',
  lote_tiss_origem_id  BIGINT UNSIGNED NULL,
  lote_tiss_destino_id BIGINT UNSIGNED NULL,
  motivo               VARCHAR(500) NOT NULL,
  observacao           VARCHAR(1000) NULL,
  transferido_em       DATETIME(3) NOT NULL,
  usuario_id           BIGINT UNSIGNED NOT NULL COMMENT 'Autor da transferência',
  valor_total_origem   DECIMAL(15,2) NOT NULL DEFAULT 0,
  valor_total_destino  DECIMAL(15,2) NOT NULL DEFAULT 0 COMMENT 'Valor recalculado pelas regras da conta de destino',
  situacao             VARCHAR(30) NOT NULL DEFAULT 'efetivada',
  estornado_em         DATETIME(3) NULL,
  estorno_usuario_id   BIGINT UNSIGNED NULL,
  motivo_estorno       VARCHAR(500) NULL,
  origem               VARCHAR(20) NOT NULL DEFAULT 'sistema',
  criado_em            DATETIME(3) NOT NULL,
  criado_por           BIGINT UNSIGNED NULL,
  alterado_em          DATETIME(3) NULL,
  alterado_por         BIGINT UNSIGNED NULL,
  versao               INT UNSIGNED NOT NULL DEFAULT 1,
  excluido_em          DATETIME(3) NULL,
  excluido_por         BIGINT UNSIGNED NULL,
  UNIQUE KEY uq_transferencia_conta_estabelecimento_numero (estabelecimento_id, numero),
  KEY ix_transferencia_conta_conta_origem_id (conta_origem_id),
  KEY ix_transferencia_conta_conta_destino_id (conta_destino_id),
  KEY ix_transferencia_conta_fonte_pagadora_origem_id (fonte_pagadora_origem_id),
  KEY ix_transferencia_conta_fonte_pagadora_destino_id (fonte_pagadora_destino_id),
  KEY ix_transferencia_conta_estabelecimento_destino_id (estabelecimento_destino_id),
  KEY ix_transferencia_conta_lote_tiss_origem_id (lote_tiss_origem_id),
  KEY ix_transferencia_conta_lote_tiss_destino_id (lote_tiss_destino_id),
  KEY ix_transferencia_conta_usuario_id (usuario_id, transferido_em),
  KEY ix_transferencia_conta_estorno_usuario_id (estorno_usuario_id),
  CONSTRAINT ck_transferencia_conta_tipo CHECK (tipo IN ('fonte_pagadora','conta','estabelecimento','lote')),
  CONSTRAINT ck_transferencia_conta_situacao CHECK (situacao IN ('efetivada','estornada')),
  CONSTRAINT ck_transferencia_conta_origem CHECK (origem IN ('sistema','migracao','integracao')),
  CONSTRAINT ck_transferencia_conta_contas CHECK (conta_origem_id <> conta_destino_id OR tipo = 'lote'),
  CONSTRAINT ck_transferencia_conta_fonte CHECK (tipo <> 'fonte_pagadora' OR (fonte_pagadora_origem_id IS NOT NULL AND fonte_pagadora_destino_id IS NOT NULL AND fonte_pagadora_origem_id <> fonte_pagadora_destino_id)),
  CONSTRAINT ck_transferencia_conta_estabelecimento CHECK (tipo <> 'estabelecimento' OR estabelecimento_destino_id IS NOT NULL),
  CONSTRAINT ck_transferencia_conta_estorno CHECK (situacao <> 'estornada' OR (estornado_em IS NOT NULL AND estorno_usuario_id IS NOT NULL AND motivo_estorno IS NOT NULL)),
  CONSTRAINT ck_transferencia_conta_valores CHECK (valor_total_origem >= 0 AND valor_total_destino >= 0)
) COMMENT='Troca de fonte pagadora, conta ou estabelecimento de itens já lançados, com motivo e autor';

