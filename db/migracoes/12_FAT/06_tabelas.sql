-- Faturamento (FAT), lote 06: regras de lançamento, cobrança e repasse; RPA; autorização TISS;
-- restrição de cobertura; tabela de preço; tetos e domínios do faturamento.
-- Convenções: ADR 0002, parte 2. Sem FOREIGN KEY aqui; as chaves ficam em 06_chaves.sql.

CREATE TABLE regra_lancamento (
  id                            BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
  codigo                        VARCHAR(30) NOT NULL,
  descricao                     VARCHAR(150) NOT NULL,
  gatilho                       VARCHAR(30) NOT NULL COMMENT 'Evento que dispara a regra',
  gatilho_item_faturavel_id     BIGINT UNSIGNED NULL COMMENT 'Item cujo lançamento dispara a regra (gatilho lancamento_item)',
  gatilho_grupo_faturamento_id  BIGINT UNSIGNED NULL COMMENT 'Grupo cujo lançamento dispara a regra',
  acao                          VARCHAR(20) NOT NULL DEFAULT 'incluir' COMMENT 'O que a regra faz com os itens dela na conta',
  exige_confirmacao             BOOLEAN NOT NULL DEFAULT FALSE COMMENT 'Verdadeiro: o faturista confirma antes de lançar',
  lanca_uma_vez_por_conta       BOOLEAN NOT NULL DEFAULT FALSE,
  vigencia_inicio               DATE NOT NULL,
  vigencia_fim                  DATE NULL COMMENT 'Nulo: sem data de término',
  ativo                         BOOLEAN NOT NULL DEFAULT TRUE,
  observacao                    VARCHAR(500) NULL,
  criado_em                     DATETIME(3) NOT NULL,
  criado_por                    BIGINT UNSIGNED NULL,
  alterado_em                   DATETIME(3) NULL,
  alterado_por                  BIGINT UNSIGNED NULL,
  versao                        INT UNSIGNED NOT NULL DEFAULT 1,
  UNIQUE KEY uq_regra_lancamento_codigo (codigo),
  CONSTRAINT ck_regra_lancamento_gatilho CHECK (gatilho IN ('lancamento_item','abertura_atendimento','diaria_internacao','alta','procedimento_realizado','prescricao_checada','encaminhamento','transporte','dispositivo_instalado','parecer')),
  CONSTRAINT ck_regra_lancamento_acao CHECK (acao IN ('incluir','substituir','excluir','sugerir')),
  CONSTRAINT ck_regra_lancamento_gatilho_item CHECK (gatilho <> 'lancamento_item' OR gatilho_item_faturavel_id IS NOT NULL OR gatilho_grupo_faturamento_id IS NOT NULL),
  CONSTRAINT ck_regra_lancamento_vigencia CHECK (vigencia_fim IS NULL OR vigencia_fim >= vigencia_inicio),
  KEY ix_regra_lancamento_gatilho_item_faturavel_id (gatilho_item_faturavel_id),
  KEY ix_regra_lancamento_gatilho_grupo_faturamento_id (gatilho_grupo_faturamento_id)
) COMMENT='Regra que gera itens na conta a partir de um evento clínico ou administrativo';

