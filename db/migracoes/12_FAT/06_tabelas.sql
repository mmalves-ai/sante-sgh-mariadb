  KEY ix_regra_lancamento_excecao_plano_fonte_pagadora_id (plano_fonte_pagadora_id),
  KEY ix_regra_lancamento_excecao_setor_funcional_id (setor_funcional_id),
  KEY ix_regra_lancamento_excecao_especialidade_medica_id (especialidade_medica_id),
  KEY ix_regra_lancamento_excecao_item_faturavel_id (item_faturavel_id),
  KEY ix_regra_lancamento_excecao_grupo_faturamento_id (grupo_faturamento_id)
) COMMENT='Exceção à regra de lançamento por fonte pagadora, setor ou item';

CREATE TABLE regra_lancamento_item (
  id                          BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
  regra_lancamento_id         BIGINT UNSIGNED NOT NULL,
  sequencia                   SMALLINT UNSIGNED NOT NULL,
  item_faturavel_id           BIGINT UNSIGNED NULL,
  grupo_faturamento_id        BIGINT UNSIGNED NULL COMMENT 'Grupo inteiro (alternativa ao item)',
  tabela_preco_id             BIGINT UNSIGNED NULL COMMENT 'Tabela de preço forçada; nulo: a do acordo',
  quantidade                  DECIMAL(15,4) NOT NULL DEFAULT 1,
  tipo_valor                  VARCHAR(20) NOT NULL DEFAULT 'tabela',
  percentual                  DECIMAL(7,4) NULL COMMENT 'Percentual sobre o valor do item gatilho (tipo_valor percentual)',
  valor                       DECIMAL(15,2) NULL COMMENT 'Valor fixo (tipo_valor valor_fixo)',
  executante_profissional_id  BIGINT UNSIGNED NULL COMMENT 'Executante fixo do item lançado',
  funcao_equipe_cobranca_id   BIGINT UNSIGNED NULL,
  setor_funcional_id          BIGINT UNSIGNED NULL COMMENT 'Setor em que o item é lançado; nulo: o do gatilho',
  faturamento_direto          BOOLEAN NOT NULL DEFAULT FALSE,
  exige_auditoria             BOOLEAN NOT NULL DEFAULT FALSE,
  incide_exame                BOOLEAN NOT NULL DEFAULT FALSE COMMENT 'Incide sobre exames do atendimento',
  aplica_internacao           BOOLEAN NOT NULL DEFAULT TRUE,
  aplica_ambulatorial         BOOLEAN NOT NULL DEFAULT TRUE,
  aplica_externo              BOOLEAN NOT NULL DEFAULT TRUE,
  aplica_urgencia             BOOLEAN NOT NULL DEFAULT TRUE,
  aplica_domiciliar           BOOLEAN NOT NULL DEFAULT TRUE,
  condicao                    VARCHAR(500) NULL COMMENT 'Condição adicional descrita para o faturista',
  origem                      VARCHAR(20) NOT NULL DEFAULT 'sistema',
  criado_em                   DATETIME(3) NOT NULL,
  criado_por                  BIGINT UNSIGNED NULL,
  alterado_em                 DATETIME(3) NULL,
  alterado_por                BIGINT UNSIGNED NULL,
  versao                      INT UNSIGNED NOT NULL DEFAULT 1,
  excluido_em                 DATETIME(3) NULL,
  excluido_por                BIGINT UNSIGNED NULL,
  UNIQUE KEY uq_regra_lancamento_item_regra_sequencia (regra_lancamento_id, sequencia),
  CONSTRAINT ck_regra_lancamento_item_alvo CHECK (item_faturavel_id IS NOT NULL OR grupo_faturamento_id IS NOT NULL),
  CONSTRAINT ck_regra_lancamento_item_quantidade CHECK (quantidade > 0),
  CONSTRAINT ck_regra_lancamento_item_tipo_valor CHECK (tipo_valor IN ('tabela','percentual','valor_fixo')),
  CONSTRAINT ck_regra_lancamento_item_valor CHECK ((tipo_valor <> 'percentual' OR percentual IS NOT NULL) AND (tipo_valor <> 'valor_fixo' OR valor IS NOT NULL)),
  CONSTRAINT ck_regra_lancamento_item_faixas CHECK ((percentual IS NULL OR percentual >= 0) AND (valor IS NULL OR valor >= 0)),
  CONSTRAINT ck_regra_lancamento_item_origem CHECK (origem IN ('sistema','migracao','integracao')),
  KEY ix_regra_lancamento_item_item_faturavel_id (item_faturavel_id),
  KEY ix_regra_lancamento_item_grupo_faturamento_id (grupo_faturamento_id),
  KEY ix_regra_lancamento_item_tabela_preco_id (tabela_preco_id),
  KEY ix_regra_lancamento_item_executante_profissional_id (executante_profissional_id),
  KEY ix_regra_lancamento_item_funcao_equipe_cobranca_id (funcao_equipe_cobranca_id),
  KEY ix_regra_lancamento_item_setor_funcional_id (setor_funcional_id)
) COMMENT='Itens que a regra lança, com quantidade e condição';

