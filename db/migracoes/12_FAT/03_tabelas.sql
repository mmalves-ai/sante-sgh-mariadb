CREATE TABLE franquia_contrato (
  id                          BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
  contrato_fonte_pagadora_id  BIGINT UNSIGNED NOT NULL,
  plano_fonte_pagadora_id     BIGINT UNSIGNED NULL COMMENT 'Nulo: vale para todos os planos do acordo',
  descricao                   VARCHAR(150) NOT NULL,
  regime_atendimento_id       BIGINT UNSIGNED NULL COMMENT 'Nulo: vale para qualquer regime',
  item_faturavel_id           BIGINT UNSIGNED NULL,
  grupo_faturamento_id        BIGINT UNSIGNED NULL,
  aplica_titular              BOOLEAN NOT NULL DEFAULT TRUE,
  aplica_dependente           BOOLEAN NOT NULL DEFAULT TRUE,
  aplica_pensionista          BOOLEAN NOT NULL DEFAULT TRUE,
  idade_minima                SMALLINT UNSIGNED NULL,
  idade_maxima                SMALLINT UNSIGNED NULL,
  tipo_franquia               VARCHAR(30) NOT NULL,
  valor_franquia              DECIMAL(15,2) NULL COMMENT 'Limite em valor abaixo do qual não se cobra',
  quantidade_pontos           DECIMAL(15,4) NULL COMMENT 'Limite em pontos ou quantidade',
  valor_ponto                 DECIMAL(15,2) NULL,
  percentual_participacao     DECIMAL(7,4) NULL COMMENT 'Participação cobrada sobre o valor',
  valor_participacao          DECIMAL(15,2) NULL COMMENT 'Participação fixa cobrada',
  vigencia_inicio             DATE NOT NULL,
  vigencia_fim                DATE NULL,
  ativo                       BOOLEAN NOT NULL DEFAULT TRUE,
  criado_em                   DATETIME(3) NOT NULL,
  criado_por                  BIGINT UNSIGNED NULL,
  alterado_em                 DATETIME(3) NULL,
  alterado_por                BIGINT UNSIGNED NULL,
  versao                      INT UNSIGNED NOT NULL DEFAULT 1,
  CONSTRAINT ck_franquia_contrato_tipo CHECK (tipo_franquia IN ('valor','quantidade','percentual')),
  CONSTRAINT ck_franquia_contrato_parametro CHECK (
    (tipo_franquia = 'valor' AND valor_franquia IS NOT NULL)
    OR (tipo_franquia = 'quantidade' AND quantidade_pontos IS NOT NULL)
    OR (tipo_franquia = 'percentual' AND percentual_participacao IS NOT NULL)),
  CONSTRAINT ck_franquia_contrato_valores CHECK ((valor_franquia IS NULL OR valor_franquia >= 0) AND (quantidade_pontos IS NULL OR quantidade_pontos >= 0) AND (percentual_participacao IS NULL OR percentual_participacao BETWEEN 0 AND 100) AND (valor_participacao IS NULL OR valor_participacao >= 0)),
  CONSTRAINT ck_franquia_contrato_idade CHECK (idade_minima IS NULL OR idade_maxima IS NULL OR idade_maxima >= idade_minima),
  CONSTRAINT ck_franquia_contrato_vigencia CHECK (vigencia_fim IS NULL OR vigencia_fim >= vigencia_inicio),
  KEY ix_franquia_contrato_contrato (contrato_fonte_pagadora_id, vigencia_inicio),
  KEY ix_franquia_contrato_plano (plano_fonte_pagadora_id),
  KEY ix_franquia_contrato_regime (regime_atendimento_id),
  KEY ix_franquia_contrato_item (item_faturavel_id),
  KEY ix_franquia_contrato_grupo (grupo_faturamento_id)
) COMMENT='Franquia de valor ou quantidade no acordo, abaixo da qual o hospital não cobra ou cobra diferente';

