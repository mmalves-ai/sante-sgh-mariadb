CREATE TABLE pacote_item_incluso (
  id                     BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
  pacote_id              BIGINT UNSIGNED NOT NULL,
  sequencia              SMALLINT UNSIGNED NOT NULL,
  item_faturavel_id      BIGINT UNSIGNED NULL COMMENT 'Item incluído (nulo quando a inclusão é por grupo)',
  grupo_faturamento_id   BIGINT UNSIGNED NULL COMMENT 'Grupo inteiro incluído no pacote',
  item_referencia_matmed_id BIGINT UNSIGNED NULL COMMENT 'Material ou medicamento incluído (item da tabela de referência de mat/med)',
  centro_custo_id        BIGINT UNSIGNED NULL COMMENT 'Centro de custo em que o item é coberto (nulo: qualquer um)',
  item_faturavel_similar_id BIGINT UNSIGNED NULL COMMENT 'Item similar aceito no lugar do item incluído',
  fator_conversao_similar DECIMAL(15,4) NULL COMMENT 'Quantas unidades do similar equivalem a uma do item',
  funcao_equipe_cobranca_id BIGINT UNSIGNED NULL COMMENT 'Função da equipe coberta (honorário incluído)',
  setor_funcional_id     BIGINT UNSIGNED NULL COMMENT 'Setor em que o item é coberto (nulo: qualquer setor)',
  quantidade_limite      DECIMAL(15,4) NULL COMMENT 'Quantidade coberta; o excedente é cobrado fora do pacote (nulo: sem limite)',
  quantidade_por_diaria  BOOLEAN NOT NULL DEFAULT FALSE COMMENT 'A quantidade limite vale por diária do pacote',
  frequencia             DECIMAL(15,4) NULL COMMENT 'Frequência prevista de uso no protocolo do pacote',
  valor_unitario         DECIMAL(15,2) NULL COMMENT 'Valor de referência do item dentro do pacote',
  observacao             VARCHAR(500) NULL,
  origem                 VARCHAR(20) NOT NULL DEFAULT 'sistema',
  criado_em              DATETIME(3) NOT NULL,
  criado_por             BIGINT UNSIGNED NULL,
  alterado_em            DATETIME(3) NULL,
  alterado_por           BIGINT UNSIGNED NULL,
  versao                 INT UNSIGNED NOT NULL DEFAULT 1,
  excluido_em            DATETIME(3) NULL,
  excluido_por           BIGINT UNSIGNED NULL,
  CONSTRAINT ck_pacote_item_incluso_origem CHECK (origem IN ('sistema','migracao','integracao')),
  CONSTRAINT ck_pacote_item_incluso_alvo CHECK (item_faturavel_id IS NOT NULL OR grupo_faturamento_id IS NOT NULL OR item_referencia_matmed_id IS NOT NULL),
  CONSTRAINT ck_pacote_item_incluso_quantidade CHECK (quantidade_limite IS NULL OR quantidade_limite > 0),
  CONSTRAINT ck_pacote_item_incluso_valor CHECK (valor_unitario IS NULL OR valor_unitario >= 0),
  UNIQUE KEY uq_pacote_item_incluso_pacote_sequencia (pacote_id, sequencia),
  UNIQUE KEY uq_pacote_item_incluso_pacote_item_grupo_setor (pacote_id, item_faturavel_id, grupo_faturamento_id, setor_funcional_id),
  KEY ix_pacote_item_incluso_item_faturavel_id (item_faturavel_id),
  KEY ix_pacote_item_incluso_item_referencia_matmed_id (item_referencia_matmed_id),
  KEY ix_pacote_item_incluso_centro_custo_id (centro_custo_id),
  KEY ix_pacote_item_incluso_grupo_faturamento_id (grupo_faturamento_id),
  KEY ix_pacote_item_incluso_item_faturavel_similar_id (item_faturavel_similar_id),
  KEY ix_pacote_item_incluso_funcao_equipe_cobranca_id (funcao_equipe_cobranca_id),
  KEY ix_pacote_item_incluso_setor_funcional_id (setor_funcional_id)
) COMMENT='Itens incluídos no pacote, com quantidade limite';

CREATE TABLE pacote_teto (
  id                     BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
  pacote_id              BIGINT UNSIGNED NOT NULL,
  grupo_faturamento_id   BIGINT UNSIGNED NULL COMMENT 'Teto do grupo (nulo: teto geral do pacote)',
  dias_teto              SMALLINT UNSIGNED NULL COMMENT 'Dias de permanência acima dos quais o pacote se descaracteriza',
  quantidade_teto        DECIMAL(15,4) NULL,
