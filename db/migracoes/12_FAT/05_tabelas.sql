  criado_por             BIGINT UNSIGNED NULL,
  alterado_em            DATETIME(3) NULL,
  alterado_por           BIGINT UNSIGNED NULL,
  versao                 INT UNSIGNED NOT NULL DEFAULT 1,
  CONSTRAINT ck_pacote_teto_algum CHECK (dias_teto IS NOT NULL OR quantidade_teto IS NOT NULL OR quantidade_indice_teto IS NOT NULL OR valor_teto IS NOT NULL),
