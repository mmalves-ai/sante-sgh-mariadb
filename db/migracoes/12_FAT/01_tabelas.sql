  justificativa              VARCHAR(1000) NOT NULL,
  situacao                   VARCHAR(30) NOT NULL DEFAULT 'pendente_aprovacao',
  solicitado_em              DATETIME(3) NOT NULL,
  solicitado_por_usuario_id  BIGINT UNSIGNED NOT NULL,
  pedido_aprovacao_id        BIGINT UNSIGNED NULL COMMENT 'Pedido no mecanismo de alçada de aprovação',
  decidido_em                DATETIME(3) NULL,
  decidido_por_usuario_id    BIGINT UNSIGNED NULL,
  origem                     VARCHAR(20) NOT NULL DEFAULT 'sistema',
  criado_em                          DATETIME(3) NOT NULL,
  criado_por                        BIGINT UNSIGNED NULL,
  alterado_em                      DATETIME(3) NULL,
  alterado_por                    BIGINT UNSIGNED NULL,
  versao                                INT UNSIGNED NOT NULL DEFAULT 1,
  excluido_em                DATETIME(3) NULL,
  excluido_por               BIGINT UNSIGNED NULL,
  CONSTRAINT ck_ajuste_conta_origem CHECK (origem IN ('sistema','migracao','integracao')),
  CONSTRAINT ck_ajuste_conta_tipo CHECK (tipo IN ('acrescimo','desconto')),
  CONSTRAINT ck_ajuste_conta_forma_calculo CHECK (forma_calculo IN ('valor','percentual')),
  CONSTRAINT ck_ajuste_conta_percentual CHECK (forma_calculo = 'valor' OR percentual IS NOT NULL),
  CONSTRAINT ck_ajuste_conta_valor CHECK (valor > 0),
  CONSTRAINT ck_ajuste_conta_situacao CHECK (situacao IN ('pendente_aprovacao','aprovado','recusado','cancelado')),
  CONSTRAINT ck_ajuste_conta_decisao CHECK (situacao NOT IN ('aprovado','recusado') OR (decidido_em IS NOT NULL AND decidido_por_usuario_id IS NOT NULL)),
  KEY ix_ajuste_conta_conta_hospitalar_id_situacao (conta_hospitalar_id, situacao),
  KEY ix_ajuste_conta_estabelecimento_id (estabelecimento_id),
  KEY ix_ajuste_conta_motivo_ajuste_conta_id (motivo_ajuste_conta_id),
  KEY ix_ajuste_conta_solicitado_por_usuario_id (solicitado_por_usuario_id),
  KEY ix_ajuste_conta_pedido_aprovacao_id (pedido_aprovacao_id),
  KEY ix_ajuste_conta_decidido_por_usuario_id (decidido_por_usuario_id)
) COMMENT='Acréscimo ou desconto manual na conta, com motivo, valor, autor e aprovação';

