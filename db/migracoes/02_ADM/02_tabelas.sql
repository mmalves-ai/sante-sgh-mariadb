CREATE TABLE exportacao_documento (
  id                BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
  estabelecimento_id BIGINT UNSIGNED NOT NULL,
  documento_prontuario_id BIGINT UNSIGNED NULL,
  documento_emitido_id BIGINT UNSIGNED NULL,
  documento_assinado_id BIGINT UNSIGNED NULL,
  entidade          VARCHAR(64) NULL COMMENT 'Tabela do registro exportado, quando não é documento do prontuário',
  entidade_id       BIGINT UNSIGNED NULL,
  paciente_id       BIGINT UNSIGNED NULL,
  atendimento_id    BIGINT UNSIGNED NULL,
  tipo_operacao     VARCHAR(30) NOT NULL COMMENT 'impressao, reimpressao, exportacao, envio',
  formato           VARCHAR(30) NOT NULL,
  destino           VARCHAR(30) NOT NULL,
  impressora_id     BIGINT UNSIGNED NULL,
  quantidade_copias SMALLINT UNSIGNED NOT NULL DEFAULT 1,
  tipo_justificativa_exportacao_id BIGINT UNSIGNED NULL,
  motivo_reimpressao_id BIGINT UNSIGNED NULL,
  justificativa     VARCHAR(500) NULL COMMENT 'Texto livre complementar à justificativa padronizada',
  ocupacao_cbo_id   BIGINT UNSIGNED NULL COMMENT 'Ocupação do profissional no momento da exportação',
  arquivo_id        BIGINT UNSIGNED NULL COMMENT 'Arquivo gerado, quando guardado',
  hash_sha256       CHAR(64) NULL COMMENT 'Resumo do conteúdo exportado, para conferência posterior',
  estacao_trabalho_id BIGINT UNSIGNED NULL,
  endereco_ip       VARCHAR(45) NULL,
  dados             JSON NULL COMMENT 'Parâmetros da exportação (páginas, filtros, destinatário)',
  ocorrido_em       DATETIME(3) NOT NULL,
  usuario_id        BIGINT UNSIGNED NOT NULL COMMENT 'Usuário que imprimiu ou exportou',
  criado_em         DATETIME(3) NOT NULL,
  criado_por        BIGINT UNSIGNED NULL,
  alterado_em       DATETIME(3) NULL,
  alterado_por      BIGINT UNSIGNED NULL,
  versao            INT UNSIGNED NOT NULL DEFAULT 1,
  CONSTRAINT ck_exportacao_documento_tipo_operacao CHECK (tipo_operacao IN ('impressao','reimpressao','exportacao','envio')),
  CONSTRAINT ck_exportacao_documento_formato CHECK (formato IN ('impresso','pdf','xml','json','fhir','imagem','texto','outro')),
  CONSTRAINT ck_exportacao_documento_destino CHECK (destino IN ('impressora','download','email','integracao','portal','midia_externa')),
  CONSTRAINT ck_exportacao_documento_copias CHECK (quantidade_copias BETWEEN 1 AND 999),
  CONSTRAINT ck_exportacao_documento_alvo CHECK (documento_prontuario_id IS NOT NULL OR documento_emitido_id IS NOT NULL OR documento_assinado_id IS NOT NULL OR entidade IS NOT NULL),
  CONSTRAINT ck_exportacao_documento_justificativa CHECK (tipo_justificativa_exportacao_id IS NOT NULL OR motivo_reimpressao_id IS NOT NULL OR justificativa IS NOT NULL OR tipo_operacao = 'impressao'),
  KEY ix_exportacao_documento_estabelecimento (estabelecimento_id, ocorrido_em),
  KEY ix_exportacao_documento_documento_prontuario (documento_prontuario_id),
  KEY ix_exportacao_documento_documento_emitido (documento_emitido_id),
  KEY ix_exportacao_documento_documento_assinado (documento_assinado_id),
  KEY ix_exportacao_documento_entidade (entidade, entidade_id),
  KEY ix_exportacao_documento_paciente (paciente_id, ocorrido_em),
  KEY ix_exportacao_documento_atendimento (atendimento_id),
  KEY ix_exportacao_documento_impressora (impressora_id),
  KEY ix_exportacao_documento_tipo_justificativa (tipo_justificativa_exportacao_id),
  KEY ix_exportacao_documento_motivo_reimpressao (motivo_reimpressao_id),
  KEY ix_exportacao_documento_ocupacao_cbo (ocupacao_cbo_id),
  KEY ix_exportacao_documento_arquivo (arquivo_id),
  KEY ix_exportacao_documento_estacao (estacao_trabalho_id),
  KEY ix_exportacao_documento_usuario (usuario_id, ocorrido_em)
) COMMENT='Cada impressão ou exportação de documento do prontuário, com justificativa, usuário, formato e destino';

