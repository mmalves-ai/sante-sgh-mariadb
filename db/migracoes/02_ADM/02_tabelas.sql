CREATE TABLE parametro_valor (
  id                BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
  parametro_definicao_id BIGINT UNSIGNED NOT NULL,
  nivel             VARCHAR(30) NOT NULL,
  estabelecimento_id BIGINT UNSIGNED NULL,
  unidade_assistencial_id BIGINT UNSIGNED NULL,
  perfil_acesso_id  BIGINT UNSIGNED NULL,
  usuario_id        BIGINT UNSIGNED NULL,
  escopo_chave      VARCHAR(120) AS (CONCAT_WS(':', nivel, COALESCE(estabelecimento_id, 0), COALESCE(unidade_assistencial_id, 0), COALESCE(perfil_acesso_id, 0), COALESCE(usuario_id, 0))) PERSISTENT COMMENT 'Apoio à unicidade do escopo',
  valor             TEXT NOT NULL,
  vigencia_inicio   DATETIME(3) NOT NULL,
  vigencia_fim      DATETIME(3) NULL,
  motivo            VARCHAR(500) NULL,
  criado_em         DATETIME(3) NOT NULL,
  criado_por        BIGINT UNSIGNED NULL,
  alterado_em       DATETIME(3) NULL,
  alterado_por      BIGINT UNSIGNED NULL,
  versao            INT UNSIGNED NOT NULL DEFAULT 1,
  CONSTRAINT ck_parametro_valor_nivel CHECK (nivel IN ('rede','estabelecimento','unidade','perfil','usuario')),
  CONSTRAINT ck_parametro_valor_escopo CHECK (
    (nivel = 'rede' AND estabelecimento_id IS NULL AND unidade_assistencial_id IS NULL AND perfil_acesso_id IS NULL AND usuario_id IS NULL)
    OR (nivel = 'estabelecimento' AND estabelecimento_id IS NOT NULL AND unidade_assistencial_id IS NULL AND perfil_acesso_id IS NULL AND usuario_id IS NULL)
    OR (nivel = 'unidade' AND unidade_assistencial_id IS NOT NULL AND perfil_acesso_id IS NULL AND usuario_id IS NULL)
    OR (nivel = 'perfil' AND perfil_acesso_id IS NOT NULL AND usuario_id IS NULL)
    OR (nivel = 'usuario' AND usuario_id IS NOT NULL)),
  CONSTRAINT ck_parametro_valor_vigencia CHECK (vigencia_fim IS NULL OR vigencia_fim > vigencia_inicio),
  UNIQUE KEY uq_parametro_valor_escopo_vigencia (parametro_definicao_id, escopo_chave, vigencia_inicio),
  KEY ix_parametro_valor_estabelecimento (estabelecimento_id),
  KEY ix_parametro_valor_unidade (unidade_assistencial_id),
  KEY ix_parametro_valor_perfil (perfil_acesso_id),
  KEY ix_parametro_valor_usuario (usuario_id)
) COMMENT='Valor de um parâmetro num escopo (rede, estabelecimento, unidade, usuário), com vigência';

