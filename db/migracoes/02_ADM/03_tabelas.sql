CREATE TABLE pedido_titular (
  id                BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
  estabelecimento_id BIGINT UNSIGNED NOT NULL,
  numero            VARCHAR(30) NOT NULL COMMENT 'Número de protocolo do pedido (sequencia_negocio)',
  paciente_id       BIGINT UNSIGNED NULL COMMENT 'Paciente titular, quando o titular é paciente',
  titular_nome      VARCHAR(150) NOT NULL,
  titular_cpf       CHAR(11) NULL,
  titular_email     VARCHAR(254) NULL,
  titular_telefone  VARCHAR(20) NULL,
  representante_nome VARCHAR(150) NULL COMMENT 'Procurador ou responsável legal, quando o pedido não é do próprio titular',
  tipo              VARCHAR(40) NOT NULL,
  canal_recebimento VARCHAR(30) NOT NULL,
  descricao         TEXT NOT NULL COMMENT 'O que o titular pediu',
  recebido_em       DATETIME(3) NOT NULL,
  prazo_em          DATE NOT NULL COMMENT 'Prazo legal de resposta (15 dias, regra do domínio)',
  identidade_confirmada BOOLEAN NOT NULL DEFAULT FALSE,
  identidade_confirmada_em DATETIME(3) NULL,
  responsavel_usuario_id BIGINT UNSIGNED NULL COMMENT 'Encarregado ou analista que conduz o pedido',
  situacao          VARCHAR(30) NOT NULL DEFAULT 'recebido',
  resposta          TEXT NULL,
  respondido_em     DATETIME(3) NULL,
  resposta_arquivo_id BIGINT UNSIGNED NULL COMMENT 'Documento entregue ao titular',
  motivo_indeferimento VARCHAR(500) NULL,
  origem            VARCHAR(20) NOT NULL DEFAULT 'sistema' COMMENT 'sistema, migracao ou integracao',
  criado_em         DATETIME(3) NOT NULL,
  criado_por        BIGINT UNSIGNED NULL,
  alterado_em       DATETIME(3) NULL,
  alterado_por      BIGINT UNSIGNED NULL,
  versao            INT UNSIGNED NOT NULL DEFAULT 1,
  excluido_em       DATETIME(3) NULL,
  excluido_por      BIGINT UNSIGNED NULL,
  CONSTRAINT ck_pedido_titular_tipo CHECK (tipo IN ('confirmacao','acesso','correcao','anonimizacao','portabilidade','eliminacao','informacao_compartilhamento','revogacao_consentimento','oposicao','revisao_decisao_automatizada')),
  CONSTRAINT ck_pedido_titular_canal CHECK (canal_recebimento IN ('presencial','email','portal','telefone','carta')),
  CONSTRAINT ck_pedido_titular_situacao CHECK (situacao IN ('recebido','em_analise','aguardando_titular','atendido','atendido_parcial','indeferido','cancelado')),
  CONSTRAINT ck_pedido_titular_indeferimento CHECK (situacao <> 'indeferido' OR motivo_indeferimento IS NOT NULL),
  UNIQUE KEY uq_pedido_titular_estabelecimento_numero (estabelecimento_id, numero),
  KEY ix_pedido_titular_situacao_prazo (situacao, prazo_em),
  CONSTRAINT ck_pedido_titular_origem CHECK (origem IN ('sistema','migracao','integracao')),
  KEY ix_pedido_titular_paciente (paciente_id),
  KEY ix_pedido_titular_responsavel_usuario (responsavel_usuario_id),
  KEY ix_pedido_titular_resposta_arquivo (resposta_arquivo_id)
) COMMENT='Pedido do titular (acesso, correção, portabilidade, eliminação), com prazo legal, responsável e resposta';

