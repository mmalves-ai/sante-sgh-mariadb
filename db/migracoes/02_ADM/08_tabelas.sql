-- pedido do lote 02-04
CREATE TABLE saneamento_acesso_item (
  id                BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
  estabelecimento_id BIGINT UNSIGNED NOT NULL,
  perfil_origem_id  BIGINT UNSIGNED NOT NULL COMMENT 'Perfil de acesso amplo em saneamento',
  usuario_id        BIGINT UNSIGNED NULL COMMENT 'Conta decidida; nulo na dissolução do perfil',
  decisao           VARCHAR(30) NOT NULL,
  perfil_destino_id BIGINT UNSIGNED NULL COMMENT 'Perfil de trabalho de destino (decisão trocar_perfil)',
  perdas_total      INT UNSIGNED NOT NULL DEFAULT 0 COMMENT 'Ações que a conta perde',
  perdas_usadas     INT UNSIGNED NOT NULL DEFAULT 0 COMMENT 'Dessas, as usadas na janela do uso',
  exige_aprovacao   BOOLEAN NOT NULL DEFAULT FALSE,
  situacao          VARCHAR(20) NOT NULL DEFAULT 'proposto',
  motivo            VARCHAR(200) NOT NULL,
  area              VARCHAR(60) NULL COMMENT 'Área que aprovou a perda de ação usada',
  aprovador_usuario_id BIGINT UNSIGNED NULL,
  aprovado_em       DATETIME(3) NULL,
  motivo_aprovacao  VARCHAR(200) NULL,
  reservado_por     BIGINT UNSIGNED NULL COMMENT 'Reserva da aplicação (vence em minutos)',
  reservado_em      DATETIME(3) NULL,
  aplicado_por      BIGINT UNSIGNED NULL,
  aplicado_em       DATETIME(3) NULL,
  descartado_por    BIGINT UNSIGNED NULL,
  descartado_em     DATETIME(3) NULL,
  erro              VARCHAR(200) NULL COMMENT 'Código curto da falha da aplicação, sem dado de pessoa',
  criado_em         DATETIME(3) NOT NULL,
  criado_por        BIGINT UNSIGNED NULL COMMENT 'Quem propôs a decisão',
  alterado_em       DATETIME(3) NULL,
  alterado_por      BIGINT UNSIGNED NULL,
  versao            INT UNSIGNED NOT NULL DEFAULT 1,
  excluido_em       DATETIME(3) NULL,
  excluido_por      BIGINT UNSIGNED NULL,
  CONSTRAINT ck_saneamento_acesso_item_decisao CHECK (decisao IN ('trocar_perfil','bloquear','manter_administrador','dissolver_perfil')),
  CONSTRAINT ck_saneamento_acesso_item_situacao CHECK (situacao IN ('proposto','aprovado','aplicado','descartado','falhou')),
  CONSTRAINT ck_saneamento_acesso_item_destino CHECK ((decisao = 'trocar_perfil') = (perfil_destino_id IS NOT NULL)),
  CONSTRAINT ck_saneamento_acesso_item_alvo CHECK ((decisao = 'dissolver_perfil') = (usuario_id IS NULL)),
  CONSTRAINT ck_saneamento_acesso_item_a_si CHECK (usuario_id IS NULL OR criado_por IS NULL OR usuario_id <> criado_por),
  CONSTRAINT ck_saneamento_acesso_item_aprovador CHECK (aprovador_usuario_id IS NULL OR ((criado_por IS NULL OR aprovador_usuario_id <> criado_por) AND (usuario_id IS NULL OR aprovador_usuario_id <> usuario_id))),
  CONSTRAINT ck_saneamento_acesso_item_aprovacao CHECK (situacao <> 'aprovado' OR (exige_aprovacao AND aprovador_usuario_id IS NOT NULL AND aprovado_em IS NOT NULL)),
  CONSTRAINT ck_saneamento_acesso_item_perdas CHECK (perdas_usadas <= perdas_total),
  CONSTRAINT ck_saneamento_acesso_item_aplicado CHECK (situacao <> 'aplicado' OR NOT exige_aprovacao OR aprovador_usuario_id IS NOT NULL),
  KEY ix_saneamento_acesso_item_estabelecimento (estabelecimento_id, situacao),
  KEY ix_saneamento_acesso_item_perfil_origem (perfil_origem_id),
  KEY ix_saneamento_acesso_item_usuario (usuario_id),
  KEY ix_saneamento_acesso_item_perfil_destino (perfil_destino_id),
  KEY ix_saneamento_acesso_item_aprovador (aprovador_usuario_id)
) COMMENT='Plano do saneamento dos perfis de acesso amplo: a decisão por conta (trocar de perfil, bloquear, manter administrador) ou a dissolução do perfil, com aprovação da área e a aplicação';

-- pedido do lote 02-04
CREATE TABLE uso_acao_usuario (
  id                BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
  estabelecimento_id BIGINT UNSIGNED NOT NULL,
  usuario_id        BIGINT UNSIGNED NOT NULL,
  acao_sistema_id   BIGINT UNSIGNED NOT NULL,
  dia               DATE NOT NULL COMMENT 'Dia do uso (UTC)',
  quantidade        INT UNSIGNED NOT NULL DEFAULT 1 COMMENT 'Usos da ação pela conta no dia',
  primeiro_uso_em   DATETIME(3) NOT NULL,
  ultimo_uso_em     DATETIME(3) NOT NULL,
  criado_em         DATETIME(3) NOT NULL,
  criado_por        BIGINT UNSIGNED NULL,
  alterado_em       DATETIME(3) NULL,
  alterado_por      BIGINT UNSIGNED NULL,
  versao            INT UNSIGNED NOT NULL DEFAULT 1,
  UNIQUE KEY uq_uso_acao_usuario_dia (estabelecimento_id, usuario_id, acao_sistema_id, dia),
  KEY ix_uso_acao_usuario_estabelecimento_dia (estabelecimento_id, dia),
  KEY ix_uso_acao_usuario_usuario (usuario_id),
  KEY ix_uso_acao_usuario_acao (acao_sistema_id),
  CONSTRAINT ck_uso_acao_usuario_quantidade CHECK (quantidade > 0),
  CONSTRAINT ck_uso_acao_usuario_periodo CHECK (ultimo_uso_em >= primeiro_uso_em)
) COMMENT='Uso das ações do sistema por conta, estabelecimento e dia, contado pela guarda de permissão (base do saneamento e da recertificação dos perfis)';

-- pedido do lote 02-06
CREATE TABLE ciclo_certificacao (
  id                BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
  estabelecimento_id BIGINT UNSIGNED NOT NULL,
  tipo              VARCHAR(30) NOT NULL COMMENT 'Autoavaliação, pré-auditoria ou auditoria formal',
  competencia       CHAR(7) NOT NULL COMMENT 'Mês de referência AAAA-MM',
  versao_software   VARCHAR(40) NOT NULL COMMENT 'Versão do sistema avaliada',
  referencia        VARCHAR(120) NOT NULL COMMENT 'Manual de certificação de referência',
  avaliador         VARCHAR(120) NULL COMMENT 'Organização do consultor externo ou da auditoria',
  situacao          VARCHAR(30) NOT NULL DEFAULT 'aberto',
  parecer           VARCHAR(30) NULL,
  parecer_texto     VARCHAR(1000) NULL,
  certificado       VARCHAR(40) NULL COMMENT 'Número do certificado (auditoria formal apta)',
  motivo_cancelamento VARCHAR(200) NULL,
  aberto_por_usuario_id BIGINT UNSIGNED NOT NULL,
  aberto_em         DATETIME(3) NOT NULL,
  concluido_por_usuario_id BIGINT UNSIGNED NULL COMMENT 'Quem concluiu ou cancelou',
  concluido_em      DATETIME(3) NULL,
  origem            VARCHAR(20) NOT NULL DEFAULT 'sistema',
  criado_em         DATETIME(3) NOT NULL,
  criado_por        BIGINT UNSIGNED NULL,
  alterado_em       DATETIME(3) NULL,
  alterado_por      BIGINT UNSIGNED NULL,
  versao            INT UNSIGNED NOT NULL DEFAULT 1,
  excluido_em       DATETIME(3) NULL,
  excluido_por      BIGINT UNSIGNED NULL,
  tipo_aberto       VARCHAR(30) AS (CASE WHEN situacao = 'aberto' AND excluido_em IS NULL THEN tipo END) PERSISTENT COMMENT 'Auxiliar da unicidade: um ciclo aberto por tipo no estabelecimento',
  CONSTRAINT ck_ciclo_certificacao_tipo CHECK (tipo IN ('autoavaliacao','pre_auditoria','auditoria')),
  CONSTRAINT ck_ciclo_certificacao_situacao CHECK (situacao IN ('aberto','concluido','cancelado')),
  CONSTRAINT ck_ciclo_certificacao_parecer CHECK (parecer IS NULL OR parecer IN ('apto','com_bloqueante')),
  CONSTRAINT ck_ciclo_certificacao_competencia CHECK (competencia REGEXP '^[0-9]{4}-(0[1-9]|1[0-2])$'),
  CONSTRAINT ck_ciclo_certificacao_fechamento CHECK ((situacao = 'aberto') = (concluido_em IS NULL)),
  CONSTRAINT ck_ciclo_certificacao_concluido CHECK (situacao <> 'concluido' OR parecer IS NOT NULL),
  CONSTRAINT ck_ciclo_certificacao_cancelado CHECK (situacao <> 'cancelado' OR motivo_cancelamento IS NOT NULL),
  CONSTRAINT ck_ciclo_certificacao_origem CHECK (origem IN ('sistema','migracao','integracao')),
  UNIQUE KEY uq_ciclo_certificacao_tipo_aberto (estabelecimento_id, tipo_aberto),
  KEY ix_ciclo_certificacao_estabelecimento (estabelecimento_id, tipo, situacao),
  KEY ix_ciclo_certificacao_aberto_por (aberto_por_usuario_id),
  KEY ix_ciclo_certificacao_concluido_por (concluido_por_usuario_id)
) COMMENT='Ciclo de avaliação da certificação do prontuário eletrônico (autoavaliação, pré-auditoria, auditoria) com parecer';

-- pedido do lote 02-06
CREATE TABLE ciclo_certificacao_item (
  id                BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
  ciclo_certificacao_id BIGINT UNSIGNED NOT NULL,
  requisito         VARCHAR(20) NOT NULL COMMENT 'Código do requisito no catálogo do produto (REQUISITOS_SBIS)',
  resultado         VARCHAR(30) NOT NULL DEFAULT 'pendente',
  severidade        VARCHAR(30) NULL COMMENT 'Severidade da não conformidade',
  origem_nao_conformidade VARCHAR(30) NULL,
  evidencia         VARCHAR(500) NULL,
  observacao        VARCHAR(500) NULL,
  avaliado_por_usuario_id BIGINT UNSIGNED NULL,
  avaliado_em       DATETIME(3) NULL,
  situacao_correcao VARCHAR(30) NULL,
  descricao_correcao VARCHAR(500) NULL,
  corrigido_por_usuario_id BIGINT UNSIGNED NULL,
  corrigido_em      DATETIME(3) NULL,
  verificado_por_usuario_id BIGINT UNSIGNED NULL,
  verificado_em     DATETIME(3) NULL,
  origem            VARCHAR(20) NOT NULL DEFAULT 'sistema',
  criado_em         DATETIME(3) NOT NULL,
  criado_por        BIGINT UNSIGNED NULL,
  alterado_em       DATETIME(3) NULL,
  alterado_por      BIGINT UNSIGNED NULL,
  versao            INT UNSIGNED NOT NULL DEFAULT 1,
  excluido_em       DATETIME(3) NULL,
  excluido_por      BIGINT UNSIGNED NULL,
  CONSTRAINT ck_ciclo_certificacao_item_resultado CHECK (resultado IN ('pendente','conforme','nao_conforme','concessao','nao_aplicavel')),
  CONSTRAINT ck_ciclo_certificacao_item_severidade CHECK (severidade IS NULL OR severidade IN ('bloqueante','maior','menor','observacao')),
  CONSTRAINT ck_ciclo_certificacao_item_origem_nc CHECK (origem_nao_conformidade IS NULL OR origem_nao_conformidade IN ('defeito','concessao','documentacao')),
  CONSTRAINT ck_ciclo_certificacao_item_correcao CHECK (situacao_correcao IS NULL OR situacao_correcao IN ('aberta','corrigida','verificada')),
  CONSTRAINT ck_ciclo_certificacao_item_nc CHECK ((resultado = 'nao_conforme') = (situacao_correcao IS NOT NULL)),
  CONSTRAINT ck_ciclo_certificacao_item_verificador CHECK (verificado_por_usuario_id IS NULL OR verificado_por_usuario_id <> corrigido_por_usuario_id),
  CONSTRAINT ck_ciclo_certificacao_item_origem CHECK (origem IN ('sistema','migracao','integracao')),
  UNIQUE KEY uq_ciclo_certificacao_item_requisito (ciclo_certificacao_id, requisito),
  KEY ix_ciclo_certificacao_item_avaliado_por (avaliado_por_usuario_id),
  KEY ix_ciclo_certificacao_item_corrigido_por (corrigido_por_usuario_id),
  KEY ix_ciclo_certificacao_item_verificado_por (verificado_por_usuario_id)
) COMMENT='Requisito avaliado num ciclo de certificação: resultado, não conformidade, correção e verificação por outra pessoa';
