CREATE TABLE acao_sistema (
  id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
  codigo VARCHAR(30) NOT NULL,
  descricao VARCHAR(150) NOT NULL,
  ativo BOOLEAN NOT NULL DEFAULT TRUE,
  modulo_sistema_id BIGINT UNSIGNED NULL,
  tela_sistema_id BIGINT UNSIGNED NULL COMMENT 'Tela onde a ação existe (nulo para ação do módulo inteiro)',
  funcionalidade_sistema_id BIGINT UNSIGNED NULL,
  tipo_acao VARCHAR(30) NOT NULL,
  auditavel BOOLEAN NOT NULL DEFAULT TRUE COMMENT 'Gera evento na trilha de auditoria',
  permissionavel BOOLEAN NOT NULL DEFAULT TRUE COMMENT 'Pode ser concedida ou negada a perfil',
  nivel_criticidade_auditoria_id BIGINT UNSIGNED NULL,
  ordem SMALLINT UNSIGNED NOT NULL DEFAULT 0,
  criado_em DATETIME(3) NOT NULL,
  criado_por BIGINT UNSIGNED NULL,
  alterado_em DATETIME(3) NULL,
  alterado_por BIGINT UNSIGNED NULL,
  versao INT UNSIGNED NOT NULL DEFAULT 1,
  CONSTRAINT ck_acao_sistema_tipo_acao CHECK (tipo_acao IN ('ver','incluir','alterar','excluir','aprovar','imprimir','exportar','executar','assinar','liberar')),
  UNIQUE KEY uq_acao_sistema_codigo (codigo),
  KEY ix_acao_sistema_modulo_sistema_id (modulo_sistema_id),
  KEY ix_acao_sistema_tela_sistema_id (tela_sistema_id),
  KEY ix_acao_sistema_funcionalidade_sistema_id (funcionalidade_sistema_id),
  KEY ix_acao_sistema_nivel_criticidade_auditoria_id (nivel_criticidade_auditoria_id)
) COMMENT='Catálogo de ações permissionáveis e auditáveis do sistema (ver, incluir, alterar, excluir, aprovar), por tela e módulo';

