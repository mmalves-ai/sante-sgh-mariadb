CREATE TABLE alcada_aprovacao_nivel (
  id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
  alcada_aprovacao_id BIGINT UNSIGNED NOT NULL,
  sequencia SMALLINT UNSIGNED NOT NULL,
  nivel SMALLINT UNSIGNED NOT NULL COMMENT 'Nível de aprovação (1 = primeiro)',
  perfil_acesso_id BIGINT UNSIGNED NULL COMMENT 'Aprovador por perfil (excludente com aprovador_usuario_id)',
  aprovador_usuario_id BIGINT UNSIGNED NULL,
  valor_unitario_minimo DECIMAL(15,2) NOT NULL DEFAULT 0,
  valor_unitario_maximo DECIMAL(15,2) NULL COMMENT 'Nulo: sem teto',
  valor_acumulado_maximo DECIMAL(15,2) NULL COMMENT 'Teto acumulado no período',
  periodo_acumulado VARCHAR(20) NULL,
  obrigatorio BOOLEAN NOT NULL DEFAULT TRUE,
  prazo_horas INT UNSIGNED NULL,
  vigencia_inicio DATE NULL,
  vigencia_fim DATE NULL,
  origem VARCHAR(20) NOT NULL DEFAULT 'sistema',
  criado_em DATETIME(3) NOT NULL,
  criado_por BIGINT UNSIGNED NULL,
  alterado_em DATETIME(3) NULL,
  alterado_por BIGINT UNSIGNED NULL,
  versao INT UNSIGNED NOT NULL DEFAULT 1,
  excluido_em DATETIME(3) NULL,
  excluido_por BIGINT UNSIGNED NULL,
  CONSTRAINT ck_alcada_aprovacao_nivel_origem CHECK (origem IN ('sistema','migracao','integracao')),
  UNIQUE KEY uq_alcada_aprovacao_nivel_sequencia (alcada_aprovacao_id, sequencia),
  CONSTRAINT ck_alcada_aprovacao_nivel_aprovador CHECK ((perfil_acesso_id IS NULL) <> (aprovador_usuario_id IS NULL)),
  CONSTRAINT ck_alcada_aprovacao_nivel_faixa CHECK (valor_unitario_maximo IS NULL OR valor_unitario_maximo >= valor_unitario_minimo),
  CONSTRAINT ck_alcada_aprovacao_nivel_periodo_acumulado CHECK (periodo_acumulado IS NULL OR periodo_acumulado IN ('dia','semana','mes','ano')),
  CONSTRAINT ck_alcada_aprovacao_nivel_vigencia CHECK (vigencia_fim IS NULL OR vigencia_inicio IS NULL OR vigencia_fim >= vigencia_inicio),
  CONSTRAINT ck_alcada_aprovacao_nivel_nivel CHECK (nivel >= 1),
  KEY ix_alcada_aprovacao_nivel_perfil_acesso_id (perfil_acesso_id),
  KEY ix_alcada_aprovacao_nivel_aprovador_usuario_id (aprovador_usuario_id)
) COMMENT='Faixa de valor e aprovador (perfil ou usuário) de cada nível da regra de alçada';

