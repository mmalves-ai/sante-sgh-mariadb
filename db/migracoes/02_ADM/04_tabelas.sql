  KEY ix_verificacao_backup_iniciado (iniciado_em),
  KEY ix_verificacao_backup_situacao (situacao, iniciado_em),
  KEY ix_verificacao_backup_usuario (usuario_id)
) COMMENT='Registro de cada cópia de segurança: tipo, início, fim, tamanho, resumo de integridade e situação';

