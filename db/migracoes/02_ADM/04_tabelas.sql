CREATE TABLE tipo_escopo_acesso (
  id                BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
  codigo            VARCHAR(30) NOT NULL,
  descricao         VARCHAR(150) NOT NULL,
  ativo             BOOLEAN NOT NULL DEFAULT TRUE,
  entidade          VARCHAR(64) NOT NULL COMMENT 'Tabela cujos registros servem de recorte (ex.: local_estoque, caixa, setor_diagnostico, especialidade)',
  modulo_sistema_id BIGINT UNSIGNED NULL COMMENT 'Módulo em que o recorte vale (nulo para todos)',
  permite_operacao  BOOLEAN NOT NULL DEFAULT TRUE COMMENT 'O recorte pode distinguir consulta de operação',
  criado_em         DATETIME(3) NOT NULL,
  criado_por        BIGINT UNSIGNED NULL,
  alterado_em       DATETIME(3) NULL,
  alterado_por      BIGINT UNSIGNED NULL,
  versao            INT UNSIGNED NOT NULL DEFAULT 1,
  UNIQUE KEY uq_tipo_escopo_acesso_codigo (codigo),
  KEY ix_tipo_escopo_acesso_modulo_sistema (modulo_sistema_id)
) COMMENT='Dimensões extras de recorte de acesso que um hospital pode ligar (estoque, caixa, setor de exame, oficina, especialidade)';

