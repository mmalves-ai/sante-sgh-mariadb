CREATE TABLE usuario (
  id                BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
  login             VARCHAR(60) NOT NULL,
  nome              VARCHAR(150) NOT NULL,
  nome_social       VARCHAR(150) NULL,
  cpf               CHAR(11) NULL COMMENT 'Obrigatório para conta de pessoa, salvo dispensa registrada',
  dispensa_cpf      BOOLEAN NOT NULL DEFAULT FALSE COMMENT 'Conta de pessoa autorizada sem CPF (ex.: estrangeiro), com motivo na trilha',
  email             VARCHAR(254) NULL,
  telefone_celular  VARCHAR(20) NULL,
  data_nascimento   DATE NULL,
  matricula         VARCHAR(20) NULL COMMENT 'Matrícula funcional no hospital',
  ramal             VARCHAR(20) NULL,
  ocupacao_cbo_id   BIGINT UNSIGNED NULL,
  tipo_conta        VARCHAR(20) NOT NULL DEFAULT 'pessoa',
  situacao          VARCHAR(20) NOT NULL DEFAULT 'ativo',
  motivo_bloqueio_usuario_id BIGINT UNSIGNED NULL,
  bloqueado_em      DATETIME(3) NULL,
  tentativas_login_invalidas SMALLINT UNSIGNED NOT NULL DEFAULT 0,
  administrador_plataforma BOOLEAN NOT NULL DEFAULT FALSE COMMENT 'Acesso total de administração da plataforma',
  exige_troca_senha BOOLEAN NOT NULL DEFAULT FALSE COMMENT 'Força troca de senha no próximo acesso',
  expira_em         DATETIME(3) NULL COMMENT 'Fim de validade da conta (terceiros, residentes, temporários)',
  ultimo_acesso_em  DATETIME(3) NULL,
  idioma            VARCHAR(10) NOT NULL DEFAULT 'pt-BR',
  tema              VARCHAR(40) NULL,
  foto_arquivo_id   BIGINT UNSIGNED NULL,
  observacao        VARCHAR(2000) NULL,
  origem            VARCHAR(20) NOT NULL DEFAULT 'sistema',
  criado_em         DATETIME(3) NOT NULL,
  criado_por        BIGINT UNSIGNED NULL,
  alterado_em       DATETIME(3) NULL,
  alterado_por      BIGINT UNSIGNED NULL,
  versao            INT UNSIGNED NOT NULL DEFAULT 1,
  excluido_em       DATETIME(3) NULL,
  excluido_por      BIGINT UNSIGNED NULL,
  CONSTRAINT ck_usuario_tipo_conta CHECK (tipo_conta IN ('pessoa','servico','integracao')),
  CONSTRAINT ck_usuario_situacao CHECK (situacao IN ('ativo','bloqueado','dormente','inativo')),
  CONSTRAINT ck_usuario_cpf CHECK (cpf IS NULL OR cpf REGEXP '^[0-9]{11}$'),
  CONSTRAINT ck_usuario_cpf_pessoa CHECK (tipo_conta <> 'pessoa' OR cpf IS NOT NULL OR dispensa_cpf),
  CONSTRAINT ck_usuario_bloqueio CHECK (situacao <> 'bloqueado' OR bloqueado_em IS NOT NULL),
  CONSTRAINT ck_usuario_origem CHECK (origem IN ('sistema','migracao','integracao')),
  UNIQUE KEY uq_usuario_login (login),
  UNIQUE KEY uq_usuario_cpf (cpf),
  KEY ix_usuario_nome (nome),
  KEY ix_usuario_email (email),
  KEY ix_usuario_situacao (situacao, ultimo_acesso_em),
  KEY ix_usuario_ocupacao_cbo (ocupacao_cbo_id),
  KEY ix_usuario_motivo_bloqueio_usuario (motivo_bloqueio_usuario_id),
  KEY ix_usuario_foto_arquivo (foto_arquivo_id)
) COMMENT='Conta de acesso de uma pessoa ao sistema, com login, nome, e-mail, situação, datas de criação, expiração e último uso';

