CREATE TABLE verificacao_backup (
  id                BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
  operacao          VARCHAR(20) NOT NULL DEFAULT 'inclusao',
  processo          VARCHAR(20) NOT NULL COMMENT 'Cópia de segurança ou restauração',
  modalidade        VARCHAR(20) NOT NULL,
  iniciado_em       DATETIME(3) NOT NULL,
  concluido_em      DATETIME(3) NULL,
  tamanho_bytes     BIGINT UNSIGNED NULL,
  resumo_integridade VARCHAR(128) NULL COMMENT 'Hash ou soma de verificação da cópia',
  destino           VARCHAR(255) NULL COMMENT 'Local lógico da cópia (sem credenciais)',
  situacao          VARCHAR(20) NOT NULL,
  mensagem_erro     VARCHAR(2000) NULL,
  dados             JSON NULL,
  ocorrido_em       DATETIME(3) NOT NULL,
  usuario_id        BIGINT UNSIGNED NULL COMMENT 'Quem disparou (nulo para rotina agendada)',
  criado_em         DATETIME(3) NOT NULL,
  criado_por        BIGINT UNSIGNED NULL,
  alterado_em       DATETIME(3) NULL,
  alterado_por      BIGINT UNSIGNED NULL,
  versao            INT UNSIGNED NOT NULL DEFAULT 1,
  CONSTRAINT ck_verificacao_backup_operacao CHECK (operacao IN ('inclusao','alteracao','exclusao')),
  CONSTRAINT ck_verificacao_backup_processo CHECK (processo IN ('copia','restauracao')),
  CONSTRAINT ck_verificacao_backup_modalidade CHECK (modalidade IN ('completa','incremental','diferencial','log')),
  CONSTRAINT ck_verificacao_backup_situacao CHECK (situacao IN ('em_andamento','concluido','falhou','cancelado')),
  CONSTRAINT ck_verificacao_backup_periodo CHECK (concluido_em IS NULL OR concluido_em >= iniciado_em),
