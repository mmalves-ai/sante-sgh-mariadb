  CONSTRAINT ck_item_agendavel_conflito_intervalo CHECK (intervalo_minimo_horas > 0),
  CONSTRAINT ck_item_agendavel_conflito_direcao CHECK (direcao IN ('antes','depois','ambos')),
  UNIQUE KEY uq_item_agendavel_conflito_par (item_agendavel_id, conflito_item_agendavel_id),
  KEY ix_item_agendavel_conflito_conflito (conflito_item_agendavel_id)
) COMMENT='Itens que não podem ser marcados num intervalo entre si, com o intervalo mínimo';

