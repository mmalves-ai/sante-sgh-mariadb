  criado_por        BIGINT UNSIGNED NULL,
  alterado_em       DATETIME(3) NULL,
  alterado_por      BIGINT UNSIGNED NULL,
  versao            INT UNSIGNED NOT NULL DEFAULT 1,
  CONSTRAINT ck_item_agendavel_pre_requisito_tipo CHECK (tipo_requisito IN ('item_realizado','item_marcado','autorizacao','documento','condicao')),
