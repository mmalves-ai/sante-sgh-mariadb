CREATE TABLE item_agendavel (
  id                BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
  codigo            VARCHAR(30) NOT NULL,
  descricao         VARCHAR(150) NOT NULL,
  mnemonico         VARCHAR(20) NULL,
  tipo_item         VARCHAR(30) NOT NULL COMMENT 'consulta, exame, procedimento, sessao ou composto (pacote)',
  item_faturavel_id BIGINT UNSIGNED NULL COMMENT 'Procedimento cobrado quando o item é realizado',
  exame_id          BIGINT UNSIGNED NULL COMMENT 'Exame do apoio diagnóstico, quando o item é um exame',
  duracao_minutos   SMALLINT UNSIGNED NOT NULL COMMENT 'Duração padrão de realização',
  dias_preparo      SMALLINT UNSIGNED NULL COMMENT 'Dias de preparo do paciente antes da realização',
  orientacao_preparo TEXT NULL COMMENT 'Orientação padrão ao paciente, exibida e impressa na marcação',
  intervalo_repeticao_minutos INT UNSIGNED NULL COMMENT 'Intervalo mínimo entre duas realizações do item no mesmo paciente',
  sugere_ajuste_tempo_anestesia BOOLEAN NOT NULL DEFAULT FALSE,
  exige_paciente_cadastrado BOOLEAN NOT NULL DEFAULT FALSE COMMENT 'Não aceita marcação só com pré-cadastro',
  exige_indicacao_clinica BOOLEAN NOT NULL DEFAULT FALSE,
  exige_autorizacao BOOLEAN NOT NULL DEFAULT FALSE COMMENT 'Exige guia autorizada pela fonte pagadora antes da realização',
  envia_prontuario  BOOLEAN NOT NULL DEFAULT FALSE COMMENT 'Pede o prontuário físico ao arquivo para a data marcada',
  teleatendimento   BOOLEAN NOT NULL DEFAULT FALSE COMMENT 'Pode ser realizado por teleatendimento',
  observacao        VARCHAR(2000) NULL,
  ativo             BOOLEAN NOT NULL DEFAULT TRUE,
  origem            VARCHAR(20) NOT NULL DEFAULT 'sistema',
  criado_em         DATETIME(3) NOT NULL,
  criado_por        BIGINT UNSIGNED NULL,
  alterado_em       DATETIME(3) NULL,
  alterado_por      BIGINT UNSIGNED NULL,
  versao            INT UNSIGNED NOT NULL DEFAULT 1,
  excluido_em       DATETIME(3) NULL,
  excluido_por      BIGINT UNSIGNED NULL,
  CONSTRAINT ck_item_agendavel_tipo_item CHECK (tipo_item IN ('consulta','exame','procedimento','sessao','composto')),
  CONSTRAINT ck_item_agendavel_duracao CHECK (duracao_minutos BETWEEN 1 AND 1440),
  CONSTRAINT ck_item_agendavel_exame CHECK (tipo_item = 'exame' OR exame_id IS NULL),
  CONSTRAINT ck_item_agendavel_origem CHECK (origem IN ('sistema','migracao','integracao')),
  UNIQUE KEY uq_item_agendavel_codigo (codigo),
  KEY ix_item_agendavel_item_faturavel (item_faturavel_id),
  KEY ix_item_agendavel_exame (exame_id),
  KEY ix_item_agendavel_descricao (descricao)
) COMMENT='O que se agenda (exame, procedimento, sessão), com duração, preparo padrão e procedimento cobrado';

CREATE TABLE item_agendavel_composicao (
  id                BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
  item_agendavel_id BIGINT UNSIGNED NOT NULL COMMENT 'Item composto (pacote)',
  sequencia         SMALLINT UNSIGNED NOT NULL,
  componente_item_agendavel_id BIGINT UNSIGNED NOT NULL COMMENT 'Item que faz parte do pacote',
  quantidade        DECIMAL(15,4) NOT NULL DEFAULT 1,
  origem            VARCHAR(20) NOT NULL DEFAULT 'sistema',
  criado_em         DATETIME(3) NOT NULL,
  criado_por        BIGINT UNSIGNED NULL,
  alterado_em       DATETIME(3) NULL,
  alterado_por      BIGINT UNSIGNED NULL,
  versao            INT UNSIGNED NOT NULL DEFAULT 1,
  excluido_em       DATETIME(3) NULL,
  excluido_por      BIGINT UNSIGNED NULL,
  CONSTRAINT ck_item_agendavel_composicao_distinto CHECK (componente_item_agendavel_id <> item_agendavel_id),
  CONSTRAINT ck_item_agendavel_composicao_quantidade CHECK (quantidade > 0),
  CONSTRAINT ck_item_agendavel_composicao_origem CHECK (origem IN ('sistema','migracao','integracao')),
  UNIQUE KEY uq_item_agendavel_composicao_sequencia (item_agendavel_id, sequencia),
  UNIQUE KEY uq_item_agendavel_composicao_componente (item_agendavel_id, componente_item_agendavel_id),
  KEY ix_item_agendavel_composicao_componente (componente_item_agendavel_id)
) COMMENT='Itens que compõem um item composto (pacote de exames)';

CREATE TABLE item_agendavel_conflito (
  id                BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
  item_agendavel_id BIGINT UNSIGNED NOT NULL,
  conflito_item_agendavel_id BIGINT UNSIGNED NOT NULL COMMENT 'Item que não pode ser marcado dentro do intervalo',
