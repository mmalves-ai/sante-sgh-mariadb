  dias_retorno      SMALLINT UNSIGNED NULL COMMENT 'Prazo em dias em que nova consulta com o mesmo profissional conta como retorno',
  dias_liberacao    SMALLINT UNSIGNED NULL COMMENT 'Quantos dias à frente a grade fica aberta para marcação',
  idade_minima_anos TINYINT UNSIGNED NULL,
  idade_maxima_anos TINYINT UNSIGNED NULL,
  peso_maximo_kg    DECIMAL(6,2) NULL COMMENT 'Limite do equipamento (ex.: mesa de exame)',
