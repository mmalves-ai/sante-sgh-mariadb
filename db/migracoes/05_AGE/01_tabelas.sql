CREATE TABLE ajuste_tempo_marcacao (
  id                BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
  codigo            VARCHAR(30) NOT NULL,
  descricao         VARCHAR(150) NOT NULL,
  minutos_ajuste    SMALLINT NOT NULL COMMENT 'Minutos somados (positivo) ou descontados (negativo) da duração padrão do item',
  ativo             BOOLEAN NOT NULL DEFAULT TRUE,
  criado_em         DATETIME(3) NOT NULL,
  criado_por        BIGINT UNSIGNED NULL,
  alterado_em       DATETIME(3) NULL,
  alterado_por      BIGINT UNSIGNED NULL,
  versao            INT UNSIGNED NOT NULL DEFAULT 1,
  CONSTRAINT ck_ajuste_tempo_marcacao_minutos CHECK (minutos_ajuste <> 0 AND minutos_ajuste BETWEEN -240 AND 240),
  UNIQUE KEY uq_ajuste_tempo_marcacao_codigo (codigo)
) COMMENT='Acréscimo ou redução de minutos sobre a duração padrão do item marcado (paciente idoso, sedação, acesso difícil)';

CREATE TABLE canal_marcacao (
  id                BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
  codigo            VARCHAR(30) NOT NULL,
  descricao         VARCHAR(150) NOT NULL,
  canal_digital     BOOLEAN NOT NULL DEFAULT FALSE COMMENT 'Canal sem atendente (portal, aplicativo, mensagem automática)',
