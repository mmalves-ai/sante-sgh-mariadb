CREATE TABLE item_agendavel_pre_requisito (
  id                BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
  item_agendavel_id BIGINT UNSIGNED NOT NULL,
  tipo_requisito    VARCHAR(30) NOT NULL COMMENT 'item_realizado, item_marcado, autorizacao, documento ou condicao',
  requisito_item_agendavel_id BIGINT UNSIGNED NULL COMMENT 'Item exigido antes, quando o requisito é outro item',
