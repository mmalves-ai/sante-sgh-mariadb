  CONSTRAINT ck_recurso_agendavel_faixa CHECK (faixa_final IS NULL OR faixa_inicial IS NULL OR faixa_final >= faixa_inicial),
  CONSTRAINT ck_recurso_agendavel_horas CHECK (horas_uso_maximo_dia IS NULL OR horas_uso_maximo_dia BETWEEN 1 AND 24),
  CONSTRAINT ck_recurso_agendavel_origem CHECK (origem IN ('sistema','migracao','integracao')),
  UNIQUE KEY uq_recurso_agendavel_estabelecimento_codigo (estabelecimento_id, codigo),
  KEY ix_recurso_agendavel_setor_funcional (setor_funcional_id),
  KEY ix_recurso_agendavel_unidade_assistencial (unidade_assistencial_id),
  KEY ix_recurso_agendavel_setor_diagnostico (setor_diagnostico_id),
  KEY ix_recurso_agendavel_local_fisico (local_fisico_id),
  KEY ix_recurso_agendavel_equipamento_saude (equipamento_saude_id),
  KEY ix_recurso_agendavel_complexidade_sessao (complexidade_sessao_id),
  KEY ix_recurso_agendavel_duracao_sessao (duracao_sessao_id)
) COMMENT='Sala, equipamento ou cadeira agendável, com setor, tipo e capacidade';

