CREATE TABLE perfil_marcacao_usuario (
  id                BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
  perfil_marcacao_id BIGINT UNSIGNED NOT NULL,
  usuario_id        BIGINT UNSIGNED NOT NULL,
  vigencia_inicio   DATE NULL,
  vigencia_fim      DATE NULL,
  criado_em         DATETIME(3) NOT NULL,
  criado_por        BIGINT UNSIGNED NULL,
  alterado_em       DATETIME(3) NULL,
  alterado_por      BIGINT UNSIGNED NULL,
  versao            INT UNSIGNED NOT NULL DEFAULT 1,
  excluido_em       DATETIME(3) NULL,
  excluido_por      BIGINT UNSIGNED NULL,
  CONSTRAINT ck_perfil_marcacao_usuario_vigencia CHECK (vigencia_fim IS NULL OR vigencia_inicio IS NULL OR vigencia_fim >= vigencia_inicio),
  UNIQUE KEY uq_perfil_marcacao_usuario_perfil_usuario (perfil_marcacao_id, usuario_id),
  KEY ix_perfil_marcacao_usuario_usuario (usuario_id)
) COMMENT='Usuários de cada perfil de agendamento';

CREATE TABLE protocolo_tratamento_seriado (
  id                BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
  codigo            VARCHAR(30) NOT NULL,
  descricao         VARCHAR(150) NOT NULL,
  tipo_plano        VARCHAR(30) NOT NULL COMMENT 'Natureza do tratamento em sessões',
  codigo_cid10      VARCHAR(4) NULL COMMENT 'Diagnóstico (CID-10, sem ponto) a que o protocolo se aplica',
  item_agendavel_id BIGINT UNSIGNED NULL COMMENT 'Item marcado em cada sessão',
  item_faturavel_id BIGINT UNSIGNED NULL COMMENT 'Procedimento cobrado em cada sessão',
  procedimento_sigtap_id BIGINT UNSIGNED NULL COMMENT 'Procedimento SUS de cada sessão',
  descricao_procedimento VARCHAR(150) NULL COMMENT 'Texto do procedimento exibido na grade de sessões',
  total_dias        SMALLINT UNSIGNED NULL COMMENT 'Duração total do tratamento em dias',
  total_ciclos      SMALLINT UNSIGNED NULL,
  sessoes_por_ciclo SMALLINT UNSIGNED NULL,
  intervalo_dias    SMALLINT UNSIGNED NULL COMMENT 'Intervalo entre sessões ou ciclos',
  intervalo_fixo    BOOLEAN NOT NULL DEFAULT FALSE COMMENT 'O intervalo não se ajusta quando uma sessão atrasa',
  dia_fixo          BOOLEAN NOT NULL DEFAULT FALSE COMMENT 'As sessões caem em dias fixos do ciclo (D1, D8...)',
  unidade_contagem  VARCHAR(30) NOT NULL DEFAULT 'dias' COMMENT 'Unidade em que o intervalo é contado',
  duracao_minutos   SMALLINT UNSIGNED NULL COMMENT 'Duração prevista de cada sessão',
  idade_minima_anos SMALLINT UNSIGNED NULL,
  idade_maxima_anos SMALLINT UNSIGNED NULL,
  exibe_data_procedimento BOOLEAN NOT NULL DEFAULT FALSE,
  observacao_padrao VARCHAR(2000) NULL COMMENT 'Texto que abre como observação no plano do paciente',
  vigencia_inicio   DATE NULL,
  vigencia_fim      DATE NULL,
  ativo             BOOLEAN NOT NULL DEFAULT TRUE,
  criado_em         DATETIME(3) NOT NULL,
  criado_por        BIGINT UNSIGNED NULL,
  alterado_em       DATETIME(3) NULL,
  alterado_por      BIGINT UNSIGNED NULL,
  versao            INT UNSIGNED NOT NULL DEFAULT 1,
  CONSTRAINT ck_protocolo_tratamento_seriado_tipo_plano CHECK (tipo_plano IN ('quimioterapia','infusao','fisioterapia','hemodialise','radioterapia','outra')),
  CONSTRAINT ck_protocolo_tratamento_seriado_unidade_contagem CHECK (unidade_contagem IN ('dias','semanas','ciclos')),
  CONSTRAINT ck_protocolo_tratamento_seriado_idade CHECK (idade_maxima_anos IS NULL OR idade_minima_anos IS NULL OR idade_maxima_anos >= idade_minima_anos),
  CONSTRAINT ck_protocolo_tratamento_seriado_idade_faixa CHECK (idade_maxima_anos IS NULL OR idade_maxima_anos <= 150),
  CONSTRAINT ck_protocolo_tratamento_seriado_vigencia CHECK (vigencia_fim IS NULL OR vigencia_inicio IS NULL OR vigencia_fim >= vigencia_inicio),
  CONSTRAINT ck_protocolo_tratamento_seriado_duracao CHECK (duracao_minutos IS NULL OR duracao_minutos BETWEEN 10 AND 720),
  CONSTRAINT ck_protocolo_tratamento_seriado_quantidades CHECK ((total_ciclos IS NULL OR total_ciclos > 0) AND (sessoes_por_ciclo IS NULL OR sessoes_por_ciclo > 0) AND (intervalo_dias IS NULL OR intervalo_dias > 0)),
  UNIQUE KEY uq_protocolo_tratamento_seriado_codigo (codigo),
  KEY ix_protocolo_tratamento_seriado_codigo_cid10 (codigo_cid10),
  KEY ix_protocolo_tratamento_seriado_item_agendavel (item_agendavel_id),
  KEY ix_protocolo_tratamento_seriado_item_faturavel (item_faturavel_id),
  KEY ix_protocolo_tratamento_seriado_procedimento_sigtap (procedimento_sigtap_id)
) COMMENT='Modelo de tratamento em sessões por diagnóstico: total de dias, ciclos, intervalo, faixa de idade e procedimento';

CREATE TABLE protocolo_tratamento_seriado_dependencia (
  id                BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
  protocolo_tratamento_seriado_id BIGINT UNSIGNED NOT NULL COMMENT 'Protocolo principal',
  dependente_protocolo_tratamento_seriado_id BIGINT UNSIGNED NOT NULL COMMENT 'Protocolo que corre nos mesmos ciclos do principal',
  ordem             SMALLINT UNSIGNED NOT NULL DEFAULT 1 COMMENT 'Ordem de execução dentro do ciclo',
  criado_em         DATETIME(3) NOT NULL,
  criado_por        BIGINT UNSIGNED NULL,
  alterado_em       DATETIME(3) NULL,
  alterado_por      BIGINT UNSIGNED NULL,
  versao            INT UNSIGNED NOT NULL DEFAULT 1,
  excluido_em       DATETIME(3) NULL,
  excluido_por      BIGINT UNSIGNED NULL,
  CONSTRAINT ck_protocolo_tratamento_seriado_dependencia_distintos CHECK (protocolo_tratamento_seriado_id <> dependente_protocolo_tratamento_seriado_id),
  UNIQUE KEY uq_protocolo_tratamento_seriado_dependencia_par (protocolo_tratamento_seriado_id, dependente_protocolo_tratamento_seriado_id),
  KEY ix_protocolo_tratamento_seriado_dependencia_dependente (dependente_protocolo_tratamento_seriado_id)
) COMMENT='Protocolos que correm nos mesmos ciclos de outro protocolo, com a ordem de execução';

