  id                     BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
  analise_incidente_id   BIGINT UNSIGNED NOT NULL,
  sequencia              SMALLINT UNSIGNED NOT NULL,
  categoria              VARCHAR(30) NULL COMMENT 'Categoria do diagrama de causa e efeito',
  fator_contribuinte_id  BIGINT UNSIGNED NULL,
  descricao              VARCHAR(1000) NOT NULL,
  causa_raiz             BOOLEAN NOT NULL DEFAULT FALSE,
  ordem_porque           TINYINT UNSIGNED NULL COMMENT 'Posição na cadeia de porquês (1 a 7)',
  causa_pai_id           BIGINT UNSIGNED NULL COMMENT 'Causa da qual esta deriva',
  gravidade              TINYINT UNSIGNED NULL COMMENT 'Priorização GUT: gravidade 1 a 5',
  urgencia               TINYINT UNSIGNED NULL COMMENT 'Priorização GUT: urgência 1 a 5',
  tendencia              TINYINT UNSIGNED NULL COMMENT 'Priorização GUT: tendência 1 a 5',
  prioridade             SMALLINT UNSIGNED AS (gravidade * urgencia * tendencia) STORED COMMENT 'Gravidade x urgência x tendência',
  origem                 VARCHAR(20) NOT NULL DEFAULT 'sistema',
  criado_em              DATETIME(3) NOT NULL,
  criado_por             BIGINT UNSIGNED NULL,
  alterado_em            DATETIME(3) NULL,
  alterado_por           BIGINT UNSIGNED NULL,
  versao                 INT UNSIGNED NOT NULL DEFAULT 1,
  excluido_em            DATETIME(3) NULL,
  excluido_por           BIGINT UNSIGNED NULL,
  CONSTRAINT ck_analise_incidente_causa_categoria CHECK (categoria IN ('metodo','maquina','material','mao_de_obra','meio_ambiente','medida')),
  CONSTRAINT ck_analise_incidente_causa_ordem_porque CHECK (ordem_porque IS NULL OR ordem_porque BETWEEN 1 AND 7),
