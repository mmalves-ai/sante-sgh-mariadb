CREATE TABLE processo_institucional (
  id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
  estabelecimento_id BIGINT UNSIGNED NOT NULL,
  codigo VARCHAR(30) NOT NULL COMMENT 'Número do processo na cadeia de valor (ex.: 2.3.1)',
  nome VARCHAR(150) NOT NULL,
  descricao TEXT NULL,
  nivel VARCHAR(30) NOT NULL DEFAULT 'processo',
  processo_pai_id BIGINT UNSIGNED NULL COMMENT 'Processo ou macroprocesso superior',
  cadeia_valor VARCHAR(30) NULL COMMENT 'Posição na cadeia de valor: finalistico, apoio ou gestao',
  dono_usuario_id BIGINT UNSIGNED NOT NULL COMMENT 'Dono do processo',
  setor_funcional_id BIGINT UNSIGNED NULL COMMENT 'Setor responsável pela execução',
  entradas TEXT NULL COMMENT 'Insumos e informações que entram no processo',
  saidas TEXT NULL COMMENT 'Produtos e resultados entregues',
  clientes VARCHAR(500) NULL COMMENT 'Clientes internos e externos do processo',
  ativo BOOLEAN NOT NULL DEFAULT TRUE,
  origem VARCHAR(20) NOT NULL DEFAULT 'sistema' COMMENT 'sistema, migracao ou integracao',
  criado_em DATETIME(3) NOT NULL,
  criado_por BIGINT UNSIGNED NULL,
  alterado_em DATETIME(3) NULL,
  alterado_por BIGINT UNSIGNED NULL,
  versao INT UNSIGNED NOT NULL DEFAULT 1,
  excluido_em DATETIME(3) NULL,
  excluido_por BIGINT UNSIGNED NULL,
  CONSTRAINT ck_processo_institucional_nivel CHECK (nivel IN ('macroprocesso','processo','subprocesso')),
  CONSTRAINT ck_processo_institucional_cadeia_valor CHECK (cadeia_valor IS NULL OR cadeia_valor IN ('finalistico','apoio','gestao')),
  UNIQUE KEY uq_processo_institucional_estabelecimento_codigo (estabelecimento_id, codigo),
  CONSTRAINT ck_processo_institucional_origem CHECK (origem IN ('sistema','migracao','integracao')),
  KEY ix_processo_institucional_processo_pai (processo_pai_id),
  KEY ix_processo_institucional_dono_usuario (dono_usuario_id),
  KEY ix_processo_institucional_setor_funcional (setor_funcional_id)
) COMMENT='Macroprocesso ou processo da cadeia de valor, hierárquico, com dono, setor, entradas, saídas e clientes';

