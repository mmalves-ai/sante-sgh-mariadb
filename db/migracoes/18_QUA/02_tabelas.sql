CREATE TABLE escala_avaliacao_risco (
  id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
  metodologia VARCHAR(30) NOT NULL COMMENT 'Matriz probabilidade e impacto, GUT ou FMEA',
  dimensao VARCHAR(30) NOT NULL,
  nivel SMALLINT UNSIGNED NOT NULL COMMENT 'Valor do nível na dimensão (ex.: 1 a 5)',
  nome VARCHAR(100) NOT NULL,
  descricao TEXT NULL,
  peso DECIMAL(7,4) NOT NULL DEFAULT 1,
  pontuacao_minima SMALLINT UNSIGNED NULL COMMENT 'Faixa de prioridade: menor pontuação incluída',
  pontuacao_maxima SMALLINT UNSIGNED NULL COMMENT 'Faixa de prioridade: maior pontuação incluída (até 125 no GUT e no FMEA)',
  cor CHAR(7) NULL COMMENT 'Cor da célula ou faixa em hexadecimal (#RRGGBB)',
  ativo BOOLEAN NOT NULL DEFAULT TRUE,
  criado_em DATETIME(3) NOT NULL,
  criado_por BIGINT UNSIGNED NULL,
  alterado_em DATETIME(3) NULL,
  alterado_por BIGINT UNSIGNED NULL,
  versao INT UNSIGNED NOT NULL DEFAULT 1,
  CONSTRAINT ck_escala_avaliacao_risco_metodologia CHECK (metodologia IN ('probabilidade_impacto','gut','fmea')),
  CONSTRAINT ck_escala_avaliacao_risco_dimensao CHECK (dimensao IN ('probabilidade','impacto','deteccao','gravidade','urgencia','tendencia','prioridade')),
  CONSTRAINT ck_escala_avaliacao_risco_nivel CHECK (nivel BETWEEN 1 AND 10),
  CONSTRAINT ck_escala_avaliacao_risco_faixa CHECK (pontuacao_maxima IS NULL OR pontuacao_minima IS NULL OR pontuacao_maxima >= pontuacao_minima),
  CONSTRAINT ck_escala_avaliacao_risco_prioridade CHECK (dimensao <> 'prioridade' OR (pontuacao_minima IS NOT NULL AND pontuacao_maxima IS NOT NULL)),
  CONSTRAINT ck_escala_avaliacao_risco_cor CHECK (cor IS NULL OR cor REGEXP '^#[0-9A-Fa-f]{6}$'),
  UNIQUE KEY uq_escala_avaliacao_risco_nivel (metodologia, dimensao, nivel)
) COMMENT='Escala da matriz de risco: dimensão (probabilidade, impacto, detecção, gravidade, urgência, tendência ou faixa de prioridade), nível, peso, pontuação e cor';

