CREATE TABLE documento_qualidade_distribuicao (
  id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
  documento_qualidade_id BIGINT UNSIGNED NOT NULL,
  tipo_destinatario VARCHAR(30) NOT NULL COMMENT 'Quem recebe: setor, cargo, perfil de acesso ou usuário',
  setor_funcional_id BIGINT UNSIGNED NULL,
  cargo_id BIGINT UNSIGNED NULL,
  perfil_acesso_id BIGINT UNSIGNED NULL,
  usuario_id BIGINT UNSIGNED NULL,
  pode_visualizar BOOLEAN NOT NULL DEFAULT TRUE,
  pode_imprimir BOOLEAN NOT NULL DEFAULT FALSE,
  pode_baixar BOOLEAN NOT NULL DEFAULT FALSE,
  acesso_negado BOOLEAN NOT NULL DEFAULT FALSE COMMENT 'Regra de exceção que bloqueia o acesso deste destinatário',
  exige_ciencia BOOLEAN NOT NULL DEFAULT TRUE COMMENT 'O destinatário precisa registrar leitura',
  copia_controlada BOOLEAN NOT NULL DEFAULT FALSE COMMENT 'Recebe cópia controlada impressa',
  quantidade_copias SMALLINT UNSIGNED NULL,
  prioridade SMALLINT UNSIGNED NOT NULL DEFAULT 0 COMMENT 'Ordem de aplicação quando regras se sobrepõem',
  criado_em DATETIME(3) NOT NULL,
  criado_por BIGINT UNSIGNED NULL,
  alterado_em DATETIME(3) NULL,
  alterado_por BIGINT UNSIGNED NULL,
  versao INT UNSIGNED NOT NULL DEFAULT 1,
  excluido_em DATETIME(3) NULL,
  excluido_por BIGINT UNSIGNED NULL,
  CONSTRAINT ck_documento_qualidade_distribuicao_tipo CHECK (tipo_destinatario IN ('setor','cargo','perfil','usuario')),
  CONSTRAINT ck_documento_qualidade_distribuicao_alvo CHECK (
    (tipo_destinatario = 'setor' AND setor_funcional_id IS NOT NULL AND cargo_id IS NULL AND perfil_acesso_id IS NULL AND usuario_id IS NULL) OR
    (tipo_destinatario = 'cargo' AND cargo_id IS NOT NULL AND setor_funcional_id IS NULL AND perfil_acesso_id IS NULL AND usuario_id IS NULL) OR
    (tipo_destinatario = 'perfil' AND perfil_acesso_id IS NOT NULL AND setor_funcional_id IS NULL AND cargo_id IS NULL AND usuario_id IS NULL) OR
    (tipo_destinatario = 'usuario' AND usuario_id IS NOT NULL AND setor_funcional_id IS NULL AND cargo_id IS NULL AND perfil_acesso_id IS NULL)),
  CONSTRAINT ck_documento_qualidade_distribuicao_copias CHECK (copia_controlada = FALSE OR quantidade_copias >= 1),
  UNIQUE KEY uq_documento_qualidade_distribuicao_destinatario (documento_qualidade_id, tipo_destinatario, setor_funcional_id, cargo_id, perfil_acesso_id, usuario_id),
  KEY ix_documento_qualidade_distribuicao_setor_funcional (setor_funcional_id),
  KEY ix_documento_qualidade_distribuicao_cargo (cargo_id),
  KEY ix_documento_qualidade_distribuicao_perfil_acesso (perfil_acesso_id),
  KEY ix_documento_qualidade_distribuicao_usuario (usuario_id)
) COMMENT='Setor, cargo, perfil ou pessoa que deve receber e ler o documento controlado, com indicação de cópia controlada impressa';

