-- Módulo SUS, lote 03: remessas ao gestor (BPA, CIHA, RAAS, SISAIH), retorno do gestor, serviço/classificação da
-- tabela unificada, teto financeiro, tipo de laudo APAC, remanejamento de cota e valor complementar.
-- Sem FOREIGN KEY aqui; as chaves ficam em 03_chaves.sql.

CREATE TABLE remessa_bpa (
  id                       BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
  estabelecimento_id       BIGINT UNSIGNED NOT NULL,
  competencia_sus_id       BIGINT UNSIGNED NOT NULL COMMENT 'Competência de apresentação da produção',
  numero                   VARCHAR(20) NOT NULL COMMENT 'Número de negócio da remessa, gerado pela sequencia_negocio',
  descricao                VARCHAR(150) NULL,
  tipo_bpa                 VARCHAR(30) NOT NULL COMMENT 'Instrumento de registro: consolidado, individualizado ou os dois no mesmo arquivo',
  orgao_destino            VARCHAR(30) NOT NULL DEFAULT 'municipal' COMMENT 'Gestor que recebe o arquivo: municipal ou estadual',
  responsavel_setor_funcional_id BIGINT UNSIGNED NULL COMMENT 'Setor responsável pela remessa',
  situacao                 VARCHAR(30) NOT NULL DEFAULT 'aberta',
  aberta_em                DATETIME(3) NOT NULL,
  fechada_em               DATETIME(3) NULL,
  folha_inicial            INT UNSIGNED NOT NULL DEFAULT 1 COMMENT 'Primeira folha do BPA consolidado nesta remessa (continua a anterior)',
  ultima_folha             INT UNSIGNED NULL COMMENT 'Última folha usada, para a numeração da próxima remessa',
  leiaute                  VARCHAR(30) NULL COMMENT 'Leiaute oficial usado na geração',
  versao_leiaute           VARCHAR(20) NULL,
  conferido_contra_oficial BOOLEAN NOT NULL DEFAULT FALSE COMMENT 'Descritor do leiaute conferido contra o documento oficial vigente',
  arquivo_id               BIGINT UNSIGNED NULL COMMENT 'Arquivo gerado, guardado no armazenamento de objetos',
  nome_arquivo             VARCHAR(100) NULL,
  hash_sha256              CHAR(64) NULL COMMENT 'SHA-256 do conteúdo, em hexadecimal',
  tamanho_bytes            BIGINT UNSIGNED NULL,
  quantidade_linhas        INT UNSIGNED NOT NULL DEFAULT 0,
  quantidade_registros     INT UNSIGNED NOT NULL DEFAULT 0,
  quantidade_procedimentos DECIMAL(15,4) NOT NULL DEFAULT 0,
  valor_apresentado        DECIMAL(15,2) NOT NULL DEFAULT 0,
  sem_movimento            BOOLEAN NOT NULL DEFAULT FALSE,
  gerada_em                DATETIME(3) NULL,
  gerador_usuario_id       BIGINT UNSIGNED NULL,
  enviada_em               DATETIME(3) NULL,
  remetente_usuario_id     BIGINT UNSIGNED NULL,
  protocolo_envio          VARCHAR(60) NULL COMMENT 'Protocolo devolvido pelo gestor ou pelo transmissor',
  cobrada                  BOOLEAN NOT NULL DEFAULT FALSE COMMENT 'Produção já cobrada do gestor (retorno conciliado)',
  substituta_remessa_bpa_id BIGINT UNSIGNED NULL COMMENT 'Remessa que substituiu esta, quando regerada',
  observacao               VARCHAR(500) NULL,
  origem                   VARCHAR(20) NOT NULL DEFAULT 'sistema',
  criado_em                DATETIME(3) NOT NULL,
  criado_por               BIGINT UNSIGNED NULL,
  alterado_em              DATETIME(3) NULL,
  alterado_por             BIGINT UNSIGNED NULL,
  versao                   INT UNSIGNED NOT NULL DEFAULT 1,
  excluido_em              DATETIME(3) NULL,
  excluido_por             BIGINT UNSIGNED NULL,
  CONSTRAINT ck_remessa_bpa_tipo_bpa CHECK (tipo_bpa IN ('consolidado','individualizado','misto')),
  CONSTRAINT ck_remessa_bpa_orgao_destino CHECK (orgao_destino IN ('municipal','estadual')),
  CONSTRAINT ck_remessa_bpa_situacao CHECK (situacao IN ('aberta','fechada','gerada','conferida','enviada','substituida','cancelada')),
  CONSTRAINT ck_remessa_bpa_arquivo CHECK (situacao NOT IN ('gerada','conferida','enviada') OR (hash_sha256 IS NOT NULL AND arquivo_id IS NOT NULL)),
  CONSTRAINT ck_remessa_bpa_envio CHECK (situacao <> 'enviada' OR enviada_em IS NOT NULL),
  CONSTRAINT ck_remessa_bpa_folhas CHECK (ultima_folha IS NULL OR ultima_folha >= folha_inicial),
  CONSTRAINT ck_remessa_bpa_datas CHECK (fechada_em IS NULL OR fechada_em >= aberta_em),
  CONSTRAINT ck_remessa_bpa_origem CHECK (origem IN ('sistema','migracao','integracao')),
  UNIQUE KEY uq_remessa_bpa_estabelecimento_numero (estabelecimento_id, numero),
  KEY ix_remessa_bpa_competencia_situacao (competencia_sus_id, situacao),
  KEY ix_remessa_bpa_responsavel_setor (responsavel_setor_funcional_id),
  KEY ix_remessa_bpa_arquivo (arquivo_id),
  KEY ix_remessa_bpa_gerador_usuario (gerador_usuario_id),
  KEY ix_remessa_bpa_remetente_usuario (remetente_usuario_id),
  KEY ix_remessa_bpa_substituta (substituta_remessa_bpa_id),
  KEY ix_remessa_bpa_hash (hash_sha256)
) COMMENT='Arquivo do BPA da competência, com hash, caminho e situação';

