CREATE TABLE retorno_sus (
  id                       BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
  estabelecimento_id       BIGINT UNSIGNED NOT NULL,
  competencia_sus_id       BIGINT UNSIGNED NOT NULL COMMENT 'Competência processada pelo gestor',
  numero                   VARCHAR(20) NOT NULL COMMENT 'Número de negócio da importação, gerado pela sequencia_negocio',
  instrumento              VARCHAR(30) NOT NULL COMMENT 'Instrumento do retorno: aih, bpa, apac, raas ou ciha',
  remessa_bpa_id           BIGINT UNSIGNED NULL,
  remessa_apac_id          BIGINT UNSIGNED NULL,
  remessa_raas_id          BIGINT UNSIGNED NULL,
  remessa_sisaih_id        BIGINT UNSIGNED NULL,
  remessa_ciha_id          BIGINT UNSIGNED NULL,
  situacao                 VARCHAR(30) NOT NULL DEFAULT 'importado',
  arquivo_id               BIGINT UNSIGNED NOT NULL COMMENT 'Arquivo de retorno recebido do gestor',
  nome_arquivo             VARCHAR(255) NOT NULL,
  hash_sha256              CHAR(64) NOT NULL COMMENT 'SHA-256 do arquivo importado, impede importação repetida',
  importado_em             DATETIME(3) NOT NULL,
  importador_usuario_id    BIGINT UNSIGNED NULL,
  processado_em            DATE NULL COMMENT 'Data de processamento informada pelo gestor',
  quantidade_registros     INT UNSIGNED NOT NULL DEFAULT 0,
  quantidade_aprovados     INT UNSIGNED NOT NULL DEFAULT 0,
  quantidade_rejeitados    INT UNSIGNED NOT NULL DEFAULT 0,
  quantidade_glosados      INT UNSIGNED NOT NULL DEFAULT 0,
  valor_apresentado        DECIMAL(15,2) NOT NULL DEFAULT 0,
  valor_aprovado           DECIMAL(15,2) NOT NULL DEFAULT 0,
  valor_glosado            DECIMAL(15,2) NOT NULL DEFAULT 0,
  conciliado_em            DATETIME(3) NULL,
  conciliador_usuario_id   BIGINT UNSIGNED NULL,
  observacao               VARCHAR(500) NULL,
  origem                   VARCHAR(20) NOT NULL DEFAULT 'sistema',
  criado_em                DATETIME(3) NOT NULL,
  criado_por               BIGINT UNSIGNED NULL,
  alterado_em              DATETIME(3) NULL,
  alterado_por             BIGINT UNSIGNED NULL,
  versao                   INT UNSIGNED NOT NULL DEFAULT 1,
  excluido_em              DATETIME(3) NULL,
  excluido_por             BIGINT UNSIGNED NULL,
  CONSTRAINT ck_retorno_sus_instrumento CHECK (instrumento IN ('aih','bpa','apac','raas','ciha')),
  CONSTRAINT ck_retorno_sus_remessa CHECK (
    (remessa_bpa_id IS NULL OR instrumento = 'bpa') AND
    (remessa_apac_id IS NULL OR instrumento = 'apac') AND
    (remessa_raas_id IS NULL OR instrumento = 'raas') AND
    (remessa_sisaih_id IS NULL OR instrumento = 'aih') AND
    (remessa_ciha_id IS NULL OR instrumento = 'ciha')),
  CONSTRAINT ck_retorno_sus_situacao CHECK (situacao IN ('importado','em_conciliacao','conciliado','cancelado')),
  CONSTRAINT ck_retorno_sus_conciliado CHECK (situacao <> 'conciliado' OR conciliado_em IS NOT NULL),
  CONSTRAINT ck_retorno_sus_quantidades CHECK (quantidade_aprovados + quantidade_rejeitados + quantidade_glosados <= quantidade_registros),
  CONSTRAINT ck_retorno_sus_valores CHECK (valor_apresentado >= 0 AND valor_aprovado >= 0 AND valor_glosado >= 0),
  CONSTRAINT ck_retorno_sus_origem CHECK (origem IN ('sistema','migracao','integracao')),
  UNIQUE KEY uq_retorno_sus_estabelecimento_numero (estabelecimento_id, numero),
  UNIQUE KEY uq_retorno_sus_estabelecimento_hash (estabelecimento_id, hash_sha256),
  KEY ix_retorno_sus_competencia_instrumento (competencia_sus_id, instrumento),
  KEY ix_retorno_sus_remessa_bpa (remessa_bpa_id),
  KEY ix_retorno_sus_remessa_apac (remessa_apac_id),
  KEY ix_retorno_sus_remessa_raas (remessa_raas_id),
  KEY ix_retorno_sus_remessa_sisaih (remessa_sisaih_id),
  KEY ix_retorno_sus_remessa_ciha (remessa_ciha_id),
  KEY ix_retorno_sus_arquivo (arquivo_id),
  KEY ix_retorno_sus_importador_usuario (importador_usuario_id),
  KEY ix_retorno_sus_conciliador_usuario (conciliador_usuario_id)
) COMMENT='Retorno do processamento do gestor por competência e instrumento, com valores aprovados';

