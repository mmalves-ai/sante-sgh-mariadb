-- Núcleo: mecanismos comuns (ADR 0002, parte 2). Exemplo canônico das convenções do DDL.
-- Sem FK de outro módulo aqui; as chaves ficam em 00_nucleo_chaves.sql.

CREATE TABLE trilha_auditoria (
  id                BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
  estabelecimento_id BIGINT UNSIGNED NULL COMMENT 'Estabelecimento onde a ação ocorreu (nulo para ações da plataforma)',
  usuario_id        BIGINT UNSIGNED NULL COMMENT 'Usuário que executou a ação (nulo para processos automáticos)',
  ocorrido_em       DATETIME(3) NOT NULL,
  acao              VARCHAR(30) NOT NULL,
  entidade          VARCHAR(64) NOT NULL COMMENT 'Nome da tabela afetada',
  entidade_id       BIGINT UNSIGNED NULL,
  dados_antes       JSON NULL,
  dados_depois      JSON NULL,
  motivo            VARCHAR(500) NULL,
  endereco_ip       VARCHAR(45) NULL,
  correlacao        VARCHAR(64) NULL COMMENT 'Identificador da requisição ou operação, para juntar eventos',
  criado_em         DATETIME(3) NOT NULL,
  criado_por        BIGINT UNSIGNED NULL,
  alterado_em       DATETIME(3) NULL,
  alterado_por      BIGINT UNSIGNED NULL,
  versao            INT UNSIGNED NOT NULL DEFAULT 1,
  CONSTRAINT ck_trilha_auditoria_acao CHECK (acao IN ('inclusao','alteracao','exclusao','consulta','impressao','exportacao','login','logout','acesso_negado','quebra_de_vidro','operacao')),
  KEY ix_trilha_auditoria_entidade (entidade, entidade_id),
  KEY ix_trilha_auditoria_usuario (usuario_id, ocorrido_em),
  KEY ix_trilha_auditoria_estabelecimento (estabelecimento_id, ocorrido_em)
) COMMENT='Trilha única de auditoria: quem fez o quê, quando e em qual registro';

CREATE TABLE sequencia_negocio (
  id                BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
  estabelecimento_id BIGINT UNSIGNED NULL COMMENT 'Nulo para sequência do cliente inteiro',
  tipo              VARCHAR(60) NOT NULL COMMENT 'Ex.: prontuario, atendimento, conta, guia_tiss, lote_tiss, nfse',
  prefixo           VARCHAR(20) NULL,
  proximo_valor     BIGINT UNSIGNED NOT NULL DEFAULT 1,
  incremento        INT UNSIGNED NOT NULL DEFAULT 1,
  valor_maximo      BIGINT UNSIGNED NULL,
  ativo             BOOLEAN NOT NULL DEFAULT TRUE,
  criado_em         DATETIME(3) NOT NULL,
  criado_por        BIGINT UNSIGNED NULL,
  alterado_em       DATETIME(3) NULL,
  alterado_por      BIGINT UNSIGNED NULL,
  versao            INT UNSIGNED NOT NULL DEFAULT 1,
  estabelecimento_chave BIGINT UNSIGNED AS (COALESCE(estabelecimento_id, 0)) PERSISTENT COMMENT 'Auxiliar da unicidade: 0 na sequência do cliente inteiro (o UNIQUE aceita vários NULL)',
  UNIQUE KEY uq_sequencia_negocio_estabelecimento_tipo (estabelecimento_chave, tipo),
  KEY ix_sequencia_negocio_estabelecimento (estabelecimento_id)
) COMMENT='Gerador dos números de negócio (prontuário, conta, guia, nota), separado do id';

CREATE TABLE arquivo (
  id                BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
  estabelecimento_id BIGINT UNSIGNED NULL,
  entidade          VARCHAR(64) NULL COMMENT 'Tabela dona do arquivo',
  entidade_id       BIGINT UNSIGNED NULL,
  finalidade        VARCHAR(60) NOT NULL COMMENT 'Ex.: documento_assinado, anexo, imagem, logotipo, laudo',
  nome_original     VARCHAR(255) NOT NULL,
  tipo_mime         VARCHAR(127) NOT NULL,
  tamanho_bytes     BIGINT UNSIGNED NOT NULL,
  hash_sha256       CHAR(64) NOT NULL,
  chave_armazenamento VARCHAR(512) NOT NULL COMMENT 'Caminho relativo na raiz de arquivos',
  retencao_ate      DATE NULL COMMENT 'Guarda legal (ex.: prontuário, 20 anos)',
  imutavel          BOOLEAN NOT NULL DEFAULT FALSE,
  origem            VARCHAR(20) NOT NULL DEFAULT 'sistema',
  criado_em         DATETIME(3) NOT NULL,
  criado_por        BIGINT UNSIGNED NULL,
  alterado_em       DATETIME(3) NULL,
  alterado_por      BIGINT UNSIGNED NULL,
  versao            INT UNSIGNED NOT NULL DEFAULT 1,
  excluido_em       DATETIME(3) NULL,
  excluido_por      BIGINT UNSIGNED NULL,
  CONSTRAINT ck_arquivo_origem CHECK (origem IN ('sistema','migracao','integracao')),
  UNIQUE KEY uq_arquivo_chave_armazenamento (chave_armazenamento),
  KEY ix_arquivo_entidade (entidade, entidade_id),
  KEY ix_arquivo_hash_sha256 (hash_sha256),
  KEY ix_arquivo_estabelecimento (estabelecimento_id)
) COMMENT='Metadado de documento ou anexo binário guardado no armazenamento de arquivos da instalação';

CREATE TABLE pendencia (
  id                BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
  estabelecimento_id BIGINT UNSIGNED NULL,
  tipo              VARCHAR(60) NOT NULL COMMENT 'Ex.: documento_obrigatorio, conferencia, migracao, autorizacao',
  entidade          VARCHAR(64) NULL,
  entidade_id       BIGINT UNSIGNED NULL,
  descricao         VARCHAR(500) NOT NULL,
  situacao          VARCHAR(30) NOT NULL DEFAULT 'aberta',
  critica           BOOLEAN NOT NULL DEFAULT FALSE,
  responsavel_usuario_id BIGINT UNSIGNED NULL,
  prazo_em          DATETIME(3) NULL,
  resolvida_em      DATETIME(3) NULL,
  resolvida_por     BIGINT UNSIGNED NULL,
  resolucao         VARCHAR(500) NULL,
  criado_em         DATETIME(3) NOT NULL,
  criado_por        BIGINT UNSIGNED NULL,
  alterado_em       DATETIME(3) NULL,
  alterado_por      BIGINT UNSIGNED NULL,
  versao            INT UNSIGNED NOT NULL DEFAULT 1,
  CONSTRAINT ck_pendencia_situacao CHECK (situacao IN ('aberta','em_andamento','resolvida','cancelada')),
  KEY ix_pendencia_entidade (entidade, entidade_id),
  KEY ix_pendencia_responsavel (responsavel_usuario_id, situacao),
  KEY ix_pendencia_estabelecimento (estabelecimento_id, situacao)
) COMMENT='Pendência genérica cobrada de alguém, de qualquer módulo';

CREATE TABLE integracao_mensagem (
  id                BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
  estabelecimento_id BIGINT UNSIGNED NULL,
  ponto             VARCHAR(80) NOT NULL COMMENT 'Ponto de integração (ex.: tiss_lote, laboratorio_resultado, rnds)',
  direcao           VARCHAR(10) NOT NULL,
  situacao          VARCHAR(20) NOT NULL DEFAULT 'pendente',
  tentativas        INT UNSIGNED NOT NULL DEFAULT 0,
  proxima_tentativa_em DATETIME(3) NULL,
  entidade          VARCHAR(64) NULL,
  entidade_id       BIGINT UNSIGNED NULL,
  referencia_externa VARCHAR(120) NULL,
  conteudo          LONGTEXT NULL,
  resposta          LONGTEXT NULL,
  erro              TEXT NULL,
  processada_em     DATETIME(3) NULL,
  criado_em         DATETIME(3) NOT NULL,
  criado_por        BIGINT UNSIGNED NULL,
  alterado_em       DATETIME(3) NULL,
  alterado_por      BIGINT UNSIGNED NULL,
  versao            INT UNSIGNED NOT NULL DEFAULT 1,
  CONSTRAINT ck_integracao_mensagem_direcao CHECK (direcao IN ('entrada','saida')),
  CONSTRAINT ck_integracao_mensagem_situacao CHECK (situacao IN ('pendente','enviada','processada','erro','descartada')),
  KEY ix_integracao_mensagem_fila (ponto, situacao, proxima_tentativa_em),
  KEY ix_integracao_mensagem_entidade (entidade, entidade_id),
  KEY ix_integracao_mensagem_estabelecimento (estabelecimento_id)
) COMMENT='Fila e registro único das mensagens de integração de entrada e saída';

CREATE TABLE idempotencia_operacao (
  id                BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
  operacao          VARCHAR(120) NOT NULL COMMENT 'Nome da operação do executor do núcleo',
  chave             VARCHAR(80) NOT NULL COMMENT 'Chave de idempotência enviada por quem pediu a gravação',
  estabelecimento_id BIGINT UNSIGNED NULL,
  usuario_id        BIGINT UNSIGNED NULL COMMENT 'Quem gravou; a mesma chave usada por outra pessoa é recusada',
  hash_entrada      CHAR(64) NOT NULL COMMENT 'SHA-256 da entrada canônica; a mesma chave com outra entrada é recusada',
  resultado         JSON NOT NULL COMMENT 'Resultado devolvido na repetição (só ids e códigos)',
  trilha_auditoria_id BIGINT UNSIGNED NULL,
  criado_em         DATETIME(3) NOT NULL,
  criado_por        BIGINT UNSIGNED NULL,
  alterado_em       DATETIME(3) NULL,
  alterado_por      BIGINT UNSIGNED NULL,
  versao            INT UNSIGNED NOT NULL DEFAULT 1,
  UNIQUE KEY uq_idempotencia_operacao_chave (operacao, chave),
  KEY ix_idempotencia_operacao_estabelecimento (estabelecimento_id),
  KEY ix_idempotencia_operacao_usuario (usuario_id),
  KEY ix_idempotencia_operacao_trilha (trilha_auditoria_id)
) COMMENT='Gravações já feitas por chave de idempotência: a repetição devolve o resultado sem gravar de novo';
