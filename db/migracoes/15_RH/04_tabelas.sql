CREATE TABLE troca_plantao (
  id                    BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
  estabelecimento_id    BIGINT UNSIGNED NOT NULL,
  tipo                  VARCHAR(20) NOT NULL COMMENT 'troca: um plantão por outro; cessao: o colega assume sem devolver',
  plantao_id            BIGINT UNSIGNED NOT NULL COMMENT 'Plantão de quem pede',
  solicitante_colaborador_id BIGINT UNSIGNED NOT NULL,
  colega_colaborador_id BIGINT UNSIGNED NOT NULL,
  colega_plantao_id     BIGINT UNSIGNED NULL COMMENT 'Plantão do colega que volta para quem pede (só na troca)',
  motivo                VARCHAR(500) NOT NULL,
  situacao              VARCHAR(30) NOT NULL DEFAULT 'pedida',
  solicitado_em         DATETIME(3) NOT NULL,
  respondido_em         DATETIME(3) NULL COMMENT 'Aceite ou recusa do colega',
  motivo_recusa         VARCHAR(500) NULL,
  decidido_em           DATETIME(3) NULL COMMENT 'Aprovação ou reprovação da coordenação',
  decisor_usuario_id    BIGINT UNSIGNED NULL,
  motivo_decisao        VARCHAR(500) NULL,
  cancelado_em          DATETIME(3) NULL,
  motivo_cancelamento   VARCHAR(500) NULL,
  trava_plantao_aberto     BIGINT UNSIGNED AS (IF(situacao IN ('pedida','aceita') AND excluido_em IS NULL, plantao_id, NULL)) PERSISTENT COMMENT 'Trava: um plantão só entra em uma troca aberta por vez',
  trava_colega_plantao_aberto BIGINT UNSIGNED AS (IF(situacao IN ('pedida','aceita') AND excluido_em IS NULL, colega_plantao_id, NULL)) PERSISTENT COMMENT 'Mesma trava para o plantão do colega',
  origem                VARCHAR(20) NOT NULL DEFAULT 'sistema',
  excluido_em           DATETIME(3) NULL,
  excluido_por          BIGINT UNSIGNED NULL,
  criado_em             DATETIME(3) NOT NULL,
  criado_por            BIGINT UNSIGNED NULL,
  alterado_em           DATETIME(3) NULL,
  alterado_por          BIGINT UNSIGNED NULL,
  versao                INT UNSIGNED NOT NULL DEFAULT 1,
  UNIQUE KEY uq_troca_plantao_plantao_aberto (trava_plantao_aberto),
  UNIQUE KEY uq_troca_plantao_colega_plantao_aberto (trava_colega_plantao_aberto),
  CONSTRAINT ck_troca_plantao_tipo CHECK (tipo IN ('troca','cessao')),
  CONSTRAINT ck_troca_plantao_tipo_plantao CHECK ((tipo = 'troca' AND colega_plantao_id IS NOT NULL) OR (tipo = 'cessao' AND colega_plantao_id IS NULL)),
  CONSTRAINT ck_troca_plantao_partes CHECK (solicitante_colaborador_id <> colega_colaborador_id),
  CONSTRAINT ck_troca_plantao_plantoes CHECK (colega_plantao_id IS NULL OR colega_plantao_id <> plantao_id),
  CONSTRAINT ck_troca_plantao_situacao CHECK (situacao IN ('pedida','aceita','aprovada','recusada','reprovada','cancelada')),
  CONSTRAINT ck_troca_plantao_decisao CHECK (situacao NOT IN ('aprovada','reprovada') OR (decidido_em IS NOT NULL AND decisor_usuario_id IS NOT NULL)),
  CONSTRAINT ck_troca_plantao_reprovacao CHECK (situacao <> 'reprovada' OR motivo_decisao IS NOT NULL),
  CONSTRAINT ck_troca_plantao_cancelamento CHECK (situacao <> 'cancelada' OR (cancelado_em IS NOT NULL AND motivo_cancelamento IS NOT NULL)),
  CONSTRAINT ck_troca_plantao_origem CHECK (origem IN ('sistema','migracao','integracao')),
  KEY ix_troca_plantao_estabelecimento (estabelecimento_id, situacao),
  KEY ix_troca_plantao_plantao (plantao_id),
  KEY ix_troca_plantao_colega_plantao (colega_plantao_id),
  KEY ix_troca_plantao_solicitante (solicitante_colaborador_id),
  KEY ix_troca_plantao_colega (colega_colaborador_id),
  KEY ix_troca_plantao_decisor (decisor_usuario_id)
) COMMENT='Troca ou cessão de plantão entre colaboradores, com aceite e aprovação';

