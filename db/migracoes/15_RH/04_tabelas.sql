CREATE TABLE tipo_rescisao (
  id                        BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
  codigo                    VARCHAR(30) NOT NULL,
  descricao                 VARCHAR(150) NOT NULL,
  iniciativa                VARCHAR(30) NOT NULL COMMENT 'Quem dá causa ao desligamento',
  motivo_desligamento_codigo_esocial_id BIGINT UNSIGNED NULL COMMENT 'Motivo de desligamento da tabela oficial do eSocial',
  codigo_rais               SMALLINT UNSIGNED NULL COMMENT 'Código oficial de rescisão da RAIS',
  codigo_sefip              CHAR(2) NULL COMMENT 'Código oficial de movimentação da SEFIP',
  codigo_caged              SMALLINT UNSIGNED NULL COMMENT 'Código oficial de desligamento do CAGED',
  codigo_saque_fgts         VARCHAR(3) NULL COMMENT 'Código de saque do FGTS',
  codigo_causa_afastamento  VARCHAR(3) NULL COMMENT 'Código de causa de afastamento definitivo',
  exige_aviso_previo        BOOLEAN NOT NULL DEFAULT FALSE,
  paga_multa_fgts           BOOLEAN NOT NULL DEFAULT FALSE,
  percentual_multa_fgts     DECIMAL(7,4) NULL COMMENT 'Percentual da multa rescisória sobre o saldo do FGTS',
  permite_saque_fgts        BOOLEAN NOT NULL DEFAULT FALSE,
  paga_ferias_proporcionais BOOLEAN NOT NULL DEFAULT TRUE,
  paga_decimo_proporcional  BOOLEAN NOT NULL DEFAULT TRUE,
  da_direito_seguro_desemprego BOOLEAN NOT NULL DEFAULT FALSE,
  ativo                     BOOLEAN NOT NULL DEFAULT TRUE,
  criado_em                 DATETIME(3) NOT NULL,
  criado_por                BIGINT UNSIGNED NULL,
  alterado_em               DATETIME(3) NULL,
  alterado_por              BIGINT UNSIGNED NULL,
  versao                    INT UNSIGNED NOT NULL DEFAULT 1,
  UNIQUE KEY uq_tipo_rescisao_codigo (codigo),
  CONSTRAINT ck_tipo_rescisao_iniciativa CHECK (iniciativa IN ('empregador','empregado','acordo','termino_contrato','falecimento','aposentadoria','outro')),
  CONSTRAINT ck_tipo_rescisao_percentual_multa CHECK (percentual_multa_fgts IS NULL OR percentual_multa_fgts BETWEEN 0 AND 100),
  CONSTRAINT ck_tipo_rescisao_multa CHECK (paga_multa_fgts = FALSE OR percentual_multa_fgts IS NOT NULL),
  KEY ix_tipo_rescisao_motivo_esocial (motivo_desligamento_codigo_esocial_id)
) COMMENT='Tipos de rescisão com os códigos oficiais de RAIS, SEFIP, CAGED e saque';

