  percentual_tecnico   DECIMAL(7,4) NOT NULL,
  indice_seguranca_tecnica DECIMAL(7,4) NOT NULL COMMENT 'Acréscimo para férias, faltas e afastamentos',
  jornada_semanal_horas DECIMAL(15,4) NOT NULL DEFAULT 36,
