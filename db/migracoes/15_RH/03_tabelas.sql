  faltas_injustificadas SMALLINT UNSIGNED NOT NULL DEFAULT 0,
  dias_afastamento     SMALLINT UNSIGNED NOT NULL DEFAULT 0,
  dias_direito         SMALLINT UNSIGNED NOT NULL DEFAULT 30,
  dias_gozados         SMALLINT UNSIGNED NOT NULL DEFAULT 0,
  dias_abono           SMALLINT UNSIGNED NOT NULL DEFAULT 0,
  dias_saldo           SMALLINT UNSIGNED NOT NULL DEFAULT 30,
  situacao             VARCHAR(30) NOT NULL DEFAULT 'aberto',
  motivo_perda         VARCHAR(200) NULL,
  origem               VARCHAR(20) NOT NULL DEFAULT 'sistema',
  criado_em            DATETIME(3) NOT NULL,
  criado_por           BIGINT UNSIGNED NULL,
  alterado_em          DATETIME(3) NULL,
  alterado_por         BIGINT UNSIGNED NULL,
  versao               INT UNSIGNED NOT NULL DEFAULT 1,
  excluido_em          DATETIME(3) NULL,
  excluido_por         BIGINT UNSIGNED NULL,
  CONSTRAINT ck_periodo_aquisitivo_origem CHECK (origem IN ('sistema','migracao','integracao')),
  CONSTRAINT ck_periodo_aquisitivo_datas CHECK (fim > inicio AND limite_concessivo > fim),
  CONSTRAINT ck_periodo_aquisitivo_dias CHECK (dias_direito <= 30 AND dias_abono <= 10 AND dias_gozados + dias_abono <= dias_direito),
  CONSTRAINT ck_periodo_aquisitivo_situacao CHECK (situacao IN ('aberto','adquirido','parcialmente_gozado','quitado','perdido','vencido')),
  CONSTRAINT ck_periodo_aquisitivo_perda CHECK (situacao <> 'perdido' OR motivo_perda IS NOT NULL),
  UNIQUE KEY uq_periodo_aquisitivo_colaborador_inicio (colaborador_id, inicio),
  KEY ix_periodo_aquisitivo_limite (estabelecimento_id, situacao, limite_concessivo)
) COMMENT='Período aquisitivo de férias, com faltas, direito e saldo';

