CREATE TABLE motivo_afastamento (
  id                   BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
  codigo               VARCHAR(30) NOT NULL,
  descricao            VARCHAR(150) NOT NULL,
  ativo                BOOLEAN NOT NULL DEFAULT TRUE,
  codigo_esocial       VARCHAR(2) NULL COMMENT 'Código do motivo na tabela 18 do eSocial',
  exige_cid            BOOLEAN NOT NULL DEFAULT FALSE,
  gera_lancamento_automatico BOOLEAN NOT NULL DEFAULT FALSE COMMENT 'Lança automaticamente as rubricas do afastamento na folha',
  dias_pagos_empresa   SMALLINT UNSIGNED NULL COMMENT 'Dias a cargo do empregador antes do benefício (ex.: 15 no auxílio-doença)',
  conta_tempo_servico  BOOLEAN NOT NULL DEFAULT TRUE,
  vigencia_inicio      DATE NULL,
  vigencia_fim         DATE NULL,
  criado_em            DATETIME(3) NOT NULL,
  criado_por           BIGINT UNSIGNED NULL,
  alterado_em          DATETIME(3) NULL,
  alterado_por         BIGINT UNSIGNED NULL,
  versao               INT UNSIGNED NOT NULL DEFAULT 1,
  UNIQUE KEY uq_motivo_afastamento_codigo (codigo),
  CONSTRAINT ck_motivo_afastamento_vigencia CHECK (vigencia_fim IS NULL OR vigencia_inicio IS NULL OR vigencia_fim >= vigencia_inicio),
  KEY ix_motivo_afastamento_codigo_esocial (codigo_esocial)
) COMMENT='Motivos de afastamento usados pelo hospital, ligados ao código oficial';

