  vigencia_fim         DATE NULL,
  ativo                BOOLEAN NOT NULL DEFAULT TRUE,
  criado_em            DATETIME(3) NOT NULL,
  criado_por           BIGINT UNSIGNED NULL,
  alterado_em          DATETIME(3) NULL,
  alterado_por         BIGINT UNSIGNED NULL,
  versao               INT UNSIGNED NOT NULL DEFAULT 1,
  CONSTRAINT ck_parametro_dimensionamento_tipo_cuidado CHECK (tipo_cuidado IN ('minimo','intermediario','alta_dependencia','semi_intensivo','intensivo')),
  CONSTRAINT ck_parametro_dimensionamento_valores CHECK (horas_enfermagem_paciente > 0 AND percentual_enfermeiro BETWEEN 0 AND 100 AND percentual_tecnico BETWEEN 0 AND 100 AND indice_seguranca_tecnica >= 0 AND jornada_semanal_horas > 0),
  CONSTRAINT ck_parametro_dimensionamento_vigencia CHECK (vigencia_fim IS NULL OR vigencia_fim >= vigencia_inicio),
  UNIQUE KEY uq_parametro_dimensionamento_vigencia (estabelecimento_id, tipo_cuidado, vigencia_inicio)
) COMMENT='Horas de enfermagem por tipo de cuidado e índice de segurança, por vigência da resolução';

