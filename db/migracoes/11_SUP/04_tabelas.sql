CREATE TABLE nota_entrada_imposto (
  id                           BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
  nota_entrada_item_id         BIGINT UNSIGNED NOT NULL,
  sequencia                    SMALLINT UNSIGNED NOT NULL,
  tributo_id                   BIGINT UNSIGNED NOT NULL,
  dado_fiscal_item_id          BIGINT UNSIGNED NULL COMMENT 'Regra fiscal que sugeriu a tributação',
  situacao_tributaria          VARCHAR(10) NULL COMMENT 'CST ou CSOSN aplicado na entrada',
  situacao_tributaria_sugerida VARCHAR(10) NULL COMMENT 'CST ou CSOSN sugerido pela regra fiscal',
  base_calculo                 DECIMAL(15,2) NOT NULL DEFAULT 0,
  aliquota_percentual          DECIMAL(7,4) NOT NULL DEFAULT 0,
  valor                        DECIMAL(15,2) NOT NULL DEFAULT 0,
  compoe_custo                 BOOLEAN NOT NULL DEFAULT FALSE COMMENT 'O imposto entra no custo do insumo (não recuperável)',
  recuperavel                  BOOLEAN NOT NULL DEFAULT FALSE COMMENT 'Gera crédito tributário',
  origem                       VARCHAR(20) NOT NULL DEFAULT 'sistema',
  criado_em                    DATETIME(3) NOT NULL,
  criado_por                   BIGINT UNSIGNED NULL,
  alterado_em                  DATETIME(3) NULL,
  alterado_por                 BIGINT UNSIGNED NULL,
  versao                       INT UNSIGNED NOT NULL DEFAULT 1,
  excluido_em                  DATETIME(3) NULL,
  excluido_por                 BIGINT UNSIGNED NULL,
  CONSTRAINT ck_nota_entrada_imposto_origem CHECK (origem IN ('sistema','migracao','integracao')),
  CONSTRAINT ck_nota_entrada_imposto_valores CHECK (base_calculo >= 0 AND valor >= 0 AND aliquota_percentual BETWEEN 0 AND 100),
  CONSTRAINT ck_nota_entrada_imposto_custo CHECK (NOT (compoe_custo AND recuperavel)),
  UNIQUE KEY uq_nota_entrada_imposto_sequencia (nota_entrada_item_id, sequencia),
  UNIQUE KEY uq_nota_entrada_imposto_tributo (nota_entrada_item_id, tributo_id),
  KEY ix_nota_entrada_imposto_tributo_id (tributo_id),
  KEY ix_nota_entrada_imposto_dado_fiscal_item_id (dado_fiscal_item_id)
) COMMENT='Imposto destacado por item da nota (base, alíquota, valor), que compõe ou não o custo';

