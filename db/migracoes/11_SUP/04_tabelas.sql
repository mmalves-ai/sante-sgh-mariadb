  CONSTRAINT ck_nota_entrada_item_valores CHECK (valor_unitario >= 0 AND valor_desconto >= 0 AND valor_frete >= 0 AND valor_outras_despesas >= 0 AND valor_total >= 0 AND custo_unitario >= 0),
