CREATE TABLE nivel_servico (
  id                       BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
  codigo                   VARCHAR(30) NOT NULL,
  descricao                VARCHAR(150) NOT NULL,
  ativo                    BOOLEAN NOT NULL DEFAULT TRUE,
  percentual_nivel_servico DECIMAL(7,4) NOT NULL COMMENT 'Probabilidade desejada de não faltar o insumo, em % (ex.: 95)',
  fator_seguranca          DECIMAL(7,4) NOT NULL COMMENT 'Fator z da distribuição normal correspondente ao nível de serviço',
  criado_em                DATETIME(3) NOT NULL,
  criado_por               BIGINT UNSIGNED NULL,
  alterado_em              DATETIME(3) NULL,
  alterado_por             BIGINT UNSIGNED NULL,
  versao                   INT UNSIGNED NOT NULL DEFAULT 1,
  UNIQUE KEY uq_nivel_servico_codigo (codigo),
  CONSTRAINT ck_nivel_servico_percentual CHECK (percentual_nivel_servico > 0 AND percentual_nivel_servico < 100),
  CONSTRAINT ck_nivel_servico_fator CHECK (fator_seguranca >= 0),
  UNIQUE KEY uq_nivel_servico_percentual (percentual_nivel_servico)
) COMMENT='Nível de serviço desejado que define o estoque de segurança';

