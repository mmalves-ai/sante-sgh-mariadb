CREATE TABLE grupo_insumo (
  id                 BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
  codigo             VARCHAR(30) NOT NULL,
  descricao          VARCHAR(150) NOT NULL,
  natureza           VARCHAR(30) NOT NULL COMMENT 'medicamento, material, dieta, solucao, gas_medicinal, opme, limpeza, expediente ou outro',
  antimicrobiano     BOOLEAN NOT NULL DEFAULT FALSE COMMENT 'Os insumos do grupo exigem ficha de antimicrobiano',
  exige_rastreio     BOOLEAN NOT NULL DEFAULT FALSE COMMENT 'Os insumos do grupo exigem controle de lote e validade',
  exige_norma_especial BOOLEAN NOT NULL DEFAULT FALSE COMMENT 'Os insumos do grupo seguem norma específica de guarda ou uso',
  prazo_entrega_dias SMALLINT UNSIGNED NULL COMMENT 'Prazo padrão de entrega pelo fornecedor, em dias',
  codigo_tiss        VARCHAR(10) NULL COMMENT 'Código do grupo na terminologia TISS, quando houver',
  ativo              BOOLEAN NOT NULL DEFAULT TRUE,
  criado_em          DATETIME(3) NOT NULL,
  criado_por         BIGINT UNSIGNED NULL,
  alterado_em        DATETIME(3) NULL,
  alterado_por       BIGINT UNSIGNED NULL,
  versao             INT UNSIGNED NOT NULL DEFAULT 1,
  CONSTRAINT ck_grupo_insumo_natureza CHECK (natureza IN ('medicamento','material','dieta','solucao','gas_medicinal','opme','limpeza','expediente','outro')),
  CONSTRAINT ck_grupo_insumo_prazo CHECK (prazo_entrega_dias IS NULL OR prazo_entrega_dias <= 365),
  UNIQUE KEY uq_grupo_insumo_codigo (codigo)
) COMMENT='Grupo do insumo (medicamento, material médico, dieta, limpeza, expediente)';

