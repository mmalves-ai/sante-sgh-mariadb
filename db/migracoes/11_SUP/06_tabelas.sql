-- Suprimentos, lote 06: domínios de estoque, unidade de medida, unificação de insumos, permissões do usuário de
-- estoque, veículos de entrega e vínculo com portal de cotação. Sem FOREIGN KEY aqui (ficam em 06_chaves.sql).

CREATE TABLE tipo_embalagem_insumo (
  id                BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
  codigo            VARCHAR(30) NOT NULL,
  descricao         VARCHAR(150) NOT NULL,
  sigla             VARCHAR(10) NULL COMMENT 'Abreviatura usada em etiqueta e relatório (ex.: AMP, FR, CX)',
  primaria          BOOLEAN NOT NULL DEFAULT FALSE COMMENT 'Embalagem primária (em contato com o produto), usada na análise do insumo',
  ativo             BOOLEAN NOT NULL DEFAULT TRUE,
  criado_em         DATETIME(3) NOT NULL,
  criado_por        BIGINT UNSIGNED NULL,
  alterado_em       DATETIME(3) NULL,
  alterado_por      BIGINT UNSIGNED NULL,
  versao            INT UNSIGNED NOT NULL DEFAULT 1,
  UNIQUE KEY uq_tipo_embalagem_insumo_codigo (codigo)
) COMMENT='Tipos de embalagem do produto (frasco, ampola, blister, caixa), usados na análise e no cadastro';

CREATE TABLE tipo_entrada_estoque (
  id                BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
  codigo            VARCHAR(30) NOT NULL,
  descricao         VARCHAR(150) NOT NULL,
  natureza          VARCHAR(30) NOT NULL COMMENT 'Natureza da entrada, que define o efeito no custo e no financeiro',
  tipo_movimento_estoque_id BIGINT UNSIGNED NULL COMMENT 'Tipo de movimento gerado no estoque por esta entrada',
  cfop_id           BIGINT UNSIGNED NULL COMMENT 'CFOP padrão sugerido na nota de entrada',
  conta_contabil_id BIGINT UNSIGNED NULL COMMENT 'Conta contábil de contrapartida da entrada',
  exige_documento_fiscal BOOLEAN NOT NULL DEFAULT TRUE,
  atualiza_custo_medio BOOLEAN NOT NULL DEFAULT TRUE,
  atualiza_ultimo_preco BOOLEAN NOT NULL DEFAULT TRUE COMMENT 'Atualiza o último preço de compra do insumo',
  gera_conta_pagar  BOOLEAN NOT NULL DEFAULT FALSE,
  retem_imposto     BOOLEAN NOT NULL DEFAULT FALSE,
  exige_fornecedor  BOOLEAN NOT NULL DEFAULT TRUE,
  exige_pedido_compra BOOLEAN NOT NULL DEFAULT FALSE,
  ativo             BOOLEAN NOT NULL DEFAULT TRUE,
  criado_em         DATETIME(3) NOT NULL,
  criado_por        BIGINT UNSIGNED NULL,
  alterado_em       DATETIME(3) NULL,
  alterado_por      BIGINT UNSIGNED NULL,
  versao            INT UNSIGNED NOT NULL DEFAULT 1,
  UNIQUE KEY uq_tipo_entrada_estoque_codigo (codigo),
  CONSTRAINT ck_tipo_entrada_estoque_natureza CHECK (natureza IN ('compra','doacao','bonificacao','consignacao','emprestimo','devolucao_emprestimo','devolucao_paciente','transferencia','producao_interna','ajuste','outra')),
  CONSTRAINT ck_tipo_entrada_estoque_conta_pagar CHECK (gera_conta_pagar = FALSE OR natureza IN ('compra','consignacao','outra')),
  KEY ix_tipo_entrada_estoque_tipo_movimento (tipo_movimento_estoque_id),
  KEY ix_tipo_entrada_estoque_cfop (cfop_id),
  KEY ix_tipo_entrada_estoque_conta_contabil (conta_contabil_id)
) COMMENT='Tipo de entrada (compra, doação, bonificação, consignação, empréstimo), com efeito no custo e no financeiro';

CREATE TABLE tipo_movimento_estoque (
  id                BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
  codigo            VARCHAR(30) NOT NULL,
  descricao         VARCHAR(150) NOT NULL,
  natureza          VARCHAR(30) NOT NULL COMMENT 'Família do movimento, fixa do sistema',
  sentido           VARCHAR(10) NOT NULL COMMENT 'Efeito no saldo: entrada soma, saida subtrai, neutro não altera',
  afeta_saldo       BOOLEAN NOT NULL DEFAULT TRUE,
  afeta_custo_medio BOOLEAN NOT NULL DEFAULT FALSE,
  gera_consumo      BOOLEAN NOT NULL DEFAULT FALSE COMMENT 'Conta como consumo do centro de custo',
  exige_centro_custo BOOLEAN NOT NULL DEFAULT FALSE,
  exige_paciente    BOOLEAN NOT NULL DEFAULT FALSE,
  exige_motivo      BOOLEAN NOT NULL DEFAULT FALSE,
  conta_contabil_id BIGINT UNSIGNED NULL COMMENT 'Conta contábil do lançamento do movimento',
  sistema           BOOLEAN NOT NULL DEFAULT FALSE COMMENT 'Tipo nativo do sistema, que o hospital não pode excluir',
  ativo             BOOLEAN NOT NULL DEFAULT TRUE,
  criado_em         DATETIME(3) NOT NULL,
  criado_por        BIGINT UNSIGNED NULL,
  alterado_em       DATETIME(3) NULL,
  alterado_por      BIGINT UNSIGNED NULL,
  versao            INT UNSIGNED NOT NULL DEFAULT 1,
  UNIQUE KEY uq_tipo_movimento_estoque_codigo (codigo),
  CONSTRAINT ck_tipo_movimento_estoque_natureza CHECK (natureza IN ('entrada','saida','consumo_paciente','consumo_setor','transferencia','devolucao','devolucao_fornecedor','ajuste','inventario','baixa','perda','emprestimo','producao')),
  CONSTRAINT ck_tipo_movimento_estoque_sentido CHECK (sentido IN ('entrada','saida','neutro')),
  CONSTRAINT ck_tipo_movimento_estoque_saldo CHECK (afeta_saldo = (sentido <> 'neutro')),
  KEY ix_tipo_movimento_estoque_conta_contabil (conta_contabil_id)
) COMMENT='Tipo de movimento de estoque, com sentido, efeito no custo e conta contábil';

CREATE TABLE unidade_medida (
  id                BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
  codigo            VARCHAR(30) NOT NULL,
  descricao         VARCHAR(150) NOT NULL,
  sigla             VARCHAR(10) NOT NULL COMMENT 'Abreviatura exibida (ex.: CX, AMP, FR, CP, ML, MG/KG/MIN)',
  grupo_unidade_medida_id BIGINT UNSIGNED NULL COMMENT 'Grandeza da unidade (massa, volume, contagem), para conversão',
  fator_base        DECIMAL(20,8) NULL COMMENT 'Fator para a unidade base do grupo (ex.: g = 0,001 kg)',
  uso_estoque       BOOLEAN NOT NULL DEFAULT TRUE,
  uso_compra        BOOLEAN NOT NULL DEFAULT TRUE,
  uso_consumo       BOOLEAN NOT NULL DEFAULT TRUE,
  uso_dose          BOOLEAN NOT NULL DEFAULT FALSE COMMENT 'Usada em prescrição e cálculo de dose (ex.: mg/kg/min)',
  uso_afericao      BOOLEAN NOT NULL DEFAULT FALSE COMMENT 'Usada em sinais vitais e aferições',
  termo_tiss_id     BIGINT UNSIGNED NULL COMMENT 'Termo equivalente na terminologia TISS de unidade de medida',
  ordem_exibicao    SMALLINT UNSIGNED NULL,
  ativo             BOOLEAN NOT NULL DEFAULT TRUE,
  criado_em         DATETIME(3) NOT NULL,
  criado_por        BIGINT UNSIGNED NULL,
  alterado_em       DATETIME(3) NULL,
  alterado_por      BIGINT UNSIGNED NULL,
  versao            INT UNSIGNED NOT NULL DEFAULT 1,
  UNIQUE KEY uq_unidade_medida_codigo (codigo),
  UNIQUE KEY uq_unidade_medida_sigla (sigla),
  CONSTRAINT ck_unidade_medida_fator_base CHECK (fator_base IS NULL OR fator_base > 0),
  CONSTRAINT ck_unidade_medida_uso CHECK (uso_estoque OR uso_compra OR uso_consumo OR uso_dose OR uso_afericao),
  KEY ix_unidade_medida_grupo (grupo_unidade_medida_id),
  KEY ix_unidade_medida_termo_tiss (termo_tiss_id)
) COMMENT='Unidade de medida de estoque, compra e consumo (caixa, ampola, frasco, comprimido)';

CREATE TABLE unificacao_insumo (
  id                BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
  numero            VARCHAR(30) NOT NULL COMMENT 'Número de negócio, gerado por sequencia_negocio',
  insumo_permanece_id BIGINT UNSIGNED NOT NULL COMMENT 'Insumo que permanece no cadastro único e recebe saldos e históricos',
  situacao          VARCHAR(30) NOT NULL DEFAULT 'rascunho',
  motivo            VARCHAR(500) NOT NULL,
  transfere_saldo   BOOLEAN NOT NULL DEFAULT TRUE,
  transfere_historico BOOLEAN NOT NULL DEFAULT TRUE,
  inativa_absorvidos BOOLEAN NOT NULL DEFAULT TRUE COMMENT 'Inativa os insumos absorvidos ao concluir',
  solicitante_usuario_id BIGINT UNSIGNED NOT NULL,
  solicitado_em     DATETIME(3) NOT NULL,
  aprovador_usuario_id BIGINT UNSIGNED NULL,
  aprovado_em       DATETIME(3) NULL,
  executado_em      DATETIME(3) NULL,
  cancelado_em      DATETIME(3) NULL,
  motivo_cancelamento VARCHAR(500) NULL,
  observacao        TEXT NULL,
  origem            VARCHAR(20) NOT NULL DEFAULT 'sistema',
  criado_em         DATETIME(3) NOT NULL,
  criado_por        BIGINT UNSIGNED NULL,
  alterado_em       DATETIME(3) NULL,
  alterado_por      BIGINT UNSIGNED NULL,
  versao            INT UNSIGNED NOT NULL DEFAULT 1,
  excluido_em       DATETIME(3) NULL,
  excluido_por      BIGINT UNSIGNED NULL,
  UNIQUE KEY uq_unificacao_insumo_numero (numero),
  CONSTRAINT ck_unificacao_insumo_situacao CHECK (situacao IN ('rascunho','aguardando_aprovacao','aprovada','em_execucao','concluida','cancelada','erro')),
  CONSTRAINT ck_unificacao_insumo_origem CHECK (origem IN ('sistema','migracao','integracao')),
  CONSTRAINT ck_unificacao_insumo_aprovacao CHECK (situacao NOT IN ('aprovada','em_execucao','concluida') OR (aprovador_usuario_id IS NOT NULL AND aprovado_em IS NOT NULL)),
  CONSTRAINT ck_unificacao_insumo_conclusao CHECK (situacao <> 'concluida' OR executado_em IS NOT NULL),
  CONSTRAINT ck_unificacao_insumo_cancelamento CHECK (situacao <> 'cancelada' OR (cancelado_em IS NOT NULL AND motivo_cancelamento IS NOT NULL)),
  KEY ix_unificacao_insumo_permanece (insumo_permanece_id),
  KEY ix_unificacao_insumo_situacao (situacao, solicitado_em),
  KEY ix_unificacao_insumo_solicitante (solicitante_usuario_id),
  KEY ix_unificacao_insumo_aprovador (aprovador_usuario_id)
) COMMENT='Unificação de insumos duplicados em um cadastro único da rede, com o insumo que permanece';

CREATE TABLE unificacao_insumo_item (
  id                BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
  unificacao_insumo_id BIGINT UNSIGNED NOT NULL,
  sequencia         SMALLINT UNSIGNED NOT NULL,
  insumo_absorvido_id BIGINT UNSIGNED NOT NULL COMMENT 'Insumo duplicado que deixa de ser usado',
  descricao_absorvido VARCHAR(240) NOT NULL COMMENT 'Descrição do insumo absorvido no momento da unificação, para rastreio',
  unidade_medida_absorvido_id BIGINT UNSIGNED NULL COMMENT 'Unidade de estoque do insumo absorvido',
  fator_conversao   DECIMAL(20,8) NOT NULL DEFAULT 1 COMMENT 'Quantas unidades do insumo que permanece equivalem a uma do absorvido',
  situacao          VARCHAR(30) NOT NULL DEFAULT 'pendente',
  quantidade_saldo_transferida DECIMAL(15,4) NULL COMMENT 'Saldo somado de todos os locais, já convertido',
  transferido_em    DATETIME(3) NULL,
  mensagem_erro     VARCHAR(500) NULL,
  origem            VARCHAR(20) NOT NULL DEFAULT 'sistema',
  criado_em         DATETIME(3) NOT NULL,
  criado_por        BIGINT UNSIGNED NULL,
  alterado_em       DATETIME(3) NULL,
  alterado_por      BIGINT UNSIGNED NULL,
  versao            INT UNSIGNED NOT NULL DEFAULT 1,
  excluido_em       DATETIME(3) NULL,
  excluido_por      BIGINT UNSIGNED NULL,
  UNIQUE KEY uq_unificacao_insumo_item_sequencia (unificacao_insumo_id, sequencia),
  UNIQUE KEY uq_unificacao_insumo_item_absorvido (unificacao_insumo_id, insumo_absorvido_id),
  CONSTRAINT ck_unificacao_insumo_item_situacao CHECK (situacao IN ('pendente','transferido','erro','ignorado')),
  CONSTRAINT ck_unificacao_insumo_item_fator CHECK (fator_conversao > 0),
  CONSTRAINT ck_unificacao_insumo_item_transferido CHECK (situacao <> 'transferido' OR transferido_em IS NOT NULL),
  CONSTRAINT ck_unificacao_insumo_item_origem CHECK (origem IN ('sistema','migracao','integracao')),
  KEY ix_unificacao_insumo_item_absorvido (insumo_absorvido_id),
  KEY ix_unificacao_insumo_item_unidade (unidade_medida_absorvido_id)
) COMMENT='Insumo absorvido na unificação e a transferência de saldos e históricos';

CREATE TABLE usuario_estoque_centro_custo (
  id                BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
  estabelecimento_id BIGINT UNSIGNED NOT NULL,
  usuario_id        BIGINT UNSIGNED NOT NULL,
  centro_custo_id   BIGINT UNSIGNED NOT NULL,
  permite_requisitar BOOLEAN NOT NULL DEFAULT TRUE,
  permite_saida     BOOLEAN NOT NULL DEFAULT FALSE COMMENT 'Pode dar saída de estoque para este centro de custo',
  vigencia_inicio   DATE NOT NULL,
  vigencia_fim      DATE NULL,
  criado_em         DATETIME(3) NOT NULL,
  criado_por        BIGINT UNSIGNED NULL,
  alterado_em       DATETIME(3) NULL,
  alterado_por      BIGINT UNSIGNED NULL,
  versao            INT UNSIGNED NOT NULL DEFAULT 1,
  excluido_em       DATETIME(3) NULL,
  excluido_por      BIGINT UNSIGNED NULL,
  UNIQUE KEY uq_usuario_estoque_centro_custo_par (usuario_id, centro_custo_id, vigencia_inicio),
  CONSTRAINT ck_usuario_estoque_centro_custo_vigencia CHECK (vigencia_fim IS NULL OR vigencia_fim >= vigencia_inicio),
  CONSTRAINT ck_usuario_estoque_centro_custo_permissao CHECK (permite_requisitar OR permite_saida),
  KEY ix_usuario_estoque_centro_custo_estabelecimento (estabelecimento_id, usuario_id),
  KEY ix_usuario_estoque_centro_custo_centro_custo (centro_custo_id)
) COMMENT='Centros de custo para os quais o usuário pode requisitar ou dar saída';

CREATE TABLE usuario_estoque_classificacao (
  id                BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
  estabelecimento_id BIGINT UNSIGNED NOT NULL,
  usuario_id        BIGINT UNSIGNED NOT NULL,
  grupo_insumo_id   BIGINT UNSIGNED NOT NULL,
  subgrupo_insumo_id BIGINT UNSIGNED NULL COMMENT 'Nulo: vale para o grupo inteiro',
  permite_requisitar BOOLEAN NOT NULL DEFAULT TRUE,
  permite_movimentar BOOLEAN NOT NULL DEFAULT FALSE COMMENT 'Pode lançar entrada, saída e transferência do grupo',
  permite_comprar   BOOLEAN NOT NULL DEFAULT FALSE COMMENT 'Pode gerar solicitação e pedido de compra do grupo',
  vigencia_inicio   DATE NOT NULL,
  vigencia_fim      DATE NULL,
  subgrupo_chave    BIGINT UNSIGNED AS (COALESCE(subgrupo_insumo_id, 0)) STORED COMMENT 'Apoio da unicidade quando o subgrupo é nulo',
  criado_em         DATETIME(3) NOT NULL,
  criado_por        BIGINT UNSIGNED NULL,
  alterado_em       DATETIME(3) NULL,
  alterado_por      BIGINT UNSIGNED NULL,
  versao            INT UNSIGNED NOT NULL DEFAULT 1,
  excluido_em       DATETIME(3) NULL,
  excluido_por      BIGINT UNSIGNED NULL,
  UNIQUE KEY uq_usuario_estoque_classificacao_par (estabelecimento_id, usuario_id, grupo_insumo_id, subgrupo_chave, vigencia_inicio),
  CONSTRAINT ck_usuario_estoque_classificacao_vigencia CHECK (vigencia_fim IS NULL OR vigencia_fim >= vigencia_inicio),
  CONSTRAINT ck_usuario_estoque_classificacao_permissao CHECK (permite_requisitar OR permite_movimentar OR permite_comprar),
  KEY ix_usuario_estoque_classificacao_usuario (usuario_id),
  KEY ix_usuario_estoque_classificacao_grupo (grupo_insumo_id),
  KEY ix_usuario_estoque_classificacao_subgrupo (subgrupo_insumo_id)
) COMMENT='Grupos de insumo que cada usuário pode movimentar';

CREATE TABLE veiculo_entrega (
  id                BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
  codigo            VARCHAR(30) NOT NULL,
  descricao         VARCHAR(150) NOT NULL,
  placa             VARCHAR(10) NOT NULL,
  marca             VARCHAR(50) NULL,
  modelo            VARCHAR(50) NULL,
  cor               VARCHAR(30) NULL,
  ano_fabricacao    SMALLINT UNSIGNED NULL,
  ano_modelo        SMALLINT UNSIGNED NULL,
  tipo_combustivel_id BIGINT UNSIGNED NULL,
  renavam           VARCHAR(11) NULL,
  chassi            VARCHAR(17) NULL,
  numero_motor      VARCHAR(50) NULL,
  capacidade_carga_kg DECIMAL(15,4) NULL,
  capacidade_volume_m3 DECIMAL(15,4) NULL,
  refrigerado       BOOLEAN NOT NULL DEFAULT FALSE COMMENT 'Tem baú refrigerado para termolábeis',
  proprio           BOOLEAN NOT NULL DEFAULT TRUE COMMENT 'Falso: veículo de transportadora contratada',
  transportadora_empresa_fornecedora_id BIGINT UNSIGNED NULL COMMENT 'Transportadora dona do veículo, quando não é próprio',
  estabelecimento_id BIGINT UNSIGNED NULL COMMENT 'Unidade em que o veículo fica lotado (nulo: atende a rede)',
  motivo_inativacao VARCHAR(200) NULL,
  observacao        TEXT NULL,
  ativo             BOOLEAN NOT NULL DEFAULT TRUE,
  criado_em         DATETIME(3) NOT NULL,
  criado_por        BIGINT UNSIGNED NULL,
  alterado_em       DATETIME(3) NULL,
  alterado_por      BIGINT UNSIGNED NULL,
  versao            INT UNSIGNED NOT NULL DEFAULT 1,
  UNIQUE KEY uq_veiculo_entrega_codigo (codigo),
  UNIQUE KEY uq_veiculo_entrega_placa (placa),
  UNIQUE KEY uq_veiculo_entrega_renavam (renavam),
  UNIQUE KEY uq_veiculo_entrega_chassi (chassi),
  CONSTRAINT ck_veiculo_entrega_ano CHECK ((ano_fabricacao IS NULL OR ano_fabricacao BETWEEN 1950 AND 2100) AND (ano_modelo IS NULL OR ano_modelo BETWEEN 1950 AND 2100)),
  CONSTRAINT ck_veiculo_entrega_ano_modelo CHECK (ano_fabricacao IS NULL OR ano_modelo IS NULL OR ano_modelo BETWEEN ano_fabricacao AND ano_fabricacao + 1),
  CONSTRAINT ck_veiculo_entrega_capacidade CHECK ((capacidade_carga_kg IS NULL OR capacidade_carga_kg > 0) AND (capacidade_volume_m3 IS NULL OR capacidade_volume_m3 > 0)),
  CONSTRAINT ck_veiculo_entrega_proprio CHECK (proprio OR transportadora_empresa_fornecedora_id IS NOT NULL),
  CONSTRAINT ck_veiculo_entrega_inativacao CHECK (ativo OR motivo_inativacao IS NOT NULL),
  KEY ix_veiculo_entrega_tipo_combustivel (tipo_combustivel_id),
  KEY ix_veiculo_entrega_transportadora (transportadora_empresa_fornecedora_id),
  KEY ix_veiculo_entrega_estabelecimento (estabelecimento_id)
) COMMENT='Veículo usado nas entregas entre unidades';

CREATE TABLE vinculo_portal_cotacao (
  id                BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
  portal_cotacao_id BIGINT UNSIGNED NOT NULL,
  tipo_entidade     VARCHAR(30) NOT NULL COMMENT 'Qual registro local está vinculado ao identificador do portal',
  cotacao_id        BIGINT UNSIGNED NULL,
  cotacao_item_id   BIGINT UNSIGNED NULL,
  pedido_compra_id  BIGINT UNSIGNED NULL,
  empresa_fornecedora_id BIGINT UNSIGNED NULL,
  insumo_id         BIGINT UNSIGNED NULL,
  unidade_medida_id BIGINT UNSIGNED NULL,
  identificador_externo VARCHAR(100) NOT NULL COMMENT 'Código do registro no portal de cotação',
  entidade_chave    BIGINT UNSIGNED AS (COALESCE(cotacao_id, cotacao_item_id, pedido_compra_id, empresa_fornecedora_id, insumo_id, unidade_medida_id)) STORED COMMENT 'Apoio da unicidade do registro local por portal',
  vigencia_inicio   DATE NULL,
  vigencia_fim      DATE NULL,
  sincronizado_em   DATETIME(3) NULL COMMENT 'Última troca de dados com o portal',
  criado_em         DATETIME(3) NOT NULL,
  criado_por        BIGINT UNSIGNED NULL,
  alterado_em       DATETIME(3) NULL,
  alterado_por      BIGINT UNSIGNED NULL,
  versao            INT UNSIGNED NOT NULL DEFAULT 1,
  excluido_em       DATETIME(3) NULL,
  excluido_por      BIGINT UNSIGNED NULL,
  UNIQUE KEY uq_vinculo_portal_cotacao_externo (portal_cotacao_id, tipo_entidade, identificador_externo),
  UNIQUE KEY uq_vinculo_portal_cotacao_local (portal_cotacao_id, tipo_entidade, entidade_chave),
  CONSTRAINT ck_vinculo_portal_cotacao_tipo CHECK (tipo_entidade IN ('cotacao','cotacao_item','pedido_compra','fornecedor','insumo','unidade_medida')),
  CONSTRAINT ck_vinculo_portal_cotacao_entidade CHECK (
    (cotacao_id IS NOT NULL) + (cotacao_item_id IS NOT NULL) + (pedido_compra_id IS NOT NULL)
    + (empresa_fornecedora_id IS NOT NULL) + (insumo_id IS NOT NULL) + (unidade_medida_id IS NOT NULL) = 1
    AND (tipo_entidade <> 'cotacao' OR cotacao_id IS NOT NULL)
    AND (tipo_entidade <> 'cotacao_item' OR cotacao_item_id IS NOT NULL)
    AND (tipo_entidade <> 'pedido_compra' OR pedido_compra_id IS NOT NULL)
    AND (tipo_entidade <> 'fornecedor' OR empresa_fornecedora_id IS NOT NULL)
    AND (tipo_entidade <> 'insumo' OR insumo_id IS NOT NULL)
    AND (tipo_entidade <> 'unidade_medida' OR unidade_medida_id IS NOT NULL)),
  CONSTRAINT ck_vinculo_portal_cotacao_vigencia CHECK (vigencia_fim IS NULL OR vigencia_inicio IS NULL OR vigencia_fim >= vigencia_inicio),
  KEY ix_vinculo_portal_cotacao_cotacao (cotacao_id),
  KEY ix_vinculo_portal_cotacao_cotacao_item (cotacao_item_id),
  KEY ix_vinculo_portal_cotacao_pedido_compra (pedido_compra_id),
  KEY ix_vinculo_portal_cotacao_fornecedor (empresa_fornecedora_id),
  KEY ix_vinculo_portal_cotacao_insumo (insumo_id),
  KEY ix_vinculo_portal_cotacao_unidade_medida (unidade_medida_id)
) COMMENT='Identificador da cotação, do item e do fornecedor no portal externo';
