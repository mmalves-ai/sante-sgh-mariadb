  KEY ix_inventario_estoque_item_unidade_medida_id (unidade_medida_id),
  KEY ix_inventario_estoque_item_endereco_armazem_id (endereco_armazem_id),
  KEY ix_inventario_estoque_item_contagem_usuario_id (contagem_usuario_id)
) COMMENT='Quantidade contada por insumo em cada rodada e saldo do sistema na data de corte';

