  alterado_por           BIGINT UNSIGNED NULL,
  versao                 INT UNSIGNED NOT NULL DEFAULT 1,
  excluido_em            DATETIME(3) NULL,
  excluido_por           BIGINT UNSIGNED NULL,
  UNIQUE KEY uq_insumo_unidade_insumo_unidade (insumo_id, unidade_medida_id),
  KEY ix_insumo_unidade_codigo_barras (codigo_barras),
  CONSTRAINT ck_insumo_unidade_fator CHECK (fator_conversao > 0),
  CONSTRAINT ck_insumo_unidade_dose CHECK (dose_minima IS NULL OR dose_maxima IS NULL OR dose_maxima >= dose_minima),
