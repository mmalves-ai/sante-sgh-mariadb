CREATE TABLE insumo_palavra_chave (
  id            BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
  insumo_id     BIGINT UNSIGNED NOT NULL,
  sequencia     SMALLINT UNSIGNED NOT NULL,
  palavra_chave VARCHAR(100) NOT NULL,
  origem        VARCHAR(20) NOT NULL DEFAULT 'sistema',
  criado_em     DATETIME(3) NOT NULL,
  criado_por    BIGINT UNSIGNED NULL,
  alterado_em   DATETIME(3) NULL,
  alterado_por  BIGINT UNSIGNED NULL,
  versao        INT UNSIGNED NOT NULL DEFAULT 1,
  excluido_em   DATETIME(3) NULL,
  excluido_por  BIGINT UNSIGNED NULL,
  UNIQUE KEY uq_insumo_palavra_chave_insumo_sequencia (insumo_id, sequencia),
  UNIQUE KEY uq_insumo_palavra_chave_insumo_palavra (insumo_id, palavra_chave),
  KEY ix_insumo_palavra_chave_palavra_chave (palavra_chave),
  CONSTRAINT ck_insumo_palavra_chave_origem CHECK (origem IN ('sistema','migracao','integracao'))
) COMMENT='Palavras-chave ligadas ao insumo para busca em compras, requisição e prescrição';

