CREATE TABLE inventario_estoque (
  id                           BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
  estabelecimento_id           BIGINT UNSIGNED NOT NULL,
  numero                       VARCHAR(20) NOT NULL COMMENT 'Número de negócio (sequencia_negocio)',
  local_estoque_id             BIGINT UNSIGNED NOT NULL,
  tipo                         VARCHAR(30) NOT NULL,
  curva_abc                    CHAR(1) NULL COMMENT 'Curva escolhida no inventário cíclico',
  motivo_inventario_estoque_id BIGINT UNSIGNED NULL,
  data_corte                   DATETIME(3) NOT NULL COMMENT 'Momento do saldo de referência',
  situacao                     VARCHAR(30) NOT NULL DEFAULT 'aberto',
  contagem_cega                BOOLEAN NOT NULL DEFAULT TRUE COMMENT 'O contador não vê o saldo do sistema',
  rodadas_maximas              TINYINT UNSIGNED NOT NULL DEFAULT 3,
  limite_divergencia_pct       DECIMAL(7,4) NULL COMMENT 'Diferença percentual aceita sem recontagem',
  controla_lote                BOOLEAN NOT NULL DEFAULT TRUE,
  abertura_usuario_id          BIGINT UNSIGNED NOT NULL,
  aberto_em                    DATETIME(3) NOT NULL,
  fechamento_usuario_id        BIGINT UNSIGNED NULL,
  fechado_em                   DATETIME(3) NULL,
  aprovacao_usuario_id         BIGINT UNSIGNED NULL,
  aprovado_em                  DATETIME(3) NULL,
  justificativa                VARCHAR(250) NULL COMMENT 'Justificativa da aprovação ou do cancelamento',
  documento_estoque_id         BIGINT UNSIGNED NULL COMMENT 'Documento de balanço gerado na aprovação',
  observacao                   VARCHAR(500) NULL,
  origem                       VARCHAR(20) NOT NULL DEFAULT 'sistema',
  criado_em                    DATETIME(3) NOT NULL,
  criado_por                   BIGINT UNSIGNED NULL,
  alterado_em                  DATETIME(3) NULL,
  alterado_por                 BIGINT UNSIGNED NULL,
  versao                       INT UNSIGNED NOT NULL DEFAULT 1,
  excluido_em                  DATETIME(3) NULL,
  excluido_por                 BIGINT UNSIGNED NULL,
  UNIQUE KEY uq_inventario_estoque_estabelecimento_numero (estabelecimento_id, numero),
  KEY ix_inventario_estoque_local_situacao (local_estoque_id, situacao),
  CONSTRAINT ck_inventario_estoque_tipo CHECK (tipo IN ('geral','ciclico','inicial','auditoria','doacao')),
  CONSTRAINT ck_inventario_estoque_situacao CHECK (situacao IN ('aberto','contagem','recontagem','aprovado','cancelado')),
  CONSTRAINT ck_inventario_estoque_curva CHECK (curva_abc IS NULL OR curva_abc IN ('A','B','C')),
  CONSTRAINT ck_inventario_estoque_limite CHECK (limite_divergencia_pct IS NULL OR limite_divergencia_pct BETWEEN 0 AND 100),
  CONSTRAINT ck_inventario_estoque_rodadas CHECK (rodadas_maximas BETWEEN 1 AND 9),
  CONSTRAINT ck_inventario_estoque_origem CHECK (origem IN ('sistema','migracao','integracao')),
  KEY ix_inventario_estoque_motivo_inventario_estoque_id (motivo_inventario_estoque_id),
  KEY ix_inventario_estoque_abertura_usuario_id (abertura_usuario_id),
  KEY ix_inventario_estoque_fechamento_usuario_id (fechamento_usuario_id),
  KEY ix_inventario_estoque_aprovacao_usuario_id (aprovacao_usuario_id),
  KEY ix_inventario_estoque_documento_estoque_id (documento_estoque_id)
) COMMENT='Inventário ou balanço de um local (geral, rotativo, inicial), com data de corte e situação';

