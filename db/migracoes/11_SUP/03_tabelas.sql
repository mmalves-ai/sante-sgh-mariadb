CREATE TABLE insumo_referencia_preco (
  id                          BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
  insumo_id                   BIGINT UNSIGNED NOT NULL,
  item_referencia_matmed_id   BIGINT UNSIGNED NOT NULL,
  edicao_referencia_matmed_id BIGINT UNSIGNED NULL COMMENT 'Edição da referência em que o vínculo passou a valer',
