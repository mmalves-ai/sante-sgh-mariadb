CREATE TABLE acao_dose (
  id           BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
  codigo       VARCHAR(30) NOT NULL,
  descricao    VARCHAR(150) NOT NULL,
  ativo        BOOLEAN NOT NULL DEFAULT TRUE,
  notifica     BOOLEAN NOT NULL DEFAULT FALSE COMMENT 'Exibe aviso ao prescritor e ao farmacêutico',
  bloqueia     BOOLEAN NOT NULL DEFAULT FALSE COMMENT 'Impede a gravação da prescrição até ajuste ou justificativa',
  criado_em    DATETIME(3) NOT NULL,
  criado_por   BIGINT UNSIGNED NULL,
  alterado_em  DATETIME(3) NULL,
  alterado_por BIGINT UNSIGNED NULL,
  versao       INT UNSIGNED NOT NULL DEFAULT 1,
  UNIQUE KEY uq_acao_dose_codigo (codigo),
  CONSTRAINT ck_acao_dose_bloqueia_notifica CHECK (bloqueia = FALSE OR notifica = TRUE)
) COMMENT='O que o sistema faz quando a dose prescrita passa do limite do item: nada, avisar ou bloquear';

