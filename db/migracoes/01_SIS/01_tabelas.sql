  registros_lidos   BIGINT UNSIGNED NOT NULL DEFAULT 0,
  registros_gravados BIGINT UNSIGNED NOT NULL DEFAULT 0,
  registros_atualizados BIGINT UNSIGNED NOT NULL DEFAULT 0,
  registros_rejeitados BIGINT UNSIGNED NOT NULL DEFAULT 0,
  registros_ignorados BIGINT UNSIGNED NOT NULL DEFAULT 0 COMMENT 'Sem alteração desde a marca anterior',
  marca_inicial     VARCHAR(100) NULL COMMENT 'Marca de sincronismo no início da leitura',
  marca_final       VARCHAR(100) NULL COMMENT 'Marca de sincronismo atingida ao fim',
  inicio_em         DATETIME(3) NULL,
  fim_em            DATETIME(3) NULL,
  duracao_ms        BIGINT UNSIGNED NULL,
  mensagem_erro     TEXT NULL,
  origem            VARCHAR(20) NOT NULL DEFAULT 'sistema',
  criado_em         DATETIME(3) NOT NULL,
  criado_por        BIGINT UNSIGNED NULL,
  alterado_em       DATETIME(3) NULL,
  alterado_por      BIGINT UNSIGNED NULL,
  versao            INT UNSIGNED NOT NULL DEFAULT 1,
  excluido_em       DATETIME(3) NULL,
  excluido_por      BIGINT UNSIGNED NULL,
  CONSTRAINT ck_lote_carga_legado_tabela_situacao CHECK (situacao IN ('pendente','em_execucao','concluida','concluida_com_rejeicoes','falhou','ignorada')),
  CONSTRAINT ck_lote_carga_legado_tabela_periodo CHECK (fim_em IS NULL OR inicio_em IS NULL OR fim_em >= inicio_em),
  CONSTRAINT ck_lote_carga_legado_tabela_origem CHECK (origem IN ('sistema','migracao','integracao')),
  UNIQUE KEY uq_lote_carga_legado_tabela_lote_sequencia (lote_carga_legado_id, sequencia),
  UNIQUE KEY uq_lote_carga_legado_tabela_lote_tabela (lote_carga_legado_id, tabela_origem)
) COMMENT='Resultado da carga por tabela de origem: lidos, gravados, rejeitados e tempo';

CREATE TABLE divergencia_carga (
  id                BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
  lote_carga_legado_tabela_id BIGINT UNSIGNED NOT NULL,
  sequencia         INT UNSIGNED NOT NULL,
  chave_origem      VARCHAR(200) NOT NULL COMMENT 'Chave do registro na tabela de origem (nunca o conteúdo)',
  coluna_origem     VARCHAR(64) NULL,
  regra_violada     VARCHAR(100) NOT NULL COMMENT 'Código da regra de limpeza ou integridade violada',
  descricao         VARCHAR(1000) NULL COMMENT 'Explicação da divergência, sem valores de pessoa',
  severidade        VARCHAR(30) NOT NULL DEFAULT 'erro',
  tratamento        VARCHAR(30) NOT NULL DEFAULT 'pendente',
  tratado_em        DATETIME(3) NULL,
  tratado_por_usuario_id BIGINT UNSIGNED NULL,
  observacao_tratamento VARCHAR(1000) NULL,
  pendencia_id      BIGINT UNSIGNED NULL COMMENT 'Pendência aberta para a área tratar',
  origem            VARCHAR(20) NOT NULL DEFAULT 'sistema',
  criado_em         DATETIME(3) NOT NULL,
  criado_por        BIGINT UNSIGNED NULL,
  alterado_em       DATETIME(3) NULL,
  alterado_por      BIGINT UNSIGNED NULL,
  versao            INT UNSIGNED NOT NULL DEFAULT 1,
  excluido_em       DATETIME(3) NULL,
  excluido_por      BIGINT UNSIGNED NULL,
  CONSTRAINT ck_divergencia_carga_severidade CHECK (severidade IN ('erro','alerta','informacao')),
  CONSTRAINT ck_divergencia_carga_tratamento CHECK (tratamento IN ('pendente','corrigido_na_origem','corrigido_no_destino','aceito','descartado')),
  CONSTRAINT ck_divergencia_carga_tratado CHECK (tratamento = 'pendente' OR tratado_em IS NOT NULL),
  CONSTRAINT ck_divergencia_carga_origem CHECK (origem IN ('sistema','migracao','integracao')),
  UNIQUE KEY uq_divergencia_carga_tabela_sequencia (lote_carga_legado_tabela_id, sequencia),
  KEY ix_divergencia_carga_regra (regra_violada, tratamento),
  KEY ix_divergencia_carga_tratado_por (tratado_por_usuario_id),
  KEY ix_divergencia_carga_pendencia (pendencia_id)
) COMMENT='Registro rejeitado ou divergente na carga, com regra violada, valor e tratamento';

CREATE TABLE aceite_carga_area (
  id                BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
  lote_carga_legado_id BIGINT UNSIGNED NOT NULL,
  modulo_sistema_id BIGINT UNSIGNED NOT NULL COMMENT 'Área avaliadora, pelo módulo do sistema',
  ocorrido_em       DATETIME(3) NOT NULL,
  usuario_id        BIGINT UNSIGNED NOT NULL COMMENT 'Responsável da área que avaliou',
  resultado         VARCHAR(30) NOT NULL,
  ressalva          TEXT NULL,
  dados             JSON NULL COMMENT 'Contagens e conferências apresentadas na avaliação',
  criado_em         DATETIME(3) NOT NULL,
  criado_por        BIGINT UNSIGNED NULL,
  alterado_em       DATETIME(3) NULL,
  alterado_por      BIGINT UNSIGNED NULL,
  versao            INT UNSIGNED NOT NULL DEFAULT 1,
  CONSTRAINT ck_aceite_carga_area_resultado CHECK (resultado IN ('aprovado','aprovado_com_ressalva','reprovado')),
  CONSTRAINT ck_aceite_carga_area_ressalva CHECK (resultado = 'aprovado' OR ressalva IS NOT NULL),
  KEY ix_aceite_carga_area_lote (lote_carga_legado_id, modulo_sistema_id, ocorrido_em),
  KEY ix_aceite_carga_area_modulo_sistema (modulo_sistema_id),
  KEY ix_aceite_carga_area_usuario (usuario_id)
) COMMENT='Avaliação dos dados carregados por cada área (dia 1): aprovado ou com ressalva, responsável e data';

CREATE TABLE mapa_identificador_legado (
  id                BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
  sistema_origem    VARCHAR(60) NOT NULL,
  tabela_origem     VARCHAR(64) NOT NULL,
  chave_origem      VARCHAR(200) NOT NULL COMMENT 'Chave original, composta quando a origem usa várias colunas',
  entidade          VARCHAR(64) NOT NULL COMMENT 'Tabela própria de destino',
  entidade_id       BIGINT UNSIGNED NOT NULL COMMENT 'Id do registro próprio na tabela de destino',
  hash_origem       CHAR(64) NULL COMMENT 'SHA-256 do registro de origem, para detectar alteração no diferencial',
  lote_carga_legado_id BIGINT UNSIGNED NOT NULL COMMENT 'Lote que criou o vínculo',
  ultimo_lote_carga_legado_id BIGINT UNSIGNED NULL COMMENT 'Último lote que tocou o registro',
  criado_em         DATETIME(3) NOT NULL,
  criado_por        BIGINT UNSIGNED NULL,
  alterado_em       DATETIME(3) NULL,
  alterado_por      BIGINT UNSIGNED NULL,
  versao            INT UNSIGNED NOT NULL DEFAULT 1,
  excluido_em       DATETIME(3) NULL,
  excluido_por      BIGINT UNSIGNED NULL,
  UNIQUE KEY uq_mapa_identificador_legado_origem (sistema_origem, tabela_origem, chave_origem, entidade),
  KEY ix_mapa_identificador_legado_entidade (entidade, entidade_id),
  KEY ix_mapa_identificador_legado_lote (lote_carga_legado_id),
  KEY ix_mapa_identificador_legado_ultimo_lote (ultimo_lote_carga_legado_id)
) COMMENT='De-para entre a chave do sistema de origem e a chave própria, por entidade';

CREATE TABLE marca_sincronismo (
  id                BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
  estabelecimento_id BIGINT UNSIGNED NOT NULL,
  sistema_origem    VARCHAR(60) NOT NULL,
  tabela_origem     VARCHAR(64) NOT NULL,
  tipo_marca        VARCHAR(30) NOT NULL DEFAULT 'data_hora',
  valor_marca       VARCHAR(100) NULL COMMENT 'Ponto de corte atingido (data e hora, sequencial ou resumo), nunca dado de pessoa',
  marcado_em        DATETIME(3) NULL,
  ultimo_lote_carga_legado_id BIGINT UNSIGNED NULL,
  ativo             BOOLEAN NOT NULL DEFAULT TRUE,
  criado_em         DATETIME(3) NOT NULL,
  criado_por        BIGINT UNSIGNED NULL,
  alterado_em       DATETIME(3) NULL,
  alterado_por      BIGINT UNSIGNED NULL,
  versao            INT UNSIGNED NOT NULL DEFAULT 1,
  CONSTRAINT ck_marca_sincronismo_tipo_marca CHECK (tipo_marca IN ('data_hora','sequencial','resumo','completa')),
  CONSTRAINT ck_marca_sincronismo_valor CHECK (valor_marca IS NULL OR marcado_em IS NOT NULL),
  UNIQUE KEY uq_marca_sincronismo_estabelecimento_tabela (estabelecimento_id, sistema_origem, tabela_origem),
  KEY ix_marca_sincronismo_ultimo_lote (ultimo_lote_carga_legado_id)
) COMMENT='Ponto de corte do sincronismo diferencial por tabela de origem';
