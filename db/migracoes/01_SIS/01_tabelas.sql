  CONSTRAINT ck_cadastro_padrao_vigencia CHECK (vigencia_fim IS NULL OR vigencia_inicio IS NULL OR vigencia_fim >= vigencia_inicio),
  CONSTRAINT ck_cadastro_padrao_confirmacao CHECK (situacao NOT IN ('validado','publicado') OR confirmado_em IS NOT NULL),
  UNIQUE KEY uq_cadastro_padrao_tipo_descricao (tipo_cadastro_padrao_id, descricao),
  KEY ix_cadastro_padrao_tipo_cadastro_padrao (tipo_cadastro_padrao_id),
  KEY ix_cadastro_padrao_pai (cadastro_padrao_pai_id),
  KEY ix_cadastro_padrao_unidade_medida (unidade_medida_id),
  KEY ix_cadastro_padrao_sexo (sexo_id),
  KEY ix_cadastro_padrao_confirmado_por (confirmado_por_usuario_id),
  KEY ix_cadastro_padrao_codigo_tuss (codigo_tuss)
) COMMENT='Biblioteca de registros-modelo de cadastro (itens, procedimentos, materiais) oferecida para carga na implantação';

