CREATE TABLE lote_carga_legado (
  id                BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
  estabelecimento_id BIGINT UNSIGNED NOT NULL,
  numero            BIGINT UNSIGNED NOT NULL COMMENT 'Número de negócio do lote, por estabelecimento',
  tipo              VARCHAR(30) NOT NULL,
  sistema_origem    VARCHAR(60) NOT NULL COMMENT 'Identificação neutra do sistema de onde os dados vêm',
  imagem_origem     VARCHAR(255) NULL COMMENT 'Identificação da cópia somente leitura usada na carga',
  imagem_gerada_em  DATETIME(3) NULL COMMENT 'Momento em que a cópia de origem foi gerada',
  corte_inicio_em   DATETIME(3) NULL COMMENT 'Início da janela de alterações coberta (carga diferencial)',
  corte_fim_em      DATETIME(3) NULL COMMENT 'Fim da janela de alterações coberta',
  lote_anterior_id  BIGINT UNSIGNED NULL COMMENT 'Lote que este continua (cadeia de diferenciais)',
  execucao_rotina_id BIGINT UNSIGNED NULL,
  disparado_por_usuario_id BIGINT UNSIGNED NULL,
  inicio_em         DATETIME(3) NULL,
  fim_em            DATETIME(3) NULL,
  situacao          VARCHAR(30) NOT NULL DEFAULT 'agendado',
  tabelas_total     INT UNSIGNED NOT NULL DEFAULT 0,
  registros_lidos   BIGINT UNSIGNED NOT NULL DEFAULT 0,
  registros_gravados BIGINT UNSIGNED NOT NULL DEFAULT 0,
  registros_rejeitados BIGINT UNSIGNED NOT NULL DEFAULT 0,
  mensagem_erro     TEXT NULL,
  observacao        VARCHAR(1000) NULL,
  origem            VARCHAR(20) NOT NULL DEFAULT 'sistema',
  criado_em         DATETIME(3) NOT NULL,
  criado_por        BIGINT UNSIGNED NULL,
  alterado_em       DATETIME(3) NULL,
  alterado_por      BIGINT UNSIGNED NULL,
  versao            INT UNSIGNED NOT NULL DEFAULT 1,
  excluido_em       DATETIME(3) NULL,
  excluido_por      BIGINT UNSIGNED NULL,
  CONSTRAINT ck_lote_carga_legado_tipo CHECK (tipo IN ('inicial','diferencial','reprocessamento')),
  CONSTRAINT ck_lote_carga_legado_situacao CHECK (situacao IN ('agendado','em_execucao','concluido','concluido_com_rejeicoes','falhou','cancelado')),
  CONSTRAINT ck_lote_carga_legado_falha CHECK (situacao <> 'falhou' OR mensagem_erro IS NOT NULL),
  CONSTRAINT ck_lote_carga_legado_periodo CHECK (fim_em IS NULL OR inicio_em IS NULL OR fim_em >= inicio_em),
  CONSTRAINT ck_lote_carga_legado_corte CHECK (corte_fim_em IS NULL OR corte_inicio_em IS NULL OR corte_fim_em >= corte_inicio_em),
  CONSTRAINT ck_lote_carga_legado_origem CHECK (origem IN ('sistema','migracao','integracao')),
  UNIQUE KEY uq_lote_carga_legado_estabelecimento_numero (estabelecimento_id, numero),
  KEY ix_lote_carga_legado_lote_anterior (lote_anterior_id),
  KEY ix_lote_carga_legado_execucao_rotina (execucao_rotina_id),
  KEY ix_lote_carga_legado_disparado_por (disparado_por_usuario_id),
  KEY ix_lote_carga_legado_situacao (estabelecimento_id, situacao, inicio_em)
) COMMENT='Lote de carga do sistema de origem (dia 0 ou diferencial): início, fim, origem, situação e volumes';

CREATE TABLE lote_carga_legado_tabela (
