  rotina_agendada_id BIGINT UNSIGNED NOT NULL,
  ocorrido_em       DATETIME(3) NOT NULL COMMENT 'Momento do disparo',
  usuario_id        BIGINT UNSIGNED NULL COMMENT 'Quem disparou; nulo quando foi o agendador',
  disparo           VARCHAR(30) NOT NULL DEFAULT 'agendado',
  tentativa         TINYINT UNSIGNED NOT NULL DEFAULT 1,
  inicio_em         DATETIME(3) NULL,
  fim_em            DATETIME(3) NULL,
  situacao          VARCHAR(30) NOT NULL DEFAULT 'em_execucao',
  registros_lidos   BIGINT UNSIGNED NOT NULL DEFAULT 0,
  registros_gravados BIGINT UNSIGNED NOT NULL DEFAULT 0,
  registros_rejeitados BIGINT UNSIGNED NOT NULL DEFAULT 0,
  codigo_saida      VARCHAR(30) NULL,
  mensagem_erro     TEXT NULL,
  dados             JSON NULL COMMENT 'Parâmetros efetivos e resumo da execução',
  servidor          VARCHAR(100) NULL COMMENT 'Instância do executor que processou',
  correlacao        VARCHAR(64) NULL COMMENT 'Identificador para juntar com a trilha de auditoria e os logs',
  criado_em         DATETIME(3) NOT NULL,
  criado_por        BIGINT UNSIGNED NULL,
  alterado_em       DATETIME(3) NULL,
  alterado_por      BIGINT UNSIGNED NULL,
  versao            INT UNSIGNED NOT NULL DEFAULT 1,
  CONSTRAINT ck_execucao_rotina_disparo CHECK (disparo IN ('agendado','manual','reprocessamento')),
  CONSTRAINT ck_execucao_rotina_situacao CHECK (situacao IN ('aguardando','em_execucao','concluida','concluida_com_avisos','falhou','cancelada','expirada')),
  CONSTRAINT ck_execucao_rotina_falha CHECK (situacao <> 'falhou' OR mensagem_erro IS NOT NULL),
  CONSTRAINT ck_execucao_rotina_periodo CHECK (fim_em IS NULL OR inicio_em IS NULL OR fim_em >= inicio_em),
  KEY ix_execucao_rotina_rotina_agendada (rotina_agendada_id, ocorrido_em),
  KEY ix_execucao_rotina_usuario (usuario_id),
  KEY ix_execucao_rotina_situacao (situacao, ocorrido_em)
) COMMENT='Cada execução de rotina: início, fim, situação, volumes, mensagem de erro e quem disparou';

