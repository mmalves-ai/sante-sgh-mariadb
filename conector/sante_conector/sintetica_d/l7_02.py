def formas():
    """{tabela: [(coluna, tipo, not_null)]} lido do próprio DDL (as tabelas de parâmetros têm até 141 colunas)."""
    out = {}
    for m in re.finditer(r"CREATE TABLE (\w+) \((.*?)\);", " ".join(DDL.split()), re.S):
        out[m.group(1)] = [(c, t.strip(), bool(nn)) for c, t, nn in
                           re.findall(r'"(\w+)" ([A-Z]+(?:\(\d+(?:,\d+)?\))?(?: PRECISION| SUB_TYPE \d)?)( NOT NULL)?', m.group(2))]
    return out


def _neutra(forma, r, fixos):
    """Linha de tabela não carregada: chave e obrigatórias preenchidas; S/N sorteado nas colunas de um caractere."""
    v = []
    for c, t, nn in forma:
        if c in fixos:
            v.append(fixos[c])
        elif t in ("CHAR(1)", "VARCHAR(1)"):
            v.append(r.choice("SN"))
        elif nn:
            v.append(1 if t in ("SMALLINT", "INTEGER", "BIGINT") else "x")
        else:
            v.append(None)
    return v


