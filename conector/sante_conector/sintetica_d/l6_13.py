LACUNAS = (1, 2, 5, 9)  # chaves com lacunas
DATA_ZERO = datetime.datetime(1899, 12, 30)


def _colunas(espec):
    out = []
    for x in espec.split():
        nome, tipo = x.split(":", 1)
        out.append((nome, tipo.rstrip("!~"), "!" in tipo, "~" in tipo))
    return out


