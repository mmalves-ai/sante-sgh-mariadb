CHAVE = {t: k.split(",") for t, k, _ in TABELAS}


def _ddl_tipo(tipo, texto):
    if tipo == "BLOB":
        return "BLOB SUB_TYPE %d" % (1 if texto else 0)
    return "DOUBLE PRECISION" if tipo == "DOUBLE" else tipo


